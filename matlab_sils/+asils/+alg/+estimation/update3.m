function [q, b, p, took] = update3(q0, b0, p0, h, r, y, gate)
%UPDATE3  The Joseph-form update with a 3-row measurement H (3 x 6), noise R and innovation y. With
%   gate > 0 an update whose chi-square y' S^-1 y passes the gate is refused (took = false).
%   q0: real[1][4] (passed a plain number)
%   b0: real[1][3] (passed a plain number)
%   p0: real[1][6][6] (passed a plain number)
%   h: real[1][6][3] (passed a plain number)
%   r: real[1][3][3] (passed a plain number)
%   y: real[1][3] (passed a plain number)
%   gate: real[1] (passed a plain number)
%   returns q: real[1][4] (passed a plain number)
%   returns b: real[1][3] (passed a plain number)
%   returns p: real[1][6][6] (passed a plain number)
%   returns took: bool (passed true or false)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    q = zeros(4, 1);
    b = zeros(3, 1);
    p = zeros(6, 6);
    took = false;
    q = q0;
    b = b0;
    p = p0;
    took = false;
    pht = zeros(6, 3);
    for i = (0):((6) - 1)
        for j = (0):((3) - 1)
            pht((i) + 1, (j) + 1) = 0;
            for l = (0):((6) - 1)
                pht((i) + 1, (j) + 1) = (pht((i) + 1, (j) + 1) + (p0((i) + 1, (l) + 1) * h((j) + 1, (l) + 1)));
            end
        end
    end
    s = zeros(3, 3);
    for i = (0):((3) - 1)
        for j = (0):((3) - 1)
            s((i) + 1, (j) + 1) = r((i) + 1, (j) + 1);
            for l = (0):((6) - 1)
                s((i) + 1, (j) + 1) = (s((i) + 1, (j) + 1) + (h((i) + 1, (l) + 1) * pht((l) + 1, (j) + 1)));
            end
        end
    end
    [si, ok] = asils.alg.math.inv3(s);
    if ok
        chi = 0;
        for i = (0):((3) - 1)
            for j = (0):((3) - 1)
                chi = (chi + ((y((i) + 1) * si((i) + 1, (j) + 1)) * y((j) + 1)));
            end
        end
        if ((chi == chi) && (~((gate > 0) && (chi > gate))))
            took = true;
            g = zeros(6, 3);
            for i = (0):((6) - 1)
                for j = (0):((3) - 1)
                    g((i) + 1, (j) + 1) = 0;
                    for l = (0):((3) - 1)
                        g((i) + 1, (j) + 1) = (g((i) + 1, (j) + 1) + (pht((i) + 1, (l) + 1) * si((l) + 1, (j) + 1)));
                    end
                end
            end
            dx = zeros(6, 1);
            for i = (0):((6) - 1)
                dx((i) + 1) = 0;
                for l = (0):((3) - 1)
                    dx((i) + 1) = (dx((i) + 1) + (g((i) + 1, (l) + 1) * y((l) + 1)));
                end
            end
            q = asils.alg.math.qnorm(asils.alg.math.qmult(q0, [(0.5 * dx(1)); (0.5 * dx(2)); (0.5 * dx(3)); 1]));
            for i = (0):((3) - 1)
                b((i) + 1) = (b0((i) + 1) + dx(((i + 3)) + 1));
            end
            ikh = zeros(6, 6);
            for i = (0):((6) - 1)
                for j = (0):((6) - 1)
                    ikh((i) + 1, (j) + 1) = asils.pc.choose((i == j), 1, 0);
                    for l = (0):((3) - 1)
                        ikh((i) + 1, (j) + 1) = (ikh((i) + 1, (j) + 1) - (g((i) + 1, (l) + 1) * h((l) + 1, (j) + 1)));
                    end
                end
            end
            t = zeros(6, 6);
            for i = (0):((6) - 1)
                for j = (0):((6) - 1)
                    t((i) + 1, (j) + 1) = 0;
                    for l = (0):((6) - 1)
                        t((i) + 1, (j) + 1) = (t((i) + 1, (j) + 1) + (ikh((i) + 1, (l) + 1) * p0((l) + 1, (j) + 1)));
                    end
                end
            end
            for i = (0):((6) - 1)
                for j = (0):((6) - 1)
                    p((i) + 1, (j) + 1) = 0;
                    for l = (0):((6) - 1)
                        p((i) + 1, (j) + 1) = (p((i) + 1, (j) + 1) + (t((i) + 1, (l) + 1) * ikh((j) + 1, (l) + 1)));
                    end
                end
            end
            for i = (0):((6) - 1)
                for j = (0):((6) - 1)
                    for a = (0):((3) - 1)
                        for c = (0):((3) - 1)
                            p((i) + 1, (j) + 1) = (p((i) + 1, (j) + 1) + ((g((i) + 1, (a) + 1) * r((a) + 1, (c) + 1)) * g((j) + 1, (c) + 1)));
                        end
                    end
                end
            end
        end
    end
end
