function [pa] = triad_cov(b1, b2, s1, s2)
%TRIAD_COV  The covariance of the TRIAD attitude in the body frame [rad^2], from the geometry and the two vectors' noises s1 (the
%   first, whose direction the attitude keeps exactly) and s2 (S11.6, G1; Shuster and Oh 1981, J. Guidance and Control 4(1):70-77,
%   the covariance of the TRIAD error). In the frame of the first vector t0, the normal t1 of the pair's plane and t2 = t0 x t1,
%   with c and sn the cosine and sine of the angle between the vectors: variance (s2^2 + c^2 s1^2)/sn^2 about t0, s1^2 about t1
%   and t2, and -c s1^2/sn between t0 and t2. The attitude about t0 is only as good as the second vector over sn.
%   b1: real[1][3] (passed a plain number)
%   b2: real[1][3] (passed a plain number)
%   s1: real[1] (passed a plain number)
%   s2: real[1] (passed a plain number)
%   returns pa: real[1][3][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    pa = zeros(3, 3);
    n1 = sqrt(b1(1)*b1(1) + b1(2)*b1(2) + b1(3)*b1(3));
    n2 = sqrt(b2(1)*b2(1) + b2(2)*b2(2) + b2(3)*b2(3));
    cr = [b1(2)*b2(3) - b1(3)*b2(2); b1(3)*b2(1) - b1(1)*b2(3); b1(1)*b2(2) - b1(2)*b2(1)];
    h__37 = sqrt(b1(1)*b1(1) + b1(2)*b1(2) + b1(3)*b1(3));
    if 1e-30 > h__37, h__37 = 1e-30; end
    t0 = (b1 / h__37);
    h__38 = sqrt(cr(1)*cr(1) + cr(2)*cr(2) + cr(3)*cr(3));
    if 1e-30 > h__38, h__38 = 1e-30; end
    t1 = (cr / h__38);
    t2 = [t0(2)*t1(3) - t0(3)*t1(2); t0(3)*t1(1) - t0(1)*t1(3); t0(1)*t1(2) - t0(2)*t1(1)];
    sn = (sqrt(cr(1)*cr(1) + cr(2)*cr(2) + cr(3)*cr(3)) / (n1 * n2));
    c = ((b1(1)*b2(1) + b1(2)*b2(2) + b1(3)*b2(3)) / (n1 * n2));
    d0 = (((s2 * s2) + (((c * c) * s1) * s1)) / (sn * sn));
    x = ((((-(c)) * s1) * s1) / sn);
    pa = zeros(3, 3);
    i = ((0):((3) - 1)).';
    j = (0):((3) - 1);
    pa((i) + 1, (j) + 1) = (((((d0 .* reshape(t0((i) + 1), [], 1)) .* reshape(t0((j) + 1), 1, [])) + (((s1 * s1) .* reshape(t1((i) + 1), [], 1)) .* reshape(t1((j) + 1), 1, []))) + (((s1 * s1) .* reshape(t2((i) + 1), [], 1)) .* reshape(t2((j) + 1), 1, []))) + (x .* ((reshape(t0((i) + 1), [], 1) .* reshape(t2((j) + 1), 1, [])) + (reshape(t2((i) + 1), [], 1) .* reshape(t0((j) + 1), 1, [])))));
end
