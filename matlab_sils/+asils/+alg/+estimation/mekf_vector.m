function [q, b, p, took] = mekf_vector(q0, b0, p0, bm, rr, sigma, gate)
%MEKF_VECTOR  A vector measurement: the body vector bm against the reference rr (both made unit), noise sigma.
%   q0: real[1][4] (passed a plain number)
%   b0: real[1][3] (passed a plain number)
%   p0: real[1][6][6] (passed a plain number)
%   bm: real[1][3] (passed a plain number)
%   rr: real[1][3] (passed a plain number)
%   sigma: real[1] (passed a plain number)
%   gate: real[1] (passed a plain number)
%   returns q: real[1][4] (passed a plain number)
%   returns b: real[1][3] (passed a plain number)
%   returns p: real[1][6][6] (passed a plain number)
%   returns took: bool (passed true or false)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    q = zeros(4, 1);
    b = zeros(3, 1);
    p = zeros(6, 6);
    took = false;
    bu = asils.pc.unit_(bm);
    ru = asils.pc.unit_(rr);
    bh = asils.pc.mv(asils.alg.math.dcm(q0), ru);
    sk = asils.alg.math.skew(bh);
    h = zeros(3, 6);
    for i = (0):((3) - 1)
        for j = (0):((6) - 1)
            h((i) + 1, (j) + 1) = asils.pc.choose_lazy((j < 3), @() sk((i) + 1, (j) + 1), @() 0);
        end
    end
    r = zeros(3, 3);
    for i = (0):((3) - 1)
        for j = (0):((3) - 1)
            r((i) + 1, (j) + 1) = asils.pc.choose((i == j), (sigma * sigma), 0);
        end
    end
    [t__1, t__2, t__3, t__4] = asils.alg.estimation.update3(q0, b0, p0, h, r, (bu - bh), gate);
    q = t__1;
    b = t__2;
    p = t__3;
    took = t__4;
end
