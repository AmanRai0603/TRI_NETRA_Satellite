function [q, p] = mekf_predict(q0, b, p0, arw, rrw, wm, dt)
%MEKF_PREDICT  The prediction over dt on the measured rate wm, with gyro angle and rate random walks arw, rrw:
%   q <- q fromrotvec((wm - b) dt), P <- Phi P Phi' + Q.
%   q0: real[1][4] (passed a plain number)
%   b: real[1][3] (passed a plain number)
%   p0: real[1][6][6] (passed a plain number)
%   arw: real[1] (passed a plain number)
%   rrw: real[1] (passed a plain number)
%   wm: real[1][3] (passed a plain number)
%   dt: real[1] (passed a plain number)
%   returns q: real[1][4] (passed a plain number)
%   returns p: real[1][6][6] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    q = zeros(4, 1);
    p = zeros(6, 6);
    sv2 = (arw * arw);
    su2 = (rrw * rrw);
    w = (wm - b);
    q = asils.alg.math.qnorm(asils.alg.math.qmult(q0, asils.alg.math.fromrotvec((w * dt))));
    ww = asils.alg.math.skew(w);
    w2 = asils.pc.mm(ww, ww);
    phi = zeros(6, 6);
    for i = (0):((3) - 1)
        j = ((0):((3) - 1)).';
        phi((i) + 1, (j) + 1) = (((asils.pc.vchoose((i == j), 1, 0) - ((ww((i) + 1, (j) + 1)).' .* dt)) + (((0.5 .* (w2((i) + 1, (j) + 1)).') .* dt) .* dt))).';
        phi((i) + 1, ((i + 3)) + 1) = (-(dt));
        phi(((i + 3)) + 1, ((i + 3)) + 1) = 1;
    end
    t = zeros(6, 6);
    i = ((0):((6) - 1)).';
    j = (0):((6) - 1);
    t((i) + 1, (j) + 1) = 0;
    for l = (0):((6) - 1)
        t((i) + 1, (j) + 1) = (t((i) + 1, (j) + 1) + (phi((i) + 1, (l) + 1) .* p0((l) + 1, (j) + 1)));
    end
    p = zeros(6, 6);
    i = ((0):((6) - 1)).';
    j = (0):((6) - 1);
    p((i) + 1, (j) + 1) = 0;
    for l = (0):((6) - 1)
        p((i) + 1, (j) + 1) = (p((i) + 1, (j) + 1) + (t((i) + 1, (l) + 1) .* (phi((j) + 1, (l) + 1)).'));
    end
    for i = (0):((3) - 1)
        p((i) + 1, (i) + 1) = (p((i) + 1, (i) + 1) + ((sv2 * dt) + ((((su2 * dt) * dt) * dt) / 3)));
        p((i) + 1, ((i + 3)) + 1) = (p((i) + 1, ((i + 3)) + 1) + ((((-(su2)) * dt) * dt) / 2));
        p(((i + 3)) + 1, (i) + 1) = (p(((i + 3)) + 1, (i) + 1) + ((((-(su2)) * dt) * dt) / 2));
        p(((i + 3)) + 1, ((i + 3)) + 1) = (p(((i + 3)) + 1, ((i + 3)) + 1) + (su2 * dt));
    end
end
