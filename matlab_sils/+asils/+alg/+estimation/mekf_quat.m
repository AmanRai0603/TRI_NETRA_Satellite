function [q, b, p, took] = mekf_quat(q0, b0, p0, qm, sc, sr, bs, gate)
%MEKF_QUAT  A star-tracker quaternion qm with cross-boresight and roll noises sc, sr about boresight bs.
%   q0: real[1][4] (passed a plain number)
%   b0: real[1][3] (passed a plain number)
%   p0: real[1][6][6] (passed a plain number)
%   qm: real[1][4] (passed a plain number)
%   sc: real[1] (passed a plain number)
%   sr: real[1] (passed a plain number)
%   bs: real[1][3] (passed a plain number)
%   gate: real[1] (passed a plain number)
%   returns q: real[1][4] (passed a plain number)
%   returns b: real[1][3] (passed a plain number)
%   returns p: real[1][6][6] (passed a plain number)
%   returns took: bool (passed true or false)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    q = zeros(4, 1);
    b = zeros(3, 1);
    p = zeros(6, 6);
    took = false;
    dq = asils.alg.math.qerr(q0, qm);
    y = zeros(3, 1);
    for i = (0):((3) - 1)
        y((i) + 1) = (2 * dq((i) + 1));
    end
    h = zeros(3, 6);
    r = zeros(3, 3);
    for i = (0):((3) - 1)
        for j = (0):((6) - 1)
            h((i) + 1, (j) + 1) = asils.pc.choose((i == j), 1, 0);
        end
        for j = (0):((3) - 1)
            r((i) + 1, (j) + 1) = (asils.pc.choose((i == j), (sc * sc), 0) + ((((sr * sr) - (sc * sc)) * bs((i) + 1)) * bs((j) + 1)));
        end
    end
    [t__5, t__6, t__7, t__8] = asils.alg.estimation.update3(q0, b0, p0, h, r, y, gate);
    q = t__5;
    b = t__6;
    p = t__7;
    took = t__8;
end
