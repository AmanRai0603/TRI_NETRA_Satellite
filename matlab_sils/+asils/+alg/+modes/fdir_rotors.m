function [s] = fdir_rotors(st, rp, t, dt, zh)
%FDIR_ROTORS  The rotor FDIR in the momentum-device states: a fixed rotor that does not follow its command is
%   isolated. Instantaneous: the momentum rate against the command clipped to what the rotor can do;
%   windowed (fluid loops only): the momentum change over fdir_win_s against the change commanded,
%   missed in 2 windows in a row.
%   vectors: 160
%   st: RotorFdir (passed rec)
%   rp: RotorParams (passed rec)
%   t: real[s] (passed in s)
%   dt: real[s] (passed in s)
%   zh: real[N m s][8] (passed in m^2 kg/s)
%   returns s: RotorFdir (passed rec)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    s = asils.alg.modes.RotorFdir_zero();
    s = st;
    nr = rp.nr;
    if ((nr > 0) && s.h_prev_ok)
        for i = (0):((nr) - 1)
            tmax = rp.rot_tmax((i) + 1);
            meas = ((zh((i) + 1) - s.h_prev((i) + 1)) / dt);
            expect = asils.pc.clamp(s.cmd_r_prev((i) + 1), ((-(0.8)) * tmax), (0.8 * tmax));
            bad = ((((asils.pc.fabs((meas - expect)) > (0.5 * tmax)) && (rp.rot_gi((i) + 1) == 0)) && (asils.pc.fabs(expect) > (0.2 * tmax))) && (asils.pc.fabs(zh((i) + 1)) < (0.9 * rp.rot_hmax((i) + 1))));
            s.fd_count((i) + 1) = asils.pc.choose_lazy(bad, @() (s.fd_count((i) + 1) + dt), @() 0);
            if ((s.fd_count((i) + 1) > rp.fdir_s) && (~s.rot_failed((i) + 1)))
                s.rot_failed((i) + 1) = true;
                s.faults = bitor(s.faults, bitshift(1, i));
            end
        end
        if ((~s.fw_on) || ((t - s.fw_last) > (1.5 * dt)))
            for i = (0):((nr) - 1)
                s.fw_e((i) + 1) = 0;
                s.fw_h0((i) + 1) = zh((i) + 1);
            end
            s.fw_t0 = t;
            s.fw_on = true;
        else
            for i = (0):((nr) - 1)
                s.fw_e((i) + 1) = (s.fw_e((i) + 1) + (asils.pc.clamp(s.cmd_r_prev((i) + 1), ((-(0.8)) * rp.rot_tmax((i) + 1)), (0.8 * rp.rot_tmax((i) + 1))) * dt));
            end
            if ((t - s.fw_t0) >= (rp.fdir_win_s - 1e-9))
                for i = (0):((nr) - 1)
                    hmax = rp.rot_hmax((i) + 1);
                    e = s.fw_e((i) + 1);
                    m = (zh((i) + 1) - s.fw_h0((i) + 1));
                    skip = ((((((rp.rot_kind((i) + 1) ~= 1) || (rp.rot_gi((i) + 1) ~= 0)) || s.rot_failed((i) + 1)) || (asils.pc.fabs(e) <= (rp.fdir_h_frac * hmax))) || (asils.pc.fabs(zh((i) + 1)) >= (0.9 * hmax))) || (asils.pc.fabs(s.fw_h0((i) + 1)) >= (0.9 * hmax)));
                    if (~skip)
                        s.fw_bad((i) + 1) = asils.pc.choose_lazy((asils.pc.fabs((m - e)) > (0.5 * asils.pc.fabs(e))), @() (s.fw_bad((i) + 1) + 1), @() 0);
                        if (s.fw_bad((i) + 1) >= 2)
                            s.rot_failed((i) + 1) = true;
                            s.faults = bitor(s.faults, bitshift(1, i));
                        end
                    end
                end
                for i = (0):((nr) - 1)
                    s.fw_e((i) + 1) = 0;
                    s.fw_h0((i) + 1) = zh((i) + 1);
                end
                s.fw_t0 = t;
            end
        end
        s.fw_last = t;
    end
end
