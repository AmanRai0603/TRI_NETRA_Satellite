function [tau, ok] = mtq_avanzini(q, w, q_ref, w_ref, j, k, lam)
%MTQ_AVANZINI  P16 Avanzini, de Angelis & Giulietti 2021: the pitch axis spun at the reference rate and aligned
%   with the orbit normal, the pitch error removed slowly. ok = false (and no torque) when the
%   reference does not rotate.
%   q: real[1][4] (passed a plain number)
%   w: real[1][3] (passed a plain number)
%   q_ref: real[1][4] (passed a plain number)
%   w_ref: real[1][3] (passed a plain number)
%   j: real[1][3][3] (passed a plain number)
%   k: real[1] (passed a plain number)
%   lam: real[1] (passed a plain number)
%   returns tau: real[1][3] (passed a plain number)
%   returns ok: bool (passed true or false)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    tau = zeros(3, 1);
    ok = false;
    tau = zeros(3, 1);
    n = sqrt(w_ref(1)*w_ref(1) + w_ref(2)*w_ref(2) + w_ref(3)*w_ref(3));
    ok = (n >= 1e-9);
    if ok
        [qe, s, wr, we] = asils.alg.control.mtq_err(q, w, q_ref, w_ref);
        ep = zeros(3, 1);
        for i = (0):((3) - 1)
            ep((i) + 1) = (w_ref((i) + 1) / n);
        end
        sg = asils.pc.mv(asils.alg.math.dcm(qe), ep);
        jep = [j(1, 1)*ep(1) + j(1, 2)*ep(2) + j(1, 3)*ep(3); j(2, 1)*ep(1) + j(2, 2)*ep(2) + j(2, 3)*ep(3); j(3, 1)*ep(1) + j(3, 2)*ep(2) + j(3, 3)*ep(3)];
        jp = (ep(1)*jep(1) + ep(2)*jep(2) + ep(3)*jep(3));
        th = ((2 * s) * (((qe(1) * ep(1)) + (qe(2) * ep(2))) + (qe(3) * ep(3))));
        eta = ((jp * n) * (1 - (lam * th)));
        jw = [j(1, 1)*w(1) + j(1, 2)*w(2) + j(1, 3)*w(3); j(2, 1)*w(1) + j(2, 2)*w(2) + j(2, 3)*w(3); j(3, 1)*w(1) + j(3, 2)*w(2) + j(3, 3)*w(3)];
        for i = (0):((3) - 1)
            tau((i) + 1) = ((k * ((eta * sg((i) + 1)) - jw((i) + 1))) + (k * ((eta * ep((i) + 1)) - jw((i) + 1))));
        end
    end
end
