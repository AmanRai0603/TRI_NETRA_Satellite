function [m0] = sun_spin_deruiter(b, w, s, eclipse, j, spin_dps, k, k1, k2)
%SUN_SPIN_DERUITER  P2 de Ruiter 2011 on the Sun line: body z spins at spin_dps with -z on the Sun, one Lyapunov
%   function for spin axis, spin rate and nutation; nothing in eclipse.
%   b: real[1][3] (passed a plain number)
%   w: real[1][3] (passed a plain number)
%   s: real[1][3] (passed a plain number)
%   eclipse: bool (passed true or false)
%   j: real[1][3][3] (passed a plain number)
%   spin_dps: real[1] (passed a plain number)
%   k: real[1] (passed a plain number)
%   k1: real[1] (passed a plain number)
%   k2: real[1] (passed a plain number)
%   returns m0: real[1][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    m0 = zeros(3, 1);
    m0 = zeros(3, 1);
    if (~eclipse)
        ws = asils.pc.fabs((spin_dps * (pi / 180)));
        sg = sign(w(3));
        if (sg == 0)
            sg = 1;
        end
        h = [j(1, 1)*w(1) + j(1, 2)*w(2) + j(1, 3)*w(3); j(2, 1)*w(1) + j(2, 2)*w(2) + j(2, 3)*w(3); j(3, 1)*w(1) + j(3, 2)*w(2) + j(3, 3)*w(3)];
        ehz = (h(3) - ((sg * j(3, 3)) * ws));
        x = zeros(3, 1);
        for i = (0):((3) - 1)
            x((i) + 1) = (h((i) + 1) + (((sg * j(3, 3)) * ws) * s((i) + 1)));
        end
        x(3) = (x(3) + (k1 * ehz));
        x(1) = (x(1) + (k2 * w(1)));
        x(2) = (x(2) + (k2 * w(2)));
        aa = [b(2)*x(3) - b(3)*x(2); b(3)*x(1) - b(1)*x(3); b(1)*x(2) - b(2)*x(1)];
        bs = (b(1)*b(1) + b(2)*b(2) + b(3)*b(3));
        if (bs >= 1e-18)
            for i = (0):((3) - 1)
                m0((i) + 1) = (((-(k)) * aa((i) + 1)) / bs);
            end
        end
    end
end
