function [cmd_r, cmd_g] = alloc_rotors(tau_rot, a, cmd_r0, cmd_g0, nr, ng, rot_gi, rot_kind, rot_failed, zh, gim_axis, gim_rate_max, cmg_lam0, cmg_mu, cmg_k_null, rot_h0, rot_tmax, rot_hmax)
%ALLOC_ROTORS  The rotor commands for a torque: the fixed rotors still working by the minimum-norm inverse,
%   the gimbals by singularity-robust steering (VSCMG rotors take their momentum rate and a null
%   motion back to their nominal momentum). Commands of rotors not set keep their value.
%   S11.6 (G2): a rotor whose momentum is at its capacity (|h| >= h_max) and whose command would add to it is saturated: it is
%   dropped from the allocation (it holds, command zero) and the others are solved again without it; and a command beyond a
%   rotor's torque limit (rot_tmax) scales the whole vector of the fixed rotors' commands together, so the torque on the body
%   keeps its direction (a per-rotor clip bends it), as the gimbal rates are scaled as a vector in steer_sr.
%   tau_rot: real[1][3] (passed a plain number)
%   a: real[1][8][3] (passed a plain number)
%   cmd_r0: real[1][8] (passed a plain number)
%   cmd_g0: real[1][4] (passed a plain number)
%   nr: int (passed a whole number)
%   ng: int (passed a whole number)
%   rot_gi: int[8] (passed a whole number)
%   rot_kind: int[8] (passed a whole number)
%   rot_failed: bool[8] (passed true or false)
%   zh: real[1][8] (passed a plain number)
%   gim_axis: real[1][3][4] (passed a plain number)
%   gim_rate_max: real[1] (passed a plain number)
%   cmg_lam0: real[1] (passed a plain number)
%   cmg_mu: real[1] (passed a plain number)
%   cmg_k_null: real[1] (passed a plain number)
%   rot_h0: real[1][8] (passed a plain number)
%   rot_tmax: real[1][8] (passed a plain number)
%   rot_hmax: real[1][8] (passed a plain number)
%   returns cmd_r: real[1][8] (passed a plain number)
%   returns cmd_g: real[1][4] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    cmd_r = zeros(8, 1);
    cmd_g = zeros(4, 1);
    cmd_r = cmd_r0;
    cmd_g = cmd_g0;
    drop = zeros(8, 1);
    for pass = (0):((9) - 1)
        fixed = zeros(8, 1);
        nf = 0;
        for i = (0):((nr) - 1)
            if (((rot_gi((i) + 1) == 0) && (~rot_failed((i) + 1))) && (drop((i) + 1) == 0))
                fixed((nf) + 1) = i;
                nf = (nf + 1);
            end
        end
        if (nf > 0)
            af = zeros(3, 8);
            i = ((0):((nf) - 1)).';
            if ~isempty(i)
                k = (0):((3) - 1);
                af((k) + 1, (i) + 1) = ((a((k) + 1, (reshape(fixed((i) + 1), [], 1)) + 1)).').';
            end
            pi8 = asils.alg.math.pinv_rows(af, nf);
            sc = 1;
            more = 0;
            for i = (0):((nf) - 1)
                c = (-((((pi8((i) + 1, 1) * tau_rot(1)) + (pi8((i) + 1, 2) * tau_rot(2))) + (pi8((i) + 1, 3) * tau_rot(3)))));
                ki = fixed((i) + 1);
                cmd_r((ki) + 1) = c;
                if ((rot_tmax((ki) + 1) > 0) && (asils.pc.fabs(c) > (sc * rot_tmax((ki) + 1))))
                    h__92 = c;
                    if h__92 < 0, h__92 = -h__92; elseif h__92 == 0, h__92 = 0; end
                    sc = (h__92 / rot_tmax((ki) + 1));
                end
                if (((rot_hmax((ki) + 1) > 0) && (asils.pc.fabs(zh((ki) + 1)) >= rot_hmax((ki) + 1))) && ((c * zh((ki) + 1)) > 0))
                    drop((ki) + 1) = 1;
                    more = (more + 1);
                end
            end
            if (more == 0)
                for i = (0):((nf) - 1)
                    cmd_r((fixed((i) + 1)) + 1) = (cmd_r((fixed((i) + 1)) + 1) / sc);
                end
            end
        end
    end
    i = ((0):((nr) - 1)).';
    if ~isempty(i)
        m__18 = logical((reshape(drop((i) + 1), [], 1) == 1));
        if any(m__18)
            cmd_r((i(m__18)) + 1) = 0;
        end
    end
    if (ng > 0)
        wheels = false;
        t__19 = ((0):((nr) - 1)).';
        for i = t__19(logical((rot_kind((t__19) + 1) == 3))).'
            wheels = true;
        end
        [gd, hd] = asils.alg.allocation.steer_sr(tau_rot, a, zh, nr, ng, rot_gi, gim_axis, gim_rate_max, cmg_lam0, cmg_mu, wheels);
        j = ((0):((ng) - 1)).';
        if ~isempty(j)
            cmd_g((j) + 1) = reshape(gd((j) + 1), [], 1);
        end
        if wheels
            i = ((0):((nr) - 1)).';
            if ~isempty(i)
                m__20 = logical((reshape(rot_gi((i) + 1), [], 1) > 0));
                if any(m__20)
                    cmd_r((i(m__20)) + 1) = (reshape(hd((i(m__20)) + 1), [], 1) - (cmg_k_null .* (reshape(zh((i(m__20)) + 1), [], 1) - reshape(rot_h0((i(m__20)) + 1), [], 1))));
                end
            end
        end
    end
end
