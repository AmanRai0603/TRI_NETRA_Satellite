function [r, v, have_r] = onboard_orbit(r0, v0, have, ok, r_fix, v_fix, ecef, lat, jd, dt, mu)
%ONBOARD_ORBIT  The onboard orbit after the tick's step 1, from the orbit it held (r0, v0; have: whether it holds one) and the
%   receiver's fix (ok, r_fix, v_fix; in ECEF when ecef; lat seconds old) at the Julian date jd: a usable fix, taken from
%   ECEF at its epoch jd - lat when it is Earth-fixed, carried forward to now by one Verlet step of lat when lat > 0; else
%   the orbit held carried one tick dt; else none. The orbit, and whether there is one.
%   vectors: 48
%   r0: real[1][3] (passed a plain number)
%   v0: real[1][3] (passed a plain number)
%   have: bool (passed true or false)
%   ok: bool (passed true or false)
%   r_fix: real[1][3] (passed a plain number)
%   v_fix: real[1][3] (passed a plain number)
%   ecef: bool (passed true or false)
%   lat: real[1] (passed a plain number)
%   jd: real[1] (passed a plain number)
%   dt: real[1] (passed a plain number)
%   mu: real[1] (passed a plain number)
%   returns r: real[1][3] (passed a plain number)
%   returns v: real[1][3] (passed a plain number)
%   returns have_r: bool (passed true or false)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    r = zeros(3, 1);
    v = zeros(3, 1);
    have_r = false;
    r = r0;
    v = v0;
    have_r = have;
    if asils.alg.navorbit.gnss_usable(ok, r_fix)
        if ecef
            [t__9, t__10] = asils.alg.navorbit.fix_eci(r_fix, v_fix, (jd - (lat / 86400)));
            r = t__9;
            v = t__10;
        else
            r = r_fix;
            v = v_fix;
        end
        if (lat > 0)
            [t__11, t__12] = asils.alg.navorbit.verlet(r, v, lat, mu);
            r = t__11;
            v = t__12;
        end
        have_r = true;
    elseif have
        [t__13, t__14] = asils.alg.navorbit.verlet(r0, v0, dt, mu);
        r = t__13;
        v = t__14;
    end
end
