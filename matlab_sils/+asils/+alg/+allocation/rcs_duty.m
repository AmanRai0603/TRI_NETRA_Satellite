function [duty, tau] = rcs_duty(req, nc, rcs_tau, rcs_mib, rcs_res, t)
%RCS_DUTY  The on-time of each thruster couple over T for a torque request: one couple per axis and sense
%   (2 ax for +, 2 ax + 1 for -), on-time below the minimum impulse bit dropped, rounded to the
%   valve resolution; returns each duty and the torque fed forward.
%   req: real[1][3] (passed a plain number)
%   nc: int (passed a whole number)
%   rcs_tau: real[1][3][6] (passed a plain number)
%   rcs_mib: real[1] (passed a plain number)
%   rcs_res: real[1] (passed a plain number)
%   t: real[1] (passed a plain number)
%   returns duty: real[1][6] (passed a plain number)
%   returns tau: real[1][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    duty = zeros(6, 1);
    tau = zeros(3, 1);
    duty = zeros(6, 1);
    tau = zeros(3, 1);
    for ax = (0):((3) - 1)
        u = req((ax) + 1);
        if (u ~= 0)
            k = asils.pc.choose((u > 0), (2 * ax), ((2 * ax) + 1));
            if ((k < nc) && (asils.pc.fabs(rcs_tau((k) + 1, (ax) + 1)) > 0))
                on = (asils.pc.fabs(u) / asils.pc.fabs(rcs_tau((k) + 1, (ax) + 1)));
                if (on > 1)
                    on = 1;
                end
                on = (on * t);
                if (~(on < rcs_mib))
                    on = (round((on / rcs_res)) * rcs_res);
                    duty((k) + 1) = (on / t);
                    for i = (0):((3) - 1)
                        tau((i) + 1) = (tau((i) + 1) + (rcs_tau((k) + 1, (i) + 1) * duty((k) + 1)));
                    end
                end
            end
        end
    end
end
