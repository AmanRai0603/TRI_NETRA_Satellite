function [adv_ns, kind] = clock_advance(d_ns, dt_ns, max_ns)
%CLOCK_ADVANCE  One tick of the carried clock: the clock's own step d_ns (the difference of its last two readings, which may be negative),
%   the tick's length dt_ns and the bound max_ns, all in ns. The time it advances by, and what happened: 0 the step as read,
%   1 a step back (held: no advance), 2 a step forward beyond the bound (refused: one tick).
%   vectors: 48
%   d_ns: int (passed a whole number)
%   dt_ns: int (passed a whole number)
%   max_ns: int (passed a whole number)
%   returns adv_ns: int (passed a whole number)
%   returns kind: int (passed a whole number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    adv_ns = 0;
    kind = 0;
    adv_ns = d_ns;
    kind = 0;
    if (d_ns < 0)
        adv_ns = 0;
        kind = 1;
    elseif (d_ns > max_ns)
        adv_ns = dt_ns;
        kind = 2;
    end
end
