function [t_new_ns, adopted] = clock_adopt(t_ns, have, jd, jd0)
%CLOCK_ADOPT  The time since the blob's date (t_ns), corrected by a fix's date jd (have: a fix holds one) against the blob's date jd0:
%   adopted when they differ by more than 20 ms (four times the 5 ms of timestamp jitter the rig flies), and the fix is not
%   before the blob's date. The time, and whether the fix's date was adopted.
%   vectors: 48
%   t_ns: int (passed a whole number)
%   have: bool (passed true or false)
%   jd: real[1] (passed a plain number)
%   jd0: real[1] (passed a plain number)
%   returns t_new_ns: int (passed a whole number)
%   returns adopted: bool (passed true or false)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    t_new_ns = 0;
    adopted = false;
    t_new_ns = t_ns;
    adopted = false;
    tg = ((jd - jd0) * 86400);
    if ((have && (tg >= 0)) && (asils.pc.fabs((tg - (t_ns * 1e-9))) > 0.02))
        t_new_ns = fix(((tg * 1000000000) + 0.5));
        adopted = true;
    end
end
