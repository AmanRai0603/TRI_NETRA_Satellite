function [pwm, rot_words, gim_words, valves] = drv_write(m_body, m_max, cmd_r, rot_tmax, nr, cmd_g, gim_rate_max, ng, duty, nc, dt)
%DRV_WRITE  The command words the drivers put on the buses: the coils' PWM (Q15 of m_max), each rotor's
%   torque (Q15 of its torque_max, CAN 0x100 + i), each gimbal's rate (Q15 of gim_rate_max, CAN
%   0x140 + j) and each thruster couple's on-time in ms (0 .. 255, CAN 0x300). A word with no frame is 0.
%   m_body: real[1][3] (passed a plain number)
%   m_max: real[1] (passed a plain number)
%   cmd_r: real[1][8] (passed a plain number)
%   rot_tmax: real[1][8] (passed a plain number)
%   nr: int (passed a whole number)
%   cmd_g: real[1][4] (passed a plain number)
%   gim_rate_max: real[1] (passed a plain number)
%   ng: int (passed a whole number)
%   duty: real[1][6] (passed a plain number)
%   nc: int (passed a whole number)
%   dt: real[1] (passed a plain number)
%   returns pwm: int[3] (passed a whole number)
%   returns rot_words: int[8] (passed a whole number)
%   returns gim_words: int[4] (passed a whole number)
%   returns valves: int[6] (passed a whole number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    pwm = zeros(3, 1);
    rot_words = zeros(8, 1);
    gim_words = zeros(4, 1);
    valves = zeros(6, 1);
    pwm = zeros(3, 1);
    rot_words = zeros(8, 1);
    gim_words = zeros(4, 1);
    valves = zeros(6, 1);
    for i = (0):((3) - 1)
        pwm((i) + 1) = asils.alg.drivers.q15((m_body((i) + 1) / m_max));
    end
    for i = (0):((nr) - 1)
        rot_words((i) + 1) = asils.alg.drivers.q15((cmd_r((i) + 1) / rot_tmax((i) + 1)));
    end
    for j = (0):((ng) - 1)
        gim_words((j) + 1) = asils.alg.drivers.q15((cmd_g((j) + 1) / gim_rate_max));
    end
    if (nc > 0)
        for i = (0):((nc) - 1)
            ms = (((duty((i) + 1) * dt) / 0.001) + 0.5);
            if (~((ms - ms) == 0))
                valves((i) + 1) = 0;
            elseif (ms > 255)
                valves((i) + 1) = 255;
            elseif (ms < 0)
                valves((i) + 1) = 0;
            else
                valves((i) + 1) = fix(ms);
            end
        end
    end
end
