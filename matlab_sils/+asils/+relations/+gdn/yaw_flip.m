function [flip_out] = yaw_flip(r, v, q_off, sun_axis, roll_axis, sun_eci, flip, hyst)
%YAW_FLIP  The nadir-family yaw flip with hysteresis h: turn 180 deg about the boresight when the power face
%   would look away from the Sun. Returns the new flip.
%   r: real[m][3] (passed in m)
%   v: real[m/s][3] (passed in m/s)
%   q_off: real[1][4] (passed a plain number)
%   sun_axis: real[1][3] (passed a plain number)
%   roll_axis: real[1][3] (passed a plain number)
%   sun_eci: real[1][3] (passed a plain number)
%   flip: bool (passed true or false)
%   hyst: real[1] (passed a plain number)
%   returns flip_out: bool (passed true or false)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    flip_out = false;
    z = zeros(3, 1);
    [q, w, wd] = asils.relations.gdn.guidance(0, r, v, 0, q_off, 0, 0, 1, z, [0; 0; 0; 1], sun_axis, roll_axis, sun_eci, false);
    h__66 = asils.relations.gdn.dcm(q);
    h__67 = sqrt(sun_eci(1)*sun_eci(1) + sun_eci(2)*sun_eci(2) + sun_eci(3)*sun_eci(3));
    if 1e-30 > h__67, h__67 = 1e-30; end
    h__68 = (sun_eci / h__67);
    sb = [h__66(1, 1)*h__68(1) + h__66(1, 2)*h__68(2) + h__66(1, 3)*h__68(3); h__66(2, 1)*h__68(1) + h__66(2, 2)*h__68(2) + h__66(2, 3)*h__68(3); h__66(3, 1)*h__68(1) + h__66(3, 2)*h__68(2) + h__66(3, 3)*h__68(3)];
    a = [0; 0; (-(1))];
    if (sqrt(sun_axis(1)*sun_axis(1) + sun_axis(2)*sun_axis(2) + sun_axis(3)*sun_axis(3)) > 0)
        h__69 = sqrt(sun_axis(1)*sun_axis(1) + sun_axis(2)*sun_axis(2) + sun_axis(3)*sun_axis(3));
        if 1e-30 > h__69, h__69 = 1e-30; end
        a = (sun_axis / h__69);
    end
    d = (a(1)*sb(1) + a(2)*sb(2) + a(3)*sb(3));
    flip_out = flip;
    if (d < (-(hyst)))
        flip_out = true;
    elseif (d > hyst)
        flip_out = false;
    end
end
