function [mag_ok, b, w, b_good, mag_age, mag_seen, gyro_age] = fdir_sensors(mag_ok0, b0, bref_ok, bref, b_good0, mag_age0, mag_seen0, has_gyro, gyro_ok, w0, gyro_age0, dt)
%FDIR_SENSORS  Sensor health after the drivers read: a field outside [0.25, 4] x the model is no reading; the
%   last good field is held; the age of each sensor's last good sample.
%   mag_ok0: bool (passed true or false)
%   b0: real[1][3] (passed a plain number)
%   bref_ok: bool (passed true or false)
%   bref: real[1][3] (passed a plain number)
%   b_good0: real[1][3] (passed a plain number)
%   mag_age0: real[1] (passed a plain number)
%   mag_seen0: bool (passed true or false)
%   has_gyro: bool (passed true or false)
%   gyro_ok: bool (passed true or false)
%   w0: real[1][3] (passed a plain number)
%   gyro_age0: real[1] (passed a plain number)
%   dt: real[1] (passed a plain number)
%   returns mag_ok: bool (passed true or false)
%   returns b: real[1][3] (passed a plain number)
%   returns w: real[1][3] (passed a plain number)
%   returns b_good: real[1][3] (passed a plain number)
%   returns mag_age: real[1] (passed a plain number)
%   returns mag_seen: bool (passed true or false)
%   returns gyro_age: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    mag_ok = false;
    b = zeros(3, 1);
    w = zeros(3, 1);
    b_good = zeros(3, 1);
    mag_age = 0;
    mag_seen = false;
    gyro_age = 0;
    mag_ok = mag_ok0;
    b = b0;
    w = w0;
    b_good = b_good0;
    mag_age = mag_age0;
    mag_seen = mag_seen0;
    gyro_age = gyro_age0;
    if (mag_ok && bref_ok)
        bn = asils.pc.norm_(b);
        rn = asils.pc.norm_(bref);
        if (~((bn > (0.25 * rn)) && (bn < (4 * rn))))
            mag_ok = false;
        end
    end
    if mag_ok
        b_good = b;
        mag_age = 0;
        mag_seen = true;
    else
        b = b_good;
        mag_age = (mag_age + dt);
    end
    if ((~has_gyro) || gyro_ok)
        gyro_age = 0;
    else
        gyro_age = (gyro_age + dt);
    end
    if ((~gyro_ok) && (~has_gyro))
        w = zeros(3, 1);
    end
end
