    lo = 0;
    sw = 0;
    r = 0;
    d = 0;
    m = 0;
    c = 65535;
    for i = (0):((4) - 1)
        c = bitxor(c, bitshift(b((i) + 1), 8));
        for k = (0):((8) - 1)
            c = asils.pc.choose((bitand(c, 32768) ~= 0), bitand(bitxor(bitshift(c, 1), 4129), 65535), bitand(bitshift(c, 1), 65535));
