function [ok, s, u] = css_sample(u, d, s_b, nu, nadir_b, earth_ang)
%CSS_SAMPLE  The Sun the cells give (body, unit) and whether they give one, for the Sun s_b and nadir nadir_b (body, unit), the
%   sunlit fraction nu and the Earth's half-angle earth_ang [rad].
%   u: inout CssUnit (passed rec)
%   d: CssDesc (passed rec)
%   s_b: real[1][3] (passed a plain number)
%   nu: real[1] (passed a plain number)
%   nadir_b: real[1][3] (passed a plain number)
%   earth_ang: real[1] (passed a plain number)
%   returns ok: bool (passed true or false)
%   returns s: real[1][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    ok = false;
    s = zeros(3, 1);
    c0 = (-(asils.pc.dot_(s_b, nadir_b)));
    geo = ((sin(earth_ang) * sin(earth_ang)) * asils.pc.choose((c0 > 0), c0, 0));
    iv = zeros(8, 1);
    g = u.g;
    for j = (0):((d.n) - 1)
        cs = asils.pc.dot_((d.normals((j) + 1, :)).', s_b);
        ce = asils.pc.dot_((d.normals((j) + 1, :)).', nadir_b);
        [t__96, t__97] = asils.pc.stream_normal(g);
        z = t__96;
        g = t__97;
        iv((j) + 1) = ((u.scale((j) + 1) * ((nu * asils.pc.choose((cs > 0), cs, 0)) + ((d.albedo * geo) * asils.pc.choose((ce > 0), ce, 0)))) + (d.noise * z));
        if u.dead((j) + 1)
            iv((j) + 1) = 0;
        end
    end
    u.g = g;
    est = zeros(3, 1);
    for ax = (0):((3) - 1)
        p = (-(1));
        m = (-(1));
        for k = (0):((d.n) - 1)
            if ((p < 0) && (d.normals((k) + 1, (ax) + 1) > 0.9))
                p = k;
            end
            if ((m < 0) && (d.normals((k) + 1, (ax) + 1) < (-(0.9))))
                m = k;
            end
        end
        if ((p >= 0) && (m >= 0))
            est((ax) + 1) = (iv((p) + 1) - iv((m) + 1));
        end
    end
    ok = ((nu > 0.5) && (asils.pc.norm_(est) > 0.3));
    s = [0; 0; 0];
    if ok
        s = asils.pc.mv(u.r, asils.models.facets.unit_or_zero(est));
    end
end
