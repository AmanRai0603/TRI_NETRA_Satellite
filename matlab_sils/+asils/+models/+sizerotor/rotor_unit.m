function [h_unit, tau_unit, mass_unit, p_unit] = rotor_unit(k, h, tau, mass, p, h_cluster, tau_cluster, mass_cluster, p_cluster)
%ROTOR_UNIT  What a model offers as one unit of its kind k: a cluster its datasheet's cluster momentum, torque, mass and power (nan
%   where the datasheet states none: then the single unit's own), any other model its own.
%   k: CatalogueKind (passed a choice, as its option's number)
%   h: real[1] (passed a plain number)
%   tau: real[1] (passed a plain number)
%   mass: real[1] (passed a plain number)
%   p: real[1] (passed a plain number)
%   h_cluster: real[1] (passed a plain number)
%   tau_cluster: real[1] (passed a plain number)
%   mass_cluster: real[1] (passed a plain number)
%   p_cluster: real[1] (passed a plain number)
%   returns h_unit: real[1] (passed a plain number)
%   returns tau_unit: real[1] (passed a plain number)
%   returns mass_unit: real[1] (passed a plain number)
%   returns p_unit: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    h_unit = 0;
    tau_unit = 0;
    mass_unit = 0;
    p_unit = 0;
    h_unit = h;
    tau_unit = tau;
    mass_unit = mass;
    p_unit = p;
    if (k == 2)
        if (~isnan(h_cluster))
            h_unit = h_cluster;
        end
        if (~isnan(tau_cluster))
            tau_unit = tau_cluster;
        end
        if (~isnan(mass_cluster))
            mass_unit = mass_cluster;
        end
        if (~isnan(p_cluster))
            p_unit = p_cluster;
        end
    end
end
