function [pick, met, h, tau, mass, p, v] = rotor_pick(h, tau, mass, p, v, n, h_need, tau_need)
%ROTOR_PICK  The model fitted among the n candidates (momentum h, torque tau, mass, steady power p and volume v of each, in the
%   catalogue's order): the lightest that meets the need, then the least power, then the least volume, the first of equals
%   (met); when none meets it, the one with the most momentum, the last of equals (not met).
%   length: 8
%   h: inout real[1][*] (passed a plain number)
%   tau: inout real[1][*] (passed a plain number)
%   mass: inout real[1][*] (passed a plain number)
%   p: inout real[1][*] (passed a plain number)
%   v: inout real[1][*] (passed a plain number)
%   n: int (passed a whole number)
%   h_need: real[1] (passed a plain number)
%   tau_need: real[1] (passed a plain number)
%   returns pick: int (passed a whole number)
%   returns met: bool (passed true or false)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    pick = 0;
    met = false;
    pick = (-(1));
    met = false;
    for i = (0):((n) - 1)
        if asils.models.sizerotor.rotor_meets(h((i) + 1), tau((i) + 1), h_need, tau_need)
            if (~met)
                pick = i;
                met = true;
            elseif ((mass((i) + 1) < mass((pick) + 1)) || ((mass((i) + 1) == mass((pick) + 1)) && ((p((i) + 1) < p((pick) + 1)) || ((p((i) + 1) == p((pick) + 1)) && (v((i) + 1) < v((pick) + 1))))))
                pick = i;
            end
        end
    end
    if (~met)
        pick = 0;
        for i = (1):((n) - 1)
            if (h((i) + 1) >= h((pick) + 1))
                pick = i;
            end
        end
    end
end
