function [cp, ct] = sentman(s, delta, a_t, tw, talt)
%SENTMAN  drag.sentman(s, delta, aT, Tw, Talt) -> (cp, ct): the pressure and shear coefficients of a panel at incidence delta
%   [rad] (0 head-on), speed ratio s, energy accommodation a_t, wall temperature tw and gas temperature talt [K].
%   s: real[1] (passed a plain number)
%   delta: real[1] (passed a plain number)
%   a_t: real[1] (passed a plain number)
%   tw: real[1] (passed a plain number)
%   talt: real[1] (passed a plain number)
%   returns cp: real[1] (passed a plain number)
%   returns ct: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    cp = 0;
    ct = 0;
    c = cos(delta);
    sn = (s * c);
    ti = (((2 / 3) * (s)^(2)) * talt);
    e = (1 + erf(sn));
    p = exp((-((sn)^(2))));
    sqpi = sqrt(pi);
    cp = ((((c / (sqpi * s)) * p) + (((1 / (2 * (s)^(2))) + (c)^(2)) * e)) + ((0.5 * sqrt(((2 / 3) * (1 + (a_t * ((tw / ti) - 1)))))) * (((sqpi * c) * e) + ((1 / s) * p))));
    ct = ((sin(delta) / (sqpi * s)) * (p + ((sqpi * sn) * e)));
end
