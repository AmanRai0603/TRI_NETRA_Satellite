function [kroll, kdroll] = fsw_mtq_roll(e, j, n, roll_wn_orbits, roll_zeta, roll_gain)
%FSW_MTQ_ROLL  Celani 2026's weak roll about the payload axis in the nadir state, so the power face is held: its own PD on the
%   boresight's inertia J_e = e'J e, at roll_wn_orbits orbit rates (wr = roll_wn_orbits n) and damping roll_zeta, scaled by
%   roll_gain: k_roll = roll_gain J_e wr^2, k_droll = 2 roll_zeta J_e wr. (A bare share of the boresight gain is not enough:
%   at the tuned rate gain the loop's Floquet multiplier grows to 4 an orbit, docs/MTQ_LITERATURE.md.)
%   e: real[1][3] (passed a plain number)
%   j: real[1][3][3] (passed a plain number)
%   n: real[1] (passed a plain number)
%   roll_wn_orbits: real[1] (passed a plain number)
%   roll_zeta: real[1] (passed a plain number)
%   roll_gain: real[1] (passed a plain number)
%   returns kroll: real[1] (passed a plain number)
%   returns kdroll: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    kroll = 0;
    kdroll = 0;
    je = (((e(1) * (((j(1, 1) * e(1)) + (j(1, 2) * e(2))) + (j(1, 3) * e(3)))) + (e(2) * (((j(2, 1) * e(1)) + (j(2, 2) * e(2))) + (j(2, 3) * e(3))))) + (e(3) * (((j(3, 1) * e(1)) + (j(3, 2) * e(2))) + (j(3, 3) * e(3)))));
    wr = (roll_wn_orbits * n);
    kroll = (((roll_gain * je) * wr) * wr);
    kdroll = (((2 * roll_zeta) * je) * wr);
end
