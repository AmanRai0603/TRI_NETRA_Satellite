function [pth, pw] = fsw_mtq_tango(ii, wn, z, gp, gd)
%FSW_MTQ_TANGO  TANGO's frozen Riccati gains: P from the CARE with the orbit-averaged B_u R^-1 B_u^T. An isotropic field average gives
%   E[Gamma D Gamma]_ii = (7/15) D_i + tr(D)/15, D = J^-2 (the double integrator's CARE on each axis); Q is chosen (inverse
%   LQR) so the average axis gets the common bandwidth wn and damping z, and each axis the gain its averaged authority calls
%   for, R = 1 (the paper's Q and R are unpublished): the gains on the attitude error P21/R and on the rate error P22/R,
%   scaled by gp and gd, on the diagonal.
%   ii: real[1][3] (passed a plain number)
%   wn: real[1] (passed a plain number)
%   z: real[1] (passed a plain number)
%   gp: real[1] (passed a plain number)
%   gd: real[1] (passed a plain number)
%   returns pth: real[1][3][3] (passed a plain number)
%   returns pw: real[1][3][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    pth = zeros(3, 3);
    pw = zeros(3, 3);
    r = 1;
    jm = (((ii(1) + ii(2)) + ii(3)) / 3);
    d = [(1 / (ii(1) * ii(1))); (1 / (ii(2) * ii(2))); (1 / (ii(3) * ii(3)))];
    trd = ((d(1) + d(2)) + d(3));
    mi = zeros(3, 1);
    ax = ((0):((3) - 1)).';
    mi((ax) + 1) = ((((7 / 15) .* reshape(d((ax) + 1), [], 1)) + (trd / 15)) ./ r);
    mref = (((mi(1) + mi(2)) + mi(3)) / 3);
    h__556 = (((jm * wn) * wn) * r);
    qt = (mref * (h__556 * h__556));
    h__557 = ((((2 * z) * jm) * wn) * r);
    h__558 = (qt / mref);
    if h__558 < 0, h__558 = NaN; else, h__558 = sqrt(h__558); end
    qw0 = ((mref * (h__557 * h__557)) - (2 * h__558));
    if (qw0 > 0)
        h__559 = qw0;
    else
        h__559 = 0;
    end
    qw = h__559;
    pth = zeros(3, 3);
    pw = zeros(3, 3);
    for ax = (0):((3) - 1)
        h__560 = (qt / mi((ax) + 1));
        if h__560 < 0, h__560 = NaN; else, h__560 = sqrt(h__560); end
        p12 = h__560;
        h__561 = ((qw + (2 * p12)) / mi((ax) + 1));
        if h__561 < 0, h__561 = NaN; else, h__561 = sqrt(h__561); end
        p22 = h__561;
        pth((ax) + 1, (ax) + 1) = ((gp * p12) / r);
        pw((ax) + 1, (ax) + 1) = ((gd * p22) / r);
    end
end
