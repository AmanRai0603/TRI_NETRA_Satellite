function [k1, k2, k16, lam16, sb_kp, sb_kd] = fsw_mtq_literature(law, ii, wn, z, eps, gp, gd, k_over_n, lam, n)
%FSW_MTQ_LITERATURE  The magnetorquer-only literature laws' gains, torque-level on the common bandwidth: k_p = gp J_m wn^2/eps^2 and the
%   derivative gain gd 2 z wn/eps (Lovera and Astolfi multiply the rate by J; law 4) or gd 2 z J_m wn/eps (Celani does not),
%   J_m the mean principal inertia, eps the averaging laws' time scale (fsw_param_mtq_eps); Avanzini 2021's k = gd (k/n) n
%   (below 0.5 (1 + 2 sin xi_m) n; the paper flies 0.84 n) and its pitch-correction rate gp lambda; Celani 2026's boresight
%   gains gp J_m wn^2 and gd 2 z J_m wn.
%   law: int (passed a whole number)
%   ii: real[1][3] (passed a plain number)
%   wn: real[1] (passed a plain number)
%   z: real[1] (passed a plain number)
%   eps: real[1] (passed a plain number)
%   gp: real[1] (passed a plain number)
%   gd: real[1] (passed a plain number)
%   k_over_n: real[1] (passed a plain number)
%   lam: real[1] (passed a plain number)
%   n: real[1] (passed a plain number)
%   returns k1: real[1] (passed a plain number)
%   returns k2: real[1] (passed a plain number)
%   returns k16: real[1] (passed a plain number)
%   returns lam16: real[1] (passed a plain number)
%   returns sb_kp: real[1] (passed a plain number)
%   returns sb_kd: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    k1 = 0;
    k2 = 0;
    k16 = 0;
    lam16 = 0;
    sb_kp = 0;
    sb_kd = 0;
    jm = (((ii(1) + ii(2)) + ii(3)) / 3);
    k1 = ((((gp * jm) * wn) * wn) / (eps * eps));
    if (law == 4)
        k2 = ((((gd * 2) * z) * wn) / eps);
    else
        k2 = (((((gd * 2) * z) * jm) * wn) / eps);
    end
    k16 = ((gd * k_over_n) * n);
    lam16 = (gp * lam);
    sb_kp = (((gp * jm) * wn) * wn);
    sb_kd = ((((gd * 2) * z) * jm) * wn);
end
