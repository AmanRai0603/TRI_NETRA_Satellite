function [b, q, r, p0] = fsw_mtq_lqr_weights(i, wn)
%FSW_MTQ_LQR_WEIGHTS  The weights of the magnetic pointing's LQR on one axis of inertia i: the chain of the attitude error's integral, the
%   error and the rate (A = [0 1 0; 0 0 1; 0 0 0], B = [0; 0; b], b = 1/i), Q = diag(1e-12, 1/th^2, 1/(wn th)^2) and
%   R = 1/(i wn^2 th)^2 for an error of th = 0.05 rad, and the bandwidth p0 = wn the Riccati solve starts its pole placement
%   from. Its gain is the toolbox's Riccati solve of them (Kleinman's iteration, adcs-sim lqr.rs chain3).
%   i: real[1] (passed a plain number)
%   wn: real[1] (passed a plain number)
%   returns b: real[1] (passed a plain number)
%   returns q: real[1][3] (passed a plain number)
%   returns r: real[1] (passed a plain number)
%   returns p0: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    b = 0;
    q = zeros(3, 1);
    r = 0;
    p0 = 0;
    th = 0.05;
    q = [1e-12; (1 / (th * th)); (1 / ((wn * th) * (wn * th)))];
    r = (1 / ((((i * wn) * wn) * th) * (((i * wn) * wn) * th)));
    b = (1 / i);
    p0 = wn;
end
