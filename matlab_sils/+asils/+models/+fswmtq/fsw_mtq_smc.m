function [lambda, gs] = fsw_mtq_smc(wn, z, phi)
%FSW_MTQ_SMC  The magnetic sliding mode: its surface s = w + lambda e acts on the quaternion's vector part (half the angle), so the slope
%   that puts the surface at wn/(2 z) on the ANGLE is lambda = wn/z, the fine pointing's too (S11.6: the two laws state the
%   same slope; the "twice" the audit found was this factor 2 on one of them only); its gain Gs = 2 z wn phi on each axis,
%   phi the boundary layer (fsw_param_mtq_phi).
%   wn: real[1] (passed a plain number)
%   z: real[1] (passed a plain number)
%   phi: real[1] (passed a plain number)
%   returns lambda: real[1] (passed a plain number)
%   returns gs: real[1][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    lambda = 0;
    gs = zeros(3, 1);
    lambda = (wn / z);
    g = (((2 * z) * wn) * phi);
    gs = [g; g; g];
end
