function [nu] = frac_conical(r_sat, r_sun, re, rsun)
%FRAC_CONICAL  The sunlit fraction of the solar disc of radius rsun seen from r_sat past a spherical Earth of radius re, the Sun at
%   r_sun (Octave's scaled norms).
%   tolerance: 1e-8
%   (The shadow's partial area, lens_area, is r1^2 acos(.) + r2^2 acos(.) - d h: terms of about 1 less one of about 1e-2,
%   to leave an area of about 1e-4, so a last-bit difference in the maths library's acos between the reference interpreter
%   and the platform grows about 1e5 times, in the lit fraction nu and so in the acceleration. One unit in the last place
%   of the separation angle moves nu by 1.2e-10 at nu = 0.045, 2.7e-9 of it; the srp_force vector of the fine shadow at
%   nu = 0.045 differed by 2.8e-11. The bound holds for a nu of about 0.01 and above.)
%   r_sat: real[1][3] (passed a plain number)
%   r_sun: real[1][3] (passed a plain number)
%   re: real[1] (passed a plain number)
%   rsun: real[1] (passed a plain number)
%   returns nu: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    nu = 0;
    d = [(r_sun(1) - r_sat(1)); (r_sun(2) - r_sat(2)); (r_sun(3) - r_sat(3))];
    ds = asils.models.gravity.onorm(d);
    s = [(d(1) / ds); (d(2) / ds); (d(3) / ds)];
    rr = asils.models.gravity.onorm(r_sat);
    e = [((-(r_sat(1))) / rr); ((-(r_sat(2))) / rr); ((-(r_sat(3))) / rr)];
    se = (s(1)*e(1) + s(2)*e(2) + s(3)*e(3));
    if (se < 0)
        nu = 1;
    else
        h__492 = asin(asils.models.srp.min_one((rsun / ds)));
        if ~isreal(h__492), h__492 = NaN; end
        th_s = h__492;
        h__493 = asin(asils.models.srp.min_one((re / rr)));
        if ~isreal(h__493), h__493 = NaN; end
        th_e = h__493;
        h__494 = acos(asils.models.thirdbody.unit_clip(se));
        if ~isreal(h__494), h__494 = NaN; end
        th_sep = h__494;
        if (th_sep >= (th_s + th_e))
            nu = 1;
        elseif ((th_e - th_s) >= th_sep)
            nu = 0;
        elseif ((th_s - th_e) >= th_sep)
            q = (th_e / th_s);
            nu = (1 - (q * q));
        else
            occ = asils.models.srp.lens_area(th_sep, th_s, th_e);
            nu = (1 - (occ / (pi * (th_s * th_s))));
        end
    end
end
