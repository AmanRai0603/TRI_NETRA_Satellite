function [acc, force] = srp_boxwing(p, nu, s, r_b2i, f, mass)
%SRP_BOXWING  [a, F] = srp.boxwing(P, nu, sunUnit_sat2sun, R_b2i, sc): the box-wing acceleration [m/s^2] (scaled by nu) and force
%   [N] (before it), the body-to-inertial matrix r_b2i.
%   p: real[1] (passed a plain number)
%   nu: real[1] (passed a plain number)
%   s: real[1][3] (passed a plain number)
%   r_b2i: real[1][3][3] (passed a plain number)
%   f: ScFacets (passed rec)
%   mass: real[1] (passed a plain number)
%   returns acc: real[1][3] (passed a plain number)
%   returns force: real[1][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    acc = zeros(3, 1);
    force = zeros(3, 1);
    h__489 = (r_b2i).';
    s_b = [h__489(1, 1)*s(1) + h__489(1, 2)*s(2) + h__489(1, 3)*s(3); h__489(2, 1)*s(1) + h__489(2, 2)*s(2) + h__489(2, 3)*s(3); h__489(3, 1)*s(1) + h__489(3, 2)*s(2) + h__489(3, 3)*s(3)];
    fb = asils.models.srp.facet_sum(f, s_b, p);
    force = [r_b2i(1, 1)*fb(1) + r_b2i(1, 2)*fb(2) + r_b2i(1, 3)*fb(3); r_b2i(2, 1)*fb(1) + r_b2i(2, 2)*fb(2) + r_b2i(2, 3)*fb(3); r_b2i(3, 1)*fb(1) + r_b2i(3, 2)*fb(2) + r_b2i(3, 3)*fb(3)];
    acc = [((nu * force(1)) / mass); ((nu * force(2)) / mass); ((nu * force(3)) / mass)];
end
