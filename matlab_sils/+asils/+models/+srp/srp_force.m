function [acc] = srp_force(r, sun, p_srp, model, ecl, cr, aref, mass, r_bi, f)
%SRP_FORCE  forces.srp(ctx): the solar radiation pressure acceleration [m/s^2] at r (ECI), the Sun at sun (geocentric) and its
%   pressure p_srp there, in the shadow of the model (default opts), on a cannonball of reflectivity factor cr and area
%   to mass aref/mass, or on the box-wing facets at the attitude r_bi (body to ECI).
%   tolerance: 1e-8
%   (The shadow's partial area, lens_area, is r1^2 acos(.) + r2^2 acos(.) - d h: terms of about 1 less one of about 1e-2,
%   to leave an area of about 1e-4, so a last-bit difference in the maths library's acos between the reference interpreter
%   and the platform grows about 1e5 times, in the lit fraction nu and so in the acceleration. One unit in the last place
%   of the separation angle moves nu by 1.2e-10 at nu = 0.045, 2.7e-9 of it; the srp_force vector of the fine shadow at
%   nu = 0.045 differed by 2.8e-11. The bound holds for a nu of about 0.01 and above.)
%   r: real[1][3] (passed a plain number)
%   sun: real[1][3] (passed a plain number)
%   p_srp: real[1] (passed a plain number)
%   model: SrpModel (passed a choice, as its option's number)
%   ecl: EclipseModel (passed a choice, as its option's number)
%   cr: real[1] (passed a plain number)
%   aref: real[1] (passed a plain number)
%   mass: real[1] (passed a plain number)
%   r_bi: real[1][3][3] (passed a plain number)
%   f: ScFacets (passed rec)
%   returns acc: real[1][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    acc = zeros(3, 1);
    d = [(sun(1) - r(1)); (sun(2) - r(2)); (sun(3) - r(3))];
    nd = sqrt(d(1)*d(1) + d(2)*d(2) + d(3)*d(3));
    shat = [(d(1) / nd); (d(2) / nd); (d(3) / nd)];
    [re, rp, rsun, h_atm] = asils.models.srp.eclipse_default();
    nu = asils.models.srp.srp_eclipse(r, sun, ecl, re, rp, rsun, h_atm);
    if (model == 0)
        acc = asils.models.srp.srp_cannonball(p_srp, nu, shat, cr, (aref / mass));
    else
        [a1, f1] = asils.models.srp.srp_boxwing(p_srp, nu, shat, r_bi, f, mass);
        acc = a1;
    end
end
