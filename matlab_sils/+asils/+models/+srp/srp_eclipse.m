function [nu] = srp_eclipse(r_sat, r_sun, model, re, rp, rsun, h_atm)
%SRP_ECLIPSE  srp.eclipse(rSat, rSun, model, opts): the lighting fraction nu in [0, 1] (1 sunlit, 0 umbra), the Sun at r_sun
%   (geocentric), with the Earth's radii re and rp, the Sun's rsun and the opaque atmosphere h_atm [m].
%   vectors: 160
%   tolerance: 1e-8
%   (The shadow's partial area, lens_area, is r1^2 acos(.) + r2^2 acos(.) - d h: terms of about 1 less one of about 1e-2,
%   to leave an area of about 1e-4, so a last-bit difference in the maths library's acos between the reference interpreter
%   and the platform grows about 1e5 times, in the lit fraction nu and so in the acceleration. One unit in the last place
%   of the separation angle moves nu by 1.2e-10 at nu = 0.045, 2.7e-9 of it; the srp_force vector of the fine shadow at
%   nu = 0.045 differed by 2.8e-11. The bound holds for a nu of about 0.01 and above.)
%   r_sat: real[1][3] (passed a plain number)
%   r_sun: real[1][3] (passed a plain number)
%   model: EclipseModel (passed a choice, as its option's number)
%   re: real[1] (passed a plain number)
%   rp: real[1] (passed a plain number)
%   rsun: real[1] (passed a plain number)
%   h_atm: real[1] (passed a plain number)
%   returns nu: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    nu = 0;
    if (model == 0)
        d = [(r_sun(1) - r_sat(1)); (r_sun(2) - r_sat(2)); (r_sun(3) - r_sat(3))];
        nd = sqrt(d(1)*d(1) + d(2)*d(2) + d(3)*d(3));
        s = [(d(1) / nd); (d(2) / nd); (d(3) / nd)];
        m = [(-(r_sat(1))); (-(r_sat(2))); (-(r_sat(3)))];
        ms = (m(1)*s(1) + m(2)*s(2) + m(3)*s(3));
        if (ms < 0)
            nu = 1;
        else
            h__504 = [(m(1) - (ms * s(1))); (m(2) - (ms * s(2))); (m(3) - (ms * s(3)))];
            perp = sqrt(h__504(1)*h__504(1) + h__504(2)*h__504(2) + h__504(3)*h__504(3));
            if (perp >= re)
                h__505 = 1;
            else
                h__505 = 0;
            end
            nu = h__505;
        end
    elseif (model == 1)
        nu = asils.models.srp.frac_conical(r_sat, r_sun, re, rsun);
    else
        sz = (re / rp);
        rs = [r_sat(1); r_sat(2); (r_sat(3) * sz)];
        rn = [r_sun(1); r_sun(2); (r_sun(3) * sz)];
        nu = asils.models.srp.frac_conical(rs, rn, (re + h_atm), rsun);
    end
end
