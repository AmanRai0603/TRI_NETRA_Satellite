function [rho, out, inp] = jb2008_density(utc, lon_deg, lat_deg, alt_km)
%JB2008_DENSITY  jb2008_density(t, lon_deg, lat_deg, alt_km) for one epoch (the in-RHS case, no decimation): the SET indices with the
%   spec's lags (F10 and S10 at t - 1 d, M10 at t - 2 d, Y10 at t - 5 d, DSTDTC at t), linear with extrapolation, the
%   Sun, GMST and the core. utc = [Y M D h m s].
%   utc: real[1][6] (passed a plain number)
%   lon_deg: real[1] (passed a plain number)
%   lat_deg: real[1] (passed a plain number)
%   alt_km: real[1] (passed a plain number)
%   returns rho: real[1] (passed a plain number)
%   returns out: JbOut (passed rec)
%   returns inp: JbCoreInputs (passed rec)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    rho = 0;
    out = asils.models.jb2008.JbOut_zero();
    inp = asils.models.jb2008.JbCoreInputs_zero();
    dnum = asils.models.timescales.datenum(utc(1), utc(2), utc(3), utc(4), utc(5), utc(6));
    mjd = (dnum - 678942);
    f10 = asils.models.jb2008.sol_interp(0, (dnum - 1));
    f10b = asils.models.jb2008.sol_interp(1, (dnum - 1));
    s10 = asils.models.jb2008.sol_interp(2, (dnum - 1));
    s10b = asils.models.jb2008.sol_interp(3, (dnum - 1));
    m10 = asils.models.jb2008.sol_interp(4, (dnum - 2));
    m10b = asils.models.jb2008.sol_interp(5, (dnum - 2));
    y10 = asils.models.jb2008.sol_interp(6, (dnum - 5));
    y10b = asils.models.jb2008.sol_interp(7, (dnum - 5));
    dstdtc = asils.models.jb2008.dtc_interp(dnum);
    [ra_sun, dec_sun] = asils.models.jb2008.sun_radec(mjd);
    gmst = asils.models.jb2008.gmst_rad(mjd);
    ra_sat = asils.models.timescales.omod((asils.models.timescales.deg2rad(lon_deg) + gmst), (2 * pi));
    lat_r = asils.models.timescales.deg2rad(lat_deg);
    inp = asils.models.jb2008.JbCoreInputs_zero();
    inp.mjd = mjd;
    inp.sun = [ra_sun; dec_sun];
    inp.sat = [ra_sat; lat_r; alt_km];
    inp.ind = [f10; f10b; s10; s10b; m10; m10b; y10; y10b; dstdtc];
    out = asils.models.jb2008.jb2008_core(mjd, inp.sun, inp.sat, f10, f10b, s10, s10b, m10, m10b, y10, y10b, dstdtc);
    rho = out.rho;
end
