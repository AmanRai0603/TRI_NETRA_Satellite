function [rho] = jb_finish(aln_in, z, mjd, sat, f10b, s10b, xm10b)
%JB_FINISH  The end of the JB2008 core: the J70 seasonal-latitudinal and the semiannual variations added to the log number
%   densities, their sum to a density, and the exospheric correction above 1000 km.
%   aln_in: real[1][6] (passed a plain number)
%   z: real[1] (passed a plain number)
%   mjd: real[1] (passed a plain number)
%   sat: real[1][3] (passed a plain number)
%   f10b: real[1] (passed a plain number)
%   s10b: real[1] (passed a plain number)
%   xm10b: real[1] (passed a plain number)
%   returns rho: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    rho = 0;
    al10 = 2.3025851;
    amw = [28.0134; 31.9988; 15.9994; 39.948; 4.0026; 1.00797];
    avogad = 6.02257e+26;
    twopi = (2 * pi);
    cht = [0.22; (-(0.002)); 0.00115; (-(0.00000211))];
    zht = sat(3);
    aln = aln_in;
    trash = ((mjd - 36204) / 365.2422);
    capphi = asils.models.timescales.omod(trash, 1);
    dlrsl = (((((0.02 * (sat(3) - 90)) * exp(((-(0.045)) * (sat(3) - 90)))) * asils.models.jb2008.jb_sign(1, sat(2))) * sin(((twopi * capphi) + 1.72))) * (sin(sat(2)))^(2));
    dlrsa = 0;
    if (z < 2000)
        yrday = asils.models.jb2008.tmoutd(mjd);
        [fzz, gtz, d] = asils.models.jb2008.semian08(yrday, zht, f10b, s10b, xm10b);
        dlrsa = d;
        if (fzz < 0)
            dlrsa = 0;
        end
    end
    dlr = (al10 * (dlrsl + dlrsa));
    for i = (0):((6) - 1)
        aln((i) + 1) = (aln((i) + 1) + dlr);
    end
    sumnm = 0;
    for i = (0):((6) - 1)
        an = exp(aln((i) + 1));
        sumnm = (sumnm + (an * amw((i) + 1)));
    end
    rho = (sumnm / avogad);
    fex = 1;
    if ((zht >= 1000) && (zht < 1500))
        zeta = ((zht - 1000) * 0.002);
        zeta2 = (zeta * zeta);
        zeta3 = (zeta * zeta2);
        f15c = (((cht(1) + (cht(2) * f10b)) + (cht(3) * 1500)) + ((cht(4) * f10b) * 1500));
        f15c_zeta = ((cht(3) + (cht(4) * f10b)) * 500);
        fex2 = (((3 * f15c) - f15c_zeta) - 3);
        fex3 = ((f15c_zeta - (2 * f15c)) + 2);
        fex = ((1 + (fex2 * zeta2)) + (fex3 * zeta3));
    end
    if (zht >= 1500)
        fex = (((cht(1) + (cht(2) * f10b)) + (cht(3) * zht)) + ((cht(4) * f10b) * zht));
    end
    rho = (rho * fex);
end
