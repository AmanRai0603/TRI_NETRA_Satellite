function [rotor_momentum, rotor_speed, rotor_torque, gimbal_rate, gimbal_power, vscmg_momentum] = catalogue_cmg(h, tau, w)
%CATALOGUE_CMG  A CMG's (or a CMG cluster's) values from its momentum h [N m s], output torque tau [N m] and rotor speed w [rad/s]:
%   the rotor's momentum and speed, its torque, the gimbal's rate limit (the output torque over the momentum) and power
%   (none apart: the datasheet's figure is the whole unit's), and the rotor's momentum as a VSCMG (half).
%   h: real[1] (passed a plain number)
%   tau: real[1] (passed a plain number)
%   w: real[1] (passed a plain number)
%   returns rotor_momentum: real[1] (passed a plain number)
%   returns rotor_speed: real[1] (passed a plain number)
%   returns rotor_torque: real[1] (passed a plain number)
%   returns gimbal_rate: real[1] (passed a plain number)
%   returns gimbal_power: real[1] (passed a plain number)
%   returns vscmg_momentum: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    rotor_momentum = 0;
    rotor_speed = 0;
    rotor_torque = 0;
    gimbal_rate = 0;
    gimbal_power = 0;
    vscmg_momentum = 0;
    [a0, a1, a2, a3, a4, a5, a6, a7, a8, a9, a10, a11, cmg_rotor_torque, a13] = asils.models.catderive.catalogue_rules();
    rotor_momentum = h;
    rotor_speed = w;
    rotor_torque = (cmg_rotor_torque * tau);
    gimbal_rate = (tau / h);
    gimbal_power = 0;
    vscmg_momentum = (h / 2);
end
