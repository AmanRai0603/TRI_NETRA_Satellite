function [selectable, miss_h, miss_torque, miss_mass, miss_power] = catalogue_selectable(h, torque, mass, p_steady)
%CATALOGUE_SELECTABLE  Whether a model is selectable: its datasheet states the momentum h [mN m s], the torque [mN m], the mass [g] and the
%   steady power [W] (nan: not stated); and which of them it does not state.
%   h: real[1] (passed a plain number)
%   torque: real[1] (passed a plain number)
%   mass: real[1] (passed a plain number)
%   p_steady: real[1] (passed a plain number)
%   returns selectable: bool (passed true or false)
%   returns miss_h: bool (passed true or false)
%   returns miss_torque: bool (passed true or false)
%   returns miss_mass: bool (passed true or false)
%   returns miss_power: bool (passed true or false)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    selectable = false;
    miss_h = false;
    miss_torque = false;
    miss_mass = false;
    miss_power = false;
    miss_h = isnan(h);
    miss_torque = isnan(torque);
    miss_mass = isnan(mass);
    miss_power = isnan(p_steady);
    selectable = (~(((miss_h || miss_torque) || miss_mass) || miss_power));
end
