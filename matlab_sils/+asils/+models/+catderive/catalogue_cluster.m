function [h, tau, mass, power] = catalogue_cluster(units, h_mnms, torque_mnm, mass_g, p_steady)
%CATALOGUE_CLUSTER  A CMG cluster's own figures (adcs-datasheet/1 units_in_cluster, cluster_h_mNms, cluster_torque_mNm, cluster_mass_g) and
%   the steady power of one unit [W]: the cluster's momentum [N m s], torque [N m] and mass [kg], and its steady power (the
%   unit's times the units it holds, the datasheet stating no cluster power); nan for each the datasheet does not state (a
%   stated zero is not stated), and for the power when the units are not stated.
%   units: real[1] (passed a plain number)
%   h_mnms: real[1] (passed a plain number)
%   torque_mnm: real[1] (passed a plain number)
%   mass_g: real[1] (passed a plain number)
%   p_steady: real[1] (passed a plain number)
%   returns h: real[1] (passed a plain number)
%   returns tau: real[1] (passed a plain number)
%   returns mass: real[1] (passed a plain number)
%   returns power: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    h = 0;
    tau = 0;
    mass = 0;
    power = 0;
    h = NaN;
    tau = NaN;
    mass = NaN;
    power = NaN;
    if ((~isnan(h_mnms)) && (h_mnms > 0))
        h = (h_mnms * 0.001);
    end
    if ((~isnan(torque_mnm)) && (torque_mnm > 0))
        tau = (torque_mnm * 0.001);
    end
    if ((~isnan(mass_g)) && (mass_g > 0))
        mass = (mass_g * 0.001);
    end
    if ((~isnan(units)) && (units > 0))
        power = (units * p_steady);
    end
end
