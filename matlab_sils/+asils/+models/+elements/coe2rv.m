function [r, v] = coe2rv(a, e, inc, raan, argp, nu, mu)
%COE2RV  The inertial position and velocity of the elements a, e, i, RAAN, argument of perigee and true anomaly (for a
%   circular orbit the argument of latitude), about a body of gravitational parameter mu.
%   a: real[m] (passed in m)
%   e: real[1] (passed a plain number)
%   inc: real[1] (passed a plain number)
%   raan: real[1] (passed a plain number)
%   argp: real[1] (passed a plain number)
%   nu: real[1] (passed a plain number)
%   mu: real[m^3/s^2] (passed in m^3/s^2)
%   returns r: real[m][3] (passed in m)
%   returns v: real[m/s][3] (passed in m/s)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    r = zeros(3, 1);
    v = zeros(3, 1);
    p = (a * (1 - (e * e)));
    r_pf = [((p * cos(nu)) / (1 + (e * cos(nu)))); ((p * sin(nu)) / (1 + (e * cos(nu)))); 0];
    h__225 = (mu / p);
    if h__225 < 0, h__225 = NaN; else, h__225 = sqrt(h__225); end
    h__226 = (mu / p);
    if h__226 < 0, h__226 = NaN; else, h__226 = sqrt(h__226); end
    v_pf = [((-(h__225)) * sin(nu)); (h__226 * (e + cos(nu))); 0];
    co = cos(raan);
    so = sin(raan);
    ci = cos(inc);
    si = sin(inc);
    cw = cos(argp);
    sw = sin(argp);
    q = [([((co * cw) - ((so * sw) * ci)); (((-(co)) * sw) - ((so * cw) * ci)); (so * si)]).'; ([((so * cw) + ((co * sw) * ci)); (((-(so)) * sw) + ((co * cw) * ci)); ((-(co)) * si)]).'; ([(sw * si); (cw * si); ci]).'];
    r = [q(1, 1)*r_pf(1) + q(1, 2)*r_pf(2) + q(1, 3)*r_pf(3); q(2, 1)*r_pf(1) + q(2, 2)*r_pf(2) + q(2, 3)*r_pf(3); q(3, 1)*r_pf(1) + q(3, 2)*r_pf(2) + q(3, 3)*r_pf(3)];
    v = [q(1, 1)*v_pf(1) + q(1, 2)*v_pf(2) + q(1, 3)*v_pf(3); q(2, 1)*v_pf(1) + q(2, 2)*v_pf(2) + q(2, 3)*v_pf(3); q(3, 1)*v_pf(1) + q(3, 2)*v_pf(2) + q(3, 3)*v_pf(3)];
end
