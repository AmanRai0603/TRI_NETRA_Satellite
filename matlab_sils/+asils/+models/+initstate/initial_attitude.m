function [q0, g] = initial_attitude(kind, q_nad, has_g, q_g, axis, angle, g)
%INITIAL_ATTITUDE  The attitude (ECI to body) a run starts at: q_nad nadir's reference, q_g the start mode's guidance reference
%   (has_g: the start mode has a guidance), axis (body) and angle [rad] the error asked for, draws from g.
%   kind: AttStart (passed a choice, as its option's number)
%   q_nad: real[1][4] (passed a plain number)
%   has_g: bool (passed true or false)
%   q_g: real[1][4] (passed a plain number)
%   axis: real[1][3] (passed a plain number)
%   angle: real[1] (passed a plain number)
%   g: inout stream (passed a random stream, as six numbers)
%   returns q0: real[1][4] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    q0 = zeros(4, 1);
    q0 = q_nad;
    if (kind == 1)
        [t__354, t__355] = asils.pc.stream_normal(g);
        x0 = t__354;
        g = t__355;
        [t__356, t__357] = asils.pc.stream_normal(g);
        x1 = t__356;
        g = t__357;
        [t__358, t__359] = asils.pc.stream_normal(g);
        x2 = t__358;
        g = t__359;
        [t__360, t__361] = asils.pc.stream_normal(g);
        x3 = t__360;
        g = t__361;
        q0 = asils.models.initstate.init_qnorm([x0; x1; x2; x3]);
    elseif ((kind == 2) || (kind == 3))
        qr = q_nad;
        if ((kind == 3) && has_g)
            qr = q_g;
        end
        q0 = asils.models.initstate.init_qnorm(asils.models.math.qmult(qr, asils.models.math.fromrotvec((asils.models.facets.unit_or_zero(axis) * angle))));
    end
end
