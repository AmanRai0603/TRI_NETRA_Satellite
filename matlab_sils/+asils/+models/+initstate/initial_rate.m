function [w0, g] = initial_rate(kind, q0, r, v, value, mag, has_g, q_g, w_g, extra, g)
%INITIAL_RATE  The body rate [rad/s] a run starts at, the body at q0, the satellite at r [m] with velocity v [m/s] (ECI): value the
%   rate stated, mag the random direction's magnitude, w_g the guidance's reference rate (in its reference frame, has_g:
%   the start mode has a guidance, q_g its reference), extra the random direction's magnitude added to it; draws from g.
%   kind: RateStart (passed a choice, as its option's number)
%   q0: real[1][4] (passed a plain number)
%   r: real[1][3] (passed a plain number)
%   v: real[1][3] (passed a plain number)
%   value: real[1][3] (passed a plain number)
%   mag: real[1] (passed a plain number)
%   has_g: bool (passed true or false)
%   q_g: real[1][4] (passed a plain number)
%   w_g: real[1][3] (passed a plain number)
%   extra: real[1] (passed a plain number)
%   g: inout stream (passed a random stream, as six numbers)
%   returns w0: real[1][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    w0 = zeros(3, 1);
    w0 = value;
    if (kind == 1)
        [t__57, t__58] = asils.pc.stream_normal3(g);
        n = t__57;
        g = t__58;
        w0 = (asils.models.facets.unit_or_zero(n) * mag);
    elseif (kind == 2)
        w0 = asils.pc.mv(asils.models.math.dcm(q0), (asils.pc.cross_(r, v) * (1 / asils.pc.dot_(r, r))));
    elseif (kind == 3)
        w = zeros(3, 1);
        if has_g
            w = asils.pc.mv(asils.models.math.dcm(asils.models.math.qmult(asils.models.math.qconj(q_g), q0)), w_g);
        end
        [t__59, t__60] = asils.pc.stream_normal3(g);
        n = t__59;
        g = t__60;
        w0 = (w + (asils.models.facets.unit_or_zero(n) * extra));
    end
end
