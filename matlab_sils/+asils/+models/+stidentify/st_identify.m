function [id, ok, pi, pj, pa, cr, cm] = st_identify(b, mag, n, pi, pj, pa, cr, cm, nc, id_tol, mag_tol)
%ST_IDENTIFY  The catalogue star (from 0, -1 none) of each of the first n spots, b their directions (head frame, unit) and mag their
%   magnitudes, against the pair table (pi, pj, pa) of the first nc catalogue stars (cr, cm): every other spot q votes, for
%   spot p, for each catalogue pair whose angle is within id_tol of theirs and whose two magnitudes match p's and q's
%   within mag_tol (either way round); p takes its most-voted star (the lowest on a tie). Then, three passes over the spots
%   in turn, a star is kept only while its angles to at least two other kept stars are within 3 id_tol of the catalogue's.
%   Whether three or more are kept.
%   length: 64
%   b: real[1][3][ST_SPOTS] (passed a plain number)
%   mag: real[1][ST_SPOTS] (passed a plain number)
%   n: int (passed a whole number)
%   pi: inout int[*] (passed a whole number)
%   pj: inout int[*] (passed a whole number)
%   pa: inout real[1][*] (passed a plain number)
%   cr: inout real[1][3][N_STARS] (passed a plain number)
%   cm: inout real[1][N_STARS] (passed a plain number)
%   nc: int (passed a whole number)
%   id_tol: real[1] (passed a plain number)
%   mag_tol: real[1] (passed a plain number)
%   returns id: int[ST_SPOTS] (passed a whole number)
%   returns ok: bool (passed true or false)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    id = zeros(32, 1);
    ok = false;
    for p0 = (0):((32) - 1)
        id((p0) + 1) = (-(1));
    end
    ok = false;
    if (n >= 3)
        np = numel(pa);
        cand = zeros(32, 1);
        for p = (0):((n) - 1)
            votes = zeros(4000, 1);
            for q = (0):((n) - 1)
                if (q ~= p)
                    th = acos(asils.pc.fmin(asils.pc.dot_((b((p) + 1, :)).', (b((q) + 1, :)).'), 1));
                    [t__184, t__185] = asils.models.stidentify.st_first_not_below(pa, np, (th - id_tol));
                    lo = t__184;
                    pa = t__185;
                    [t__186, t__187] = asils.models.stidentify.st_first_above(pa, np, (th + id_tol));
                    hi = t__186;
                    pa = t__187;
                    mp = mag((p) + 1);
                    mq = mag((q) + 1);
                    for k = (lo):((asils.pc.fmax(hi, lo)) - 1)
                        i = pi((k) + 1);
                        j = pj((k) + 1);
                        mi = cm((i) + 1);
                        mj = cm((j) + 1);
                        dip = (mi - mp);
                        djq = (mj - mq);
                        djp = (mj - mp);
                        diq = (mi - mq);
                        if ((asils.pc.fmax(dip, (-(dip))) < mag_tol) && (asils.pc.fmax(djq, (-(djq))) < mag_tol))
                            votes((i) + 1) = (votes((i) + 1) + 1);
                        end
                        if ((asils.pc.fmax(djp, (-(djp))) < mag_tol) && (asils.pc.fmax(diq, (-(diq))) < mag_tol))
                            votes((j) + 1) = (votes((j) + 1) + 1);
                        end
                    end
                end
            end
            best = 0;
            bi = (-(1));
            for k2 = (0):((nc) - 1)
                if (votes((k2) + 1) > best)
                    best = votes((k2) + 1);
                    bi = k2;
                end
            end
            cand((p) + 1) = bi;
        end
        keep = zeros(32, 1);
        for p2 = (0):((n) - 1)
            keep((p2) + 1) = (cand((p2) + 1) >= 0);
        end
        for pass = (0):((3) - 1)
            was = keep;
            for p3 = (0):((n) - 1)
                if was((p3) + 1)
                    good = 0;
                    for q3 = (0):((n) - 1)
                        if ((q3 ~= p3) && keep((q3) + 1))
                            th3 = acos(asils.pc.fmin(asils.pc.dot_((b((p3) + 1, :)).', (b((q3) + 1, :)).'), 1));
                            tc = acos(asils.pc.fmin(asils.pc.dot_((cr((cand((p3) + 1)) + 1, :)).', (cr((cand((q3) + 1)) + 1, :)).'), 1));
                            if (asils.pc.fabs((th3 - tc)) < (3 * id_tol))
                                good = (good + 1);
                            end
                        end
                    end
                    if (good < 2)
                        keep((p3) + 1) = false;
                    end
                end
            end
        end
        kept = 0;
        for p4 = (0):((n) - 1)
            if keep((p4) + 1)
                id((p4) + 1) = cand((p4) + 1);
                kept = (kept + 1);
            end
        end
        ok = (kept >= 3);
    end
end
