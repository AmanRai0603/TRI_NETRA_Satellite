function [xd] = fq_rate(law, g, c_bo, inc, n, ji, duty, nad, wref_r, t, x)
%FQ_RATE  The closed loop's rate at time t from the state x = [error rotation, body rate], about the reference: the field of an
%   aligned dipole along the circular orbit (inclination inc, mean motion n) in the reference body frame (c_bo, body <-
%   orbit), the law's torque through the coils' projection Gamma = I - b b^T at the duty d, the nadir gravity-gradient
%   feed-forward when its bit is set, the rigid body's gyroscopic and gravity-gradient torques; ji the inverse inertia,
%   nad the nadir and wref_r the reference rate in the reference body frame.
%   law: MtqAlg (passed a choice, as its option's number)
%   g: FqGains (passed rec)
%   c_bo: real[1][3][3] (passed a plain number)
%   inc: real[1] (passed a plain number)
%   n: real[1] (passed a plain number)
%   ji: real[1][3][3] (passed a plain number)
%   duty: real[1] (passed a plain number)
%   nad: real[1][3] (passed a plain number)
%   wref_r: real[1][3] (passed a plain number)
%   t: real[1] (passed a plain number)
%   x: real[1][6] (passed a plain number)
%   returns xd: real[1][6] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    xd = zeros(6, 1);
    qe = asils.models.floquet.fq_rv2q([x(1); x(2); x(3)]);
    w = [x(4); x(5); x(6)];
    am = asils.models.math.dcm(qe);
    u = (n * t);
    bo = [(cos(u) * sin(inc)); (-(cos(inc))); ((2 * sin(u)) * sin(inc))];
    h__43 = (bo / sqrt(bo(1)*bo(1) + bo(2)*bo(2) + bo(3)*bo(3)));
    h__44 = [c_bo(1, 1)*h__43(1) + c_bo(1, 2)*h__43(2) + c_bo(1, 3)*h__43(3); c_bo(2, 1)*h__43(1) + c_bo(2, 2)*h__43(2) + c_bo(2, 3)*h__43(3); c_bo(3, 1)*h__43(1) + c_bo(3, 2)*h__43(2) + c_bo(3, 3)*h__43(3)];
    b = [am(1, 1)*h__44(1) + am(1, 2)*h__44(2) + am(1, 3)*h__44(3); am(2, 1)*h__44(1) + am(2, 2)*h__44(2) + am(2, 3)*h__44(3); am(3, 1)*h__44(1) + am(3, 2)*h__44(2) + am(3, 3)*h__44(3)];
    gm = zeros(3, 3);
    i = ((0):((3) - 1)).';
    j = (0):((3) - 1);
    gm((i) + 1, (j) + 1) = (asils.pc.vchoose((i == j), 1, 0) - (reshape(b((i) + 1), [], 1) .* reshape(b((j) + 1), 1, [])));
    tau = asils.models.floquet.fq_torque(law, g, qe, w, wref_r, g.roll_axis);
    c = [am(1, 1)*nad(1) + am(1, 2)*nad(2) + am(1, 3)*nad(3); am(2, 1)*nad(1) + am(2, 2)*nad(2) + am(2, 3)*nad(3); am(3, 1)*nad(1) + am(3, 2)*nad(2) + am(3, 3)*nad(3)];
    if (bitand(g.mtq_gg_ff, 2) ~= 0)
        h__45 = [g.J(1, 1)*c(1) + g.J(1, 2)*c(2) + g.J(1, 3)*c(3); g.J(2, 1)*c(1) + g.J(2, 2)*c(2) + g.J(2, 3)*c(3); g.J(3, 1)*c(1) + g.J(3, 2)*c(2) + g.J(3, 3)*c(3)];
        tau = (tau - (((3 * n) * n) * [c(2)*h__45(3) - c(3)*h__45(2); c(3)*h__45(1) - c(1)*h__45(3); c(1)*h__45(2) - c(2)*h__45(1)]));
    end
    h__46 = [g.J(1, 1)*w(1) + g.J(1, 2)*w(2) + g.J(1, 3)*w(3); g.J(2, 1)*w(1) + g.J(2, 2)*w(2) + g.J(2, 3)*w(3); g.J(3, 1)*w(1) + g.J(3, 2)*w(2) + g.J(3, 3)*w(3)];
    h__47 = [g.J(1, 1)*c(1) + g.J(1, 2)*c(2) + g.J(1, 3)*c(3); g.J(2, 1)*c(1) + g.J(2, 2)*c(2) + g.J(2, 3)*c(3); g.J(3, 1)*c(1) + g.J(3, 2)*c(2) + g.J(3, 3)*c(3)];
    h__48 = (((-([w(2)*h__46(3) - w(3)*h__46(2); w(3)*h__46(1) - w(1)*h__46(3); w(1)*h__46(2) - w(2)*h__46(1)])) + (((3 * n) * n) * [c(2)*h__47(3) - c(3)*h__47(2); c(3)*h__47(1) - c(1)*h__47(3); c(1)*h__47(2) - c(2)*h__47(1)])) + (duty * [gm(1, 1)*tau(1) + gm(1, 2)*tau(2) + gm(1, 3)*tau(3); gm(2, 1)*tau(1) + gm(2, 2)*tau(2) + gm(2, 3)*tau(3); gm(3, 1)*tau(1) + gm(3, 2)*tau(2) + gm(3, 3)*tau(3)]));
    wd = [ji(1, 1)*h__48(1) + ji(1, 2)*h__48(2) + ji(1, 3)*h__48(3); ji(2, 1)*h__48(1) + ji(2, 2)*h__48(2) + ji(2, 3)*h__48(3); ji(3, 1)*h__48(1) + ji(3, 2)*h__48(2) + ji(3, 3)*h__48(3)];
    we = (w - [am(1, 1)*wref_r(1) + am(1, 2)*wref_r(2) + am(1, 3)*wref_r(3); am(2, 1)*wref_r(1) + am(2, 2)*wref_r(2) + am(2, 3)*wref_r(3); am(3, 1)*wref_r(1) + am(3, 2)*wref_r(2) + am(3, 3)*wref_r(3)]);
    xd = [we(1); we(2); we(3); wd(1); wd(2); wd(3)];
end
