function [phi] = fq_monodromy(law, g, c_bo, inc, n, steps)
%FQ_MONODROMY  The monodromy matrix of the loop over one orbit: the variational equation Phi' = A(t) Phi from Phi = I, by RK4 in
%   the given number of steps, A from fq_jacobian at the step's start, middle and end. The inverse inertia is the
%   toolbox's (inv3, the adjugate); c_bo's columns give the orbit normal (-y) and the nadir (z) in the reference body
%   frame, and the reference rate is n times the orbit normal.
%   tolerance: 1e-6
%   vectors: 4
%   law: MtqAlg (passed a choice, as its option's number)
%   g: FqGains (passed rec)
%   c_bo: real[1][3][3] (passed a plain number)
%   inc: real[1] (passed a plain number)
%   n: real[1] (passed a plain number)
%   steps: int (passed a whole number)
%   returns phi: real[1][6][6] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    phi = zeros(6, 6);
    [ji, ok] = asils.models.math.inv3(g.J);
    duty = (1 - (g.mtq_meas / g.mtq_period));
    ep = [(-(c_bo(1, 2))); (-(c_bo(2, 2))); (-(c_bo(3, 2)))];
    nad = [c_bo(1, 3); c_bo(2, 3); c_bo(3, 3)];
    wref_r = (n * ep);
    tp = ((2 * pi) / n);
    h = (tp / steps);
    for i = (0):((6) - 1)
        phi((i) + 1, (i) + 1) = 1;
    end
    t = 0;
    for s = (0):((steps) - 1)
        a1 = asils.models.floquet.fq_jacobian(law, g, c_bo, inc, n, ji, duty, nad, wref_r, t);
        a2 = asils.models.floquet.fq_jacobian(law, g, c_bo, inc, n, ji, duty, nad, wref_r, (t + (h / 2)));
        a3 = asils.models.floquet.fq_jacobian(law, g, c_bo, inc, n, ji, duty, nad, wref_r, (t + h));
        k1 = asils.pc.mm(a1, phi);
        k2 = asils.pc.mm(a2, (phi + ((h / 2) * k1)));
        k3 = asils.pc.mm(a2, (phi + ((h / 2) * k2)));
        k4 = asils.pc.mm(a3, (phi + (h * k3)));
        phi = (phi + ((h / 6) * (((k1 + (2 * k2)) + (2 * k3)) + k4)));
        t = (t + h);
    end
end
