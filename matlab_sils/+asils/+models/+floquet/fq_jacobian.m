function [jm] = fq_jacobian(law, g, c_bo, inc, n, ji, duty, nad, wref_r, t)
%FQ_JACOBIAN  The loop's Jacobian about the reference at time t, by central differences of step 1e-7 in each state.
%   tolerance: 1e-6
%   law: MtqAlg (passed a choice, as its option's number)
%   g: FqGains (passed rec)
%   c_bo: real[1][3][3] (passed a plain number)
%   inc: real[1] (passed a plain number)
%   n: real[1] (passed a plain number)
%   ji: real[1][3][3] (passed a plain number)
%   duty: real[1] (passed a plain number)
%   nad: real[1][3] (passed a plain number)
%   wref_r: real[1][3] (passed a plain number)
%   t: real[1] (passed a plain number)
%   returns jm: real[1][6][6] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    jm = zeros(6, 6);
    x0 = [0; 0; 0; wref_r(1); wref_r(2); wref_r(3)];
    h = 1e-7;
    for j = (0):((6) - 1)
        d = zeros(6, 1);
        d((j) + 1) = h;
        fp = asils.models.floquet.fq_rate(law, g, c_bo, inc, n, ji, duty, nad, wref_r, t, (x0 + d));
        fm = asils.models.floquet.fq_rate(law, g, c_bo, inc, n, ji, duty, nad, wref_r, t, (x0 - d));
        for i = (0):((6) - 1)
            jm((i) + 1, (j) + 1) = ((fp((i) + 1) - fm((i) + 1)) / (2 * h));
        end
    end
end
