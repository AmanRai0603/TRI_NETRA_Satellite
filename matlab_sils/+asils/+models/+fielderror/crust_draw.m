function [gc, g] = crust_draw(rms, alt_km, g)
%CRUST_DRAW  The crust's Gauss coefficients [nT], drawn from the stream g (a Gaussian each, in the IGRF's order). Each degree n carries the same
%   mean-square field, rms^2/(the number of degrees), at the radius r0 = R_E + alt_km (the orbit's radius), by the Lowes-Mauersberger
%   spectrum (Lowes 1966, JGR 71(8):2179: the mean square of the field over the sphere of radius r is the sum over n of
%   (n + 1) (a/r)^(2 n + 4) times the sum over m of (g^2 + h^2)): a coefficient of degree n has the variance
%   sigma_n^2 = rms^2 / (K (n + 1) (2 n + 1)) (r0/a)^(2 n + 4),
%   K = 7 degrees, so that the root-mean-square of the field's magnitude over the sphere at r0 is rms [nT].
%   rms: real[1] (passed a plain number)
%   alt_km: real[1] (passed a plain number)
%   g: inout stream (passed a random stream, as six numbers)
%   returns gc: real[1][245] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    gc = zeros(245, 1);
    r0 = ((6378137 / 1000) + alt_km);
    k = ((20 - 14) + 1);
    ci = 0;
    for n = (14):(((20 + 1)) - 1)
        h__271 = ((k * (n + 1)) * ((2 * n) + 1));
        if h__271 < 0, h__271 = NaN; else, h__271 = sqrt(h__271); end
        h__272 = ((r0 / 6371.2))^((n + 2));
        if ~isreal(h__272), h__272 = NaN; end
        sig = ((rms / h__271) * h__272);
        for m = (0):(((n + 1)) - 1)
            [t__480, t__481] = asils.pc.stream_normal(g);
            z = t__480;
            g = t__481;
            gc((ci) + 1) = (sig * z);
            ci = (ci + 1);
            if (m > 0)
                [t__482, t__483] = asils.pc.stream_normal(g);
                z2 = t__482;
                g = t__483;
                gc((ci) + 1) = (sig * z2);
                ci = (ci + 1);
            end
        end
    end
end
