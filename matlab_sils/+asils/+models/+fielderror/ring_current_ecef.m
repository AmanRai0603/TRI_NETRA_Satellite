function [b] = ring_current_ecef(dst, gh)
%RING_CURRENT_ECEF  The ring current's field, uniform, in the Earth-fixed frame [nT]: Dst [nT] along the geomagnetic dipole axis, against the field
%   the dipole has at the equator. The Dessler-Parker-Sckopke relation (Dessler and Parker 1959, JGR 64(12):2239; Sckopke 1966,
%   JGR 71(13):3125) gives the disturbance field of a ring current at the Earth's centre, dB/B0 = -(2/3) E_R/E_M, B0 the
%   equatorial surface field of the dipole, E_R the ring current's particle energy, E_M the dipole field's energy outside the Earth;
%   the Dst index is taken as that disturbance, the magnetopause currents and the Earth's induced currents (the corrections
%   of a Dst that is not the ring current's alone) left out, and the field as uniform over the orbit (the ring current is
%   outside it). The dipole's moment is the coefficients' (g10, g11, h11) = (gh[0], gh[1], gh[2]), at the run's date: its
%   direction is (g11, h11, g10) in the Earth-fixed frame, the field at its equator against it, so the disturbance of a
%   negative Dst (a depression of the equatorial field) is Dst against the field, which is -Dst along the moment.
%   dst: real[1] (passed a plain number)
%   gh: real[1][195] (passed a plain number)
%   returns b: real[1][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    b = zeros(3, 1);
    h__270 = (((gh(2) * gh(2)) + (gh(3) * gh(3))) + (gh(1) * gh(1)));
    if h__270 < 0, h__270 = NaN; else, h__270 = sqrt(h__270); end
    m = h__270;
    b = [(((-(dst)) * gh(2)) / m); (((-(dst)) * gh(3)) / m); (((-(dst)) * gh(1)) / m)];
end
