function [b] = field_error_eci_at(lat, lon, h, c, gh, gc, dst)
%FIELD_ERROR_ECI_AT  The truth's error field in J2000 [T, as plain numbers] at geodetic latitude, longitude [rad] and height, given the J2000 to
%   Earth-fixed matrix, the Gauss coefficients at the date (the dipole's moment), the crust's coefficients and Dst [nT]: the
%   crust turned north-east-down to Earth-fixed as the truth field is (truthfield's field_eci_at), the ring current's uniform field
%   added there, both back to J2000.
%   lat: real[1] (passed a plain number)
%   lon: real[1] (passed a plain number)
%   h: real[m] (passed in m)
%   c: real[1][3][3] (passed a plain number)
%   gh: real[1][195] (passed a plain number)
%   gc: real[1][245] (passed a plain number)
%   dst: real[1] (passed a plain number)
%   returns b: real[1][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    b = zeros(3, 1);
    bn = asils.models.fielderror.crust_ned(gc, lat, lon, (h / 1000));
    sl = sin(lat);
    cl = cos(lat);
    so = sin(lon);
    co = cos(lon);
    br = asils.models.fielderror.ring_current_ecef(dst, gh);
    be = [(((((((-(sl)) * co) * bn(1)) - (so * bn(2))) - ((cl * co) * bn(3))) + br(1)) * 1e-9); (((((((-(sl)) * so) * bn(1)) + (co * bn(2))) - ((cl * so) * bn(3))) + br(2)) * 1e-9); ((((cl * bn(1)) - (sl * bn(3))) + br(3)) * 1e-9)];
    h__278 = (c).';
    b = [h__278(1, 1)*be(1) + h__278(1, 2)*be(2) + h__278(1, 3)*be(3); h__278(2, 1)*be(1) + h__278(2, 2)*be(2) + h__278(2, 3)*be(3); h__278(3, 1)*be(1) + h__278(3, 2)*be(2) + h__278(3, 3)*be(3)];
end
