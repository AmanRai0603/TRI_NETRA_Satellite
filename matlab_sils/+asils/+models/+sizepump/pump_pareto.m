function [ok, lam, mass, power, coil, v_max, bore, b, loops] = pump_pareto(h, tau, s0, l1)
%PUMP_PARETO  The mass and steady-power Pareto front of one ring over the exchange rate (for the report): for each of seven rates
%   lambda [kg/W] (0.003 to 3) whether a design was found, its mass [kg], steady power [W], coil power [W], top speed
%   [m/s], bore [m], field [T] and loops.
%   vectors: 2
%   h: real[1] (passed a plain number)
%   tau: real[1] (passed a plain number)
%   s0: real[1] (passed a plain number)
%   l1: real[1] (passed a plain number)
%   returns ok: int[7] (passed a whole number)
%   returns lam: real[1][7] (passed a plain number)
%   returns mass: real[1][7] (passed a plain number)
%   returns power: real[1][7] (passed a plain number)
%   returns coil: real[1][7] (passed a plain number)
%   returns v_max: real[1][7] (passed a plain number)
%   returns bore: real[1][7] (passed a plain number)
%   returns b: real[1][7] (passed a plain number)
%   returns loops: real[1][7] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    ok = zeros(7, 1);
    lam = zeros(7, 1);
    mass = zeros(7, 1);
    power = zeros(7, 1);
    coil = zeros(7, 1);
    v_max = zeros(7, 1);
    bore = zeros(7, 1);
    b = zeros(7, 1);
    loops = zeros(7, 1);
    lam = [0.003; 0.01; 0.03; 0.1; 0.3; 1; 3];
    ok = zeros(7, 1);
    mass = zeros(7, 1);
    power = zeros(7, 1);
    coil = zeros(7, 1);
    v_max = zeros(7, 1);
    bore = zeros(7, 1);
    b = zeros(7, 1);
    loops = zeros(7, 1);
    ds = asils.models.sizepump.PumpDesign_zero();
    for i = (0):((7) - 1)
        ds = asils.models.sizepump.pump_design(h, tau, s0, l1, lam((i) + 1));
        if ds.found
            ok((i) + 1) = 1;
            mass((i) + 1) = ds.mass;
            power((i) + 1) = ds.p_steady;
            coil((i) + 1) = ds.p_coil;
            v_max((i) + 1) = ds.v_max;
            bore((i) + 1) = ds.d;
            b((i) + 1) = ds.b;
            loops((i) + 1) = ds.loops;
        end
    end
end
