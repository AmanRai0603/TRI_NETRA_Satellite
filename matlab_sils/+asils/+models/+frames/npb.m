function [r] = npb(gam, dphi, psi, eps)
%NPB  The matrix R1(-eps) R3(-psi) R1(eps + dphi) R3(gam) (ERFA's fw2m of the angles gam, eps + dphi, psi, eps): from the J2000
%   frame to the true equator and equinox of date when psi and eps carry the nutation. R1(-eps) R3(-psi) R1(eps) is written out
%   (its elements with 1 - cos(psi) as 2 sin^2(psi/2)) and the small rotation R1(dphi) R3(gam) applied after it, so that the
%   small elements of the product (the pole's offset from the J2000 pole, 1e-5 to 1e-3) are sums of small terms, not the
%   difference of terms of order 1.
%   gam: real[1] (passed a plain number)
%   dphi: real[1] (passed a plain number)
%   psi: real[1] (passed a plain number)
%   eps: real[1] (passed a plain number)
%   returns r: real[1][3][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    r = zeros(3, 3);
    q = ((2 * sin((psi / 2))) * sin((psi / 2)));
    ce = cos(eps);
    se = sin(eps);
    a = [([(1 - q); ((-(sin(psi))) * ce); ((-(sin(psi))) * se)]).'; ([(ce * sin(psi)); (1 - ((ce * ce) * q)); (((-(ce)) * se) * q)]).'; ([(se * sin(psi)); (((-(ce)) * se) * q); (1 - ((se * se) * q))]).'];
    rd = [([1; 0; 0]).'; ([0; cos(dphi); sin(dphi)]).'; ([0; (-(sin(dphi))); cos(dphi)]).'];
    rg = [([cos(gam); sin(gam); 0]).'; ([(-(sin(gam))); cos(gam); 0]).'; ([0; 0; 1]).'];
    r = asils.pc.mm(asils.pc.mm(a, rd), rg);
end
