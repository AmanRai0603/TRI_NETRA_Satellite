function [dpsi, deps] = nut00b(t)
%NUT00B  The IAU 2000B nutation in longitude and in obliquity [rad] at t TT centuries since J2000: the 77 luni-solar terms
%   summed smallest first, the Delaunay arguments linear in t (McCarthy and Luzum 2003: 485868.249036 + 1717915923.2178 t
%   and the like, arcseconds), and the fixed offsets that stand for the planetary terms (-0.135 and +0.388 milliarcseconds).
%   What is left out of the 2000A series: its 601 other luni-solar terms, its planetary terms, and the small J2-rate
%   scaling of the IAU 2006 adaptation (the nut06a factor, about 1e-6 of the nutation, 1e-5 arcsecond); the abridgement's own
%   error is 1 milliarcsecond.
%   t: real[1] (passed a plain number)
%   returns dpsi: real[1] (passed a plain number)
%   returns deps: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    dpsi = 0;
    deps = 0;
    D__NUT00B = asils.models.frames.NUT00B();
    as_ = (pi / (180 * 3600));
    el = (rem((485868.249036 + (1717915923.2178 * t)), 1296000) * as_);
    elp = (rem((1287104.79305 + (129596581.0481 * t)), 1296000) * as_);
    f = (rem((335779.526232 + (1739527262.8478 * t)), 1296000) * as_);
    d = (rem((1072260.70369 + (1602961601.209 * t)), 1296000) * as_);
    om = (rem((450160.398036 - (6962890.5431 * t)), 1296000) * as_);
    dpsi = 0;
    deps = 0;
    for k = (0):((77) - 1)
        j = (76 - k);
        arg = rem((((((D__NUT00B((j) + 1, 1) * el) + (D__NUT00B((j) + 1, 2) * elp)) + (D__NUT00B((j) + 1, 3) * f)) + (D__NUT00B((j) + 1, 4) * d)) + (D__NUT00B((j) + 1, 5) * om)), (2 * pi));
        sa = sin(arg);
        ca = cos(arg);
        dpsi = ((dpsi + ((D__NUT00B((j) + 1, 6) + (D__NUT00B((j) + 1, 7) * t)) * sa)) + (D__NUT00B((j) + 1, 8) * ca));
        deps = ((deps + ((D__NUT00B((j) + 1, 9) + (D__NUT00B((j) + 1, 10) * t)) * ca)) + (D__NUT00B((j) + 1, 11) * sa));
    end
    dpsi = ((dpsi * (1e-7 * as_)) - (0.000135 * as_));
    deps = ((deps * (1e-7 * as_)) + (0.000388 * as_));
end
