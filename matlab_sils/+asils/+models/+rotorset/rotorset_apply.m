function [hd, gd, p, s] = rotorset_apply(s, d, cmd_r, cmd_g, h, dt)
%ROTORSET_APPLY  The commands (each rotor's torque cmd_r [N m], each gimbal's rate cmd_g [rad/s]) at the rotors' momenta h [N m s]
%   over a step dt: (the rotors' momentum rates [N m], the gimbals' rates [rad/s], the power [W]).
%   s: inout RotorSet (passed rec)
%   d: RotorDesc (passed rec)
%   cmd_r: real[1][DYN_NR] (passed a plain number)
%   cmd_g: real[1][DYN_NG] (passed a plain number)
%   h: real[1][DYN_NR] (passed a plain number)
%   dt: real[1] (passed a plain number)
%   returns hd: real[1][DYN_NR] (passed a plain number)
%   returns gd: real[1][DYN_NG] (passed a plain number)
%   returns p: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    hd = zeros(8, 1);
    gd = zeros(4, 1);
    p = 0;
    hd = zeros(8, 1);
    gd = zeros(4, 1);
    p = 0;
    for i = (0):((d.n) - 1)
        if s.failed((i) + 1)
            hd((i) + 1) = asils.models.wheelfriction.rotor_coast(h((i) + 1), d.jrot((i) + 1), d.viscous((i) + 1), d.coulomb((i) + 1));
        elseif (d.kind((i) + 1) == 0)
            om = (h((i) + 1) / d.jrot((i) + 1));
            fr = asils.models.wheelfriction.bearing_friction(om, d.coulomb((i) + 1), d.viscous((i) + 1), s.fscale((i) + 1));
            g1 = s.g;
            [t__29, t__30] = asils.models.wheelnoise.torque_noise(d.torque_noise, d.torque_max((i) + 1), g1);
            nz = t__29;
            g1 = t__30;
            s.g = g1;
            tm0 = (asils.models.coilsat.act_clamp(cmd_r((i) + 1), (-(d.torque_max((i) + 1))), d.torque_max((i) + 1)) * s.tscale((i) + 1));
            tm = asils.models.wheelspeed.speed_limited(asils.models.wheelmotor.motor_line(tm0, om, d.t_stall((i) + 1), d.w_nl((i) + 1)), om, d.speed_max((i) + 1));
            fs = (d.f_static((i) + 1) * s.fscale((i) + 1));
            st = asils.models.wheelfriction.stribeck_excess(om, d.f_static((i) + 1), d.coulomb((i) + 1), d.w_stribeck((i) + 1), s.fscale((i) + 1));
            if asils.models.wheelfriction.static_hold(h((i) + 1), (tm + nz), fs, dt)
                hd((i) + 1) = ((-(h((i) + 1))) / dt);
            else
                hd((i) + 1) = asils.models.wheelcomp.wheel_rate(tm, fr, st, nz, d.friction_comp);
            end
            hd((i) + 1) = asils.models.wheelspeed.momentum_limited(hd((i) + 1), h((i) + 1), d.h_max((i) + 1), (-(asils.models.wheelcomp.uncompensated(fr, d.friction_comp))));
            p = (p + asils.models.wheelpower.wheel_power(d.p_steady((i) + 1), tm, om, d.eta));
        elseif (d.kind((i) + 1) == 3)
            tcv = (asils.models.coilsat.act_clamp(cmd_r((i) + 1), (-(d.torque_max((i) + 1))), d.torque_max((i) + 1)) * s.tscale((i) + 1));
            omv = (h((i) + 1) / d.jrot((i) + 1));
            frv = asils.models.wheelfriction.bearing_friction(omv, d.coulomb((i) + 1), d.viscous((i) + 1), s.fscale((i) + 1));
            g2 = s.g;
            [t__31, t__32] = asils.models.wheelnoise.torque_noise(d.torque_noise, d.torque_max((i) + 1), g2);
            nzv = t__31;
            g2 = t__32;
            s.g = g2;
            hd((i) + 1) = asils.models.wheelspeed.momentum_limited(asils.models.vscmgmodel.vscmg_rate(tcv, frv, nzv, d.friction_comp), h((i) + 1), d.h_max((i) + 1), (-(asils.models.wheelcomp.uncompensated(frv, d.friction_comp))));
            p = (p + asils.models.wheelpower.wheel_power(d.p_steady((i) + 1), tcv, omv, d.eta));
        elseif (d.kind((i) + 1) == 1)
            tsd = d.t_sd((i) + 1);
            s.htgt((i) + 1) = asils.models.ringlimits.ring_target(s.htgt((i) + 1), cmd_r((i) + 1), dt, d.h_max((i) + 1));
            g3 = s.g;
            [t__33, t__34] = asils.models.ringnoise.measured_momentum(h((i) + 1), d.flow_noise_h((i) + 1), g3);
            hm = t__33;
            g3 = t__34;
            s.g = g3;
            s.hf((i) + 1) = asils.models.ringflow.flow_filter(s.hf((i) + 1), hm, d.flow_tau, dt);
            pump = asils.models.ringlimits.ring_pump(cmd_r((i) + 1), s.hf((i) + 1), tsd, d.k_flow, s.htgt((i) + 1), d.torque_max((i) + 1));
            hd((i) + 1) = asils.models.ringlimits.ring_rate(pump, h((i) + 1), tsd, s.fscale((i) + 1), d.h_max((i) + 1));
            p = (p + asils.models.ringpump.pump_power(pump, h((i) + 1), d.k_hv((i) + 1), d.l((i) + 1), d.s((i) + 1), d.ac((i) + 1), s.eta((i) + 1)));
            s.field_on((i) + 1) = asils.models.ringfield.field_switch(s.field_on((i) + 1), (asils.pc.fabs(s.htgt((i) + 1)) / d.h_max((i) + 1)), (asils.pc.fabs(cmd_r((i) + 1)) / d.torque_max((i) + 1)));
            if s.field_on((i) + 1)
                p = (p + asils.models.ringfield.field_power(s.field_on((i) + 1), d.field_power((i) + 1)));
            end
        else
            hd((i) + 1) = asils.models.cmgmodel.cmg_rate(h((i) + 1), d.h0((i) + 1), d.k_speed, d.torque_max((i) + 1));
            p = (p + d.p_steady((i) + 1));
        end
    end
    for j = (0):((d.ng) - 1)
        if (~s.gfailed((j) + 1))
            gd((j) + 1) = asils.models.gimbals.gimbal_rate(cmd_g((j) + 1), d.gimbal_rate_max);
            p = (p + asils.models.gimbals.gimbal_power(gd((j) + 1), d.gimbal_power, d.gimbal_rate_max));
        end
    end
end
