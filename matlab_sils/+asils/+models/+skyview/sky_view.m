function [b_b, sb, mb, nb, earth_ang] = sky_view(rb, b_eci, sun_rel, moon_rel, r)
%SKY_VIEW  The body field b_b [T], the Sun sb and the Moon mb (body, unit), nadir nb (body, unit) and the Earth's half-angle
%   earth_ang [rad], from the attitude matrix rb (ECI to body), the field b_eci [T], the Sun's and the Moon's positions
%   from the satellite sun_rel and moon_rel [m] and the satellite's position r [m] (ECI).
%   rb: real[1][3][3] (passed a plain number)
%   b_eci: real[1][3] (passed a plain number)
%   sun_rel: real[1][3] (passed a plain number)
%   moon_rel: real[1][3] (passed a plain number)
%   r: real[m][3] (passed in m)
%   returns b_b: real[1][3] (passed a plain number)
%   returns sb: real[1][3] (passed a plain number)
%   returns mb: real[1][3] (passed a plain number)
%   returns nb: real[1][3] (passed a plain number)
%   returns earth_ang: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    b_b = zeros(3, 1);
    sb = zeros(3, 1);
    mb = zeros(3, 1);
    nb = zeros(3, 1);
    earth_ang = 0;
    b_b = [rb(1, 1)*b_eci(1) + rb(1, 2)*b_eci(2) + rb(1, 3)*b_eci(3); rb(2, 1)*b_eci(1) + rb(2, 2)*b_eci(2) + rb(2, 3)*b_eci(3); rb(3, 1)*b_eci(1) + rb(3, 2)*b_eci(2) + rb(3, 3)*b_eci(3)];
    sb = asils.models.skyview.sky_unit([rb(1, 1)*sun_rel(1) + rb(1, 2)*sun_rel(2) + rb(1, 3)*sun_rel(3); rb(2, 1)*sun_rel(1) + rb(2, 2)*sun_rel(2) + rb(2, 3)*sun_rel(3); rb(3, 1)*sun_rel(1) + rb(3, 2)*sun_rel(2) + rb(3, 3)*sun_rel(3)]);
    mb = asils.models.skyview.sky_unit([rb(1, 1)*moon_rel(1) + rb(1, 2)*moon_rel(2) + rb(1, 3)*moon_rel(3); rb(2, 1)*moon_rel(1) + rb(2, 2)*moon_rel(2) + rb(2, 3)*moon_rel(3); rb(3, 1)*moon_rel(1) + rb(3, 2)*moon_rel(2) + rb(3, 3)*moon_rel(3)]);
    nb = ([rb(1, 1)*r(1) + rb(1, 2)*r(2) + rb(1, 3)*r(3); rb(2, 1)*r(1) + rb(2, 2)*r(2) + rb(2, 3)*r(3); rb(3, 1)*r(1) + rb(3, 2)*r(2) + rb(3, 3)*r(3)] * ((-(1)) / sqrt(r(1)*r(1) + r(2)*r(2) + r(3)*r(3))));
    h__679 = asin((6378137 / sqrt(r(1)*r(1) + r(2)*r(2) + r(3)*r(3))));
    if ~isreal(h__679), h__679 = NaN; end
    earth_ang = h__679;
end
