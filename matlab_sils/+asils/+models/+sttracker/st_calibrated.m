function [b, m] = st_calibrated(bias_sigma, misalign_sigma, cal_stated, cal)
%ST_CALIBRATED  The mount errors' sigmas [rad] a tracker flies: the part's bias and misalignment sigmas, or, for a tracker calibrated
%   on ground (cal_stated: its product states calibrated_residual_rad), the calibration's residual cal as the bias's sigma
%   and no misalignment.
%   bias_sigma: real[1] (passed a plain number)
%   misalign_sigma: real[1] (passed a plain number)
%   cal_stated: bool (passed true or false)
%   cal: real[1] (passed a plain number)
%   returns b: real[1] (passed a plain number)
%   returns m: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    b = 0;
    m = 0;
    b = bias_sigma;
    m = misalign_sigma;
    if cal_stated
        b = cal;
        m = 0;
    end
end
