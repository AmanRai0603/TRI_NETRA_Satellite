function [q, ok, cr, cm, g] = st_quest_head(rold, dq, bs, fov, noise_cross, smear, cr, cm, want, g, vb)
%ST_QUEST_HEAD  The QUEST model's attitude for a head of boresight bs: the 12 brightest catalogue stars (cr, cm) within the field fov
%   [rad] of the boresight seen at the attitude rold (ECI to body), each through the head's true mount dq with
%   cross-direction noise (noise_cross times the smear times sqrt 8), and the q-method on them when the head answers
%   (want); (q, whether three stars or more were in the field). Each star is seen where the observer's velocity vb [m/s]
%   relative to the barycentre shows it (st_aberrate) and the q-method takes the catalogue's geometric directions, as a
%   tracker without the velocity does (S12.5b, E2). The noise is drawn whether or not the head answers.
%   rold: real[1][3][3] (passed a plain number)
%   dq: real[1][4] (passed a plain number)
%   bs: real[1][3] (passed a plain number)
%   fov: real[1] (passed a plain number)
%   noise_cross: real[1] (passed a plain number)
%   smear: real[1] (passed a plain number)
%   cr: inout real[1][3][N_STARS] (passed a plain number)
%   cm: inout real[1][N_STARS] (passed a plain number)
%   want: bool (passed true or false)
%   g: inout stream (passed a random stream, as six numbers)
%   vb: real[m/s][3] (passed in m/s)
%   returns q: real[1][4] (passed a plain number)
%   returns ok: bool (passed true or false)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    q = zeros(4, 1);
    ok = false;
    bs_eci = asils.models.math.mat3t_vec(rold, bs);
    cf = cos(fov);
    sel = zeros(12, 1);
    smag = zeros(12, 1);
    i = ((0):((12) - 1)).';
    if ~isempty(i)
        smag((i) + 1) = 1000000000;
    end
    ns = 0;
    t__714 = ((0):((4000) - 1)).';
    for s = t__714(logical((~((bs_eci(1) .* cr((t__714) + 1, 1) + bs_eci(2) .* cr((t__714) + 1, 2) + bs_eci(3) .* cr((t__714) + 1, 3)) <= cf)))).'
        if (ns < 12)
            sel((ns) + 1) = s;
            smag((ns) + 1) = cm((s) + 1);
            ns = (ns + 1);
        else
            wi = 0;
            for i = (1):((12) - 1)
                if (smag((i) + 1) > smag((wi) + 1))
                    wi = i;
                end
            end
            if (cm((s) + 1) < smag((wi) + 1))
                sel((wi) + 1) = s;
                smag((wi) + 1) = cm((s) + 1);
            end
        end
    end
    q = [0; 0; 0; 1];
    ok = (ns >= 3);
    if ok
        rm = asils.pc.mm((asils.models.math.dcm(dq)).', rold);
        h__774 = 8;
        if h__774 < 0, h__774 = NaN; else, h__774 = sqrt(h__774); end
        sc = ((noise_cross * smear) * h__774);
        bm = zeros(32, 3);
        rr = zeros(32, 3);
        for i = (0):((ns) - 1)
            r = (cr((sel((i) + 1)) + 1, :)).';
            h__775 = asils.models.starcat.st_aberrate(r, vb);
            v = [rm(1, 1)*h__775(1) + rm(1, 2)*h__775(2) + rm(1, 3)*h__775(3); rm(2, 1)*h__775(1) + rm(2, 2)*h__775(2) + rm(2, 3)*h__775(3); rm(3, 1)*h__775(1) + rm(3, 2)*h__775(2) + rm(3, 3)*h__775(3)];
            [t__715, t__716] = asils.pc.stream_normal3(g);
            n0 = t__715;
            g = t__716;
            e0 = (n0 * sc);
            e = (e0 - (v * (v(1)*e0(1) + v(2)*e0(2) + v(3)*e0(3))));
            bm((i) + 1, :) = asils.models.facets.unit_or_zero((v + e)).';
            rr((i) + 1, :) = r.';
        end
        if want
            q = asils.models.stattitude.st_qmethod(bm, rr, ns);
        end
    end
end
