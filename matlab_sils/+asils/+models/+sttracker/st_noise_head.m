function [q, g] = st_noise_head(q_old, dq, bs, noise_cross, noise_roll, smear, g)
%ST_NOISE_HEAD  The noise model's attitude for a head of boresight bs: the attitude q_old through the head's mount dq, turned by
%   normal draws across the boresight (noise_cross) and about it (noise_roll), each times the smear.
%   q_old: real[1][4] (passed a plain number)
%   dq: real[1][4] (passed a plain number)
%   bs: real[1][3] (passed a plain number)
%   noise_cross: real[1] (passed a plain number)
%   noise_roll: real[1] (passed a plain number)
%   smear: real[1] (passed a plain number)
%   g: inout stream (passed a random stream, as six numbers)
%   returns q: real[1][4] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    q = zeros(4, 1);
    [t__150, t__151] = asils.pc.stream_normal3(g);
    n0 = t__150;
    g = t__151;
    [t__152, t__153] = asils.pc.stream_normal(g);
    nr = t__152;
    g = t__153;
    e0 = (n0 * (noise_cross * smear));
    e = ((e0 - (bs * asils.pc.dot_(bs, e0))) + (bs * ((noise_roll * smear) * nr)));
    q = asils.models.math.qnorm(asils.models.math.qmult(q_old, asils.models.math.qmult(dq, asils.models.math.fromrotvec(e))));
end
