function [te, r, v] = gps_delayed(ht, hr, hv, hn, latency, t)
%GPS_DELAYED  The truth the fix at t solves for, from the history: (its epoch, position, velocity).
%   ht: real[1][GPS_HIST] (passed a plain number)
%   hr: real[1][3][GPS_HIST] (passed a plain number)
%   hv: real[1][3][GPS_HIST] (passed a plain number)
%   hn: int (passed a whole number)
%   latency: real[1] (passed a plain number)
%   t: real[1] (passed a plain number)
%   returns te: real[1] (passed a plain number)
%   returns r: real[1][3] (passed a plain number)
%   returns v: real[1][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    te = 0;
    r = zeros(3, 1);
    v = zeros(3, 1);
    tl = (t - latency);
    te = t;
    r = [0; 0; 0];
    v = [0; 0; 0];
    if (hn > 0)
        k = 0;
        going = true;
        for j = (1):((hn) - 1)
            if (going && (ht((j) + 1) <= (tl + 1e-9)))
                k = j;
            else
                going = false;
            end
        end
        if (((k + 1) == hn) || (tl <= ht((k) + 1)))
            te = asils.pc.choose_lazy((tl > ht((k) + 1)), @() tl, @() ht((k) + 1));
            r = (hr((k) + 1, :)).';
            v = (hv((k) + 1, :)).';
        else
            s = ((tl - ht((k) + 1)) / (ht(((k + 1)) + 1) - ht((k) + 1)));
            te = tl;
            for i = (0):((3) - 1)
                r((i) + 1) = (hr((k) + 1, (i) + 1) + (s * (hr(((k + 1)) + 1, (i) + 1) - hr((k) + 1, (i) + 1))));
                v((i) + 1) = (hv((k) + 1, (i) + 1) + (s * (hv(((k + 1)) + 1, (i) + 1) - hv((k) + 1, (i) + 1))));
            end
        end
    end
end
