function [n, ht, hr, hv] = gps_history(ht, hr, hv, hn, latency, t, r, v)
%GPS_HISTORY  Record the truth (r, v) at t, every tick, into the history (its epochs ht, positions hr, velocities hv, the first hn
%   held); keep what a latency [s] reaches back to. The history's length after.
%   ht: inout real[1][GPS_HIST] (passed a plain number)
%   hr: inout real[1][3][GPS_HIST] (passed a plain number)
%   hv: inout real[1][3][GPS_HIST] (passed a plain number)
%   hn: int (passed a whole number)
%   latency: real[1] (passed a plain number)
%   t: real[1] (passed a plain number)
%   r: real[1][3] (passed a plain number)
%   v: real[1][3] (passed a plain number)
%   returns n: int (passed a whole number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    n = 0;
    n = hn;
    if (n == 256)
        for i = (1):((n) - 1)
            ht(((i - 1)) + 1) = ht((i) + 1);
            hr(((i - 1)) + 1, :) = (hr((i) + 1, :)).'.';
            hv(((i - 1)) + 1, :) = (hv((i) + 1, :)).'.';
        end
        n = (n - 1);
    end
    ht((n) + 1) = t;
    hr((n) + 1, :) = r.';
    hv((n) + 1, :) = v.';
    n = (n + 1);
    tl = (t - latency);
    k = 0;
    going = true;
    for j = (1):((n) - 1)
        if (going && (ht((j) + 1) <= (tl + 1e-9)))
            k = j;
        else
            going = false;
        end
    end
    if (k > 0)
        for m = (k):((n) - 1)
            ht(((m - k)) + 1) = ht((m) + 1);
            hr(((m - k)) + 1, :) = (hr((m) + 1, :)).'.';
            hv(((m - k)) + 1, :) = (hv((m) + 1, :)).'.';
        end
        n = (n - k);
    end
end
