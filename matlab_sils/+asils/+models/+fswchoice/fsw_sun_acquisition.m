function [eclipse, rz_floor, law] = fsw_sun_acquisition(a)
%FSW_SUN_ACQUISITION  The Sun acquisition's settings: its eclipse policy (1 E1, coils off; 2 E2, the Sun propagated on the gyro), the floor
%   of the nutation-damping matrix R_z as a share of J_zz (0: the published law), and its law (0 He et al. 2023 Sun spin,
%   1 de Ruiter 2011, 2 Celani 2026 boresight). With no Sun acquisition: E1, no floor, the Sun spin.
%   a: SunAcqAlg (passed a choice, as its option's number)
%   returns eclipse: int (passed a whole number)
%   returns rz_floor: real[1] (passed a plain number)
%   returns law: int (passed a whole number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    eclipse = 0;
    rz_floor = 0;
    law = 0;
    eclipse = 1;
    rz_floor = 0;
    law = 0;
    if (a == 1)
        eclipse = 2;
    elseif (a == 2)
        eclipse = 2;
        rz_floor = 0.5;
    elseif (a == 3)
        law = 1;
    elseif (a == 4)
        eclipse = 2;
        law = 2;
    end
end
