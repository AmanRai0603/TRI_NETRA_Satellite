function [a] = fast_accel(r, v, x, zonal_max, third_body, drag, srp, mass_kg, area_m2, cd, cr)
%FAST_ACCEL  The acceleration [m/s^2] at r, v (J2000) with the node context x: the point mass, the zonals up to degree
%   zonal_max - 1 (and at most 6), the Sun and the Moon (third_body), drag on a cannonball of area_m2 and mass_kg with
%   drag coefficient cd where there is air (drag), the Sun's pressure with reflectivity factor cr in the shadow (srp).
%   r: real[m][3] (passed in m)
%   v: real[m/s][3] (passed in m/s)
%   x: FastCtx (passed rec)
%   zonal_max: int (passed a whole number)
%   third_body: bool (passed true or false)
%   drag: bool (passed true or false)
%   srp: bool (passed true or false)
%   mass_kg: real[kg] (passed in kg)
%   area_m2: real[m^2] (passed in m^2)
%   cd: real[1] (passed a plain number)
%   cr: real[1] (passed a plain number)
%   returns a: real[m/s^2][3] (passed in m/s^2)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    a = zeros(3, 1);
    rn = sqrt(r(1)*r(1) + r(2)*r(2) + r(3)*r(3));
    a = (r * ((-(398600441800000)) / ((rn * rn) * rn)));
    s = (r(3) / rn);
    rh = (r * (1 / rn));
    pm1 = 1;
    p = s;
    dpm1 = 0;
    dp = 1;
    for n = (1):((zonal_max) - 1)
        nf = n;
        pn1 = ((((((2 * nf) + 1) * s) * p) - (nf * pm1)) / (nf + 1));
        dpn1 = (dpm1 + (((2 * nf) + 1) * p));
        pm1 = p;
        p = pn1;
        dpm1 = dp;
        dp = dpn1;
        deg = (n + 1);
        if ((deg >= 2) && (deg < 7))
            df = deg;
            q = (6378137 / rn);
            qn = 1;
            for k = (0):((deg) - 1)
                qn = (qn * q);
            end
            f = ((((-(398600441800000)) * [0.0; 0.0; 0.00108262668; -0.00000253265649; -0.00000161962159; -2.27296083e-7; 5.40681239e-7]((deg) + 1)) * qn) / rn);
            for i = (0):((3) - 1)
                zi = asils.pc.choose((i == 2), 1, 0);
                a((i) + 1) = (a((i) + 1) + ((f / rn) * ((((-((df + 1))) * p) * rh((i) + 1)) + (dp * (zi - (s * rh((i) + 1)))))));
            end
        end
    end
    if third_body
        a = (a + asils.models.orbitfast.point_mass(r, x.sun, 132712440018000000000));
        a = (a + asils.models.orbitfast.point_mass(r, x.moon, 4902800000000));
    end
    am = (area_m2 / mass_kg);
    if (drag && (x.rho > 0))
        vr = asils.models.orbitfast.corotating_velocity(r, v, 0.00007292115);
        vn = sqrt(vr(1)*vr(1) + vr(2)*vr(2) + vr(3)*vr(3));
        for i = (0):((3) - 1)
            a((i) + 1) = (a((i) + 1) - (((((0.5 * cd) * am) * x.rho) * vn) * vr((i) + 1)));
        end
    end
    if srp
        nu = asils.models.shadow.shadow_fraction(r, x.sun);
        if (nu > 0)
            d = (r - x.sun);
            dn = sqrt(d(1)*d(1) + d(2)*d(2) + d(3)*d(3));
            for i = (0):((3) - 1)
                a((i) + 1) = (a((i) + 1) + (((((nu * x.p_srp) * cr) * am) * d((i) + 1)) / dn));
            end
        end
    end
end
