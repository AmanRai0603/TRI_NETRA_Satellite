function [ok, cbar, sbar, c, s, f1, f2] = sph_setup(nmax, cbar, sbar, stride, c, s, f1, f2)
%SPH_SETUP  sphericalHarmonic's denormalised C and S of a field to degree nmax (row-major, stride nmax + 1) from its normalised
%   Cbar and Sbar (row-major, stride `stride`), and the recursion's factors (2n - 1)/(n - m) and (n + m - 1)/(n - m)
%   (stride nmax + 3), the same divisions the MATLAB makes on every call.
%   vectors: 2
%   nmax: int (passed a whole number)
%   cbar: inout real[1][GRAV_CS] (passed a plain number)
%   sbar: inout real[1][GRAV_CS] (passed a plain number)
%   stride: int (passed a whole number)
%   c: inout real[1][GRAV_CS] (passed a plain number)
%   s: inout real[1][GRAV_CS] (passed a plain number)
%   f1: inout real[1][GRAV_VS] (passed a plain number)
%   f2: inout real[1][GRAV_VS] (passed a plain number)
%   returns ok: bool (passed true or false)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    ok = false;
    cs = (nmax + 1);
    for n = (0):(((nmax + 1)) - 1)
        for m = (0):(((n + 1)) - 1)
            pi_ = asils.models.gravity.denorm_factor(n, m);
            c((((n * cs) + m)) + 1) = (cbar((((n * stride) + m)) + 1) * pi_);
            if (m > 0)
                s((((n * cs) + m)) + 1) = (sbar((((n * stride) + m)) + 1) * pi_);
            end
        end
    end
    vs = (nmax + 3);
    for m = (1):(((nmax + 2)) - 1)
        for n = ((m + 2)):(((nmax + 2)) - 1)
            nf = n;
            mf = m;
            f1((((n * vs) + m)) + 1) = (((2 * nf) - 1) / (nf - mf));
            f2((((n * vs) + m)) + 1) = (((nf + mf) - 1) / (nf - mf));
        end
    end
    ok = true;
end
