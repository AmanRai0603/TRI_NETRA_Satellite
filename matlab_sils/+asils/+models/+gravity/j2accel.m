function [a, c, s, f1, f2, v, w] = j2accel(r, mu, re, j, nj, use_sh, c, s, f1, f2, v, w)
%J2ACCEL  grav.j2accel(r_ecef, mu, Re, J): the central term, J2's closed form, and, when a J3 .. J6 is not zero, the zonal
%   spherical harmonics to degree nj + 1 (set up from zonal_c, workspace c, s, f1, f2, v, w) less their central term.
%   vectors: 2
%   r: real[1][3] (passed a plain number)
%   mu: real[1] (passed a plain number)
%   re: real[1] (passed a plain number)
%   j: real[1][5] (passed a plain number)
%   nj: int (passed a whole number)
%   use_sh: bool (passed true or false)
%   c: inout real[1][GRAV_CS] (passed a plain number)
%   s: inout real[1][GRAV_CS] (passed a plain number)
%   f1: inout real[1][GRAV_VS] (passed a plain number)
%   f2: inout real[1][GRAV_VS] (passed a plain number)
%   v: inout real[1][GRAV_VS] (passed a plain number)
%   w: inout real[1][GRAV_VS] (passed a plain number)
%   returns a: real[1][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    a = zeros(3, 1);
    rn = asils.models.gravity.onorm(r);
    rn3 = (rn)^(3);
    a = [(((-(mu)) * r(1)) / rn3); (((-(mu)) * r(2)) / rn3); (((-(mu)) * r(3)) / rn3)];
    if (nj > 0)
        if (j(1) ~= 0)
            j2 = j(1);
            u = (r(3) / rn);
            k = ((((1.5 * j2) * mu) * asils.pc.ipow(re, 2)) / (rn)^(4));
            u2 = asils.pc.ipow(u, 2);
            a(1) = (a(1) + (((k * ((5 * u2) - 1)) * r(1)) / rn));
            a(2) = (a(2) + (((k * ((5 * u2) - 1)) * r(2)) / rn));
            a(3) = (a(3) + (((k * ((5 * u2) - 3)) * r(3)) / rn));
        end
        if use_sh
            maxn = (nj + 1);
            [t__69, t__70, t__71, t__72, t__73, t__74, t__75] = asils.models.gravity.sph_accel(r, mu, re, maxn, maxn, 0, c, s, f1, f2, v, w);
            sh = t__69;
            c = t__70;
            s = t__71;
            f1 = t__72;
            f2 = t__73;
            v = t__74;
            w = t__75;
            tb = asils.models.gravity.two_body(r, mu);
            for i = (0):((3) - 1)
                a((i) + 1) = ((a((i) + 1) + sh((i) + 1)) - tb((i) + 1));
            end
        end
    end
end
