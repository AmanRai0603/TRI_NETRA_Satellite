function [a, c, s, f1, f2, v, w] = sph_accel(r, mu, re, nws, nmax, mmax_in, c, s, f1, f2, v, w)
%SPH_ACCEL  grav.sphericalHarmonic(r_ecef, mu, Re, Cbar, Sbar, nmax, mmax): the ECEF acceleration [m/s^2], central term
%   included, over a field set up to degree nws (sph_setup), to degree nmax and order min(mmax, nmax). V and W are the
%   recursion's workspace (stride nws + 3); they are filled row by row, which makes the operations the MATLAB's column
%   by column fill makes, on the same operands.
%   vectors: 2
%   r: real[1][3] (passed a plain number)
%   mu: real[1] (passed a plain number)
%   re: real[1] (passed a plain number)
%   nws: int (passed a whole number)
%   nmax: int (passed a whole number)
%   mmax_in: int (passed a whole number)
%   c: inout real[1][GRAV_CS] (passed a plain number)
%   s: inout real[1][GRAV_CS] (passed a plain number)
%   f1: inout real[1][GRAV_VS] (passed a plain number)
%   f2: inout real[1][GRAV_VS] (passed a plain number)
%   v: inout real[1][GRAV_VS] (passed a plain number)
%   w: inout real[1][GRAV_VS] (passed a plain number)
%   returns a: real[1][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    a = zeros(3, 1);
    mmax = asils.pc.fmin(mmax_in, nmax);
    x = r(1);
    y = r(2);
    z = r(3);
    r2 = (((x * x) + (y * y)) + (z * z));
    rn = asils.pc.sqrt_(r2);
    xf = ((re * x) / r2);
    yf = ((re * y) / r2);
    zf = ((re * z) / r2);
    rr2 = ((re * re) / r2);
    vs = (nws + 3);
    v(1) = (re / rn);
    w(1) = 0;
    mcol = (mmax + 1);
    for n = (1):(((nmax + 2)) - 1)
        nf = n;
        row = (n * vs);
        row1 = (row - vs);
        if (n == 1)
            v((row) + 1) = ((zf * 1) * v((row1) + 1));
        else
            row2 = (row - (2 * vs));
            v((row) + 1) = ((((((2 * nf) - 1) * zf) * v((row1) + 1)) - (((nf - 1) * rr2) * v((row2) + 1))) / nf);
        end
        w((row) + 1) = 0;
        if (n >= 3)
            mg = asils.pc.fmin((n - 2), mcol);
            rowb = (row - (2 * vs));
            for m = (1):(((mg + 1)) - 1)
                v(((row + m)) + 1) = (((f1(((row + m)) + 1) * zf) * v(((row1 + m)) + 1)) - ((f2(((row + m)) + 1) * rr2) * v(((rowb + m)) + 1)));
                w(((row + m)) + 1) = (((f1(((row + m)) + 1) * zf) * w(((row1 + m)) + 1)) - ((f2(((row + m)) + 1) * rr2) * w(((rowb + m)) + 1)));
            end
        end
        if ((n >= 2) && ((n - 1) <= mcol))
            md = (n - 1);
            mf = md;
            v(((row + md)) + 1) = ((((2 * mf) + 1) * zf) * v(((row1 + md)) + 1));
            w(((row + md)) + 1) = ((((2 * mf) + 1) * zf) * w(((row1 + md)) + 1));
        end
        if (n <= mcol)
            vp = v((((row1 + n) - 1)) + 1);
            wp = w((((row1 + n) - 1)) + 1);
            v(((row + n)) + 1) = (((2 * nf) - 1) * ((xf * vp) - (yf * wp)));
            w(((row + n)) + 1) = (((2 * nf) - 1) * ((xf * wp) + (yf * vp)));
        end
    end
    ax = 0;
    ay = 0;
    az = 0;
    cs = (nws + 1);
    for n = (0):(((nmax + 1)) - 1)
        mt = asils.pc.fmin(n, mmax);
        rowa = ((n + 1) * vs);
        c0 = c(((n * cs)) + 1);
        s0 = s(((n * cs)) + 1);
        if (~((c0 == 0) && (s0 == 0)))
            ax = (ax - (c0 * v(((rowa + 1)) + 1)));
            ay = (ay - (c0 * w(((rowa + 1)) + 1)));
            az = (az + ((n + 1) * (((-(c0)) * v((rowa) + 1)) - (s0 * w((rowa) + 1)))));
        end
        for m = (1):(((mt + 1)) - 1)
            cnm = c((((n * cs) + m)) + 1);
            snm = s((((n * cs) + m)) + 1);
            if (~((cnm == 0) && (snm == 0)))
                fac = (((n - m) + 1) * ((n - m) + 2));
                vp1 = v((((rowa + m) + 1)) + 1);
                wp1 = w((((rowa + m) + 1)) + 1);
                vm1 = v((((rowa + m) - 1)) + 1);
                wm1 = w((((rowa + m) - 1)) + 1);
                ax = (ax + (0.5 * ((((-(cnm)) * vp1) - (snm * wp1)) + (fac * ((cnm * vm1) + (snm * wm1))))));
                ay = (ay + (0.5 * ((((-(cnm)) * wp1) + (snm * vp1)) + (fac * (((-(cnm)) * wm1) + (snm * vm1))))));
                az = (az + (((n - m) + 1) * (((-(cnm)) * v(((rowa + m)) + 1)) - (snm * w(((rowa + m)) + 1)))));
            end
        end
    end
    scale = (mu / (re * re));
    a = [(scale * ax); (scale * ay); (scale * az)];
end
