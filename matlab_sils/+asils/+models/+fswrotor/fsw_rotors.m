function [nr, ngo, rot_kind, rot_a0, rot_gi, gim_axis, rot_tmax, rot_hmax, rot_h0, gim_rate_max] = fsw_rotors(n, ng, kind, a0, gi, g, tmax, hmax, h0, rate_max)
%FSW_ROTORS  The product's n rotors and ng gimbals as the flight software's parameters: nr, ng, rot_kind, rot_a0, rot_gi (the gimbal
%   from 1; 0 fixed), rot_tmax [N m], rot_hmax [N m s], rot_h0 [N m s], gim_axis, gim_rate_max [rad/s].
%   n: int (passed a whole number)
%   ng: int (passed a whole number)
%   kind: int[FSW_NR] (passed a whole number)
%   a0: real[1][3][FSW_NR] (passed a plain number)
%   gi: int[FSW_NR] (passed a whole number)
%   g: real[1][3][FSW_NG] (passed a plain number)
%   tmax: real[1][FSW_NR] (passed a plain number)
%   hmax: real[1][FSW_NR] (passed a plain number)
%   h0: real[1][FSW_NR] (passed a plain number)
%   rate_max: real[1] (passed a plain number)
%   returns nr: int (passed a whole number)
%   returns ngo: int (passed a whole number)
%   returns rot_kind: int[FSW_NR] (passed a whole number)
%   returns rot_a0: real[1][3][FSW_NR] (passed a plain number)
%   returns rot_gi: int[FSW_NR] (passed a whole number)
%   returns gim_axis: real[1][3][FSW_NG] (passed a plain number)
%   returns rot_tmax: real[1][FSW_NR] (passed a plain number)
%   returns rot_hmax: real[1][FSW_NR] (passed a plain number)
%   returns rot_h0: real[1][FSW_NR] (passed a plain number)
%   returns gim_rate_max: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    nr = 0;
    ngo = 0;
    rot_kind = zeros(8, 1);
    rot_a0 = zeros(8, 3);
    rot_gi = zeros(8, 1);
    gim_axis = zeros(4, 3);
    rot_tmax = zeros(8, 1);
    rot_hmax = zeros(8, 1);
    rot_h0 = zeros(8, 1);
    gim_rate_max = 0;
    nr = n;
    ngo = ng;
    rot_kind = zeros(8, 1);
    rot_a0 = zeros(8, 3);
    rot_gi = zeros(8, 1);
    gim_axis = zeros(4, 3);
    rot_tmax = zeros(8, 1);
    rot_hmax = zeros(8, 1);
    rot_h0 = zeros(8, 1);
    for i = (0):((8) - 1)
        if (i < n)
            rot_kind((i) + 1) = kind((i) + 1);
            for k = (0):((3) - 1)
                rot_a0((i) + 1, (k) + 1) = a0((i) + 1, (k) + 1);
            end
            rot_gi((i) + 1) = gi((i) + 1);
            rot_tmax((i) + 1) = tmax((i) + 1);
            rot_hmax((i) + 1) = hmax((i) + 1);
            rot_h0((i) + 1) = h0((i) + 1);
        end
    end
    for m = (0):((4) - 1)
        if (m < ng)
            for k = (0):((3) - 1)
                gim_axis((m) + 1, (k) + 1) = g((m) + 1, (k) + 1);
            end
        end
    end
    gim_rate_max = asils.pc.choose((ng > 0), rate_max, 1);
end
