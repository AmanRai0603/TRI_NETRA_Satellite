function [tot, mode_ix, feasible, usable, vstart, vval, vperf] = loop_family_violation(mode_ix, feasible, usable, b, vstart, vval, vperf, no, nm)
%LOOP_FAMILY_VIOLATION  A family's requirement violation (pipeline_base's fam_violation): for each of the nm modes, among the family's usable
%   options of that mode (bit b of usable), the least violation (0 for a feasible option, else the sum of its violations, the
%   first of equals), summed over the modes that have one.
%   length: 16
%   mode_ix: inout int[*] (passed a whole number)
%   feasible: inout int[*] (passed a whole number)
%   usable: inout int[*] (passed a whole number)
%   b: int (passed a whole number)
%   vstart: inout int[*] (passed a whole number)
%   vval: inout real[1][*] (passed a plain number)
%   vperf: inout int[*] (passed a whole number)
%   no: int (passed a whole number)
%   nm: int (passed a whole number)
%   returns tot: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    tot = 0;
    tot = 0;
    for m = (0):((nm) - 1)
        have = false;
        best = 0;
        for i = (0):((asils.pc.fmin(no, (numel(vstart) - 1))) - 1)
            if ((mode_ix((i) + 1) == m) && (bitand(bitshift(usable((i) + 1), -(b)), 1) == 1))
                x = 0;
                if (feasible((i) + 1) == 0)
                    [t__53, t__54, t__55] = asils.models.looprules.loop_option_violation(vval, vperf, vstart((i) + 1), vstart(((i + 1)) + 1), false);
                    x = t__53;
                    vval = t__54;
                    vperf = t__55;
                end
                if (~have)
                    best = x;
                    have = true;
                elseif (x < best)
                    best = x;
                end
            end
        end
        if have
            tot = (tot + best);
        end
    end
end
