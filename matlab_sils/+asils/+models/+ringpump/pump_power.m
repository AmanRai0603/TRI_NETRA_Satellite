function [p] = pump_power(pump, h, k_hv, l, s, ac, eta)
%PUMP_POWER  The pump's power [W] at torque pump [N m], the ring's momentum h [N m s] and its constants: momentum per flow speed
%   k_hv [N m s/(m/s)], channel length l [m], enclosed area s [m^2], bore area ac [m^2], efficiency eta.
%   pump: real[1] (passed a plain number)
%   h: real[1] (passed a plain number)
%   k_hv: real[1] (passed a plain number)
%   l: real[1] (passed a plain number)
%   s: real[1] (passed a plain number)
%   ac: real[1] (passed a plain number)
%   eta: real[1] (passed a plain number)
%   returns p: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    p = 0;
    v = (h / k_hv);
    dp = ((pump * l) / ((2 * s) * ac));
    p = (asils.pc.fabs(((dp * ac) * v)) / eta);
end
