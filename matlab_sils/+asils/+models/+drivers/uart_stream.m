function [b, len] = uart_stream(junk, nj, pl, n, sync2, fault, k)
%UART_STREAM  Test streams for the frame search (the vectors draw through it): nj junk bytes, a frame of the
%   n bytes pl, then (fault 1 .. 3) a second frame of pl turned by k, cut one byte short (1), with
%   a broken CRC (2) or whole (3).
%   junk: int[8] (passed a whole number)
%   nj: int (passed a whole number)
%   pl: int[36] (passed a whole number)
%   n: int (passed a whole number)
%   sync2: int (passed a whole number)
%   fault: int (passed a whole number)
%   k: int (passed a whole number)
%   returns b: int[96] (passed a whole number)
%   returns len: int (passed a whole number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    b = zeros(96, 1);
    len = 0;
    b = zeros(96, 1);
    len = 0;
    for i = (0):((nj) - 1)
        b((len) + 1) = junk((i) + 1);
        len = (len + 1);
    end
    nf = asils.pc.choose((fault == 0), 1, 2);
    for f = (0):((nf) - 1)
        p = zeros(64, 1);
        for i = (0):((n) - 1)
            p((i) + 1) = asils.pc.choose_lazy((f == 0), @() pl((i) + 1), @() pl((rem((i + k), 36)) + 1));
        end
        c = asils.models.drivers.crc16(p, n);
        if ((f == 1) && (fault == 2))
            c = bitxor(c, 1);
        end
        b((len) + 1) = 235;
        b(((len + 1)) + 1) = sync2;
        b(((len + 2)) + 1) = n;
        for i = (0):((n) - 1)
            b((((len + 3) + i)) + 1) = p((i) + 1);
        end
        b((((len + 3) + n)) + 1) = bitand(c, 255);
        b((((len + 4) + n)) + 1) = bitshift(c, -(8));
        len = ((len + n) + 5);
        if ((f == 1) && (fault == 1))
            len = (len - 1);
        end
    end
end
