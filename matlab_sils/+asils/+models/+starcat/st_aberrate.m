function [p] = st_aberrate(s, v)
%ST_ABERRATE  The direction a star appears in, to an observer moving at v [m/s] relative to the solar-system barycentre (J2000
%   axes), from its geometric direction s (unit, from the observer): the aberration of starlight to first order in v/c,
%   p = (s + v/c - s (s . v/c)) normalised, the star displaced towards the direction of motion by (|v|/c) sin(the angle
%   between s and v), at most 1.24e-4 rad at the 37.4 km/s of the Earth's orbital speed plus a low orbit's. The exact
%   special-relativistic form is the one the Explanatory Supplement to the Astronomical Almanac gives (Urban and Seidelmann
%   (eds.), 3rd edition, 2013, the chapter on aberration: p' = (s / gamma + (1 + (s . V)/(1 + 1/gamma)) V)/(1 + s . V),
%   V = v/c; the edition and the section were not to hand and the form is quoted from memory, not verified) and ERFA's ab
%   (the IAU SOFA library's iauAb): the first-order form differs from erfa.ab by less than 2e-8 rad at 37.4 km/s (the (v/c)^2
%   of the terms it drops; tests/test_aberration_oracle.py). The velocity is the spacecraft's geometric velocity relative to the
%   barycentre: its orbital velocity plus the Earth's (the truth's ephemeris gives the Earth's).
%   s: real[1][3] (passed a plain number)
%   v: real[m/s][3] (passed in m/s)
%   returns p: real[1][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    p = zeros(3, 1);
    vc = (v / 299792458);
    h__716 = ((s + vc) - (s * (s(1)*vc(1) + s(2)*vc(2) + s(3)*vc(3))));
    h__717 = sqrt(h__716(1)*h__716(1) + h__716(2)*h__716(2) + h__716(3)*h__716(3));
    if 1e-30 > h__717, h__717 = 1e-30; end
    p = (h__716 / h__717);
end
