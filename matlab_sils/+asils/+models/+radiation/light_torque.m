function [tau] = light_torque(rm, r, sun_rel, nu, p_srp, g)
%LIGHT_TORQUE  The radiation torque [N m], body axes: the Sun's light (the Sun at sun_rel from the satellite, nu its sunlit
%   fraction, p_srp its pressure at the satellite) and the Earth's albedo and infrared from the nadir; r the inertial
%   position, rm the inertial-to-body matrix.
%   rm: real[1][3][3] (passed a plain number)
%   r: real[m][3] (passed in m)
%   sun_rel: real[m][3] (passed in m)
%   nu: real[1] (passed a plain number)
%   p_srp: real[Pa] (passed in kg/(m s^2))
%   g: Facets (passed rec)
%   returns tau: real[N m][3] (passed in m^2 kg/s^2)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    tau = zeros(3, 1);
    sun = [0; 0; 0];
    if (nu > 0)
        sun = asils.models.radiation.radiation_torque(g, asils.models.facets.unit_or_zero(([rm(1, 1)*sun_rel(1) + rm(1, 2)*sun_rel(2) + rm(1, 3)*sun_rel(3); rm(2, 1)*sun_rel(1) + rm(2, 2)*sun_rel(2) + rm(2, 3)*sun_rel(3); rm(3, 1)*sun_rel(1) + rm(3, 2)*sun_rel(2) + rm(3, 3)*sun_rel(3)] * 1)), (nu * p_srp));
    end
    p_earth = (asils.models.albedo.albedo_pressure(r, sun_rel, p_srp) + asils.models.earthir.earth_ir_pressure(r));
    eb = asils.models.facets.unit_or_zero(([rm(1, 1)*r(1) + rm(1, 2)*r(2) + rm(1, 3)*r(3); rm(2, 1)*r(1) + rm(2, 2)*r(2) + rm(2, 3)*r(3); rm(3, 1)*r(1) + rm(3, 2)*r(2) + rm(3, 3)*r(3)] * (-(1))));
    tau = (sun + asils.models.radiation.radiation_torque(g, eb, p_earth));
end
