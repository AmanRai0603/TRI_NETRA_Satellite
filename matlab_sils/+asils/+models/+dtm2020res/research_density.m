function [ok, o] = research_density(alt_km, lat_deg, lon_deg, lst_hours, doy, f30, f30_bar, ap60)
%RESEARCH_DENSITY  dtm2020_density: the research model at a geodetic altitude [km], latitude and longitude [deg], local solar time [h],
%   day of year, F30 and its mean on the F10.7 scale [sfu] and the 10-slot ap60; ok is false at or below 120 km, or
%   where geogm fails.
%   alt_km: real[1] (passed a plain number)
%   lat_deg: real[1] (passed a plain number)
%   lon_deg: real[1] (passed a plain number)
%   lst_hours: real[1] (passed a plain number)
%   doy: real[1] (passed a plain number)
%   f30: real[1] (passed a plain number)
%   f30_bar: real[1] (passed a plain number)
%   ap60: real[1][10] (passed a plain number)
%   returns ok: bool (passed true or false)
%   returns o: DtmDensity (passed rec)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    ok = false;
    o = asils.models.dtm2020.DtmDensity_zero();
    o = asils.models.dtm2020.DtmDensity_zero();
    ok = (alt_km > 120);
    if ok
        hl = (((lst_hours / 24) * 2) * pi);
        alat = asils.models.timescales.deg2rad(lat_deg);
        xlon = asils.models.timescales.deg2rad(lon_deg);
        [ok5, raw] = asils.models.dtm2020res.dtm5(doy, f30, f30_bar, ap60, alt_km, hl, alat, xlon);
        ok = ok5;
        if ok
            o = asils.models.dtm2020.dtm_pack(raw);
        end
    end
end
