function [ok, o] = dtm5(day, f, fbar, ap60, alti, hl, alat, xlon)
%DTM5  dtm5: the research DTM2020 at day of year day, F30 on the F10.7 scale f and its mean fbar [sfu], the 10-slot ap60,
%   altitude alti [km], local solar time hl [rad], latitude alat and longitude xlon [rad]; ok is false only where geogm
%   would raise its angle error.
%   day: real[1] (passed a plain number)
%   f: real[1] (passed a plain number)
%   fbar: real[1] (passed a plain number)
%   ap60: real[1][10] (passed a plain number)
%   alti: real[1] (passed a plain number)
%   hl: real[1] (passed a plain number)
%   alat: real[1] (passed a plain number)
%   xlon: real[1] (passed a plain number)
%   returns ok: bool (passed true or false)
%   returns o: DtmRaw (passed rec)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    ok = false;
    o = asils.models.dtm2020.DtmRaw_zero();
    o = asils.models.dtm2020.DtmRaw_zero();
    plg = asils.models.dtm2020.plg_geographic(alat);
    crd = (180 / pi);
    dlat = (alat * crd);
    dlon = (xlon * crd);
    [gmlatd, gmlond, gok] = asils.models.dtm2020res.geogm(dlat, dlon);
    ok = gok;
    if ok
        gmlatr = (gmlatd * (pi / 180));
        cm = sin(gmlatr);
        cm2 = (cm)^(2);
        cm4 = (cm2)^(2);
        sm = cos(gmlatr);
        sm2 = (sm)^(2);
        plg.p10mg = cm;
        plg.p20mg = ((1.5 * cm2) - 0.5);
        plg.p30mg = (cm * ((2.5 * cm2) - 1.5));
        plg.p40mg = (((4.375 * cm4) - (3.75 * cm2)) + 0.375);
        plg.p50mg = (cm * (((7.875 * cm4) - (8.75 * cm2)) + 1.875));
        plg.p60mg = ((((5.5 * cm) * plg.p50mg) - (2.5 * plg.p40mg)) / 3);
        plg.p11mg = sm;
        plg.p22mg = (3 * sm2);
        plg.p31mg = (sm * ((7.5 * cm2) - 1.5));
        hloc = asils.models.dtm2020.hloc_of(hl);
        latabs = floor(asils.pc.fabs(dlat));
        ap_eff = 0;
        if (latabs >= 70)
            xl75 = ((90 - latabs) / 20);
            ap_eff = (((1 - xl75) * (((ap60(3) + ap60(2)) + ap60(4)) / 3)) + (xl75 * (((ap60(3) + ap60(4)) + ap60(5)) / 3)));
        elseif (latabs >= 30)
            xl45 = ((69 - latabs) / 40);
            ap_eff = (((1 - xl45) * (((ap60(3) + ap60(4)) + ap60(5)) / 3)) + (xl45 * (((ap60(5) + ap60(4)) + ap60(1)) / 3)));
        else
            ap_eff = (((ap60(4) + ap60(5)) + ap60(1)) / 3);
        end
        akp = [asils.models.dtm2020res.bint_oe(ap_eff); (asils.models.dtm2020res.bint_oe(ap60(2)) - asils.models.dtm2020res.bint_oe(ap60(3))); asils.models.dtm2020res.bint_oe(ap60(6)); 0; asils.models.dtm2020res.bint_oe(ap60(7)); asils.models.dtm2020res.bint_oe(ap60(8)); asils.models.dtm2020res.bint_oe(ap60(9)); asils.models.dtm2020res.bint_oe(ap60(10))];
        [gd_tt, gd_t0, gd_tp, gd] = asils.models.dtm2020res.dtm5_gdel(f, fbar, akp, day, plg, hloc, xlon);
        o = asils.models.dtm2020.dtm_profile(1, gd_tt, gd_t0, gd_tp, gd, alti);
    end
end
