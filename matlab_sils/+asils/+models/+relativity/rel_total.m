function [ok, a, parts] = rel_total(r, v, has_helio, helio_pos, helio_vel, terms, nterms, mu)
%REL_TOTAL  [a, parts] = relativity.total(rSat, vSat, E, terms, mu): the terms asked for (their numbers, nterms of them, at most 8, in the
%   order given; Lense-Thirring with J of the Earth, gamma = beta = 1) summed; ok is false when de Sitter is asked for
%   without the Earth's heliocentric state (has_helio), the MATLAB's relativity:total:noEphem.
%   r: real[1][3] (passed a plain number)
%   v: real[1][3] (passed a plain number)
%   has_helio: bool (passed true or false)
%   helio_pos: real[1][3] (passed a plain number)
%   helio_vel: real[1][3] (passed a plain number)
%   terms: int[8] (passed a whole number)
%   nterms: int (passed a whole number)
%   mu: real[1] (passed a plain number)
%   returns ok: bool (passed true or false)
%   returns a: real[1][3] (passed a plain number)
%   returns parts: RelParts (passed rec)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    ok = false;
    a = zeros(3, 1);
    parts = asils.models.relativity.RelParts_zero();
    a = zeros(3, 1);
    parts = asils.models.relativity.RelParts_zero();
    ok = true;
    for i = (0):((nterms) - 1)
        if ok
            p = zeros(3, 1);
            if (terms((i) + 1) == fix(0))
                p = asils.models.relativity.schwarzschild(r, v, mu, 1, 1);
                parts.has_schwarzschild = true;
                parts.schwarzschild = p;
            elseif (terms((i) + 1) == fix(1))
                p = asils.models.relativity.lense_thirring(r, v, mu, asils.models.relativity.j_earth(), 1);
                parts.has_lensethirring = true;
                parts.lensethirring = p;
            elseif has_helio
                p = asils.models.relativity.de_sitter(r, v, helio_pos, helio_vel, 1);
                parts.has_desitter = true;
                parts.desitter = p;
            else
                ok = false;
            end
            if ok
                k = ((0):((3) - 1)).';
                a((k) + 1) = (reshape(a((k) + 1), [], 1) + reshape(p((k) + 1), [], 1));
            end
        end
    end
end
