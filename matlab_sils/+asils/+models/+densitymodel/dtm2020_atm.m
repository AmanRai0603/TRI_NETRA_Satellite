function [st, a] = dtm2020_atm(alt_km, lat_deg, lon_deg, lst_h, doy, f107, f107a, akp)
%DTM2020_ATM  atmos.dtm2020(geo, sw): the operational DTM2020 with the species turned into m^-3.
%   alt_km: real[1] (passed a plain number)
%   lat_deg: real[1] (passed a plain number)
%   lon_deg: real[1] (passed a plain number)
%   lst_h: real[1] (passed a plain number)
%   doy: real[1] (passed a plain number)
%   f107: real[1] (passed a plain number)
%   f107a: real[1] (passed a plain number)
%   akp: real[1][4] (passed a plain number)
%   returns st: AtmosStatus (passed a choice, as its option's number)
%   returns a: AtmosOut (passed rec)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    st = 0;
    a = asils.models.densitymodel.AtmosOut_zero();
    a = asils.models.densitymodel.AtmosOut_zero();
    st = 0;
    if (~isfinite(f107))
        st = 1;
    elseif (~isfinite(f107a))
        st = 2;
    elseif (~(((isfinite(akp(1)) && isfinite(akp(2))) && isfinite(akp(3))) && isfinite(akp(4))))
        st = 3;
    else
        [ok, o] = asils.models.dtm2020.oper_density(alt_km, lat_deg, lon_deg, lst_h, doy, f107, f107a, akp);
        if (~ok)
            st = 8;
        else
            a.rho = o.rho_kgm3;
            a.t = o.t_k;
            a.species = true;
            for i = (0):((6) - 1)
                a.n((i) + 1) = (o.n_cm3((i) + 1) * 1000000);
            end
        end
    end
end
