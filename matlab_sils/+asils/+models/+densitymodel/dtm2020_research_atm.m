function [st, a] = dtm2020_research_atm(alt_km, lat_deg, lon_deg, lst_h, doy, utc, f30, f30_bar, ap60, f30_is_derived)
%DTM2020_RESEARCH_ATM  atmos.dtm2020_research(geo, sw): F30 rescaled to the F10.7 scale with the decimal year's drift (unless the F30 was
%   itself derived from F10.7), ap60 in all ten slots; the species handed on per cm^3, as the MATLAB does.
%   alt_km: real[1] (passed a plain number)
%   lat_deg: real[1] (passed a plain number)
%   lon_deg: real[1] (passed a plain number)
%   lst_h: real[1] (passed a plain number)
%   doy: real[1] (passed a plain number)
%   utc: real[1][6] (passed a plain number)
%   f30: real[1] (passed a plain number)
%   f30_bar: real[1] (passed a plain number)
%   ap60: real[1] (passed a plain number)
%   f30_is_derived: bool (passed true or false)
%   returns st: AtmosStatus (passed a choice, as its option's number)
%   returns a: AtmosOut (passed rec)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    st = 0;
    a = asils.models.densitymodel.AtmosOut_zero();
    a = asils.models.densitymodel.AtmosOut_zero();
    st = 0;
    if (~isfinite(f30))
        st = 4;
    elseif (~isfinite(f30_bar))
        st = 5;
    elseif (~isfinite(ap60))
        st = 6;
    else
        fi = f30;
        fbi = f30_bar;
        if (~f30_is_derived)
            dy = asils.models.dtm2020res.dtm_decimal_year(utc);
            fi = asils.models.dtm2020res.f30_to_f107scale(f30, dy);
            fbi = asils.models.dtm2020res.f30_to_f107scale(f30_bar, dy);
        end
        ap = [ap60; ap60; ap60; ap60; ap60; ap60; ap60; ap60; ap60; ap60];
        if (alt_km <= 120)
            st = 8;
        else
            [ok, o] = asils.models.dtm2020res.research_density(alt_km, lat_deg, lon_deg, lst_h, doy, fi, fbi, ap);
            if (~ok)
                st = 9;
            else
                a.rho = o.rho_kgm3;
                a.t = o.t_k;
                a.species = true;
                a.n = o.n_cm3;
            end
        end
    end
end
