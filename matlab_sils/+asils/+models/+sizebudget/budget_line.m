function [n, m, p, v] = budget_line(s, na, ns, nb, nn, mass, ps, pw, pm, vol)
%BUDGET_LINE  One fill line of slot s: how many units (from the lengths of the axes, spin axes, boresights and normals it lists, -1
%   where it lists none), and their mass, power and volume from the part's mass, steady power ps, power pw, power at the
%   full dipole pm and volume (nan where the part states none).
%   s: Slot (passed a choice, as its option's number)
%   na: int (passed a whole number)
%   ns: int (passed a whole number)
%   nb: int (passed a whole number)
%   nn: int (passed a whole number)
%   mass: real[1] (passed a plain number)
%   ps: real[1] (passed a plain number)
%   pw: real[1] (passed a plain number)
%   pm: real[1] (passed a plain number)
%   vol: real[1] (passed a plain number)
%   returns n: real[1] (passed a plain number)
%   returns m: real[1] (passed a plain number)
%   returns p: real[1] (passed a plain number)
%   returns v: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    n = 0;
    m = 0;
    p = 0;
    v = 0;
    n = 1;
    counts = [na; ns; nb; nn];
    for i = (0):((4) - 1)
        if (counts((i) + 1) >= 0)
            n = counts((i) + 1);
            if (s == 12)
                n = 1;
            end
        end
    end
    mm = asils.pc.choose(isnan(mass), 0, mass);
    pp = 0;
    if (~isnan(ps))
        pp = ps;
    elseif (~isnan(pw))
        pp = pw;
    elseif (~isnan(pm))
        pp = pm;
    end
    vv = asils.pc.choose(isnan(vol), 0, vol);
    m = (n * mm);
    p = (n * pp);
    v = (n * vv);
end
