function [n, rcs_tau, rcs_mib, rcs_res] = fsw_thrusters(fitted, nc, tau, mib, res)
%FSW_THRUSTERS  The product's nc couples as the flight software's parameters: nc, rcs_tau, rcs_mib, rcs_res.
%   fitted: bool (passed true or false)
%   nc: int (passed a whole number)
%   tau: real[1][3][FSW_NC] (passed a plain number)
%   mib: real[1] (passed a plain number)
%   res: real[1] (passed a plain number)
%   returns n: int (passed a whole number)
%   returns rcs_tau: real[1][3][FSW_NC] (passed a plain number)
%   returns rcs_mib: real[1] (passed a plain number)
%   returns rcs_res: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    n = 0;
    rcs_tau = zeros(6, 3);
    rcs_mib = 0;
    rcs_res = 0;
    n = 0;
    rcs_tau = zeros(6, 3);
    rcs_mib = 0;
    rcs_res = 0;
    if fitted
        n = nc;
        t__509 = ((0):((6) - 1)).';
        for c = t__509(logical((t__509 < nc))).'
            k = ((0):((3) - 1)).';
            rcs_tau((c) + 1, (k) + 1) = ((tau((c) + 1, (k) + 1)).').';
        end
        rcs_mib = mib;
        rcs_res = res;
    end
    if (~isfinite(rcs_mib))
        rcs_mib = 0;
    end
    if (~isfinite(rcs_res))
        rcs_res = 0;
    end
end
