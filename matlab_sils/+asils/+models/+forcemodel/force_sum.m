function [a] = force_sum(gravity, thirdbody, drag, srp, erp, relativity, solidtides, oceantides, empirical)
%FORCE_SUM  op.accel's sum of the forces' accelerations, in its order.
%   gravity: real[1][3] (passed a plain number)
%   thirdbody: real[1][3] (passed a plain number)
%   drag: real[1][3] (passed a plain number)
%   srp: real[1][3] (passed a plain number)
%   erp: real[1][3] (passed a plain number)
%   relativity: real[1][3] (passed a plain number)
%   solidtides: real[1][3] (passed a plain number)
%   oceantides: real[1][3] (passed a plain number)
%   empirical: real[1][3] (passed a plain number)
%   returns a: real[1][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    a = zeros(3, 1);
    a = gravity;
    a = [(a(1) + thirdbody(1)); (a(2) + thirdbody(2)); (a(3) + thirdbody(3))];
    a = [(a(1) + drag(1)); (a(2) + drag(2)); (a(3) + drag(3))];
    a = [(a(1) + srp(1)); (a(2) + srp(2)); (a(3) + srp(3))];
    a = [(a(1) + erp(1)); (a(2) + erp(2)); (a(3) + erp(3))];
    a = [(a(1) + relativity(1)); (a(2) + relativity(2)); (a(3) + relativity(3))];
    a = [(a(1) + solidtides(1)); (a(2) + solidtides(2)); (a(3) + solidtides(3))];
    a = [(a(1) + oceantides(1)); (a(2) + oceantides(2)); (a(3) + oceantides(3))];
    a = [(a(1) + empirical(1)); (a(2) + empirical(2)); (a(3) + empirical(3))];
end
