function [c, parts] = cio_c2t(u, dut1, xp, yp, dx, dy, dat)
%CIO_C2T  One epoch of the builds' loop, given its EOP: C = W R3(era) Q (r_ecef = C r_eci), and its parts. Angles rad, UT1 - UTC
%   and TAI - UTC s.
%   u: real[1][6] (passed a plain number)
%   dut1: real[1] (passed a plain number)
%   xp: real[1] (passed a plain number)
%   yp: real[1] (passed a plain number)
%   dx: real[1] (passed a plain number)
%   dy: real[1] (passed a plain number)
%   dat: real[1] (passed a plain number)
%   returns c: real[1][3][3] (passed a plain number)
%   returns parts: CioParts (passed rec)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    c = zeros(3, 3);
    parts = asils.models.iau2006.CioParts_zero();
    ts = asils.models.iau2006.time_scales(u, dut1, dat);
    fa = asils.models.iau2006.fund_args(ts.t);
    [x0, y0] = asils.models.iau2006.xy06(ts.t, fa);
    x = (x0 + dx);
    y = (y0 + dy);
    s = asils.models.iau2006.s06(ts.t, fa, x, y);
    q = asils.models.iau2006.c2ixys(x, y, s);
    era = asils.models.iau2006.era00(ts.jd_ut1(1), ts.jd_ut1(2));
    w = asils.models.iau2006.pom00(xp, yp, asils.models.iau2006.sp00(ts.t));
    c = asils.pc.mm(asils.pc.mm(w, asils.models.earthframes.rot3(era)), q);
    parts = asils.models.iau2006.CioParts_zero();
    parts.x = x;
    parts.y = y;
    parts.s = s;
    parts.era = era;
    parts.q = q;
    parts.w = w;
end
