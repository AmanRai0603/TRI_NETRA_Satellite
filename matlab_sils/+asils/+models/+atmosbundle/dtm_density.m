function [rho] = dtm_density(alt_km, lat_deg, lon_deg, lst_h, doy, f107, f107a, kp)
%DTM_DENSITY  The operational DTM2020's total density [kg/m^3] at a geodetic altitude [km], latitude and longitude [deg], local solar
%   time [h], day of year, F10.7 and its mean [sfu] and Kp (the model's array [Kp, 0, Kp, 0], one Kp for both of its slots).
%   alt_km: real[1] (passed a plain number)
%   lat_deg: real[1] (passed a plain number)
%   lon_deg: real[1] (passed a plain number)
%   lst_h: real[1] (passed a plain number)
%   doy: real[1] (passed a plain number)
%   f107: real[1] (passed a plain number)
%   f107a: real[1] (passed a plain number)
%   kp: real[1] (passed a plain number)
%   returns rho: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    rho = 0;
    akp = [kp; 0; kp; 0];
    [ok, o] = asils.models.dtm2020.oper_density(alt_km, lat_deg, lon_deg, lst_h, doy, f107, f107a, akp);
    rho = NaN;
    if ok
        rho = o.rho_kgm3;
    end
end
