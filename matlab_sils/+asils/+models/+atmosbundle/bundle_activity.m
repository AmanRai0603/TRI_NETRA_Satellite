function [f107, f107a, kp] = bundle_activity(level)
%BUNDLE_ACTIVITY  The drivers of a member: the daily F10.7 and its 81-day mean [sfu] (the bundle takes both the same, as the sizing survey
%   does) and Kp. Low 70 and high 250 are the long-term extremes of ECSS-E-ST-10-04C Rev.1 as the inventory states them; the
%   mean is the engine's default flux (env_f107_default, 130). Kp is 2 in all three (the survey's, P6 of the inventory: no
%   storm; the high activity's Ap is S12's).
%   level: SolarActivity (passed a choice, as its option's number)
%   returns f107: real[1] (passed a plain number)
%   returns f107a: real[1] (passed a plain number)
%   returns kp: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    f107 = 0;
    f107a = 0;
    kp = 0;
    f107 = 130;
    if (level == 0)
        f107 = 70;
    elseif (level == 2)
        f107 = 250;
    end
    f107a = f107;
    kp = 2;
end
