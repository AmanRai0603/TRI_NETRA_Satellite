function [st_bs, st_noise_cross, st_noise_roll, st_latency] = fsw_star_tracker(nh, bs, noise_cross, noise_roll, latency)
%FSW_STAR_TRACKER  The star tracker as the flight software is told of it: its nh heads' boresights (body) and its cross-boresight and roll
%   noises [rad] and latency [s], each 0 where unstated.
%   nh: int (passed a whole number)
%   bs: real[1][3][FSW_NH] (passed a plain number)
%   noise_cross: real[1] (passed a plain number)
%   noise_roll: real[1] (passed a plain number)
%   latency: real[1] (passed a plain number)
%   returns st_bs: real[1][3][FSW_NH] (passed a plain number)
%   returns st_noise_cross: real[1] (passed a plain number)
%   returns st_noise_roll: real[1] (passed a plain number)
%   returns st_latency: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    st_bs = zeros(2, 3);
    st_noise_cross = 0;
    st_noise_roll = 0;
    st_latency = 0;
    st_bs = zeros(2, 3);
    for h = (0):((2) - 1)
        if (h < nh)
            for k = (0):((3) - 1)
                st_bs((h) + 1, (k) + 1) = bs((h) + 1, (k) + 1);
            end
        end
    end
    st_noise_cross = asils.models.fswsens.fsw_or_zero(noise_cross);
    st_noise_roll = asils.models.fswsens.fsw_or_zero(noise_roll);
    st_latency = asils.models.fswsens.fsw_or_zero(latency);
end
