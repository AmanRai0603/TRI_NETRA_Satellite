function [sig_sun, sig_mag, mag_err] = fsw_mekf_sigmas(sun_fitted, sun_noise, sun_bias_sigma, css_albedo, mag_misalign, mag_sf_sigma, mag_bias, mag_bias_sigma, mag_noise)
%FSW_MEKF_SIGMAS  The MEKF's measurement sigmas: the Sun vector's [rad] (the fine Sun sensor's noise and bias sigma, at least 0.005; with
%   coarse cells only, half their albedo share, at least 0.1), the magnetometer direction's [rad] (its misalignment and
%   scale-factor sigma, at least 0.01), and the magnetometer's error not in that sigma [T]: sqrt(bias^2 + 3 bias_sigma^2 +
%   3 noise^2), each 0 where unstated.
%   sun_fitted: bool (passed true or false)
%   sun_noise: real[1] (passed a plain number)
%   sun_bias_sigma: real[1] (passed a plain number)
%   css_albedo: real[1] (passed a plain number)
%   mag_misalign: real[1] (passed a plain number)
%   mag_sf_sigma: real[1] (passed a plain number)
%   mag_bias: real[1] (passed a plain number)
%   mag_bias_sigma: real[1] (passed a plain number)
%   mag_noise: real[1] (passed a plain number)
%   returns sig_sun: real[1] (passed a plain number)
%   returns sig_mag: real[1] (passed a plain number)
%   returns mag_err: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    sig_sun = 0;
    sig_mag = 0;
    mag_err = 0;
    if sun_fitted
        hs = asils.models.fswsens.fsw_hyp(sun_noise, sun_bias_sigma);
        if (hs > 0.005)
            h__573 = hs;
        else
            h__573 = 0.005;
        end
        sig_sun = h__573;
    else
        ca = (0.5 * css_albedo);
        if (ca > 0.1)
            h__574 = ca;
        else
            h__574 = 0.1;
        end
        sig_sun = h__574;
    end
    hm = asils.models.fswsens.fsw_hyp(mag_misalign, mag_sf_sigma);
    if (hm > 0.01)
        h__575 = hm;
    else
        h__575 = 0.01;
    end
    sig_mag = h__575;
    b = asils.models.fswsens.fsw_or_zero(mag_bias);
    bs = asils.models.fswsens.fsw_or_zero(mag_bias_sigma);
    nz = asils.models.fswsens.fsw_or_zero(mag_noise);
    h__576 = (((b * b) + (3 * (bs * bs))) + (3 * (nz * nz)));
    if h__576 < 0, h__576 = NaN; else, h__576 = sqrt(h__576); end
    mag_err = h__576;
end
