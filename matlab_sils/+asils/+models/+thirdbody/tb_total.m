function [a, a_sun, a_moon] = tb_total(s, sun, gm_sun, moon, gm_moon, model, nmax)
%TB_TOTAL  [a, parts] = thirdbody.total(rSat, E, model, nmax): the Sun's and the Moon's accelerations and their sum.
%   The direct model's cancellation amplifies pow's last bit: a translation is held to 1e-8 of the largest output.
%   tolerance: 1e-8
%   s: real[1][3] (passed a plain number)
%   sun: real[1][3] (passed a plain number)
%   gm_sun: real[1] (passed a plain number)
%   moon: real[1][3] (passed a plain number)
%   gm_moon: real[1] (passed a plain number)
%   model: ThirdBodyModel (passed a choice, as its option's number)
%   nmax: int (passed a whole number)
%   returns a: real[1][3] (passed a plain number)
%   returns a_sun: real[1][3] (passed a plain number)
%   returns a_moon: real[1][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    a = zeros(3, 1);
    a_sun = zeros(3, 1);
    a_moon = zeros(3, 1);
    a_sun = asils.models.thirdbody.tb_accel(s, sun, gm_sun, model, nmax);
    a_moon = asils.models.thirdbody.tb_accel(s, moon, gm_moon, model, nmax);
    a = [(a_sun(1) + a_moon(1)); (a_sun(2) + a_moon(2)); (a_sun(3) + a_moon(3))];
end
