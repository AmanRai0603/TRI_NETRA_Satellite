function [ac, k_hv, tsd, hmax] = ring_constants(bore_m, s_m2, rho, mu, v_max)
%RING_CONSTANTS  A ring's constants: the bore area [m^2], the momentum per flow speed [N m s per m/s], the spin-down time [s] and the
%   momentum capacity [N m s] of a bore bore_m [m] around an enclosed area s_m2 [m^2], fluid of density rho [kg/m^3] and
%   viscosity mu [Pa s], at the largest flow speed v_max [m/s].
%   bore_m: real[1] (passed a plain number)
%   s_m2: real[1] (passed a plain number)
%   rho: real[1] (passed a plain number)
%   mu: real[1] (passed a plain number)
%   v_max: real[1] (passed a plain number)
%   returns ac: real[1] (passed a plain number)
%   returns k_hv: real[1] (passed a plain number)
%   returns tsd: real[1] (passed a plain number)
%   returns hmax: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    ac = 0;
    k_hv = 0;
    tsd = 0;
    hmax = 0;
    ac = ((pi * asils.pc.ipow(bore_m, 2)) / 4);
    k_hv = (((rho * ac) * 2) * s_m2);
    tsd = ((rho * asils.pc.ipow(bore_m, 2)) / (32 * mu));
    hmax = (k_hv * v_max);
end
