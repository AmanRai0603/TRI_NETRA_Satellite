function [boresight, sun, mode, sun_axis, roll_axis] = survey_attitude(a)
%SURVEY_ATTITUDE  The attitude a of the survey: the payload axis put on nadir (the flight software's nadir guidance, mode 0, with that
%   axis as its boresight), or the Sun on the power face (its Sun-pointing guidance, mode 4: the Sun on -Z, the roll
%   about X).
%   a: SurveyAttitude (passed a choice, as its option's number)
%   returns boresight: real[1][3] (passed a plain number)
%   returns sun: bool (passed true or false)
%   returns mode: int (passed a whole number)
%   returns sun_axis: real[1][3] (passed a plain number)
%   returns roll_axis: real[1][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    boresight = zeros(3, 1);
    sun = false;
    mode = 0;
    sun_axis = zeros(3, 1);
    roll_axis = zeros(3, 1);
    boresight = [0; 0; 0];
    sun = false;
    mode = 0;
    sun_axis = [0; 0; (-(1))];
    roll_axis = [1; 0; 0];
    if (a == 0)
        boresight = [1; 0; 0];
    elseif (a == 1)
        boresight = [0; 1; 0];
    elseif (a == 2)
        boresight = [0; 0; 1];
    else
        sun = true;
        mode = 4;
    end
end
