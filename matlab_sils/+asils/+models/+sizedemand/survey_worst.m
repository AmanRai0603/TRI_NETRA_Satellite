function [tau_peak, tau_axis_peak, h_cyclic, h_secular_orbit, b_min, eclipse_frac] = survey_worst(tau_peak_w, tau_peak_s, tap_w, tap_s, hc_w, hc_s, hs_w, hs_s, bmin_w, bmin_s, ecl_w, ecl_s)
%SURVEY_WORST  The worst of two surveys, the one so far (w) and the next (s): the larger peak torque, cyclic and secular momentum
%   and eclipse fraction, each attitude and axis on its own, and the weaker least field. The field's mean is the first
%   survey's (the code keeps it).
%   tau_peak_w: real[1][4] (passed a plain number)
%   tau_peak_s: real[1][4] (passed a plain number)
%   tap_w: real[1][4][3] (passed a plain number)
%   tap_s: real[1][4][3] (passed a plain number)
%   hc_w: real[1][4] (passed a plain number)
%   hc_s: real[1][4] (passed a plain number)
%   hs_w: real[1][4] (passed a plain number)
%   hs_s: real[1][4] (passed a plain number)
%   bmin_w: real[1] (passed a plain number)
%   bmin_s: real[1] (passed a plain number)
%   ecl_w: real[1] (passed a plain number)
%   ecl_s: real[1] (passed a plain number)
%   returns tau_peak: real[1][4] (passed a plain number)
%   returns tau_axis_peak: real[1][4][3] (passed a plain number)
%   returns h_cyclic: real[1][4] (passed a plain number)
%   returns h_secular_orbit: real[1][4] (passed a plain number)
%   returns b_min: real[1] (passed a plain number)
%   returns eclipse_frac: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    tau_peak = zeros(4, 1);
    tau_axis_peak = zeros(3, 4);
    h_cyclic = zeros(4, 1);
    h_secular_orbit = zeros(4, 1);
    b_min = 0;
    eclipse_frac = 0;
    tau_peak = tau_peak_w;
    tau_axis_peak = tap_w;
    h_cyclic = hc_w;
    h_secular_orbit = hs_w;
    for a = (0):((4) - 1)
        tau_peak((a) + 1) = asils.models.sizedemand.size_max(tau_peak_w((a) + 1), tau_peak_s((a) + 1));
        h_cyclic((a) + 1) = asils.models.sizedemand.size_max(hc_w((a) + 1), hc_s((a) + 1));
        h_secular_orbit((a) + 1) = asils.models.sizedemand.size_max(hs_w((a) + 1), hs_s((a) + 1));
        for i = (0):((3) - 1)
            tau_axis_peak((i) + 1, (a) + 1) = asils.models.sizedemand.size_max(tap_w((i) + 1, (a) + 1), tap_s((i) + 1, (a) + 1));
        end
    end
    b_min = asils.models.sizedemand.size_min(bmin_w, bmin_s);
    eclipse_frac = asils.models.sizedemand.size_max(ecl_w, ecl_s);
end
