function [k] = erp_cr_aom(has_cr_aom, cr_aom, has_cfg_cr, cfg_cr, has_sc_cr, sc_cr, aref, mass)
%ERP_CR_AOM  The CrA/m forces.erp takes: the force set's CrAoM when it states one, else its Cr (or the spacecraft's, or 1.3)
%   times the reference area over the mass.
%   has_cr_aom: bool (passed true or false)
%   cr_aom: real[1] (passed a plain number)
%   has_cfg_cr: bool (passed true or false)
%   cfg_cr: real[1] (passed a plain number)
%   has_sc_cr: bool (passed true or false)
%   sc_cr: real[1] (passed a plain number)
%   aref: real[1] (passed a plain number)
%   mass: real[1] (passed a plain number)
%   returns k: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    k = 0;
    if has_cr_aom
        k = cr_aom;
    else
        cr = 1.3;
        if has_cfg_cr
            cr = cfg_cr;
        elseif has_sc_cr
            cr = sc_cr;
        end
        k = ((cr * aref) / mass);
    end
end
