function [a, comp] = erp_boxwing(r_sat, r_sun, r_b2i, f, mass, doy, nrings, nseg)
%ERP_BOXWING  erp.boxwing(rSat, rSun, R_b2i, sc, doy, nrings, nseg): each cap element's beam, from -es, on the box-wing facets
%   (body to ECI r_b2i), short and long wave apart, per mass [m/s^2].
%   r_sat: real[1][3] (passed a plain number)
%   r_sun: real[1][3] (passed a plain number)
%   r_b2i: real[1][3][3] (passed a plain number)
%   f: ScFacets (passed rec)
%   mass: real[1] (passed a plain number)
%   doy: real[1] (passed a plain number)
%   nrings: int (passed a whole number)
%   nseg: int (passed a whole number)
%   returns a: real[1][3] (passed a plain number)
%   returns comp: ErpComp (passed rec)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    a = zeros(3, 1);
    comp = asils.models.erp.ErpComp_zero();
    c = getfield(asils.models.de440.de440_constants(), 'c');
    [zhat, e1, e2, shat, rho_max] = asils.models.erp.cap_frame(r_sat, r_sun);
    fsw = [0; 0; 0];
    flw = [0; 0; 0];
    for ir = (1):(((nrings + 1)) - 1)
        for js = (1):(((nseg + 1)) - 1)
            [vis, n_el, es, cos_e, da, rho, lat] = asils.models.erp.cap_element(r_sat, zhat, e1, e2, rho_max, ir, js, nrings, nseg);
            if vis
                [alb, emi] = asils.models.erp.zonal_coeffs(lat, doy);
                [msw, mlw, geo] = asils.models.erp.cap_exitance(alb, emi, n_el, shat, cos_e, da, rho);
                esw = (msw * geo);
                elw = (mlw * geo);
                if (~((esw <= 0) && (elw <= 0)))
                    u_b = asils.pc.mv((r_b2i).', [(-(es(1))); (-(es(2))); (-(es(3)))]);
                    s = asils.pc.mv(r_b2i, asils.models.srp.facet_sum(f, u_b, (esw / c)));
                    l = asils.pc.mv(r_b2i, asils.models.srp.facet_sum(f, u_b, (elw / c)));
                    for i = (0):((3) - 1)
                        fsw((i) + 1) = (fsw((i) + 1) + s((i) + 1));
                        flw((i) + 1) = (flw((i) + 1) + l((i) + 1));
                    end
                end
            end
        end
    end
    comp = asils.models.erp.ErpComp_zero();
    comp.sw = [(fsw(1) / mass); (fsw(2) / mass); (fsw(3) / mass)];
    comp.lw = [(flw(1) / mass); (flw(2) / mass); (flw(3) / mass)];
    a = [(comp.sw(1) + comp.lw(1)); (comp.sw(2) + comp.lw(2)); (comp.sw(3) + comp.lw(3))];
end
