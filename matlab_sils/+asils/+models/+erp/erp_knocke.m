function [a, comp] = erp_knocke(r_sat, r_sun, cr_aom, doy, nrings, nseg)
%ERP_KNOCKE  The ring model on a cannonball of CrA/m cr_aom over nrings x nseg elements, the albedo and emissivity Knocke's zonal
%   on day doy: the acceleration [m/s^2] and its parts.
%   r_sat: real[1][3] (passed a plain number)
%   r_sun: real[1][3] (passed a plain number)
%   cr_aom: real[1] (passed a plain number)
%   doy: real[1] (passed a plain number)
%   nrings: int (passed a whole number)
%   nseg: int (passed a whole number)
%   returns a: real[1][3] (passed a plain number)
%   returns comp: ErpComp (passed rec)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    a = zeros(3, 1);
    comp = asils.models.erp.ErpComp_zero();
    [zhat, e1, e2, shat, rho_max] = asils.models.erp.cap_frame(r_sat, r_sun);
    sw = [0; 0; 0];
    lw = [0; 0; 0];
    for ir = (1):(((nrings + 1)) - 1)
        for js = (1):(((nseg + 1)) - 1)
            [vis, n_el, es, cos_e, da, rho, lat] = asils.models.erp.cap_element(r_sat, zhat, e1, e2, rho_max, ir, js, nrings, nseg);
            if vis
                [alb, emi] = asils.models.erp.zonal_coeffs(lat, doy);
                [msw, mlw, geo] = asils.models.erp.cap_exitance(alb, emi, n_el, shat, cos_e, da, rho);
                [ds, dl] = asils.models.erp.cap_cannon(cr_aom, cos_e, da, rho, es, msw, mlw);
                i = ((0):((3) - 1)).';
                sw((i) + 1) = (reshape(sw((i) + 1), [], 1) + reshape(ds((i) + 1), [], 1));
                lw((i) + 1) = (reshape(lw((i) + 1), [], 1) + reshape(dl((i) + 1), [], 1));
            end
        end
    end
    comp = asils.models.erp.ErpComp_zero();
    comp.sw = sw;
    comp.lw = lw;
    a = [(sw(1) + lw(1)); (sw(2) + lw(2)); (sw(3) + lw(3))];
end
