function [msw, mlw, geo] = cap_exitance(alb, emi, n_el, shat, cos_e, da, rho)
%CAP_EXITANCE  An element's exitances [W/m^2] (its reflected sunlight at albedo alb, its emission at emissivity emi) and its
%   geometric factor cos_e dA/(pi rho^2), the Sun along shat.
%   alb: real[1] (passed a plain number)
%   emi: real[1] (passed a plain number)
%   n_el: real[1][3] (passed a plain number)
%   shat: real[1][3] (passed a plain number)
%   cos_e: real[1] (passed a plain number)
%   da: real[1] (passed a plain number)
%   rho: real[1] (passed a plain number)
%   returns msw: real[1] (passed a plain number)
%   returns mlw: real[1] (passed a plain number)
%   returns geo: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    msw = 0;
    mlw = 0;
    geo = 0;
    s = getfield(asils.models.de440.de440_constants(), 'tsi');
    cz = (n_el(1)*shat(1) + n_el(2)*shat(2) + n_el(3)*shat(3));
    if (cz > 0)
        h__247 = ((alb * s) * cz);
    else
        h__247 = 0;
    end
    msw = h__247;
    mlw = ((emi * s) / 4);
    geo = ((cos_e * da) / ((pi * rho) * rho));
end
