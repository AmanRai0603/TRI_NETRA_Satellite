function [asw, alw] = cap_cannon(cr_aom, cos_e, da, rho, es, msw, mlw)
%CAP_CANNON  A cap element's push on a cannonball of CrA/m cr_aom: its short-wave and long-wave accelerations [m/s^2].
%   cr_aom: real[1] (passed a plain number)
%   cos_e: real[1] (passed a plain number)
%   da: real[1] (passed a plain number)
%   rho: real[1] (passed a plain number)
%   es: real[1][3] (passed a plain number)
%   msw: real[1] (passed a plain number)
%   mlw: real[1] (passed a plain number)
%   returns asw: real[1][3] (passed a plain number)
%   returns alw: real[1][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    asw = zeros(3, 1);
    alw = zeros(3, 1);
    base = ((((cr_aom / getfield(asils.models.de440.de440_constants(), 'c')) * cos_e) * da) / ((pi * rho) * rho));
    ks = (base * msw);
    kl = (base * mlw);
    asw = [(ks * es(1)); (ks * es(2)); (ks * es(3))];
    alw = [(kl * es(1)); (kl * es(2)); (kl * es(3))];
end
