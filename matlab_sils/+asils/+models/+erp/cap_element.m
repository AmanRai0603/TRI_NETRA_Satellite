function [vis, n_el, es, cos_e, da, rho, lat] = cap_element(r_sat, zhat, e1, e2, rho_max, ir, js, nrings, nseg)
%CAP_ELEMENT  Element (ir, js) of the cap (from 1, of nrings rings and nseg segments): whether it faces the satellite, its unit
%   normal, the unit vector from it to the satellite, the cosine there, its area [m^2], its distance [m] and latitude.
%   r_sat: real[1][3] (passed a plain number)
%   zhat: real[1][3] (passed a plain number)
%   e1: real[1][3] (passed a plain number)
%   e2: real[1][3] (passed a plain number)
%   rho_max: real[1] (passed a plain number)
%   ir: int (passed a whole number)
%   js: int (passed a whole number)
%   nrings: int (passed a whole number)
%   nseg: int (passed a whole number)
%   returns vis: bool (passed true or false)
%   returns n_el: real[1][3] (passed a plain number)
%   returns es: real[1][3] (passed a plain number)
%   returns cos_e: real[1] (passed a plain number)
%   returns da: real[1] (passed a plain number)
%   returns rho: real[1] (passed a plain number)
%   returns lat: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    vis = false;
    n_el = zeros(3, 1);
    es = zeros(3, 1);
    cos_e = 0;
    da = 0;
    rho = 0;
    lat = 0;
    re = getfield(asils.models.de440.de440_constants(), 're_earth');
    nr = nrings;
    nsg = nseg;
    psi = (((ir - 0.5) / nr) * rho_max);
    dpsi = (rho_max / nr);
    sp = sin(psi);
    cp = cos(psi);
    az = (((2 * pi) * (js - 0.5)) / nsg);
    sa = sin(az);
    ca = cos(az);
    n_el = zeros(3, 1);
    for i = (0):((3) - 1)
        n_el((i) + 1) = ((cp * zhat((i) + 1)) + (sp * ((ca * e1((i) + 1)) + (sa * e2((i) + 1)))));
    end
    sv = [(r_sat(1) - (re * n_el(1))); (r_sat(2) - (re * n_el(2))); (r_sat(3) - (re * n_el(3)))];
    rho = sqrt(sv(1)*sv(1) + sv(2)*sv(2) + sv(3)*sv(3));
    es = [(sv(1) / rho); (sv(2) / rho); (sv(3) / rho)];
    cos_e = (n_el(1)*es(1) + n_el(2)*es(2) + n_el(3)*es(3));
    vis = (~(cos_e <= 0));
    da = ((((re * re) * sp) * dpsi) * ((2 * pi) / nsg));
    lat = asils.pc.asin_(asils.models.thirdbody.unit_clip(n_el(3)));
end
