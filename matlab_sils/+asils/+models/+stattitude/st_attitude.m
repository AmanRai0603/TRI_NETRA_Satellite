function [q, ok, id] = st_attitude(b, rs, n, id, tol)
%ST_ATTITUDE  The attitude (ECI to head) from the first n spots' directions b (head frame, unit) and their catalogue stars id (-1
%   none), rs[p] the direction (ECI, unit) of spot p's catalogue star, dropping the worst star while its miss is tol [rad]
%   or more: (q, solved). id keeps the stars the fit used.
%   b: real[1][3][ST_SPOTS] (passed a plain number)
%   rs: real[1][3][ST_SPOTS] (passed a plain number)
%   n: int (passed a whole number)
%   id: inout int[ST_SPOTS] (passed a whole number)
%   tol: real[1] (passed a plain number)
%   returns q: real[1][4] (passed a plain number)
%   returns ok: bool (passed true or false)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    q = zeros(4, 1);
    ok = false;
    q = [0; 0; 0; 1];
    ok = false;
    done = false;
    for it = (0):((n) - 1)
        if (~done)
            k = zeros(32, 1);
            nk = 0;
            t__609 = ((0):((n) - 1)).';
            for p = t__609(logical((id((t__609) + 1) >= 0))).'
                k((nk) + 1) = p;
                nk = (nk + 1);
            end
            if (nk < 3)
                done = true;
            else
                bb = zeros(32, 3);
                rr = zeros(32, 3);
                for i = (0):((nk) - 1)
                    bb((i) + 1, :) = (b((k((i) + 1)) + 1, :)).'.';
                    rr((i) + 1, :) = (rs((k((i) + 1)) + 1, :)).'.';
                end
                q = asils.models.stattitude.st_qmethod(bb, rr, nk);
                a = asils.models.math.dcm(q);
                rm = (-(Inf));
                j = 0;
                for i = (0):((nk) - 1)
                    c = asils.pc.dot_((bb((i) + 1, :)).', [a(1, 1)*rr((i) + 1, 1) + a(1, 2)*rr((i) + 1, 2) + a(1, 3)*rr((i) + 1, 3); a(2, 1)*rr((i) + 1, 1) + a(2, 2)*rr((i) + 1, 2) + a(2, 3)*rr((i) + 1, 3); a(3, 1)*rr((i) + 1, 1) + a(3, 2)*rr((i) + 1, 2) + a(3, 3)*rr((i) + 1, 3)]);
                    res = asils.pc.acos_(asils.pc.choose((c < 1), c, 1));
                    if (res > rm)
                        rm = res;
                        j = i;
                    end
                end
                if (rm < tol)
                    ok = true;
                    done = true;
                else
                    id((k((j) + 1)) + 1) = (-(1));
                end
            end
        end
    end
end
