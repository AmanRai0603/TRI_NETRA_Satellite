function [a] = solid_tides_accel(r_ecef, c, sun_eci, moon_eci, mu, re)
%SOLID_TIDES_ACCEL  forces.solidtides(ctx): the IERS 2010 step-1 coefficients from the Sun and the Moon in ECEF (C the ECI to ECEF
%   rotation), the degree-2 acceleration in ECEF, rotated to ECI with C'. [m/s^2]
%   The central difference amplifies the maths library's last bit about a million times: a translation is held to
%   1e-8 of the largest output, not 1e-12 (the browser's sin, cos, asin, atan2 and pow differ from the platform's).
%   tolerance: 1e-8
%   r_ecef: real[1][3] (passed a plain number)
%   c: real[1][3][3] (passed a plain number)
%   sun_eci: real[1][3] (passed a plain number)
%   moon_eci: real[1][3] (passed a plain number)
%   mu: real[1] (passed a plain number)
%   re: real[1] (passed a plain number)
%   returns a: real[1][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    a = zeros(3, 1);
    r_sun = [c(1, 1)*sun_eci(1) + c(1, 2)*sun_eci(2) + c(1, 3)*sun_eci(3); c(2, 1)*sun_eci(1) + c(2, 2)*sun_eci(2) + c(2, 3)*sun_eci(3); c(3, 1)*sun_eci(1) + c(3, 2)*sun_eci(2) + c(3, 3)*sun_eci(3)];
    r_moon = [c(1, 1)*moon_eci(1) + c(1, 2)*moon_eci(2) + c(1, 3)*moon_eci(3); c(2, 1)*moon_eci(1) + c(2, 2)*moon_eci(2) + c(2, 3)*moon_eci(3); c(3, 1)*moon_eci(1) + c(3, 2)*moon_eci(2) + c(3, 3)*moon_eci(3)];
    d = asils.models.solidtides.iers2010(r_moon, r_sun, mu, re);
    dc2 = [d.dc(3, 1); d.dc(3, 2); d.dc(3, 3)];
    ds2 = [d.ds(3, 1); d.ds(3, 2); d.ds(3, 3)];
    ae = asils.models.solidtides.accel_from_deg2(r_ecef, dc2, ds2, mu, re);
    h__475 = (c).';
    a = [h__475(1, 1)*ae(1) + h__475(1, 2)*ae(2) + h__475(1, 3)*ae(3); h__475(2, 1)*ae(1) + h__475(2, 2)*ae(2) + h__475(2, 3)*ae(3); h__475(3, 1)*ae(1) + h__475(3, 2)*ae(2) + h__475(3, 3)*ae(3)];
end
