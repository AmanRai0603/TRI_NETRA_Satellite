function [a] = accel_from_deg2(r, dc2, ds2, mu, re)
%ACCEL_FROM_DEG2  tideutil.accelFromDeg2(rSat_ecef, dcs, mu, Re): the ECEF acceleration [m/s^2] of the degree-2 potential of
%   dC(2, :) = dc2, dS(2, :) = ds2, by the MATLAB's central difference with h = 1 m.
%   The central difference amplifies the maths library's last bit about a million times: a translation is held to
%   1e-8 of the largest output, not 1e-12 (the browser's sin, cos, asin, atan2 and pow differ from the platform's).
%   tolerance: 1e-8
%   r: real[1][3] (passed a plain number)
%   dc2: real[1][3] (passed a plain number)
%   ds2: real[1][3] (passed a plain number)
%   mu: real[1] (passed a plain number)
%   re: real[1] (passed a plain number)
%   returns a: real[1][3] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    a = zeros(3, 1);
    h = 1;
    a = zeros(3, 1);
    for k = (0):((3) - 1)
        rp = r;
        rm = r;
        rp((k) + 1) = (rp((k) + 1) + h);
        rm((k) + 1) = (rm((k) + 1) - h);
        a((k) + 1) = ((asils.models.solidtides.deg2_potential(rp, dc2, ds2, mu, re) - asils.models.solidtides.deg2_potential(rm, dc2, ds2, mu, re)) / (2 * h));
    end
end
