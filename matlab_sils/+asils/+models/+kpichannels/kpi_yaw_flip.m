function [flip_out] = kpi_yaw_flip(on, r, v, q_off, sun_axis, roll_axis, sun_eci, flip, hyst)
%KPI_YAW_FLIP  The nadir family's yaw flip at a sample (the flight software's yaw_flip, fsw_guidance), carried from the sample before
%   (flip), when the scenario flies it (on); else as it was.
%   on: bool (passed true or false)
%   r: real[m][3] (passed in m)
%   v: real[m/s][3] (passed in m/s)
%   q_off: real[1][4] (passed a plain number)
%   sun_axis: real[1][3] (passed a plain number)
%   roll_axis: real[1][3] (passed a plain number)
%   sun_eci: real[1][3] (passed a plain number)
%   flip: bool (passed true or false)
%   hyst: real[1] (passed a plain number)
%   returns flip_out: bool (passed true or false)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    flip_out = false;
    flip_out = flip;
    if on
        flip_out = asils.models.guidance.yaw_flip(r, v, q_off, sun_axis, roll_axis, sun_eci, flip, hyst);
    end
end
