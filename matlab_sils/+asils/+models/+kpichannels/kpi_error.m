function [e, los] = kpi_error(q, qr, bs)
%KPI_ERROR  The error of the attitude q against qr (both ECI to body): the small-angle error vector e = 2 dq[0..2] [rad] of
%   dq = conj(qr) q with its scalar made positive, and the angle between the payload boresight bs (body) as q and as qr
%   point it [deg]. The performance error against the guidance's reference, the knowledge error against the estimate.
%   q: real[1][4] (passed a plain number)
%   qr: real[1][4] (passed a plain number)
%   bs: real[1][3] (passed a plain number)
%   returns e: real[1][3] (passed a plain number)
%   returns los: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    e = zeros(3, 1);
    los = 0;
    dq = asils.models.math.qmult(asils.models.math.qconj(qr), q);
    if (dq(4) < 0)
        dq = [(-(dq(1))); (-(dq(2))); (-(dq(3))); (-(dq(4)))];
    end
    e = [(2 * dq(1)); (2 * dq(2)); (2 * dq(3))];
    b_true = asils.models.math.mat3t_vec(asils.models.math.dcm(q), bs);
    h__621 = asils.models.math.mat3t_vec(asils.models.math.dcm(qr), bs);
    los = asils.models.kpichannels.kpi_acosd((b_true(1)*h__621(1) + b_true(2)*h__621(2) + b_true(3)*h__621(3)));
end
