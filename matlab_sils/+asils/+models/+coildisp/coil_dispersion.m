function [scale, a, disp] = coil_dispersion(n, axes, scale_sigma, misalign, disp)
%COIL_DISPERSION  The first n coils' scale factors and dispersed axes (body frame) from the nominal axes, the scale's sigma and the
%   axes' misalignment sigma [rad], drawn from disp.
%   n: int (passed a whole number)
%   axes: real[1][3][ACT_NS] (passed a plain number)
%   scale_sigma: real[1] (passed a plain number)
%   misalign: real[1] (passed a plain number)
%   disp: inout stream (passed a random stream, as six numbers)
%   returns scale: real[1][ACT_NS] (passed a plain number)
%   returns a: real[1][3][ACT_NS] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    scale = zeros(8, 1);
    a = zeros(8, 3);
    scale = zeros(8, 1);
    a = zeros(8, 3);
    for j = (0):((n) - 1)
        [t__0, t__1] = asils.pc.stream_normal(disp);
        z = t__0;
        disp = t__1;
        scale((j) + 1) = (1 + (scale_sigma * z));
    end
    for k = (0):((n) - 1)
        [t__2, t__3] = asils.pc.stream_normal3(disp);
        th = t__2;
        disp = t__3;
        a((k) + 1, :) = asils.pc.mv(asils.models.coildisp.small_rotation((th * misalign)), (axes((k) + 1, :)).').';
    end
end
