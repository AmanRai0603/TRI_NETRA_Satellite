function [v, spin_z, idx, w, tmp] = kpi_spin_error_stat(spin_z, idx, ni, spin_dps, st, w, tmp)
%KPI_SPIN_ERROR_STAT  The spin rate's error [deg/s]: the statistic st of | |spin_z| - spin_dps | over the window's samples idx[0..ni]
%   (spin_dps the Sun spin's rate the flight software flies, [deg/s]).
%   length: 64
%   spin_z: inout real[1][*] (passed a plain number)
%   idx: inout int[*] (passed a whole number)
%   ni: int (passed a whole number)
%   spin_dps: real[1] (passed a plain number)
%   st: MetricStat (passed a choice, as its option's number)
%   w: inout real[1][*] (passed a plain number)
%   tmp: inout real[1][*] (passed a plain number)
%   returns v: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    v = 0;
    k = 0;
    for i = (0):((ni) - 1)
        x = asils.pc.fabs((asils.pc.fabs(spin_z((idx((i) + 1)) + 1)) - spin_dps));
        if isfinite(x)
            w((k) + 1) = x;
            k = (k + 1);
        end
    end
    [t__534, t__535, t__536] = asils.models.kpistats.kpi_stat_of(w, k, st, tmp);
    v = t__534;
    w = t__535;
    tmp = t__536;
end
