function [v, t, rate, mode] = kpi_time_to_rate(t, rate, mode, n, thr, hold, end_at_exit)
%KPI_TIME_TO_RATE  The time to a rate [min]: the first time the body rate rate [deg/s] (at times t [s], n samples) goes below thr
%   [deg/s] and stays below it for hold [s]. When end_at_exit, a mission hands over to the next mode when detumble is done:
%   that hand-over, below the threshold, completes the detumble even if the next mode then spins the body up again.
%   length: 64
%   t: inout real[1][*] (passed a plain number)
%   rate: inout real[1][*] (passed a plain number)
%   mode: inout int[*] (passed a whole number)
%   n: int (passed a whole number)
%   thr: real[1] (passed a plain number)
%   hold: real[1] (passed a plain number)
%   end_at_exit: bool (passed true or false)
%   returns v: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    v = 0;
    [t__425, t__426, t__427] = asils.models.kpistats.kpi_time_to(t, rate, n, thr, hold);
    v = t__425;
    t = t__426;
    rate = t__427;
    if (end_at_exit && (n > 0))
        found = false;
        j = 0;
        for k = (0):((n) - 1)
            if ((~found) && (mode((k) + 1) ~= mode(1)))
                found = true;
                j = k;
            end
        end
        if found
            if ((rate((j) + 1) < thr) && (~(v <= t((j) + 1))))
                v = t((j) + 1);
            end
        end
    end
    v = (v / 60);
end
