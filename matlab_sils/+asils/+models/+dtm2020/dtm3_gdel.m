function [gd_tt, gd_t0, gd_tp, gd] = dtm3_gdel(f, fbar, akp, day, plg, hloc, xlon)
%DTM3_GDEL  The nine gdel of a coefficient set (tt, t0, tp, then the six species) by the operational expansion.
%   f: real[1] (passed a plain number)
%   fbar: real[1] (passed a plain number)
%   akp: real[1][4] (passed a plain number)
%   day: real[1] (passed a plain number)
%   plg: Plg (passed rec)
%   hloc: Hloc (passed rec)
%   xlon: real[1] (passed a plain number)
%   returns gd_tt: real[1] (passed a plain number)
%   returns gd_t0: real[1] (passed a plain number)
%   returns gd_tp: real[1] (passed a plain number)
%   returns gd: real[1][6] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    gd_tt = 0;
    gd_t0 = 0;
    gd_tp = 0;
    gd = zeros(6, 1);
    ff0 = [0; 0; 1; 1; 1; 1];
    gd_tt = asils.models.dtm2020.gldtm(f, fbar, akp, day, asils.models.dtm2020.dtm_column(0, 0), plg, hloc, xlon, 1);
    gd_t0 = asils.models.dtm2020.gldtm(f, fbar, akp, day, asils.models.dtm2020.dtm_column(0, 7), plg, hloc, xlon, 1);
    gd_tp = asils.models.dtm2020.gldtm(f, fbar, akp, day, asils.models.dtm2020.dtm_column(0, 8), plg, hloc, xlon, 1);
    gd = zeros(6, 1);
    for i = (0):((6) - 1)
        gd((i) + 1) = asils.models.dtm2020.gldtm(f, fbar, akp, day, asils.models.dtm2020.dtm_column(0, (i + 1)), plg, hloc, xlon, ff0((i) + 1));
    end
end
