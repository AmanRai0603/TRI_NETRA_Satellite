function [raan, a, inc, u0] = fast_orbit_start(sun, ltan_h, alt_km, inc_deg, u0_deg)
%FAST_ORBIT_START  The fast orbit's start: its RAAN from the LTAN and the Sun at the epoch, its semi-major axis from the altitude
%   alt_km [km], its inclination and argument of latitude from inc_deg and u0_deg [deg].
%   sun: real[m][3] (passed in m)
%   ltan_h: real[1] (passed a plain number)
%   alt_km: real[1] (passed a plain number)
%   inc_deg: real[1] (passed a plain number)
%   u0_deg: real[1] (passed a plain number)
%   returns raan: real[1] (passed a plain number)
%   returns a: real[m] (passed in m)
%   returns inc: real[1] (passed a plain number)
%   returns u0: real[1] (passed a plain number)
%   Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
    raan = 0;
    a = 0;
    inc = 0;
    u0 = 0;
    raan = asils.models.orbitstart.ltan_raan(sun, ltan_h);
    a = (6378137 + (alt_km * 1000));
    inc = (inc_deg * (pi / 180));
    u0 = (u0_deg * (pi / 180));
end
