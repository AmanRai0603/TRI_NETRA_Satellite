#[inline]
fn lib_sum<const N: usize>(tb: &[[f64; 11]; N], arg: &[f64; 6]) -> (f64, f64) {
    let (mut s1, mut s2) = (0.0, 0.0);
    for r in tb.iter() {
        let mut x = 0.0;
        for k in 0..6 { x += r[k] * arg[k]; }
        let ang = omod(x, TWOPI);
        let (sn, cs) = (ang.sin(), ang.cos());
        s1 += r[7] * sn + r[8] * cs;
        s2 += r[9] * sn + r[10] * cs;
    }
    (s1, s2)
}

/// `tidal_pm_libration(rmjd)`: diurnal lunisolar libration in polar motion
/// (IERS PMSDNUT2). Returns `(dxp, dyp)` in microarcseconds.
pub fn tidal_pm_libration(rmjd: f64) -> (f64, f64) { lib_sum(&PM_TB, &libration_args(rmjd)) }

/// `tidal_ut1_libration(rmjd)`: subdiurnal libration in UT1 (IERS UTLIBR).
/// Returns `(dut1 [us], dlod [us/day])`.
pub fn tidal_ut1_libration(rmjd: f64) -> (f64, f64) { lib_sum(&UT_TB, &libration_args(rmjd)) }

