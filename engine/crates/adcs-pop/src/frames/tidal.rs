//! Sub-daily and zonal tidal EOP models -- port of
//! `matlab_sils/pop/03_frames_time/tidal_eop_models/` (`tidal_eop.m`,
//! `tidal_eop_ocean.m`, `tidal_pm_libration.m`, `tidal_ut1_libration.m`,
//! `tidal_ut1_zonal.m`), which are the MATLAB ports of the IERS Conventions
//! (2010) ORTHO_EOP/CNMTX, PMSDNUT2, UTLIBR and RG_ZONT2 routines used by
//! `frames.eci2ecef_A/B/C`. Tables and formulas are copied verbatim.
use crate::time::omod;

const AS2R: f64 = 4.848136811095359935899141e-6;
const TURNAS: f64 = 1296000.0;
// MATLAB TWOPI=6.283185307179586476925287, PI=3.141592653589793238462643 (same doubles)
const TWOPI: f64 = std::f64::consts::TAU;
const PI: f64 = std::f64::consts::PI;

/// IERS-2010 Delaunay arguments (l, l', F, D, Om) in rad at `t` Julian centuries
/// (the expressions shared by the tidal routines).
#[inline]
fn delaunay(t: f64) -> [f64; 5] {
    [
        omod(485868.249036 + t * (1717915923.2178 + t * (31.8792 + t * (0.051635 + t * (-0.00024470)))), TURNAS) * AS2R,
        omod(1287104.793048 + t * (129596581.0481 + t * (-0.5532 + t * (0.000136 + t * (-0.00001149)))), TURNAS) * AS2R,
        omod(335779.526232 + t * (1739527262.8478 + t * (-12.7512 + t * (-0.001037 + t * (0.00000417)))), TURNAS) * AS2R,
        omod(1072260.703692 + t * (1602961601.2090 + t * (-6.3706 + t * (0.006593 + t * (-0.00003169)))), TURNAS) * AS2R,
        omod(450160.398036 + t * (-6962890.5431 + t * (7.4722 + t * (0.007702 + t * (-0.00005939)))), TURNAS) * AS2R,
    ]
}

/// `[GMST+pi, l, l', F, D, Om]` (rad) as built in PMSDNUT2 / UTLIBR.
#[inline]
fn libration_args(rmjd: f64) -> [f64; 6] {
    let t = (rmjd - 51544.5) / 36525.0;
    let d = delaunay(t);
    let gmst = omod(67310.54841 + t * ((8640184.812866 + 3155760000.0) + t * (0.093104 + t * (-0.0000062))), 86400.0);
    [omod(gmst / (86400.0 / TWOPI) + PI, TWOPI), d[0], d[1], d[2], d[3], d[4]]
}

/// `tidal_eop(mjd)`: full IERS sub-daily EOP correction = ocean tides + PM libration
/// + UT1 libration. Returns `(dxp, dyp, dut1)` in microarcseconds / microseconds.
pub fn tidal_eop(mjd: f64) -> (f64, f64, f64) {
    let (ox, oy, ou) = tidal_eop_ocean(mjd);
    let (px, py) = tidal_pm_libration(mjd);
    let (uu, _) = tidal_ut1_libration(mjd);
    (ox + px, oy + py, ou + uu)
}

