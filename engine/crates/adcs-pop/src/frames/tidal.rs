/// `tidal_eop_ocean(mjd)`: diurnal + semidiurnal ocean-tide variations in polar
/// motion and UT1 (IERS ORTHO_EOP). Returns `(dxp, dyp, dut1)` in uas, uas, us.
pub fn tidal_eop_ocean(mjd: f64) -> (f64, f64, f64) {
    const DT: f64 = 2.0;
    const D1960: f64 = 37076.5;
    let mut a = [[0.0f64; 3]; 2];
    let mut b = [[0.0f64; 3]; 2];
    for kk in 0..3 {
        let k = kk as f64 - 1.0;
        let dt60 = (mjd - k * DT) - D1960;
        let mut sa = [0.0f64; 2];
        let mut sb = [0.0f64; 2];
        for row in OCEAN_TBL.iter() {
            let (nj, mj, hs, phase, freq) = (row[0], row[1], row[2], row[3], row[4]);
            let ph = omod(phase - omod(nj + mj, 2.0) * TWOPI / 4.0, TWOPI) + omod(freq * dt60, TWOPI);
            let m = if mj == 1.0 { 0 } else if mj == 2.0 { 1 } else { continue };
            sa[m] += hs * ph.cos();
            sb[m] += hs * ph.sin();
        }
        for m in 0..2 {
            a[m][kk] = sa[m];
            b[m][kk] = -sb[m];
        }
    }
    let mut h = [0.0f64; 12];
    let mut c = 0;
    for m in 0..2 {
        let ap = a[m][2] + a[m][0];
        let am = a[m][2] - a[m][0];
        let bp = b[m][2] + b[m][0];
        let bm = b[m][2] - b[m][0];
        let s: [f64; 6] = [OCEAN_SP[0][m], OCEAN_SP[1][m], OCEAN_SP[2][m], OCEAN_SP[3][m], OCEAN_SP[4][m], OCEAN_SP[5][m]];
        let p = [s[0] * a[m][1], s[1] * a[m][1] - s[2] * ap, s[3] * a[m][1] - s[4] * ap + s[5] * bm];
        let q = [s[0] * b[m][1], s[1] * b[m][1] - s[2] * bp, s[3] * b[m][1] - s[4] * bp - s[5] * am];
        h[c] = p[0];
        h[c + 1] = q[0];
        h[c + 2] = p[1];
        h[c + 3] = q[1];
        h[c + 4] = p[2];
        h[c + 5] = q[2];
        c += 6;
    }
    let mut eop = [0.0f64; 3];
    for j in 0..3 {
        let mut acc = 0.0;
        for i in 0..12 { acc += h[i] * OCEAN_ORTHOW[i][j]; }
        eop[j] = acc;
    }
    (eop[0], eop[1], eop[2])
}

