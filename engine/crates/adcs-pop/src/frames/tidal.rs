/// `tidal_ut1_zonal(mjd)`: zonal-tide variation in UT1 (IERS RG_ZONT2, 62 terms),
/// in SECONDS. Used by build C to regularise UT1 before interpolation.
pub fn tidal_ut1_zonal(mjd: f64) -> f64 {
    let t = (mjd - 51544.5) / 36525.0;
    let [l, lp, f, d, om] = delaunay(t);
    let mut acc = 0.0;
    for r in ZONT.iter() {
        let arg = omod(r[0] * l + r[1] * lp + r[2] * f + r[3] * d + r[4] * om, TWOPI);
        acc += r[6] * arg.sin() + r[7] * arg.cos();
    }
    acc * 1e-4
}
