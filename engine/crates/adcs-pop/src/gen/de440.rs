/// de440.chebval over one type-2 record: the Chebyshev polynomials T_i and their derivatives at the record's tau, then
/// each component's sum and its derivative over the half-length; nc coefficients a component. [km, km/s]
/// - rec: real[1][DE_REC] (passed a plain number)
/// - nc: int (passed a whole number)
/// - et: real[1] (passed a plain number)
/// - returns pos: real[1][3] (passed a plain number)
/// - returns vel: real[1][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn cheb_state(rec: [f64; 62], nc: i64, et: f64) -> ([f64; 3], [f64; 3]) {
    let mut pos: [f64; 3] = [0.0; 3];
    let mut vel: [f64; 3] = [0.0; 3];
    let mut mid: f64 = rec[0];
    let mut radius: f64 = rec[1];
    let mut tau: f64 = ((et - mid) / radius);
    let mut t: [f64; 20] = [0.0; 20];
    let mut dt: [f64; 20] = [0.0; 20];
    t[0] = 1.0;
    if (nc > 1) {
        t[1] = tau;
    }
    {
        let __end0: i64 = nc;
        let mut i: i64 = 2;
        while i < __end0 {
            t[(i) as usize] = (((2.0 * tau) * t[((i - 1)) as usize]) - t[((i - 2)) as usize]);
            i += 1;
        }
    }
    dt[0] = 0.0;
    if (nc > 1) {
        dt[1] = 1.0;
    }
    if (nc > 2) {
        dt[2] = (4.0 * tau);
    }
    {
        let __end1: i64 = nc;
        let mut i: i64 = 3;
        while i < __end1 {
            dt[(i) as usize] = ((((2.0 * tau) * dt[((i - 1)) as usize]) + (2.0 * t[((i - 1)) as usize])) - dt[((i - 2)) as usize]);
            i += 1;
        }
    }
    pos = [0.0; 3];
    vel = [0.0; 3];
    {
        let __end2: i64 = 3;
        let mut c: i64 = 0;
        while c < __end2 {
            let mut val: f64 = 0.0;
            let mut der: f64 = 0.0;
            {
                let __end3: i64 = nc;
                let mut i: i64 = 0;
                while i < __end3 {
                    val = (val + (rec[(((2 + (c * nc)) + i)) as usize] * t[(i) as usize]));
                    der = (der + (rec[(((2 + (c * nc)) + i)) as usize] * dt[(i) as usize]));
                    i += 1;
                }
            }
            pos[(c) as usize] = val;
            vel[(c) as usize] = (der / radius);
            c += 1;
        }
    }
    (pos, vel)
}

/// The record of a segment that covers et, from env's slice, chosen as de440.state chooses it (floor((et - INIT) /
/// INTLEN), held to the segment's records); ok is false when the slice does not hold it.
/// - seg: DeSegment (passed a choice, as its option's number)
/// - et: real[1] (passed a plain number)
