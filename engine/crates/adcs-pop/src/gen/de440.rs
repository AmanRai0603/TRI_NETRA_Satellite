/// de440.sun, moon and earth from the four segments' states (km, km/s): the geocentric Sun and Moon [m, m/s] and the
/// geocentre from the solar-system barycentre [km, km/s]. The Earth-Moon barycentre to Earth record is evaluated once and
/// shared (the MATLAB evaluates it twice, with the same bits).
/// - sun_r: real[1][3] (passed a plain number)
/// - sun_v: real[1][3] (passed a plain number)
/// - emb_r: real[1][3] (passed a plain number)
/// - emb_v: real[1][3] (passed a plain number)
/// - earth_r: real[1][3] (passed a plain number)
/// - earth_v: real[1][3] (passed a plain number)
/// - moon_r: real[1][3] (passed a plain number)
/// - moon_v: real[1][3] (passed a plain number)
/// - returns rs: real[1][3] (passed a plain number)
/// - returns vs: real[1][3] (passed a plain number)
/// - returns rm: real[1][3] (passed a plain number)
/// - returns vm: real[1][3] (passed a plain number)
/// - returns re: real[1][3] (passed a plain number)
/// - returns ve: real[1][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn geocentric(sun_r: [f64; 3], sun_v: [f64; 3], emb_r: [f64; 3], emb_v: [f64; 3], earth_r: [f64; 3], earth_v: [f64; 3], moon_r: [f64; 3], moon_v: [f64; 3]) -> ([f64; 3], [f64; 3], [f64; 3], [f64; 3], [f64; 3], [f64; 3]) {
    let mut rs: [f64; 3] = [0.0; 3];
    let mut vs: [f64; 3] = [0.0; 3];
    let mut rm: [f64; 3] = [0.0; 3];
    let mut vm: [f64; 3] = [0.0; 3];
    let mut re: [f64; 3] = [0.0; 3];
    let mut ve: [f64; 3] = [0.0; 3];
    re = rt::vadd(emb_r, earth_r);
    ve = rt::vadd(emb_v, earth_v);
    rs = rt::vscale(rt::vsub(sun_r, re), 1000.0);
    vs = rt::vscale(rt::vsub(sun_v, ve), 1000.0);
    rm = rt::vscale(rt::vsub(moon_r, earth_r), 1000.0);
    vm = rt::vscale(rt::vsub(moon_v, earth_v), 1000.0);
    (rs, vs, rm, vm, re, ve)
}

/// ephemInputs(jdTDB): the force stack's one ephemeris interface, from the geocentric Sun and Moon [m, m/s].
/// - jd_tdb: real[1] (passed a plain number)
/// - rs: real[1][3] (passed a plain number)
/// - vs: real[1][3] (passed a plain number)
/// - rm: real[1][3] (passed a plain number)
/// - vm: real[1][3] (passed a plain number)
/// - returns e: EphemOut (passed rec)
#[allow(clippy::too_many_arguments)]
pub fn ephem_inputs(jd_tdb: f64, rs: [f64; 3], vs: [f64; 3], rm: [f64; 3], vm: [f64; 3]) -> EphemOut {
    let mut e: EphemOut = EphemOut::default();
    let mut k: DeConstants = crate::gen::de440::de440_constants();
    e = EphemOut::default();
    let mut d: f64 = rt::norm(rs);
    let mut q: f64 = (k.au_m / d);
    e.jd_tdb = jd_tdb;
    e.sun_unit = rt::vdiv(rs, d);
    e.sun_dist = d;
    e.flux_scale = (q * q);
    e.p_srp = (k.p0 * e.flux_scale);
    e.sun_eci = rs;
    e.sun_vel = vs;
    e.moon_eci = rm;
    e.moon_vel = vm;
    e.gm_sun = k.gm_sun;
    e.gm_moon = k.gm_moon;
    e.earth_helio_pos = rt::vneg(rs);
    e.earth_helio_vel = rt::vneg(vs);
    e.sun_ra = f64::atan2(rs[1], rs[0]);
    e.sun_dec = f64::asin((rs[2] / d));
    e
}
