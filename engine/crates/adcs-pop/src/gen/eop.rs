pub fn eop_lagrange(mjd_t: &mut [f64], xp_t: &mut [f64], yp_t: &mut [f64], dx_t: &mut [f64], dy_t: &mut [f64], ut_t: &mut [f64], ls_mjd: &mut [f64], ls_dat: &mut [f64], mjd: f64) -> (f64, f64, f64, f64, f64, f64, i64) {
    let mut dut1: f64 = 0.0;
    let mut xp: f64 = 0.0;
    let mut yp: f64 = 0.0;
    let mut dx: f64 = 0.0;
    let mut dy: f64 = 0.0;
    let mut dat: f64 = 0.0;
    let mut flag: i64 = 0;
    let mut n: i64 = ((*mjd_t).len() as i64);
    flag = (if ((mjd < (*mjd_t)[0]) || (mjd > (*mjd_t)[((n - 1)) as usize])) { 1 } else { 0 });
    let mut cnt: i64 = crate::gen::eop::count_at_or_below(&mut (*mjd_t), n, mjd);
    let mut j: i64 = (if (cnt == 0) { 1 } else { cnt });
    let mut i0: i64 = (rt::imin(rt::imax((j - 1), 1), ((n + 1) - 4)) - 1);
    let mut mw: [f64; 4] = [(*mjd_t)[(i0) as usize], (*mjd_t)[((i0 + 1)) as usize], (*mjd_t)[((i0 + 2)) as usize], (*mjd_t)[((i0 + 3)) as usize]];
    let mut xw: [f64; 4] = [(*xp_t)[(i0) as usize], (*xp_t)[((i0 + 1)) as usize], (*xp_t)[((i0 + 2)) as usize], (*xp_t)[((i0 + 3)) as usize]];
    let mut yw: [f64; 4] = [(*yp_t)[(i0) as usize], (*yp_t)[((i0 + 1)) as usize], (*yp_t)[((i0 + 2)) as usize], (*yp_t)[((i0 + 3)) as usize]];
    let mut dxw: [f64; 4] = [(*dx_t)[(i0) as usize], (*dx_t)[((i0 + 1)) as usize], (*dx_t)[((i0 + 2)) as usize], (*dx_t)[((i0 + 3)) as usize]];
    let mut dyw: [f64; 4] = [(*dy_t)[(i0) as usize], (*dy_t)[((i0 + 1)) as usize], (*dy_t)[((i0 + 2)) as usize], (*dy_t)[((i0 + 3)) as usize]];
    let (mut tx, mut ty, mut tu) = crate::gen::tidaleop::tidal_eop(mjd);
    let mut lx: f64 = crate::gen::eop::lagr(&mut mw, &mut xw, mjd);
    let mut ly: f64 = crate::gen::eop::lagr(&mut mw, &mut yw, mjd);
    let mut ldx: f64 = crate::gen::eop::lagr(&mut mw, &mut dxw, mjd);
    let mut ldy: f64 = crate::gen::eop::lagr(&mut mw, &mut dyw, mjd);
    xp = ((lx + (tx * 0.000001)) * crate::gen::iau2006::AS2R);
    yp = ((ly + (ty * 0.000001)) * crate::gen::iau2006::AS2R);
    dx = (ldx * crate::gen::iau2006::AS2R);
    dy = (ldy * crate::gen::iau2006::AS2R);
    dat = crate::gen::eop::leap_at(&mut (*ls_mjd), &mut (*ls_dat), mjd);
    let mut reg: [f64; 4] = [0.0, 0.0, 0.0, 0.0];
    {
        let __end47: i64 = 4;
        let mut k: i64 = 0;
        while k < __end47 {
            reg[(k) as usize] = ((*ut_t)[((i0 + k)) as usize] - crate::gen::tidaleop::tidal_ut1_zonal(mw[(k) as usize]));
            k += 1;
        }
    }
    let mut ut1r: f64 = crate::gen::eop::lagr(&mut mw, &mut reg, mjd);
    dut1 = (((ut1r + crate::gen::tidaleop::tidal_ut1_zonal(mjd)) + (tu * 0.000001)) + dat);
    (dut1, xp, yp, dx, dy, dat, flag)
}
