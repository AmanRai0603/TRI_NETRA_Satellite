#[allow(clippy::too_many_arguments)]
pub fn dtm3_gdel(f: f64, fbar: f64, akp: [f64; 4], day: f64, plg: Plg, hloc: Hloc, xlon: f64) -> (f64, f64, f64, [f64; 6]) {
    let mut gd_tt: f64 = 0.0;
    let mut gd_t0: f64 = 0.0;
    let mut gd_tp: f64 = 0.0;
    let mut gd: [f64; 6] = [0.0; 6];
    let mut ff0: [f64; 6] = [0.0, 0.0, 1.0, 1.0, 1.0, 1.0];
    gd_tt = crate::gen::dtm2020::gldtm(f, fbar, akp, day, crate::gen::dtm2020::dtm_column(crate::gen::dtm2020::DTMSET_OPERATIONAL, 0), plg, hloc, xlon, 1.0);
    gd_t0 = crate::gen::dtm2020::gldtm(f, fbar, akp, day, crate::gen::dtm2020::dtm_column(crate::gen::dtm2020::DTMSET_OPERATIONAL, 7), plg, hloc, xlon, 1.0);
    gd_tp = crate::gen::dtm2020::gldtm(f, fbar, akp, day, crate::gen::dtm2020::dtm_column(crate::gen::dtm2020::DTMSET_OPERATIONAL, 8), plg, hloc, xlon, 1.0);
    gd = [0.0; 6];
    {
        let __end22: i64 = 6;
        let mut i: i64 = 0;
        while i < __end22 {
            gd[(i) as usize] = crate::gen::dtm2020::gldtm(f, fbar, akp, day, crate::gen::dtm2020::dtm_column(crate::gen::dtm2020::DTMSET_OPERATIONAL, (i + 1)), plg, hloc, xlon, ff0[(i) as usize]);
            i += 1;
        }
    }
    (gd_tt, gd_t0, gd_tp, gd)
}

/// dtm3: the operational DTM2020 at day of year day, F10.7 of the day before f and its 81-day mean fbar [sfu], the Kp
/// array akp, altitude alti [km] (above 120), local solar time hl [rad], latitude alat and longitude xlon [rad].
/// - day: real[1] (passed a plain number)
/// - f: real[1] (passed a plain number)
/// - fbar: real[1] (passed a plain number)
/// - akp: real[1][4] (passed a plain number)
/// - alti: real[1] (passed a plain number)
/// - hl: real[1] (passed a plain number)
/// - alat: real[1] (passed a plain number)
/// - xlon: real[1] (passed a plain number)
/// - returns o: DtmRaw (passed rec)
#[allow(clippy::too_many_arguments)]
pub fn dtm3(day: f64, f: f64, fbar: f64, akp: [f64; 4], alti: f64, hl: f64, alat: f64, xlon: f64) -> DtmRaw {
    let mut o: DtmRaw = DtmRaw::default();
    let mut cpmg: f64 = 0.19081;
    let mut spmg: f64 = 0.98163;
    let mut xlmg: f64 = (-(1.2392));
    let mut plg: Plg = crate::gen::dtm2020::plg_geographic(alat);
    let mut c: f64 = f64::sin(alat);
    let mut s: f64 = f64::cos(alat);
    let mut clmlmg: f64 = f64::cos((xlon - xlmg));
    let mut sp: f64 = (((s * cpmg) * clmlmg) + (c * spmg));
    let mut cmg: f64 = sp;
    let mut cmg2: f64 = f64::powf(cmg, core::hint::black_box(2.0));
    let mut cmg4: f64 = f64::powf(cmg2, core::hint::black_box(2.0));
    plg.p10mg = cmg;
    plg.p20mg = ((1.5 * cmg2) - 0.5);
    plg.p40mg = (((4.375 * cmg4) - (3.75 * cmg2)) + 0.375);
    let mut hloc: Hloc = crate::gen::dtm2020::hloc_of(hl);
    let (mut gd_tt, mut gd_t0, mut gd_tp, mut gd) = crate::gen::dtm2020::dtm3_gdel(f, fbar, akp, day, plg, hloc, xlon);
    o = crate::gen::dtm2020::dtm_profile(crate::gen::dtm2020::DTMSET_OPERATIONAL, gd_tt, gd_t0, gd_tp, gd, alti);
    o
}

/// The densities of dtm3 or dtm5 in the wrappers' form: number densities [1/cm^3] from the partial densities.
/// - r: DtmRaw (passed rec)
/// - returns o: DtmDensity (passed rec)
#[allow(clippy::too_many_arguments)]
pub fn dtm_pack(r: DtmRaw) -> DtmDensity {
    let mut o: DtmDensity = DtmDensity::default();
    let mut vma: [f64; 6] = crate::gen::dtm2020::dtm_vma();
    o = DtmDensity::default();
    {
        let __end23: i64 = 6;
        let mut i: i64 = 0;
        while i < __end23 {
            o.n_cm3[(i) as usize] = (r.d[(i) as usize] / vma[(i) as usize]);
            i += 1;
        }
    }
    o.rho_gcm3 = r.ro;
    o.rho_kgm3 = (r.ro * 1000.0);
    o.t_k = r.tz;
    o.tinf_k = r.tinf;
    o.rho_species = r.d;
    o.mbar_amu = r.wmm;
    o
}

/// dtm2020_oper_density: the operational model at a geodetic altitude [km], latitude and longitude [deg], local solar
/// time [h], day of year, F10.7 and its mean [sfu] and the Kp array; ok is false at or below the model's floor, 120 km.
/// - alt_km: real[1] (passed a plain number)
/// - lat_deg: real[1] (passed a plain number)
/// - lon_deg: real[1] (passed a plain number)
/// - lst_hours: real[1] (passed a plain number)
/// - doy: real[1] (passed a plain number)
/// - f107: real[1] (passed a plain number)
/// - f107_bar: real[1] (passed a plain number)
/// - akp: real[1][4] (passed a plain number)
/// - returns ok: bool (passed true or false)
/// - returns o: DtmDensity (passed rec)
#[allow(clippy::too_many_arguments)]
pub fn oper_density(alt_km: f64, lat_deg: f64, lon_deg: f64, lst_hours: f64, doy: f64, f107: f64, f107_bar: f64, akp: [f64; 4]) -> (bool, DtmDensity) {
    let mut ok: bool = false;
    let mut o: DtmDensity = DtmDensity::default();
    o = DtmDensity::default();
    ok = (alt_km > 120.0);
    if ok {
        let mut hl: f64 = (((lst_hours / 24.0) * 2.0) * core::f64::consts::PI);
        let mut alat: f64 = crate::gen::timescales::deg2rad(lat_deg);
        let mut xlon: f64 = crate::gen::timescales::deg2rad(lon_deg);
        o = crate::gen::dtm2020::dtm_pack(crate::gen::dtm2020::dtm3(doy, f107, f107_bar, akp, alt_km, hl, alat, xlon));
    }
    (ok, o)
}
