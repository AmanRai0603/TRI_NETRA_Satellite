/// - aref: real[1] (passed a plain number)
/// - mass: real[1] (passed a plain number)
/// - r_bi: real[1][3][3] (passed a plain number)
/// - f: ScFacets (passed rec)
/// - returns acc: real[1][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn srp_force(r: [f64; 3], sun: [f64; 3], p_srp: f64, model: i64, ecl: i64, cr: f64, aref: f64, mass: f64, r_bi: [[f64; 3]; 3], f: ScFacets) -> [f64; 3] {
    let mut acc: [f64; 3] = [0.0; 3];
    let mut d: [f64; 3] = [(sun[0] - r[0]), (sun[1] - r[1]), (sun[2] - r[2])];
    let mut nd: f64 = rt::norm(d);
    let mut shat: [f64; 3] = [(d[0] / nd), (d[1] / nd), (d[2] / nd)];
    let (mut re, mut rp, mut rsun, mut h_atm) = crate::gen::srp::eclipse_default();
    let mut nu: f64 = crate::gen::srp::srp_eclipse(r, sun, ecl, re, rp, rsun, h_atm);
    if (model == crate::gen::srp::SRPMODEL_CANNONBALL) {
        acc = crate::gen::srp::srp_cannonball(p_srp, nu, shat, cr, (aref / mass));
    } else {
        let (mut a1, mut f1) = crate::gen::srp::srp_boxwing(p_srp, nu, shat, r_bi, f, mass);
        acc = a1;
    }
    acc
}
