/// The area of the lens two discs of radii r1 and r2, centres d apart, share.
/// - d: real[1] (passed a plain number)
/// - r1: real[1] (passed a plain number)
/// - r2: real[1] (passed a plain number)
/// - returns ar: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn lens_area(d: f64, r1: f64, r2: f64) -> f64 {
    let mut ar: f64 = 0.0;
    if (d >= (r1 + r2)) {
        ar = 0.0;
    } else if (d <= rt::fabs((r1 - r2))) {
        let mut m: f64 = (if (r2 < r1) { r2 } else { r1 });
        ar = (core::f64::consts::PI * (m * m));
    } else {
        let mut a: f64 = ((((d * d) + (r1 * r1)) - (r2 * r2)) / (2.0 * d));
        let mut h2: f64 = ((r1 * r1) - (a * a));
        let mut h: f64 = f64::sqrt((if (h2 > 0.0) { h2 } else { 0.0 }));
        ar = ((((r1 * r1) * f64::acos((a / r1))) + ((r2 * r2) * f64::acos(((d - a) / r2)))) - (d * h));
    }
    ar
}

/// The sunlit fraction of the solar disc of radius rsun seen from r_sat past a spherical Earth of radius re, the Sun at
/// r_sun (Octave's scaled norms).
/// - r_sat: real[1][3] (passed a plain number)
/// - r_sun: real[1][3] (passed a plain number)
/// - re: real[1] (passed a plain number)
/// - rsun: real[1] (passed a plain number)
/// - returns nu: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn frac_conical(r_sat: [f64; 3], r_sun: [f64; 3], re: f64, rsun: f64) -> f64 {
    let mut nu: f64 = 0.0;
    let mut d: [f64; 3] = [(r_sun[0] - r_sat[0]), (r_sun[1] - r_sat[1]), (r_sun[2] - r_sat[2])];
    let mut ds: f64 = crate::gen::gravity::onorm(d);
    let mut s: [f64; 3] = [(d[0] / ds), (d[1] / ds), (d[2] / ds)];
    let mut rr: f64 = crate::gen::gravity::onorm(r_sat);
    let mut e: [f64; 3] = [((-(r_sat[0])) / rr), ((-(r_sat[1])) / rr), ((-(r_sat[2])) / rr)];
    let mut se: f64 = rt::dot(s, e);
    if (se < 0.0) {
        nu = 1.0;
    } else {
        let mut th_s: f64 = f64::asin(crate::gen::srp::min_one((rsun / ds)));
        let mut th_e: f64 = f64::asin(crate::gen::srp::min_one((re / rr)));
        let mut th_sep: f64 = f64::acos(crate::gen::thirdbody::unit_clip(se));
        if (th_sep >= (th_s + th_e)) {
            nu = 1.0;
        } else if ((th_e - th_s) >= th_sep) {
            nu = 0.0;
        } else if ((th_s - th_e) >= th_sep) {
            let mut q: f64 = (th_e / th_s);
            nu = (1.0 - (q * q));
        } else {
            let mut occ: f64 = crate::gen::srp::lens_area(th_sep, th_s, th_e);
            nu = (1.0 - (occ / (core::f64::consts::PI * (th_s * th_s))));
        }
    }
    nu
}

/// srp.eclipse(rSat, rSun, model, opts): the lighting fraction nu in [0, 1] (1 sunlit, 0 umbra), the Sun at r_sun
/// (geocentric), with the Earth's radii re and rp, the Sun's rsun and the opaque atmosphere h_atm [m].
/// vectors: 160
/// - r_sat: real[1][3] (passed a plain number)
/// - r_sun: real[1][3] (passed a plain number)
/// - model: EclipseModel (passed a choice, as its option's number)
/// - re: real[1] (passed a plain number)
/// - rp: real[1] (passed a plain number)
/// - rsun: real[1] (passed a plain number)
/// - h_atm: real[1] (passed a plain number)
/// - returns nu: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn srp_eclipse(r_sat: [f64; 3], r_sun: [f64; 3], model: i64, re: f64, rp: f64, rsun: f64, h_atm: f64) -> f64 {
    let mut nu: f64 = 0.0;
    if (model == crate::gen::srp::ECLIPSEMODEL_CYLINDRICAL) {
        let mut d: [f64; 3] = [(r_sun[0] - r_sat[0]), (r_sun[1] - r_sat[1]), (r_sun[2] - r_sat[2])];
        let mut nd: f64 = rt::norm(d);
        let mut s: [f64; 3] = [(d[0] / nd), (d[1] / nd), (d[2] / nd)];
        let mut m: [f64; 3] = [(-(r_sat[0])), (-(r_sat[1])), (-(r_sat[2]))];
        let mut ms: f64 = rt::dot(m, s);
        if (ms < 0.0) {
            nu = 1.0;
        } else {
            let mut perp: f64 = rt::norm([(m[0] - (ms * s[0])), (m[1] - (ms * s[1])), (m[2] - (ms * s[2]))]);
            nu = (if (perp >= re) { 1.0 } else { 0.0 });
        }
    } else if (model == crate::gen::srp::ECLIPSEMODEL_CONICAL) {
        nu = crate::gen::srp::frac_conical(r_sat, r_sun, re, rsun);
    } else {
        let mut sz: f64 = (re / rp);
        let mut rs: [f64; 3] = [r_sat[0], r_sat[1], (r_sat[2] * sz)];
        let mut rn: [f64; 3] = [r_sun[0], r_sun[1], (r_sun[2] * sz)];
        nu = crate::gen::srp::frac_conical(rs, rn, (re + h_atm), rsun);
    }
    nu
}

/// The body-frame force of one beam of pressure p arriving from u_b (unit, from the spacecraft towards the source, body
/// axes) on the lit facets: an array's normal turned to the beam, a double-sided facet lit from behind flipped.
/// - f: ScFacets (passed rec)
/// - u_b: real[1][3] (passed a plain number)
/// - p: real[1] (passed a plain number)
/// - returns fb: real[1][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn facet_sum(f: ScFacets, u_b: [f64; 3], p: f64) -> [f64; 3] {
    let mut fb: [f64; 3] = [0.0; 3];
    fb = [0.0; 3];
    {
        let __end123: i64 = f.nf;
        let mut j: i64 = 0;
        while j < __end123 {
            let mut n: [f64; 3] = f.n[(j) as usize];
            if (f.kind[(j) as usize] == (crate::gen::srp::FACETKIND_ARRAY as i64)) {
                n = crate::gen::srp::srp_array_normal(f.axis[(j) as usize], u_b);
            }
            let mut cth: f64 = rt::dot(n, u_b);
            if ((f.dbl[(j) as usize] == 1) && (cth < 0.0)) {
                n = [(-(n[0])), (-(n[1])), (-(n[2]))];
                cth = (-(cth));
            }
            if (!(cth <= 0.0)) {
                let mut k: f64 = ((p * f.a[(j) as usize]) * cth);
                let mut ka: f64 = (f.alpha[(j) as usize] + f.rho_d[(j) as usize]);
                let mut kn: f64 = (2.0 * ((f.rho_s[(j) as usize] * cth) + (f.rho_d[(j) as usize] / 3.0)));
                {
                    let __end124: i64 = 3;
                    let mut i: i64 = 0;
                    while i < __end124 {
                        fb[(i) as usize] = (fb[(i) as usize] - (k * ((ka * u_b[(i) as usize]) + (kn * n[(i) as usize]))));
                        i += 1;
                    }
                }
            }
            j += 1;
        }
    }
    fb
}

