/// dgeom.ramAttitude(vrel): body to ECI with body +x along vrel and body +y = zref x x (zref +z, or +y when x is within
/// about 11 degrees of it).
/// - vrel: real[1][3] (passed a plain number)
/// - returns m: real[1][3][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn ram_attitude(vrel: [f64; 3]) -> [[f64; 3]; 3] {
    let mut m: [[f64; 3]; 3] = [[0.0; 3]; 3];
    let mut x: [f64; 3] = crate::gen::drag::ounit(vrel);
    let mut zref: [f64; 3] = [0.0, 0.0, 1.0];
    if (rt::fabs(rt::dot(x, zref)) > 0.98) {
        zref = [0.0, 1.0, 0.0];
    }
    let mut y: [f64; 3] = crate::gen::drag::ounit(rt::cross(zref, x));
    let mut z: [f64; 3] = rt::cross(x, y);
    m = crate::gen::drag::from_cols(x, y, z);
    m
}

/// dgeom.attitudeFromAoA(vrel, aoa_deg, sideslip_deg): the ram attitude pitched by the angle of attack about body y,
/// then yawed by the sideslip about body z [deg].
/// - vrel: real[1][3] (passed a plain number)
/// - aoa_deg: real[1] (passed a plain number)
/// - sideslip_deg: real[1] (passed a plain number)
/// - returns m: real[1][3][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn attitude_from_aoa(vrel: [f64; 3], aoa_deg: f64, sideslip_deg: f64) -> [[f64; 3]; 3] {
    let mut m: [[f64; 3]; 3] = [[0.0; 3]; 3];
    let mut rram: [[f64; 3]; 3] = crate::gen::drag::ram_attitude(vrel);
    let mut a: f64 = crate::gen::timescales::deg2rad(aoa_deg);
    let mut b: f64 = crate::gen::timescales::deg2rad(sideslip_deg);
    let mut ry: [[f64; 3]; 3] = [[f64::cos(a), 0.0, f64::sin(a)], [0.0, 1.0, 0.0], [(-(f64::sin(a))), 0.0, f64::cos(a)]];
    let mut rz: [[f64; 3]; 3] = [[f64::cos(b), (-(f64::sin(b))), 0.0], [f64::sin(b), f64::cos(b), 0.0], [0.0, 0.0, 1.0]];
    m = rt::mm(rt::mm(rram, ry), rz);
    m
}

/// sgeom.R_lvlh(r, v): body to ECI of a nadir-pointing attitude (z to nadir, y against the orbit normal, x completing,
/// about along the velocity).
/// - r: real[1][3] (passed a plain number)
/// - v: real[1][3] (passed a plain number)
/// - returns m: real[1][3][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn r_lvlh(r: [f64; 3], v: [f64; 3]) -> [[f64; 3]; 3] {
    let mut m: [[f64; 3]; 3] = [[0.0; 3]; 3];
    let mut nr: f64 = crate::gen::gravity::onorm(r);
    let mut zb: [f64; 3] = [((-(r[0])) / nr), ((-(r[1])) / nr), ((-(r[2])) / nr)];
    let mut h: [f64; 3] = rt::cross(r, v);
    let mut nh: f64 = crate::gen::gravity::onorm(h);
    let mut yb: [f64; 3] = [((-(h[0])) / nh), ((-(h[1])) / nh), ((-(h[2])) / nh)];
    let mut xb: [f64; 3] = crate::gen::drag::ounit(rt::cross(yb, zb));
    m = crate::gen::drag::from_cols(xb, yb, zb);
    m
}
