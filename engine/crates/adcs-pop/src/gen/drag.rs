/// drag.relVelocity(r, v, wind, omega): v - (omega x r) - wind, its unit vector and its size.
/// - r: real[1][3] (passed a plain number)
/// - v: real[1][3] (passed a plain number)
/// - wind: real[1][3] (passed a plain number)
/// - omega: real[1][3] (passed a plain number)
/// - returns vrel: real[1][3] (passed a plain number)
/// - returns uhat: real[1][3] (passed a plain number)
/// - returns vm: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn rel_velocity(r: [f64; 3], v: [f64; 3], wind: [f64; 3], omega: [f64; 3]) -> ([f64; 3], [f64; 3], f64) {
    let mut vrel: [f64; 3] = [0.0; 3];
    let mut uhat: [f64; 3] = [0.0; 3];
    let mut vm: f64 = 0.0;
    let mut c: [f64; 3] = rt::cross(omega, r);
    let mut vatm: [f64; 3] = [(c[0] + wind[0]), (c[1] + wind[1]), (c[2] + wind[2])];
    vrel = [(v[0] - vatm[0]), (v[1] - vatm[1]), (v[2] - vatm[2])];
    vm = crate::gen::gravity::onorm(vrel);
    uhat = [(vrel[0] / vm), (vrel[1] / vm), (vrel[2] / vm)];
    (vrel, uhat, vm)
}

/// drag.windAngles(vrel, R_bi): the angle of attack atan2(w, u) and sideslip asin(v/V) of the relative wind in body
/// axes, its speed and its body components.
/// - vrel: real[1][3] (passed a plain number)
/// - r_bi: real[1][3][3] (passed a plain number)
/// - returns alpha: real[1] (passed a plain number)
/// - returns beta: real[1] (passed a plain number)
/// - returns vm: real[1] (passed a plain number)
/// - returns vb: real[1][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn wind_angles(vrel: [f64; 3], r_bi: [[f64; 3]; 3]) -> (f64, f64, f64, [f64; 3]) {
    let mut alpha: f64 = 0.0;
    let mut beta: f64 = 0.0;
    let mut vm: f64 = 0.0;
    let mut vb: [f64; 3] = [0.0; 3];
    vb = rt::mv(rt::tr(r_bi), vrel);
    vm = crate::gen::gravity::onorm(vb);
    alpha = f64::atan2(vb[2], vb[0]);
    beta = f64::asin(crate::gen::thirdbody::unit_clip((vb[1] / vm)));
    (alpha, beta, vm, vb)
}

/// drag.bodyToWind(alpha, beta): the body-to-wind matrix (F_wind = [-D; S; -L]).
/// - alpha: real[1] (passed a plain number)
/// - beta: real[1] (passed a plain number)
/// - returns m: real[1][3][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn body_to_wind(alpha: f64, beta: f64) -> [[f64; 3]; 3] {
    let mut m: [[f64; 3]; 3] = [[0.0; 3]; 3];
    let mut ca: f64 = f64::cos(alpha);
    let mut sa: f64 = f64::sin(alpha);
    let mut cb: f64 = f64::cos(beta);
    let mut sb: f64 = f64::sin(beta);
    m = [[(cb * ca), sb, (cb * sa)], [((-(sb)) * ca), cb, ((-(sb)) * sa)], [(-(sa)), 0.0, ca]];
    m
}

/// drag.cannonball(r, v, rho, Cd, A, opts): -1/2 Cd A rho |v_r| v_r / m, v_r = v - omega x r - wind.
/// - r: real[1][3] (passed a plain number)
/// - v: real[1][3] (passed a plain number)
/// - rho: real[1] (passed a plain number)
/// - cd: real[1] (passed a plain number)
/// - area: real[1] (passed a plain number)
/// - mass: real[1] (passed a plain number)
/// - wind: real[1][3] (passed a plain number)
/// - omega: real[1][3] (passed a plain number)
/// - returns o: CannonballOut (passed rec)
#[allow(clippy::too_many_arguments)]
pub fn drag_cannonball(r: [f64; 3], v: [f64; 3], rho: f64, cd: f64, area: f64, mass: f64, wind: [f64; 3], omega: [f64; 3]) -> CannonballOut {
    let mut o: CannonballOut = CannonballOut::default();
    let mut c: [f64; 3] = rt::cross(omega, r);
    let mut t: [f64; 3] = [(v[0] - c[0]), (v[1] - c[1]), (v[2] - c[2])];
    let mut vrel: [f64; 3] = [(t[0] - wind[0]), (t[1] - wind[1]), (t[2] - wind[2])];
    let mut vm: f64 = crate::gen::gravity::onorm(vrel);
    o = CannonballOut::default();
    o.uhat = [(vrel[0] / vm), (vrel[1] / vm), (vrel[2] / vm)];
    let mut k: f64 = (((((-(0.5)) * cd) * area) * rho) * vm);
    o.f = [(k * vrel[0]), (k * vrel[1]), (k * vrel[2])];
    o.a = [(o.f[0] / mass), (o.f[1] / mass), (o.f[2] / mass)];
    o.drag = ((((0.5 * cd) * area) * rho) * f64::powf(vm, core::hint::black_box(2.0)));
    o.vrel = vm;
    o.cd = cd;
    o.qd = ((0.5 * rho) * f64::powf(vm, core::hint::black_box(2.0)));
    o.a_proj = area;
    o
}

/// arrayNormal(axis, sHat_b) of dgeom: the best-lit normal of an array turning about axis, towards s_hat_b (Octave's
/// unit vectors).
/// - axis: real[1][3] (passed a plain number)
/// - s_hat_b: real[1][3] (passed a plain number)
/// - returns nrm: real[1][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn drag_array_normal(axis: [f64; 3], s_hat_b: [f64; 3]) -> [f64; 3] {
    let mut nrm: [f64; 3] = [0.0; 3];
    let mut ax: [f64; 3] = crate::gen::drag::ounit(axis);
    let mut d: f64 = rt::dot(s_hat_b, ax);
    let mut proj: [f64; 3] = [(s_hat_b[0] - (d * ax[0])), (s_hat_b[1] - (d * ax[1])), (s_hat_b[2] - (d * ax[2]))];
    if (crate::gen::gravity::onorm(proj) < 1.0e-9) {
        let mut t: [f64; 3] = [1.0, 0.0, 0.0];
        if (rt::fabs(ax[0]) > 0.9) {
            t = [0.0, 1.0, 0.0];
        }
        let mut d2: f64 = rt::dot(t, ax);
        proj = [(t[0] - (d2 * ax[0])), (t[1] - (d2 * ax[1])), (t[2] - (d2 * ax[2]))];
    }
    nrm = crate::gen::drag::ounit(proj);
    nrm
}

/// drag.force(r, v, atm, facets, model, gsi, opts): the free-molecular force on the facets (body frame; the attitude
/// r_bi body to ECI), summed over the air's species (atm: the six DTM species, or one mean species), with the panel
/// model and the gsi; mass and aref [kg, m^2], the wind and the Earth's rate omega (ECI), the Sun's direction where a
/// facet tracks it (has_sun). The status names a facet the force cannot take (k, from 1).
/// - r: real[1][3] (passed a plain number)
/// - v: real[1][3] (passed a plain number)
/// - atm: AtmosOut (passed rec)
/// - f: ScFacets (passed rec)
/// - model: PanelModel (passed a choice, as its option's number)
/// - g: Gsi (passed rec)
/// - mass: real[1] (passed a plain number)
/// - aref: real[1] (passed a plain number)
/// - r_bi: real[1][3][3] (passed a plain number)
/// - wind: real[1][3] (passed a plain number)
/// - omega: real[1][3] (passed a plain number)
/// - has_sun: bool (passed true or false)
/// - sun: real[1][3] (passed a plain number)
/// - returns st: DragStatus (passed a choice, as its option's number)
/// - returns k: int (passed a whole number)
/// - returns o: PanelOut (passed rec)
#[allow(clippy::too_many_arguments)]
pub fn panel_force(r: [f64; 3], v: [f64; 3], atm: AtmosOut, f: ScFacets, model: i64, g: Gsi, mass: f64, aref: f64, r_bi: [[f64; 3]; 3], wind: [f64; 3], omega: [f64; 3], has_sun: bool, sun: [f64; 3]) -> (i64, i64, PanelOut) {
    let mut st: i64 = 0;
    let mut k: i64 = 0;
    let mut o: PanelOut = PanelOut::default();
    st = crate::gen::drag::DRAGSTATUS_OK;
    k = 0;
    o = PanelOut::default();
    let (mut vrel, mut uhat, mut vm) = crate::gen::drag::rel_velocity(r, v, wind, omega);
    let (mut alpha, mut beta, mut vw, mut vb) = crate::gen::drag::wind_angles(vrel, r_bi);
    let mut rho_s: [f64; 6] = [0.0; 6];
    let mut ms: [f64; 6] = [0.0; 6];
    let mut ns: i64 = 1;
    let mut n_o: f64 = atm.n_o;
    if atm.species {
        ns = 6;
        let mut mdtm: [f64; 6] = crate::gen::gsi::dtm_molar_masses();
        {
            let __end10: i64 = 6;
            let mut i: i64 = 0;
            while i < __end10 {
                ms[(i) as usize] = mdtm[(i) as usize];
                rho_s[(i) as usize] = ((atm.n[(i) as usize] * ms[(i) as usize]) / crate::gen::drag::DRAG_NA);
                i += 1;
            }
        }
        n_o = atm.n[2];
    } else {
        rho_s[0] = atm.rho;
        ms[0] = atm.mmol;
    }
    let mut a_t: f64 = 0.0;
    if ((model == crate::gen::gsi::PANELMODEL_DRIA) || (model == crate::gen::gsi::PANELMODEL_SESAM)) {
        a_t = crate::gen::gsi::sesam(n_o, atm.t);
    } else if (model == crate::gen::gsi::PANELMODEL_SENTMAN) {
        a_t = g.a_t;
    }
    let mut fs: [f64; 3] = [0.0, 0.0, 0.0];
    let mut aproj: f64 = 0.0;
    let mut s_o: f64 = crate::gen::gsi::speed_ratio(vm, atm.t, crate::gen::gsi::molar_mass(crate::gen::gsi::SPECIES_O));
    {
        let __end11: i64 = f.nf;
        let mut j: i64 = 0;
        while j < __end11 {
            if (st == crate::gen::drag::DRAGSTATUS_OK) {
                let mut nb: [f64; 3] = f.n[(j) as usize];
                if (f.kind[(j) as usize] == (crate::gen::srp::FACETKIND_ARRAY as i64)) {
                    if (!has_sun) {
                        st = crate::gen::drag::DRAGSTATUS_ARRAY_NEEDS_SUN;
                        k = (j + 1);
                    } else {
                        let mut nsun: f64 = crate::gen::gravity::onorm(sun);
                        let mut sh: [f64; 3] = [(sun[0] / nsun), (sun[1] / nsun), (sun[2] / nsun)];
                        let mut sb: [f64; 3] = rt::mv(rt::tr(r_bi), sh);
                        nb = crate::gen::drag::drag_array_normal(f.axis[(j) as usize], sb);
                    }
                }
                if ((st == crate::gen::drag::DRAGSTATUS_OK) && (crate::gen::gravity::onorm(nb) < crate::gen::drag::DRAG_EPS)) {
                    st = crate::gen::drag::DRAGSTATUS_ZERO_NORMAL;
                    k = (j + 1);
                }
                if (st == crate::gen::drag::DRAGSTATUS_OK) {
                    let mut n0: [f64; 3] = rt::mv(r_bi, nb);
                    let mut nn: f64 = crate::gen::gravity::onorm(n0);
                    let mut n: [f64; 3] = [(n0[0] / nn), (n0[1] / nn), (n0[2] / nn)];
                    let mut cosd: f64 = rt::dot(n, uhat);
                    if ((f.dbl[(j) as usize] == 1) && (cosd < 0.0)) {
                        n = [(-(n[0])), (-(n[1])), (-(n[2]))];
                        cosd = (-(cosd));
                    }
                    if (!(cosd <= 0.0)) {
                        aproj = (aproj + (f.a[(j) as usize] * cosd));
                        let mut delta: f64 = f64::acos(crate::gen::srp::min_one(cosd));
                        let mut s2: f64 = (1.0 - f64::powf(cosd, core::hint::black_box(2.0)));
                        let mut sind: f64 = f64::sqrt((if (s2 > 0.0) { s2 } else { 0.0 }));
                        let mut tgas: [f64; 3] = [0.0, 0.0, 0.0];
                        if (sind > 1.0e-9) {
                            tgas = [(((-(uhat[0])) + (cosd * n[0])) / sind), (((-(uhat[1])) + (cosd * n[1])) / sind), (((-(uhat[2])) + (cosd * n[2])) / sind)];
                        }
                        {
                            let __end12: i64 = ns;
                            let mut jj: i64 = 0;
                            while jj < __end12 {
                                let mut s: f64 = crate::gen::gsi::speed_ratio(vm, atm.t, ms[(jj) as usize]);
                                let mut cp: f64 = 0.0;
                                let mut ct: f64 = 0.0;
                                if (model == crate::gen::gsi::PANELMODEL_CLL) {
                                    let __t13 = crate::gen::gsi::cll(s, delta, g.sig_n, g.sig_t, g.tw, atm.t);
                                    cp = __t13.0;
                                    ct = __t13.1;
                                } else {
                                    let __t14 = crate::gen::gsi::sentman(s, delta, a_t, g.tw, atm.t);
                                    cp = __t14.0;
                                    ct = __t14.1;
                                }
                                let mut q: f64 = (((0.5 * rho_s[(jj) as usize]) * f64::powf(vm, core::hint::black_box(2.0))) * f.a[(j) as usize]);
                                {
                                    let __end15: i64 = 3;
                                    let mut i: i64 = 0;
                                    while i < __end15 {
                                        fs[(i) as usize] = (fs[(i) as usize] + (q * ((ct * tgas[(i) as usize]) - (cp * n[(i) as usize]))));
                                        i += 1;
                                    }
                                }
                                jj += 1;
                            }
                        }
                    }
                }
            }
            j += 1;
        }
    }
    if (st == crate::gen::drag::DRAGSTATUS_OK) {
        let mut fbody: [f64; 3] = rt::mv(rt::tr(r_bi), fs);
        let mut fwind: [f64; 3] = rt::mv(crate::gen::drag::body_to_wind(alpha, beta), fbody);
        let mut d: f64 = (-(fwind[0]));
        let mut sd: f64 = fwind[1];
        let mut l: f64 = (-(fwind[2]));
        let mut rho_tot: f64 = 0.0;
        {
            let __end16: i64 = ns;
            let mut i2: i64 = 0;
            while i2 < __end16 {
                rho_tot = (rho_tot + rho_s[(i2) as usize]);
                i2 += 1;
            }
        }
        let mut qd: f64 = ((0.5 * rho_tot) * f64::powf(vm, core::hint::black_box(2.0)));
        let mut fu: f64 = rt::dot(fs, uhat);
        let mut dv: [f64; 3] = [(fu * uhat[0]), (fu * uhat[1]), (fu * uhat[2])];
        o.f = fs;
        o.a = [(fs[0] / mass), (fs[1] / mass), (fs[2] / mass)];
        o.fbody = fbody;
        o.drag = d;
        o.side = sd;
        o.lift = l;
        o.drag_vec = dv;
        o.lift_vec = [(fs[0] - dv[0]), (fs[1] - dv[1]), (fs[2] - dv[2])];
        o.uhat = uhat;
        o.vrel = vm;
        o.s_o = s_o;
        o.qd = qd;
        o.alpha = alpha;
        o.beta = beta;
        o.cd = (d / (qd * aref));
        o.cl = (l / (qd * aref));
        o.cs = (sd / (qd * aref));
        o.a_proj = aproj;
        o.cd_a = (if (aproj > 0.0) { (d / (qd * aproj)) } else { f64::NAN });
        o.aref_used = aref;
    }
    (st, k, o)
}

/// The geodetic probe point of forces.drag: the altitude [km], latitude and longitude [deg] and the local solar time
/// mod(UT + lon/15, 24) [h] of a geodetic latitude and longitude [rad] and height [m] at the UTC date utc.
/// - lat_rad: real[1] (passed a plain number)
/// - lon_rad: real[1] (passed a plain number)
/// - alt_m: real[1] (passed a plain number)
/// - utc: real[1][6] (passed a plain number)
/// - returns alt_km: real[1] (passed a plain number)
/// - returns lat_deg: real[1] (passed a plain number)
/// - returns lon_deg: real[1] (passed a plain number)
/// - returns lst_h: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn probe_geo(lat_rad: f64, lon_rad: f64, alt_m: f64, utc: [f64; 6]) -> (f64, f64, f64, f64) {
    let mut alt_km: f64 = 0.0;
    let mut lat_deg: f64 = 0.0;
    let mut lon_deg: f64 = 0.0;
    let mut lst_h: f64 = 0.0;
    lon_deg = (lon_rad * (180.0 / core::f64::consts::PI));
    let mut utsec: f64 = (((utc[3] * 3600.0) + (utc[4] * 60.0)) + utc[5]);
    alt_km = (alt_m / 1000.0);
    lat_deg = (lat_rad * (180.0 / core::f64::consts::PI));
    lst_h = crate::gen::timescales::omod(((utsec / 3600.0) + (lon_deg / 15.0)), 24.0);
    (alt_km, lat_deg, lon_deg, lst_h)
}

/// The cannonball's drag coefficient forces.drag takes: the force set's when it states one, else the spacecraft's,
/// else 2.2.
/// - has_cfg: bool (passed true or false)
/// - cfg_cd: real[1] (passed a plain number)
/// - has_sc: bool (passed true or false)
/// - sc_cd: real[1] (passed a plain number)
/// - returns cd: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn drag_cd(has_cfg: bool, cfg_cd: f64, has_sc: bool, sc_cd: f64) -> f64 {
    let mut cd: f64 = 0.0;
    if has_cfg {
        cd = cfg_cd;
    } else if has_sc {
        cd = sc_cd;
    } else {
        cd = 2.2;
    }
    cd
}

/// The facets the panel models take: the spacecraft's, or a single +x plate of the reference area when it has none.
/// - f: ScFacets (passed rec)
