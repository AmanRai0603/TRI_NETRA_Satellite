    f = crate::gen::srp::facet_add(f, crate::gen::srp::FACETKIND_PLAIN, [1.0, 0.0, 0.0], (ly * lz), 0.0, 0.0, 0.0, z, false);
    f = crate::gen::srp::facet_add(f, crate::gen::srp::FACETKIND_PLAIN, [(-(1.0)), 0.0, 0.0], (ly * lz), 0.0, 0.0, 0.0, z, false);
