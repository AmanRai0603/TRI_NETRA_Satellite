/// - mu: real[1] (passed a plain number)
/// - re: real[1] (passed a plain number)
/// - j: real[1][5] (passed a plain number)
/// - nj: int (passed a whole number)
/// - use_sh: bool (passed true or false)
/// - c: inout real[1][GRAV_CS] (passed a plain number)
/// - s: inout real[1][GRAV_CS] (passed a plain number)
/// - f1: inout real[1][GRAV_VS] (passed a plain number)
/// - f2: inout real[1][GRAV_VS] (passed a plain number)
/// - v: inout real[1][GRAV_VS] (passed a plain number)
/// - w: inout real[1][GRAV_VS] (passed a plain number)
/// - returns a: real[1][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn j2accel(r: [f64; 3], mu: f64, re: f64, j: [f64; 5], nj: i64, use_sh: bool, c: &mut [f64; 14641], s: &mut [f64; 14641], f1: &mut [f64; 15129], f2: &mut [f64; 15129], v: &mut [f64; 15129], w: &mut [f64; 15129]) -> [f64; 3] {
    let mut a: [f64; 3] = [0.0; 3];
    let mut rn: f64 = crate::gen::gravity::onorm(r);
    let mut rn3: f64 = f64::powf(rn, core::hint::black_box(3.0));
    a = [(((-(mu)) * r[0]) / rn3), (((-(mu)) * r[1]) / rn3), (((-(mu)) * r[2]) / rn3)];
    if (nj > 0) {
        if (j[0] != 0.0) {
            let mut j2: f64 = j[0];
            let mut u: f64 = (r[2] / rn);
            let mut k: f64 = ((((1.5 * j2) * mu) * rt::ipow(re, 2)) / f64::powf(rn, core::hint::black_box(4.0)));
            let mut u2: f64 = rt::ipow(u, 2);
            a[0] = (a[0] + (((k * ((5.0 * u2) - 1.0)) * r[0]) / rn));
            a[1] = (a[1] + (((k * ((5.0 * u2) - 1.0)) * r[1]) / rn));
            a[2] = (a[2] + (((k * ((5.0 * u2) - 3.0)) * r[2]) / rn));
        }
        if use_sh {
            let mut maxn: i64 = (nj + 1);
            let mut sh: [f64; 3] = crate::gen::gravity::sph_accel(r, mu, re, maxn, maxn, 0, &mut (*c), &mut (*s), &mut (*f1), &mut (*f2), &mut (*v), &mut (*w));
            let mut tb: [f64; 3] = crate::gen::gravity::two_body(r, mu);
            {
                let __end42: i64 = 3;
                let mut i: i64 = 0;
                while i < __end42 {
                    a[(i) as usize] = ((a[(i) as usize] + sh[(i) as usize]) - tb[(i) as usize]);
                    i += 1;
                }
            }
        }
    }
    a
}

/// forces.gravity's frames: r_ecef = C r_eci.
/// - c: real[1][3][3] (passed a plain number)
/// - r: real[1][3] (passed a plain number)
/// - returns re_: real[1][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn to_ecef(c: [[f64; 3]; 3], r: [f64; 3]) -> [f64; 3] {
    let mut re_: [f64; 3] = [0.0; 3];
    re_ = rt::mv(c, r);
    re_
}

/// forces.gravity's frames: a_eci = C' a_ecef.
/// - c: real[1][3][3] (passed a plain number)
/// - a: real[1][3] (passed a plain number)
/// - returns ae: real[1][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn from_ecef(c: [[f64; 3]; 3], a: [f64; 3]) -> [f64; 3] {
    let mut ae: [f64; 3] = [0.0; 3];
    ae = rt::mv(rt::tr(c), a);
    ae
}
