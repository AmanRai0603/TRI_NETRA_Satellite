/// op.coe2rv(a, e, i, RAAN, w, nu, mu): classical elements [m, rad] to an ECI position and velocity (closed orbits).
/// - a: real[1] (passed a plain number)
/// - e: real[1] (passed a plain number)
/// - inc: real[1] (passed a plain number)
/// - raan: real[1] (passed a plain number)
/// - argp: real[1] (passed a plain number)
/// - nu: real[1] (passed a plain number)
/// - mu: real[1] (passed a plain number)
/// - returns r: real[1][3] (passed a plain number)
/// - returns v: real[1][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn pop_coe2rv(a: f64, e: f64, inc: f64, raan: f64, argp: f64, nu: f64, mu: f64) -> ([f64; 3], [f64; 3]) {
    let mut r: [f64; 3] = [0.0; 3];
    let mut v: [f64; 3] = [0.0; 3];
    let mut p: f64 = (a * (1.0 - rt::ipow(e, 2)));
    let mut rmag: f64 = (p / (1.0 + (e * f64::cos(nu))));
    let mut r_pf: [f64; 3] = [(rmag * f64::cos(nu)), (rmag * f64::sin(nu)), 0.0];
    let mut k: f64 = f64::sqrt((mu / p));
    let mut v_pf: [f64; 3] = [(k * (-(f64::sin(nu)))), (k * (e + f64::cos(nu))), 0.0];
    let mut co: f64 = f64::cos(raan);
    let mut so: f64 = f64::sin(raan);
    let mut ci: f64 = f64::cos(inc);
    let mut si: f64 = f64::sin(inc);
    let mut cw: f64 = f64::cos(argp);
    let mut sw: f64 = f64::sin(argp);
    let mut q: [[f64; 3]; 3] = [[((co * cw) - ((so * sw) * ci)), (((-(co)) * sw) - ((so * cw) * ci)), (so * si)], [((so * cw) + ((co * sw) * ci)), (((-(so)) * sw) + ((co * cw) * ci)), ((-(co)) * si)], [(sw * si), (cw * si), ci]];
    r = rt::mv(q, r_pf);
    v = rt::mv(q, v_pf);
    (r, v)
}

