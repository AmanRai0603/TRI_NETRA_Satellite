/// timeconv.convertUTC: one UTC calendar instant in every scale, given UT1 - UTC [s] (the leap looked up once: the
/// same value MATLAB looks up in each of its calls).
/// - y: real[1] (passed a plain number)
/// - mo: real[1] (passed a plain number)
/// - d: real[1] (passed a plain number)
/// - h: real[1] (passed a plain number)
/// - mi: real[1] (passed a plain number)
/// - s: real[1] (passed a plain number)
/// - dut1: real[1] (passed a plain number)
/// - returns t: Times (passed rec)
#[allow(clippy::too_many_arguments)]
pub fn convert_utc(y: f64, mo: f64, d: f64, h: f64, mi: f64, s: f64, dut1: f64) -> Times {
    let mut t: Times = Times::default();
    let mut jdu: f64 = crate::gen::timescales::cal2jd(y, mo, d, h, mi, s);
    let mut leap: f64 = crate::gen::timescales::tai_minus_utc(jdu);
    let mut tai_jd: f64 = (jdu + (leap / 86400.0));
    let mut tt_jd: f64 = crate::gen::timescales::tai2tt(tai_jd);
    let mut tdb_jd: f64 = crate::gen::timescales::tt2tdb(tt_jd);
    let mut ut1_jd: f64 = crate::gen::timescales::utc2ut1(jdu, dut1);
    let mut gps_jd: f64 = crate::gen::timescales::tai2gps(tai_jd);
    let (mut week, mut sow) = crate::gen::timescales::gps_week_sow(gps_jd);
    t = Times::default();
    t.utc_jd = jdu;
    t.tai_jd = tai_jd;
    t.tt_jd = tt_jd;
    t.tdb_jd = tdb_jd;
    t.ut1_jd = ut1_jd;
    t.gps_jd = gps_jd;
    t.utc_mjd = crate::gen::timescales::jd2mjd(jdu);
    t.tt_mjd = crate::gen::timescales::jd2mjd(tt_jd);
    t.tdb_mjd = crate::gen::timescales::jd2mjd(tdb_jd);
    t.leap = leap;
    t.dut1 = dut1;
    t.t_tt = crate::gen::timescales::tt2jc(tt_jd);
    t.j2000_tt_sec = crate::gen::timescales::j2000sec(tt_jd);
    t.gps_week = week;
    t.gps_sow = sow;
    t.gmst_rad = crate::gen::timescales::gmst82(ut1_jd);
    t.doy = crate::gen::timescales::doy(y, mo, d);
    t
}

/// Octave's leap-year rule, as datenum uses it.
/// - y: real[1] (passed a plain number)
/// - returns b: bool (passed true or false)
#[allow(clippy::too_many_arguments)]
pub fn is_leap_year(y: f64) -> bool {
    let mut b: bool = false;
    b = (((crate::gen::timescales::omod(y, 4.0) == 0.0) && (crate::gen::timescales::omod(y, 100.0) != 0.0)) || (crate::gen::timescales::omod(y, 400.0) == 0.0));
    b
}

/// Octave's datenum(year, month, day, hour, minute, second) for scalars: days since year 0.
/// - year: real[1] (passed a plain number)
/// - month: real[1] (passed a plain number)
/// - day: real[1] (passed a plain number)
/// - hour: real[1] (passed a plain number)
/// - minute: real[1] (passed a plain number)
/// - second: real[1] (passed a plain number)
/// - returns dn: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn datenum(year: f64, month: f64, day: f64, hour: f64, minute: f64, second: f64) -> f64 {
    let mut dn: f64 = 0.0;
    let mut monthstart: [f64; 12] = [306.0, 337.0, 0.0, 31.0, 61.0, 92.0, 122.0, 153.0, 184.0, 214.0, 245.0, 275.0];
    let mut monthlength: [f64; 12] = [31.0, 28.0, 31.0, 30.0, 31.0, 30.0, 31.0, 31.0, 30.0, 31.0, 30.0, 31.0];
    let mut yr: f64 = year;
    let mut mo: f64 = month;
    if (month < 1.0) {
        mo = 1.0;
    }
    let mut dd: f64 = day;
    if (mo != f64::trunc(mo)) {
        let mut fracmonth: f64 = (mo - f64::floor(mo));
        mo = f64::floor(mo);
        let mut mi: i64 = (((crate::gen::timescales::omod((mo - 1.0), 12.0) + 1.0) as i64) - 1);
        if ((mi != 1) || (!crate::gen::timescales::is_leap_year(f64::floor(yr)))) {
            dd = (dd + (fracmonth * monthlength[(mi) as usize]));
        } else {
            dd = (dd + (fracmonth * 29.0));
        }
    }
    yr = (yr + f64::ceil(((mo - 14.0) / 12.0)));
    dd = (dd + (monthstart[((((crate::gen::timescales::omod((mo - 1.0), 12.0) + 1.0) as i64) - 1)) as usize] + 60.0));
    if (yr != f64::trunc(yr)) {
        let mut fracyear: f64 = (yr - f64::floor(yr));
        yr = f64::floor(yr);
        dd = (dd + (fracyear * (365.0 + (if crate::gen::timescales::is_leap_year((yr + 1.0)) { 1.0 } else { 0.0 }))));
    }
    dd = (dd + ((((365.0 * yr) + f64::floor((yr / 4.0))) - f64::floor((yr / 100.0))) + f64::floor((yr / 400.0))));
    dn = (dd + ((hour + ((minute + (second / 60.0)) / 60.0)) / 24.0));
    dn
}

/// Octave's datevec(datenum) for a scalar: [Y Mo D H Mi S], the seconds rounded to the datenum's resolution as Octave
/// rounds them.
/// - date: real[1] (passed a plain number)
/// - returns v: real[1][6] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn datevec(date: f64) -> [f64; 6] {
    let mut v: [f64; 6] = [0.0; 6];
    let mut z: f64 = (f64::floor(date) - 60.0);
    let mut a: f64 = f64::floor(((z - 0.25) / 36524.25));
    let mut b: f64 = (((z - 0.25) + a) - f64::floor((a / 4.0)));
    let mut y: f64 = f64::floor((b / 365.25));
    let mut c: f64 = (f64::trunc((b - f64::floor((365.25 * y)))) + 1.0);
    let mut m: f64 = f64::trunc((((5.0 * c) + 456.0) / 153.0));
    let mut d: f64 = (c - f64::trunc((((153.0 * m) - 457.0) / 5.0)));
    if (m > 12.0) {
        y = (y + 1.0);
        m = (m - 12.0);
    }
    let mut fracd: f64 = (date - f64::floor(date));
    let mut tmps: f64 = rt::fabs(((2.220446049250313e-16 * 86400.0) * date));
    if (tmps == 0.0) {
        tmps = 1.0;
    }
    let mut srnd: f64 = f64::powf(2.0, f64::floor((-(f64::log2(tmps)))));
    let mut s: f64 = (f64::round(((86400.0 * fracd) * srnd)) / srnd);
    let mut h: f64 = f64::floor((s / 3600.0));
    s = (s - (3600.0 * h));
    let mut mi: f64 = f64::floor((s / 60.0));
    s = (s - (60.0 * mi));
    v = [y, m, d, h, mi, s];
    v
}

/// op.addsec: a UTC [Y Mo D H Mi S] plus some seconds, through datenum and datevec (leap seconds not represented, as
/// MATLAB).
/// - utc: real[1][6] (passed a plain number)
/// - sec: real[1] (passed a plain number)
/// - returns u: real[1][6] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn addsec(utc: [f64; 6], sec: f64) -> [f64; 6] {
    let mut u: [f64; 6] = [0.0; 6];
    let mut dn: f64 = (crate::gen::timescales::datenum(utc[0], utc[1], utc[2], utc[3], utc[4], utc[5]) + (sec / 86400.0));
    u = crate::gen::timescales::datevec(dn);
    u
}
