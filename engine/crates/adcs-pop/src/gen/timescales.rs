/// timeconv.taiMinusUTC: TAI - UTC [s] at a UTC Julian date, 10 before 1972, else the last leap-second row whose
/// first of the month (0 h UTC) is at or before it.
/// - jd_utc: real[1] (passed a plain number)
/// - returns n: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn tai_minus_utc(jd_utc: f64) -> f64 {
    let mut n: f64 = 0.0;
    n = 10.0;
    {
        let __end23: i64 = 28;
        let mut i: i64 = 0;
        while i < __end23 {
            if (jd_utc >= crate::gen::timescales::cal2jd(crate::gen::leapsec::DATA_LEAP_SECONDS[(i) as usize][0], crate::gen::leapsec::DATA_LEAP_SECONDS[(i) as usize][1], 1.0, 0.0, 0.0, 0.0)) {
                n = crate::gen::leapsec::DATA_LEAP_SECONDS[(i) as usize][2];
            }
            i += 1;
        }
    }
    n
}

