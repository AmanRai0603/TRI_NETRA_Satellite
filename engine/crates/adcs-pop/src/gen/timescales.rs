/// - jd_gps: real[1] (passed a plain number)
/// - returns week: real[1] (passed a plain number)
/// - returns sow: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn gps_week_sow(jd_gps: f64) -> (f64, f64) {
    let mut week: f64 = 0.0;
    let mut sow: f64 = 0.0;
    let mut dt: f64 = (jd_gps - 2444244.5);
    week = f64::floor((dt / 7.0));
    sow = ((dt - (week * 7.0)) * 86400.0);
    (week, sow)
}

/// timeconv.gmst82: the Greenwich mean sidereal time (IAU 1982) [rad] of a UT1 Julian date.
/// - jd_ut1: real[1] (passed a plain number)
/// - returns g: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn gmst82(jd_ut1: f64) -> f64 {
    let mut g: f64 = 0.0;
    let mut tu: f64 = ((jd_ut1 - 2451545.0) / 36525.0);
    let mut sec: f64 = (((67310.54841 + (((876600.0 * 3600.0) + 8640184.812866) * tu)) + (0.093104 * f64::powf(tu, 2.0))) - (0.0000062 * f64::powf(tu, 3.0)));
    g = crate::gen::timescales::deg2rad((crate::gen::timescales::omod(sec, 86400.0) / 240.0));
    g
}

/// timeconv.doy: the day of the year (1 .. 366).
/// - y: real[1] (passed a plain number)
