/// Octave's mod(x, y) for doubles: 0 when y is not whole and x/y is within one relative eps of a whole number, else
/// x - y floor(x/y); the result takes the sign of y.
/// - x: real[1] (passed a plain number)
/// - y: real[1] (passed a plain number)
/// - returns r: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn omod(x: f64, y: f64) -> f64 {
    let mut r: f64 = 0.0;
    if (y == 0.0) {
        r = x;
    } else {
        let mut q: f64 = (x / y);
        let mut nint_y: f64 = f64::floor((y + 0.5));
        let mut nint_q: f64 = q;
        if (q).is_finite() {
            nint_q = f64::floor((q + 0.5));
        }
        if ((nint_y != y) && (rt::fabs(((q - nint_q) / nint_q)) < 2.220446049250313e-16)) {
            r = 0.0;
        } else {
            r = (x - (y * f64::floor(q)));
        }
    }
    if ((x != y) && (y != 0.0)) {
        if (y < 0.0) {
            r = (-(rt::fabs(r)));
        } else {
            r = rt::fabs(r);
        }
    }
    r
}

/// Degrees to radians, as Octave's deg2rad: deg (pi/180).
/// - deg: real[1] (passed a plain number)
/// - returns r: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn deg2rad(deg: f64) -> f64 {
    let mut r: f64 = 0.0;
    r = (deg * (core::f64::consts::PI / 180.0));
    r
}

/// timeconv.cal2jd: a Gregorian calendar date and time to a Julian date (any scale).
/// - y: real[1] (passed a plain number)
/// - mo: real[1] (passed a plain number)
/// - d: real[1] (passed a plain number)
/// - h: real[1] (passed a plain number)
/// - mi: real[1] (passed a plain number)
/// - s: real[1] (passed a plain number)
/// - returns j: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn cal2jd(y: f64, mo: f64, d: f64, h: f64, mi: f64, s: f64) -> f64 {
    let mut j: f64 = 0.0;
    let mut a: f64 = f64::floor(((14.0 - mo) / 12.0));
    let mut yy: f64 = ((y + 4800.0) - a);
    let mut m: f64 = ((mo + (12.0 * a)) - 3.0);
    let mut jdn: f64 = ((((((d + f64::floor((((153.0 * m) + 2.0) / 5.0))) + (365.0 * yy)) + f64::floor((yy / 4.0))) - f64::floor((yy / 100.0))) + f64::floor((yy / 400.0))) - 32045.0);
    j = (((jdn + ((h - 12.0) / 24.0)) + (mi / 1440.0)) + (s / 86400.0));
    j
}

/// timeconv.jd2cal: a Julian date to the Gregorian [Y M D h mi s].
/// - j: real[1] (passed a plain number)
/// - returns u: real[1][6] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn jd2cal(j: f64) -> [f64; 6] {
    let mut u: [f64; 6] = [0.0; 6];
    let mut q: f64 = (j + 0.5);
    let mut z: f64 = f64::floor(q);
    let mut f: f64 = (q - z);
    let mut a: f64 = z;
    if (z >= 2299161.0) {
        let mut al: f64 = f64::floor(((z - 1867216.25) / 36524.25));
        a = (((z + 1.0) + al) - f64::floor((al / 4.0)));
    }
    let mut b: f64 = (a + 1524.0);
    let mut c: f64 = f64::floor(((b - 122.1) / 365.25));
    let mut dd: f64 = f64::floor((365.25 * c));
    let mut e: f64 = f64::floor(((b - dd) / 30.6001));
    let mut day: f64 = (((b - dd) - f64::floor((30.6001 * e))) + f);
    let mut m: f64 = (if (e < 14.0) { (e - 1.0) } else { (e - 13.0) });
    let mut y: f64 = (if (m > 2.0) { (c - 4716.0) } else { (c - 4715.0) });
    let mut d: f64 = f64::floor(day);
    let mut fr: f64 = ((day - d) * 24.0);
    let mut h: f64 = f64::floor(fr);
    fr = ((fr - h) * 60.0);
    let mut mi: f64 = f64::floor(fr);
    let mut s: f64 = ((fr - mi) * 60.0);
    u = [y, m, d, h, mi, s];
    u
}

