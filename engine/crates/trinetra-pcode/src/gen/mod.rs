/// Files as a translator writes them: (path, text), in the order the JavaScript sets them.
pub type Files = Vec<(String, String)>;

/// How the Rust is written (`toRust`'s options).
#[derive(Clone, Copy, Debug)]
pub struct RustOptions<'a> {
    /// the crate's title, its documentation's first line
    pub title: Option<&'a str>,
    /// the path the modules are under: `crate` (a crate of its own, `src/lib.rs`), or a module of a
    /// crate (`crate::alg`, written as `src/mod.rs`), as the flight build embeds it
    pub root: Option<&'a str>,
    /// the module the scalar maths comes from (a no_std crate's, such as `crate::m`); `f64`'s own when None
    pub math: Option<&'a str>,
    /// write the vector dispatcher (`src/dispatch.rs`, a test aid that needs the heap)
    pub dispatch: bool,
}

impl Default for RustOptions<'_> {
    fn default() -> Self {
        RustOptions { title: None, root: None, math: None, dispatch: true }
    }
}

impl Program {
    /// The program in Rust, as `toRust(program, { title })`: `src/<module>.rs` for each module,
    /// `src/dispatch.rs`, `src/rt.rs` and `src/lib.rs`, in that order.
    pub fn to_rust_files(&self, title: Option<&str>) -> Result<Files, String> {
        rust::to_rust(&self.i, &RustOptions { title, ..RustOptions::default() })
    }
    /// The program in Rust with every option (`toRust(program, { title, root, math, dispatch })`).
    pub fn to_rust_files_with(&self, o: &RustOptions) -> Result<Files, String> {
        rust::to_rust(&self.i, o)
    }
    /// The program in Rust (`to_rust_files`), by path.
    pub fn to_rust(&self, title: Option<&str>) -> Result<BTreeMap<String, String>, String> {
        self.to_rust_files(title).map(by_path)
    }
    /// The program in C99, as `toC(program, { title, lib })`: `src/<module>.c` for each module,
    /// `src/dispatch.c`, `include/<lib>.h` and `include/<lib>_rt.h` (`lib` is "pcode" when not given).
    pub fn to_c_files(&self, title: Option<&str>, lib: Option<&str>) -> Result<Files, String> {
        c::to_c(&self.i, title, lib, true)
    }
    /// The program in C99 with or without the vector dispatcher (`toC(program, { title, lib, dispatch })`).
    pub fn to_c_files_with(&self, title: Option<&str>, lib: Option<&str>, dispatch: bool) -> Result<Files, String> {
        c::to_c(&self.i, title, lib, dispatch)
    }
    /// The program in C99 (`to_c_files`), by path.
    pub fn to_c(&self, title: Option<&str>, lib: Option<&str>) -> Result<BTreeMap<String, String>, String> {
        self.to_c_files(title, lib).map(by_path)
    }
    /// The program in MATLAB, as `toMatlab(program, { pkg })`: `+<module>/<name>.m` for each fn,
    /// proc, table and record, then `call.m` and `call_seq.m`. `pkg` ("asils.physics" when not
    /// given) is the package the files are placed in; the runtime is `asils.pc` (`matlab_runtime`).
    pub fn to_matlab_files(&self, pkg: Option<&str>) -> Result<Files, String> {
        matlab::to_matlab(&self.i, pkg)
    }
    /// The program in MATLAB (`to_matlab_files`), by path.
    pub fn to_matlab(&self, pkg: Option<&str>) -> Result<BTreeMap<String, String>, String> {
        self.to_matlab_files(pkg).map(by_path)
    }
}

/// The shared MATLAB runtime (`+asils/+pc`), as `matlabRuntime()`: written once, the interpreter's
/// arithmetic, in the JavaScript's order.
pub fn matlab_runtime_files() -> Files {
    matlab::runtime()
}

/// The shared MATLAB runtime (`matlab_runtime_files`), by path.
pub fn matlab_runtime() -> BTreeMap<String, String> {
    by_path(matlab_runtime_files())
}

fn by_path(files: Files) -> BTreeMap<String, String> {
    files.into_iter().collect()
}

/// The line every generated file carries.
fn head() -> String {
    format!("Generated by tools/pcode.py from the pseudocode ({VERSION}); do not edit.")
}

/// Set a file as a JavaScript object's key is set: a new path at the end, a path already there
/// replaced where it is.
fn set_file(files: &mut Files, path: String, text: String) {
    match files.iter_mut().find(|(p, _)| *p == path) {
        Some(f) => f.1 = text,
        None => files.push((path, text)),
    }
}

/// The shortest decimal that reads back as the same double, as a float literal (pcode_gen.js `lit`):
/// JavaScript's `String(x)`, with `.0` where it has no point or exponent, and before an exponent
/// whose mantissa has no point.
pub fn lit(x: f64) -> Result<String, String> {
    if !x.is_finite() {
        return Err(format!("cannot write {} as a literal", jsfmt::num(x)));
    }
    if x == 0.0 && x.is_sign_negative() {
        return Ok("-0.0".into());
    }
    let mut s = jsfmt::num(x);
    if !s.contains(['.', 'e', 'E']) {
        s.push_str(".0");
    }
    if s.contains('e') && !s.split('e').next().unwrap_or("").contains('.') {
        s = s.replacen('e', ".0e", 1);
    }
    Ok(s)
}

/// `String(v)` of an interpreter value, as JavaScript writes it.
fn js_string(v: &Value) -> String {
    match v {
        Value::Num(x) => jsfmt::num(*x),
        Value::Bool(b) => b.to_string(),
        Value::Arr(items) => items.iter().map(js_string).collect::<Vec<_>>().join(","),
        Value::Rec(_) => "[object Object]".into(),
    }
}

/// `lit(v)` of an interpreter value: only a number is one.
fn lit_value(v: &Value) -> Result<String, String> {
    match v {
        Value::Num(x) => lit(*x),
        other => Err(format!("cannot write {} as a literal", js_string(other))),
    }
}

/// JavaScript's `trimEnd`: its white space and line terminators.
fn trim_end_js(s: &str) -> &str {
    s.trim_end_matches(|c: char| {
        matches!(c, '\t' | '\n' | '\u{b}' | '\u{c}' | '\r' | ' ' | '\u{a0}' | '\u{1680}' | '\u{2000}'..='\u{200a}' | '\u{2028}' | '\u{2029}' | '\u{202f}' | '\u{205f}' | '\u{3000}' | '\u{feff}')
    })
}

/// JavaScript's `toUpperCase`.
fn upper(s: &str) -> String {
    s.to_uppercase()
}

/// `orbit_period` -> `OrbitPeriod`; a name with an empty part fails where the JavaScript throws.
fn pascal(n: &str) -> Result<String, String> {
    let mut out = String::new();
    for w in n.split('_') {
        let mut cs = w.chars();
        let Some(first) = cs.next() else {
            return Err(format!("cannot read properties of undefined (reading 'toUpperCase'): the name {n}"));
        };
        out.extend(first.to_uppercase());
        out.push_str(cs.as_str());
    }
    Ok(out)
}

fn is_int(t: Option<&Ty>) -> bool {
    matches!(t, Some(Ty::Int))
}
fn is_real(t: Option<&Ty>) -> bool {
    matches!(t, Some(Ty::Real(_)))
}
fn is_arr(t: Option<&Ty>) -> bool {
    matches!(t, Some(Ty::Arr(..)))
}
fn leaf_is_real(t: &Ty) -> bool {
    match t {
        Ty::Arr(_, of) => leaf_is_real(of),
        t => matches!(t, Ty::Real(_)),
    }
}
/// the type with every int made a real
fn real_of(t: &Ty) -> Ty {
    match t {
        Ty::Arr(n, of) => Ty::Arr(*n, Box::new(real_of(of))),
        Ty::Int => Ty::Real(DIMLESS),
        t => t.clone(),
    }
}
/// `{ k: "real" }`: a real, wanted
const REAL: Ty = Ty::Real(DIMLESS);

/// a type as it was written: real[kg m^2], vec3 as real[1][3], int, a record's name
fn decl_text(t: &TypeDecl) -> String {
    match t {
        TypeDecl::Int => "int".into(),
        TypeDecl::Bool => "bool".into(),
        TypeDecl::Real { unit } => format!("real[{}]", if unit.is_empty() { "1" } else { unit }),
        TypeDecl::Arr { n, of } => format!("{}[{n}]", decl_text(of)),
        TypeDecl::Rec { name, .. } => name.clone(),
    }
}
/// how a value is passed: its SI unit ("in m"), or what it is when it has none
fn si_of(t: &Ty) -> String {
    let mut e = t;
    while let Ty::Arr(_, of) = e {
        e = of;
    }
    match e {
        Ty::Real(d) => {
            let d = dim_text(d);
            if d == "1" {
                "a plain number".into()
            } else {
                format!("in {d}")
            }
        }
        Ty::Bool => "true or false".into(),
        Ty::Int => "a whole number".into(),
        Ty::Rec(_) => "rec".into(),
        Ty::Arr(..) => "arr".into(),
        Ty::Tuple(_) => "tuple".into(),
    }
}
fn io(p: &Param) -> String {
    format!("{}: {} (passed {})", p.name, decl_text(&p.decl), si_of(&p.ty))
}

/// What every translator shares: the program, the interpreter for its constants, and the first
/// failure (the JavaScript throws there; the translation goes on only to be thrown away).
struct Base<'a> {
    i: &'a Interp,
    c: &'a Checked,
    err: Option<String>,
}

impl<'a> Base<'a> {
    fn new(i: &'a Interp) -> Self {
        Base { i, c: &i.c, err: None }
    }
    fn fail(&mut self, msg: impl Into<String>) -> String {
        if self.err.is_none() {
            self.err = Some(msg.into());
        }
        String::new()
    }
    fn ok<T: Default>(&mut self, r: Result<T, String>) -> T {
        match r {
            Ok(v) => v,
            Err(e) => {
                self.fail(e);
                T::default()
            }
        }
    }
    fn lit(&mut self, x: f64) -> String {
        let r = lit(x);
        self.ok(r)
    }
    fn lit_value(&mut self, v: &Value) -> String {
        let r = lit_value(v);
        self.ok(r)
    }
    fn pascal(&mut self, n: &str) -> String {
        let r = pascal(n);
        self.ok(r)
    }
    /// a constant expression's value (pcode_gen.js `constOf`)
    fn const_of(&mut self, e: usize) -> Value {
        match self.i.eval_closed(e) {
            Ok(v) => v,
            Err(er) => {
                self.fail(er.0);
                Value::Num(0.0)
            }
        }
    }
    /// an expression's type as the checker left it
    fn ty(&self, e: usize) -> Option<&'a Ty> {
        self.c.ann[e].ty.as_ref()
    }
    /// an expression's type, where the JavaScript reads it without asking whether there is one
    fn ty_of(&mut self, e: usize) -> &'a Ty {
        match self.c.ann[e].ty.as_ref() {
            Some(t) => t,
            None => {
                self.fail("an expression has no type");
                &REAL
            }
        }
    }
    fn record(&self, name: &str) -> Option<&'a crate::ast::Record> {
        self.c.records.iter().find(|r| r.name == name)
    }
    /// a value (or a record's fields) as numbers: the dispatchers' width of a type
    fn flat(&self, t: &Ty) -> usize {
        match t {
            Ty::Arr(n, of) => n * self.flat(of),
            Ty::Rec(name) => self.record(name).map_or(0, |r| r.fields.iter().map(|f| self.flat(&f.ty)).sum()),
            _ => 1,
        }
    }
    fn done(self, files: Files) -> Result<Files, String> {
        match self.err {
            Some(e) => Err(e),
            None => Ok(files),
        }
    }
}

/// `JSON.stringify(files, null, 1) + "\n"`: the text design/js/pcode_cli.mjs prints for a
/// translation, a JSON object of path to text in the order given.
pub fn files_json(files: &[(String, String)]) -> String {
    if files.is_empty() {
        return "{}\n".into();
    }
    let body: Vec<String> = files.iter().map(|(p, t)| format!(" {}: {}", jsfmt::json_str(p), jsfmt::json_str(t))).collect();
    format!("{{\n{}\n}}\n", body.join(",\n"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn literals_are_written_as_the_javascript_writes_them() {
        for (x, s) in [(1.0, "1.0"), (-2.5, "-2.5"), (1e21, "1.0e+21"), (1.5e-7, "1.5e-7"), (-0.0, "-0.0"), (0.0, "0.0"), (1e-7, "1.0e-7")] {
            assert_eq!(lit(x).unwrap(), s);
        }
        assert!(lit(f64::NAN).is_err());
        assert_eq!(files_json(&[("a".into(), "x\n\"y\"".into())]), "{\n \"a\": \"x\\n\\\"y\\\"\"\n}\n");
        assert_eq!(pascal("orbit_period").unwrap(), "OrbitPeriod");
        assert!(pascal("a__b").is_err());
    }
}
