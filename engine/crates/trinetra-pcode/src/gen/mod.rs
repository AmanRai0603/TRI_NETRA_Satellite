//! The translators: a checked program to Rust (design/js/pcode_gen.js `toRust`), to C
//! (design/js/pcode_c.js `toC`) and to MATLAB (pcode_gen.js `toMatlab`, `matlabRuntime`), a port
//! held byte for byte to the JavaScript (tests/test_translators_lib.py): the same files, the same
//! text, the same order. Each follows the JavaScript line by line: the modules in the order their
//! files were given, a module's declarations in the order they were declared, the same temporary
//! names, every literal written as JavaScript writes it, and the constants and a proc's starting
//! state evaluated by the interpreter. Where the JavaScript throws (a value that cannot be written
//! as a literal, a type with no translation), the translation stops with its message.
//! Owner: Agastya. Copyright (c) 2026 Agastya. All rights reserved.

