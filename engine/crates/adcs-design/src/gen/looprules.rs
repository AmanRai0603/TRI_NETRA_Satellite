/// - fmr: bool (passed true or false)
/// - coils_only: bool (passed true or false)
/// - fine: bool (passed true or false)
/// - has_lambda: bool (passed true or false)
/// - lambda: real[1] (passed a plain number)
/// - has_fmr_scale: bool (passed true or false)
/// - fmr_scale: real[1] (passed a plain number)
/// - has_mtqp_scale: bool (passed true or false)
/// - mtqp_scale: real[1] (passed a plain number)
/// - star_tracker: bool (passed true or false)
/// - lambda_max: real[1] (passed a plain number)
/// - scale_max: real[1] (passed a plain number)
/// - up: real[1] (passed a plain number)
/// - ek: inout int[*] (passed a whole number)
/// - eo: inout int[*] (passed a whole number)
/// - ep: inout int[*] (passed a whole number)
/// - ea: inout real[1][*] (passed a plain number)
/// - eb: inout real[1][*] (passed a plain number)
/// - ec: inout real[1][*] (passed a plain number)
/// - ef: inout int[*] (passed a whole number)
/// - returns n: int (passed a whole number)
#[allow(clippy::too_many_arguments)]
pub fn loop_robust(f_power: bool, f_perf: bool, f_know: bool, fmr: bool, coils_only: bool, fine: bool, has_lambda: bool, lambda: f64, has_fmr_scale: bool, fmr_scale: f64, has_mtqp_scale: bool, mtqp_scale: f64, star_tracker: bool, lambda_max: f64, scale_max: f64, up: f64, ek: &mut [i64], eo: &mut [i64], ep: &mut [i64], ea: &mut [f64], eb: &mut [f64], ec: &mut [f64], ef: &mut [i64]) -> i64 {
    let mut n: i64 = 0;
    let (mut d_k_tau, mut d_lambda, mut d_heads, mut d_sigma, mut d_grade, mut b0, mut b1, mut b2, mut b3, mut b4, mut b5, mut b6, mut b7, mut b8, mut b9) = crate::gen::sizedemand::sizing_knobs();
    n = 0;
    if f_power {
        let mut lam: f64 = (if has_lambda { lambda } else { d_lambda });
        if (fmr && (lam < lambda_max)) {
            n = crate::gen::looprules::loop_event(&mut (*ek), &mut (*eo), &mut (*ep), &mut (*ea), &mut (*eb), &mut (*ec), &mut (*ef), n, crate::gen::looprules::LOOPEVENT_ROBUST_LAMBDA, (-(1)), (-(1)), lam, rt::fmin(lambda_max, (lam * 3.0)), 0.0, 0);
        } else {
            n = crate::gen::looprules::loop_event(&mut (*ek), &mut (*eo), &mut (*ep), &mut (*ea), &mut (*eb), &mut (*ec), &mut (*ef), n, crate::gen::looprules::LOOPEVENT_ROBUST_POWER, (-(1)), (-(1)), 0.0, 0.0, 0.0, 0);
        }
    }
    if f_perf {
        let mut part: i64 = (-(1));
        let mut s0: f64 = 1.0;
        if fmr {
            part = (crate::gen::looprules::PART_FMR as i64);
            if has_fmr_scale {
                s0 = fmr_scale;
            }
        } else if coils_only {
            part = (crate::gen::looprules::PART_MTQP as i64);
            if has_mtqp_scale {
                s0 = mtqp_scale;
            }
        }
        if ((part >= 0) && (s0 < scale_max)) {
            n = crate::gen::looprules::loop_event(&mut (*ek), &mut (*eo), &mut (*ep), &mut (*ea), &mut (*eb), &mut (*ec), &mut (*ef), n, crate::gen::looprules::LOOPEVENT_ROBUST_AUTHORITY, (-(1)), part, s0, rt::fmin(scale_max, (s0 * up)), 0.0, 0);
        } else {
            n = crate::gen::looprules::loop_event(&mut (*ek), &mut (*eo), &mut (*ep), &mut (*ea), &mut (*eb), &mut (*ec), &mut (*ef), n, crate::gen::looprules::LOOPEVENT_ROBUST_PERFORMANCE, (-(1)), part, 0.0, 0.0, 0.0, 0);
        }
    }
    if f_know {
        if ((!star_tracker) && (!fine)) {
            n = crate::gen::looprules::loop_event(&mut (*ek), &mut (*eo), &mut (*ep), &mut (*ea), &mut (*eb), &mut (*ec), &mut (*ef), n, crate::gen::looprules::LOOPEVENT_ROBUST_STAR_TRACKER, (-(1)), (-(1)), 0.0, 0.0, 0.0, 0);
        } else {
            n = crate::gen::looprules::loop_event(&mut (*ek), &mut (*eo), &mut (*ep), &mut (*ea), &mut (*eb), &mut (*ec), &mut (*ef), n, crate::gen::looprules::LOOPEVENT_ROBUST_KNOWLEDGE, (-(1)), (-(1)), 0.0, 0.0, 0.0, 0);
        }
    }
    n
}

/// The fault campaign's lever (pipeline_design's node_redundancy): a family that carries fluid rings (fmr), loses a
/// requirement to a single ring's failure (ring_gap) and has no spare yet fits the spare ring, once.
/// - fmr: bool (passed true or false)
/// - ring_gap: bool (passed true or false)
/// - spare: bool (passed true or false)
/// - returns fit: bool (passed true or false)
#[allow(clippy::too_many_arguments)]
pub fn loop_redundancy(fmr: bool, ring_gap: bool, spare: bool) -> bool {
    let mut fit: bool = false;
    fit = ((fmr && ring_gap) && (!spare));
    fit
}
