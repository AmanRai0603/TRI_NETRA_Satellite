/// The rotor of a model from its datasheet's momentum h [mN m s], torque [mN m], speed at that momentum rpm [rpm, nan:
/// not stated], mass [g], steady and peak power [W, the peak nan when not stated]: its momentum [N m s], torque [N m],
/// speed [rad/s], inertia [kg m^2], radius [m], mass [kg], Coulomb [N m] and viscous [N m s] friction, static [kg m] and
/// dynamic [kg m^2] imbalance, the peak power [W] and the unit's mass [kg]; which values were assumed.
/// - h_mnms: real[1] (passed a plain number)
/// - torque_mnm: real[1] (passed a plain number)
/// - rpm: real[1] (passed a plain number)
/// - mass_g: real[1] (passed a plain number)
/// - p_steady: real[1] (passed a plain number)
/// - p_peak: real[1] (passed a plain number)
/// - returns h: real[1] (passed a plain number)
/// - returns tau: real[1] (passed a plain number)
/// - returns w: real[1] (passed a plain number)
/// - returns j: real[1] (passed a plain number)
/// - returns radius: real[1] (passed a plain number)
/// - returns rotor_mass: real[1] (passed a plain number)
/// - returns coulomb: real[1] (passed a plain number)
/// - returns viscous: real[1] (passed a plain number)
/// - returns static_imbalance: real[1] (passed a plain number)
/// - returns dynamic_imbalance: real[1] (passed a plain number)
/// - returns peak: real[1] (passed a plain number)
/// - returns mass: real[1] (passed a plain number)
/// - returns rpm_assumed: bool (passed true or false)
/// - returns peak_assumed: bool (passed true or false)
#[allow(clippy::too_many_arguments)]
pub fn catalogue_rotor(h_mnms: f64, torque_mnm: f64, rpm: f64, mass_g: f64, p_steady: f64, p_peak: f64) -> (f64, f64, f64, f64, f64, f64, f64, f64, f64, f64, f64, f64, bool, bool) {
    let mut h: f64 = 0.0;
    let mut tau: f64 = 0.0;
    let mut w: f64 = 0.0;
    let mut j: f64 = 0.0;
    let mut radius: f64 = 0.0;
    let mut rotor_mass: f64 = 0.0;
    let mut coulomb: f64 = 0.0;
    let mut viscous: f64 = 0.0;
    let mut static_imbalance: f64 = 0.0;
    let mut dynamic_imbalance: f64 = 0.0;
    let mut peak: f64 = 0.0;
    let mut mass: f64 = 0.0;
    let mut rpm_assumed: bool = false;
    let mut peak_assumed: bool = false;
    let (mut assumed_rpm, mut share, mut gyration, mut balance, mut c_coulomb, mut c_ref, mut c_viscous, mut peak_eff, mut a8, mut a9, mut a10, mut a11, mut a12, mut a13) = crate::gen::catderive::catalogue_rules();
    let mut rpm_rad: f64 = ((2.0 * core::f64::consts::PI) / 60.0);
    h = (h_mnms * 0.001);
    tau = (torque_mnm * 0.001);
    rpm_assumed = (rpm).is_nan();
    let mut speed: f64 = (if rpm_assumed { assumed_rpm } else { rpm });
    w = (speed * rpm_rad);
    j = (h / w);
    mass = (mass_g * 0.001);
    rotor_mass = (share * mass);
    radius = f64::sqrt((j / (gyration * rotor_mass)));
    static_imbalance = ((rotor_mass * balance) / w);
    coulomb = (c_coulomb * f64::sqrt((h / c_ref)));
    viscous = c_viscous;
    dynamic_imbalance = ((static_imbalance * radius) / 2.0);
    peak_assumed = (p_peak).is_nan();
    peak = (if peak_assumed { (p_steady + ((tau * w) / peak_eff)) } else { p_peak });
    (h, tau, w, j, radius, rotor_mass, coulomb, viscous, static_imbalance, dynamic_imbalance, peak, mass, rpm_assumed, peak_assumed)
}

/// A wheel's motor and bearing values the engine's wheel model reads: on the supply v [V] (the lowest the datasheet
/// states, nan when none: assumed), its top stated speed top_rpm [rpm, nan or 0: none, the speed at the nominal momentum
/// w [rad/s] in its place], the torque tau [N m] and the Coulomb friction [N m]: the torque constant [N m/A], the
/// winding's resistance [ohm], the supply [V], the breakaway friction [N m] and the Stribeck speed [rad/s].
/// - v: real[1] (passed a plain number)
/// - top_rpm: real[1] (passed a plain number)
/// - w: real[1] (passed a plain number)
/// - tau: real[1] (passed a plain number)
/// - coulomb: real[1] (passed a plain number)
/// - returns kt: real[1] (passed a plain number)
/// - returns resistance: real[1] (passed a plain number)
/// - returns supply: real[1] (passed a plain number)
/// - returns friction_static: real[1] (passed a plain number)
/// - returns stribeck: real[1] (passed a plain number)
/// - returns supply_assumed: bool (passed true or false)
#[allow(clippy::too_many_arguments)]
pub fn catalogue_wheel_motor(v: f64, top_rpm: f64, w: f64, tau: f64, coulomb: f64) -> (f64, f64, f64, f64, f64, bool) {
    let mut kt: f64 = 0.0;
    let mut resistance: f64 = 0.0;
    let mut supply: f64 = 0.0;
    let mut friction_static: f64 = 0.0;
    let mut stribeck: f64 = 0.0;
    let mut supply_assumed: bool = false;
    let (mut a0, mut a1, mut a2, mut a3, mut a4, mut a5, mut a6, mut a7, mut no_load, mut static_fraction, mut c_stribeck, mut c_supply, mut a12, mut a13) = crate::gen::catderive::catalogue_rules();
    let mut rpm_rad: f64 = ((2.0 * core::f64::consts::PI) / 60.0);
    supply_assumed = (v).is_nan();
    supply = (if supply_assumed { c_supply } else { v });
    let mut top: f64 = w;
    if (!((top_rpm).is_nan() || (top_rpm == 0.0))) {
        top = (top_rpm * rpm_rad);
    }
    let mut w_nl: f64 = (no_load * top);
    let mut t_stall: f64 = (tau / (1.0 - (top / w_nl)));
    kt = (supply / w_nl);
    resistance = ((kt * supply) / t_stall);
    friction_static = (static_fraction * coulomb);
    stribeck = c_stribeck;
    (kt, resistance, supply, friction_static, stribeck, supply_assumed)
}

