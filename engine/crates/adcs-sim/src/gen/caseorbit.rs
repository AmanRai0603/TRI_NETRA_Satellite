//! caseorbit: The case's orbit and epoch as the engine sets them up, transcribed from adcs-sim config.rs (build and apply_engine): the mission's UTC epoch from the case's epoch in Julian years after J2000.0, its seconds rounded to the whole second (the date the flight software is loaded with), and the same for an epoch moved by a number of days (a campaign's season); the orbit's radius at the case's altitude (a spherical Earth of the constants' R_E, as m2_5's orbit.radius), its mean motion sqrt(mu/r^3) and period 2 pi/n, and the period of a campaign's dispersed altitude, 2 pi sqrt(r^3/mu) (m2_5's circular_period, written here: the physics' orbit module cannot sit beside env's eclipse in one package; the engine's two forms of the period differ in the last bits). Calendar dates by env_calendar_time (Vallado 2013, algorithms 14 and 22). The epochs are plain numbers (Julian dates, days, years). The developer's transcription (S7.11), unsigned.
//! Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
#![allow(unused_mut, unused_variables, unused_parens, unused_assignments, unused_imports, unreachable_code, non_snake_case, clippy::all)]
use crate::gen::rt;

/// The UTC calendar date [Y M D h m s] of a Julian date with its seconds rounded to the whole second (half away from
/// zero), and that date's Julian date.
/// - jd: real[1] (passed a plain number)
/// - returns u: real[1][6] (passed a plain number)
/// - returns j: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn whole_second_epoch(jd: f64) -> ([f64; 6], f64) {
    let mut u: [f64; 6] = [0.0; 6];
    let mut j: f64 = 0.0;
    u = crate::gen::caltime::utc_of_jd(jd);
    u[5] = f64::round(u[5]);
    j = crate::gen::caltime::jd_utc(u);
    (u, j)
}

/// The mission's epoch from the case's mission.epoch, in Julian years after J2000.0: the UTC date and its Julian date.
/// - years: real[1] (passed a plain number)
/// - returns u: real[1][6] (passed a plain number)
/// - returns j: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn mission_epoch(years: f64) -> ([f64; 6], f64) {
    let mut u: [f64; 6] = [0.0; 6];
    let mut j: f64 = 0.0;
    let __t1 = crate::gen::caseorbit::whole_second_epoch((crate::gen::constants::JD_J2000 + (years * crate::gen::constants::DAYS_PER_YEAR)));
    u = __t1.0;
    j = __t1.1;
    (u, j)
}

/// The epoch moved by days [day] from the Julian date jd0: the UTC date and its Julian date.
/// - jd0: real[1] (passed a plain number)
/// - days: real[1] (passed a plain number)
/// - returns u: real[1][6] (passed a plain number)
/// - returns j: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn shifted_epoch(jd0: f64, days: f64) -> ([f64; 6], f64) {
    let mut u: [f64; 6] = [0.0; 6];
    let mut j: f64 = 0.0;
    let __t2 = crate::gen::caseorbit::whole_second_epoch((jd0 + days));
    u = __t2.0;
    j = __t2.1;
    (u, j)
}

/// The case's circular orbit at altitude h: its mean motion n and period t.
/// - h: real[km] (passed in m)
/// - returns n: real[1/s] (passed in 1/s)
/// - returns t: real[s] (passed in s)
#[allow(clippy::too_many_arguments)]
pub fn case_mean_motion(h: f64) -> (f64, f64) {
    let mut n: f64 = 0.0;
    let mut t: f64 = 0.0;
    let mut r: f64 = (crate::gen::constants::R_E + h);
    n = f64::sqrt((crate::gen::constants::MU_E / rt::ipow(r, 3)));
    t = ((2.0 * core::f64::consts::PI) / n);
    (n, t)
}

/// The period of the circular orbit at a dispersed altitude h (a campaign's alt_km).
/// - h: real[km] (passed in m)
/// - returns t: real[s] (passed in s)
#[allow(clippy::too_many_arguments)]
pub fn dispersed_period(h: f64) -> f64 {
    let mut t: f64 = 0.0;
    let mut r: f64 = (crate::gen::constants::R_E + h);
    t = ((2.0 * core::f64::consts::PI) * f64::sqrt((rt::ipow(r, 3) / crate::gen::constants::MU_E)));
    t
}
