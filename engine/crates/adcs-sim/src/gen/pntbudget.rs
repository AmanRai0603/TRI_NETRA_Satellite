//! pntbudget: The absolute pointing error budget of a flown fine-pointing scenario, transcribed from tools/pointing_budget.py (row, control_part, product_alignment, rss): ECSS-E-ST-60-10C's contributors. The flown APE holds knowledge and control together (and the star tracker's calibrated mount residual, which the engine flies), so the total adds to it only what the loop does not fly: the payload's alignment (gp_2), the thermal distortion (gp_3, the case's pointing.et) and the rotors' jitter (gp_4). The terms add in quadrature, which holds for independent random terms only (a bias adds linearly). Every angle is a plain number in degrees, as the page states it, p99.73 across the boresight; a term nobody states is nan, and a budget with one is incomplete: it never closes on a guess. The developer's transcription (S7.14), unsigned.
//! Generated by tools/pcode.py from the pseudocode (trinetra-pcode/2); do not edit.
#![allow(unused_mut, unused_variables, unused_parens, unused_assignments, unused_imports, unreachable_code, non_snake_case, clippy::all)]
use crate::gen::rt;

/// How a budget stands against the requirement: a term not stated (incomplete), its total within req.ape (closes), or
/// not (open).
/// Choice BudgetVerdict: incomplete, closes, open.
pub const BUDGETVERDICT_INCOMPLETE: i64 = 0;
pub const BUDGETVERDICT_CLOSES: i64 = 1;
pub const BUDGETVERDICT_OPEN: i64 = 2;

/// gp_0, the knowledge contribution: the flown absolute knowledge error across the boresight, ake [deg].
/// - ake: real[1] (passed a plain number)
/// - returns e_k: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn pointing_knowledge(ake: f64) -> f64 {
    let mut e_k: f64 = 0.0;
    e_k = ake;
    e_k
}

/// gp_1, the control contribution, inferred from the flown loop: the flown APE ape [deg] with the knowledge ake [deg]
/// removed in quadrature, sqrt(max(ape^2 - ake^2, 0)).
/// - ape: real[1] (passed a plain number)
/// - ake: real[1] (passed a plain number)
/// - returns e_c: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn pointing_control(ape: f64, ake: f64) -> f64 {
    let mut e_c: f64 = 0.0;
    e_c = f64::sqrt(rt::fmax(((ape * ape) - (ake * ake)), 0.0));
    e_c
}

/// gp_2, the alignment contribution: the payload's alignment to the star tracker as the product states it
/// (payload_alignment_rad) [rad], in degrees.
/// - a: real[1] (passed a plain number)
/// - returns e_a: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn pointing_alignment(a: f64) -> f64 {
    let mut e_a: f64 = 0.0;
    e_a = (a * (180.0 / core::f64::consts::PI));
    e_a
}

/// gp_4 as the budget takes it: the rotors' jitter metric j [arcsec] in degrees.
/// - j: real[1] (passed a plain number)
/// - returns e_j: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn pointing_jitter(j: f64) -> f64 {
    let mut e_j: f64 = 0.0;
    e_j = (j / 3600.0);
    e_j
}

/// The budget against the requirement req [deg]: the total, the root-sum-square of the flown APE and the terms the loop
/// does not fly (alignment e_a, thermal e_t, jitter e_j); the room req.ape leaves for alignment and thermal together once
/// the flown loop and the jitter are in, sqrt(max(req^2 - ape^2 - e_j^2, 0)); and the verdict.
/// - ape: real[1] (passed a plain number)
/// - e_a: real[1] (passed a plain number)
/// - e_t: real[1] (passed a plain number)
/// - e_j: real[1] (passed a plain number)
/// - req: real[1] (passed a plain number)
/// - returns total: real[1] (passed a plain number)
/// - returns room: real[1] (passed a plain number)
/// - returns verdict: BudgetVerdict (passed a choice, as its option's number)
#[allow(clippy::too_many_arguments)]
pub fn pointing_budget(ape: f64, e_a: f64, e_t: f64, e_j: f64, req: f64) -> (f64, f64, i64) {
    let mut total: f64 = 0.0;
    let mut room: f64 = 0.0;
    let mut verdict: i64 = 0;
    total = f64::sqrt(((((ape * ape) + (e_a * e_a)) + (e_t * e_t)) + (e_j * e_j)));
    room = f64::sqrt(rt::fmax((((req * req) - (ape * ape)) - (e_j * e_j)), 0.0));
    verdict = crate::gen::pntbudget::BUDGETVERDICT_OPEN;
    if (((e_a).is_nan() || (e_t).is_nan()) || (e_j).is_nan()) {
        verdict = crate::gen::pntbudget::BUDGETVERDICT_INCOMPLETE;
    } else if (total <= req) {
        verdict = crate::gen::pntbudget::BUDGETVERDICT_CLOSES;
    }
    (total, room, verdict)
}
