/// The flight software's epoch and Earth: the Julian date of its tick 0, the mission's epoch as env_case_orbit sets it up
/// (mission_epoch, its seconds rounded), and the Earth's gravitational parameter (the constants' MU_E).
/// - jd: real[1] (passed a plain number)
/// - returns jd0: real[1] (passed a plain number)
/// - returns mu: real[m^3/s^2] (passed in m^3/s^2)
#[allow(clippy::too_many_arguments)]
pub fn fsw_epoch_earth(jd: f64) -> (f64, f64) {
    let mut jd0: f64 = 0.0;
    let mut mu: f64 = 0.0;
    jd0 = jd;
    mu = crate::gen::constants::MU_E;
    (jd0, mu)
}

/// The flight software's model of the body: the nominal inertia j (dyn_truth_plant's principal_inertia), the calibrated
/// residual dipole (dyn_truth_plant's residual_dipole_axes), the power face (the product's Sun axis) and the roll axis of
/// Sun referencing (the product's payload boresight).
/// - j: real[1][3][3] (passed a plain number)
/// - m_res: real[1][3] (passed a plain number)
/// - sun_axis: real[1][3] (passed a plain number)
/// - boresight: real[1][3] (passed a plain number)
/// - returns jf: real[1][3][3] (passed a plain number)
/// - returns mf: real[1][3] (passed a plain number)
/// - returns sun: real[1][3] (passed a plain number)
/// - returns roll: real[1][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn fsw_body_model(j: [[f64; 3]; 3], m_res: [f64; 3], sun_axis: [f64; 3], boresight: [f64; 3]) -> ([[f64; 3]; 3], [f64; 3], [f64; 3], [f64; 3]) {
    let mut jf: [[f64; 3]; 3] = [[0.0; 3]; 3];
    let mut mf: [f64; 3] = [0.0; 3];
    let mut sun: [f64; 3] = [0.0; 3];
    let mut roll: [f64; 3] = [0.0; 3];
    jf = j;
    mf = m_res;
    sun = sun_axis;
    roll = boresight;
    (jf, mf, sun, roll)
}

/// The payload's offset from the nadir frame the guidance turns by (gd_q_off): the rotation taking +Y_B to the product's
