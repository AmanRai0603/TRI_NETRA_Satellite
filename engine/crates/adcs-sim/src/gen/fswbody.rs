#[allow(clippy::too_many_arguments)]
pub fn fsw_payload_offset(boresight: [f64; 3]) -> [f64; 4] {
    let mut q: [f64; 4] = [0.0; 4];
    q = crate::gen::guidance::boresight_offset(boresight);
    q
}

/// The body's inertia about the body axis b = a u, the unit axis u taken through the attitude matrix a: b'J b.
/// - a: real[1][3][3] (passed a plain number)
/// - j: real[1][3][3] (passed a plain number)
/// - u: real[1][3] (passed a plain number)
/// - returns ju: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn fsw_axis_inertia(a: [[f64; 3]; 3], j: [[f64; 3]; 3], u: [f64; 3]) -> f64 {
    let mut ju: f64 = 0.0;
    let mut b: [f64; 3] = rt::mv(a, u);
    let mut jb: [f64; 3] = rt::mv(j, b);
    ju = (((b[0] * jb[0]) + (b[1] * jb[1])) + (b[2] * jb[2]));
    ju
}

/// The gravity-gradient feed-forward of the magnetic pointing states (mtq_gg_ff, when the scenario states none): bit 0 the
/// Sun state, bit 1 the nadir state. In the nadir attitude the flight software's guidance gives (at a reference point of
/// the orbit, 7000 km along x moving at 7.5 km/s along y; the payload offset q_off applied) the gradient restores the
/// attitude only inside the Lagrange region, J_normal >= J_along > J_nadir (equal transverse inertias, a relative 1e-9
/// apart, are neutral, not unstable): there the nadir state keeps the gradient as its spring (1: the Sun state only);
/// outside it the nadir state cancels it too (3).
/// - q_off: real[1][4] (passed a plain number)
/// - j: real[1][3][3] (passed a plain number)
/// - returns ff: int (passed a whole number)
#[allow(clippy::too_many_arguments)]
pub fn fsw_gg_feedforward(q_off: [f64; 4], j: [[f64; 3]; 3]) -> i64 {
    let mut ff: i64 = 0;
    let mut r: [f64; 3] = [7000000.0, 0.0, 0.0];
    let mut v: [f64; 3] = [0.0, 7500.0, 0.0];
    let mut z3: [f64; 3] = [0.0; 3];
    let mut q0: [f64; 4] = [0.0; 4];
    let (mut q, mut w, mut wd) = crate::gen::guidance::guidance(0, r, v, 0.0, q_off, 0.0, 0.0, 0.0, z3, q0, z3, z3, z3, false);
    let mut a: [[f64; 3]; 3] = crate::gen::math::dcm(q);
    let mut jz: f64 = crate::gen::fswbody::fsw_axis_inertia(a, j, [(-(1.0)), 0.0, 0.0]);
    let mut ja: f64 = crate::gen::fswbody::fsw_axis_inertia(a, j, [0.0, 1.0, 0.0]);
    let mut jn: f64 = crate::gen::fswbody::fsw_axis_inertia(a, j, [0.0, 0.0, 1.0]);
    ff = 3;
    if ((jn >= (ja * (1.0 - 1.0e-9))) && (ja > (jz * (1.0 + 1.0e-9)))) {
        ff = 1;
    }
    ff
}
