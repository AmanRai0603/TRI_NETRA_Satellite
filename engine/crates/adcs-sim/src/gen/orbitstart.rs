/// The RAAN [rad], in [0, 2 pi), of an orbit whose ascending node is at local time ltan_h [h], the Sun at sun
/// (geocentric, J2000).
/// - sun: real[m][3] (passed in m)
/// - ltan_h: real[1] (passed a plain number)
/// - returns raan: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn ltan_raan(sun: [f64; 3], ltan_h: f64) -> f64 {
    let mut raan: f64 = 0.0;
    let mut x: f64 = (f64::atan2(sun[1], sun[0]) + ((((ltan_h - 12.0) * 15.0) * core::f64::consts::PI) / 180.0));
    let mut turn: f64 = (2.0 * core::f64::consts::PI);
    let mut m: f64 = (x % turn);
    raan = (if (m < 0.0) { (m + rt::fabs(turn)) } else { m });
    raan
}

/// The fast orbit's start: its RAAN from the LTAN and the Sun at the epoch, its semi-major axis from the altitude
