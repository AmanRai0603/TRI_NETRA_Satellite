/// TANGO's frozen Riccati gains: P from the CARE with the orbit-averaged B_u R^-1 B_u^T. An isotropic field average gives
/// E[Gamma D Gamma]_ii = (7/15) D_i + tr(D)/15, D = J^-2 (the double integrator's CARE on each axis); Q is chosen (inverse
/// LQR) so the average axis gets the common bandwidth wn and damping z, and each axis the gain its averaged authority calls
/// for, R = 1 (the paper's Q and R are unpublished): the gains on the attitude error P21/R and on the rate error P22/R,
/// scaled by gp and gd, on the diagonal.
/// - ii: real[1][3] (passed a plain number)
/// - wn: real[1] (passed a plain number)
/// - z: real[1] (passed a plain number)
/// - gp: real[1] (passed a plain number)
/// - gd: real[1] (passed a plain number)
/// - returns pth: real[1][3][3] (passed a plain number)
/// - returns pw: real[1][3][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn fsw_mtq_tango(ii: [f64; 3], wn: f64, z: f64, gp: f64, gd: f64) -> ([[f64; 3]; 3], [[f64; 3]; 3]) {
    let mut pth: [[f64; 3]; 3] = [[0.0; 3]; 3];
    let mut pw: [[f64; 3]; 3] = [[0.0; 3]; 3];
    let mut r: f64 = 1.0;
    let mut jm: f64 = (((ii[0] + ii[1]) + ii[2]) / 3.0);
    let mut d: [f64; 3] = [(1.0 / (ii[0] * ii[0])), (1.0 / (ii[1] * ii[1])), (1.0 / (ii[2] * ii[2]))];
    let mut trd: f64 = ((d[0] + d[1]) + d[2]);
    let mut mi: [f64; 3] = [0.0; 3];
    {
        let __end5: i64 = 3;
        let mut ax: i64 = 0;
        while ax < __end5 {
            mi[(ax) as usize] = ((((7.0 / 15.0) * d[(ax) as usize]) + (trd / 15.0)) / r);
            ax += 1;
        }
    }
    let mut mref: f64 = (((mi[0] + mi[1]) + mi[2]) / 3.0);
    let mut qt: f64 = (mref * rt::ipow((((jm * wn) * wn) * r), 2));
    let mut qw0: f64 = ((mref * rt::ipow(((((2.0 * z) * jm) * wn) * r), 2)) - (2.0 * f64::sqrt((qt / mref))));
    let mut qw: f64 = (if (qw0 > 0.0) { qw0 } else { 0.0 });
    pth = [[0.0; 3]; 3];
    pw = [[0.0; 3]; 3];
    {
        let __end6: i64 = 3;
        let mut ax: i64 = 0;
        while ax < __end6 {
            let mut p12: f64 = f64::sqrt((qt / mi[(ax) as usize]));
            let mut p22: f64 = f64::sqrt(((qw + (2.0 * p12)) / mi[(ax) as usize]));
            pth[(ax) as usize][(ax) as usize] = ((gp * p12) / r);
            pw[(ax) as usize][(ax) as usize] = ((gd * p22) / r);
            ax += 1;
        }
    }
    (pth, pw)
}
