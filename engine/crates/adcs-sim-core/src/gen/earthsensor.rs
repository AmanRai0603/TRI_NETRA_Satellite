/// The nadir the sensor gives (body, unit) and whether it gives one, for the true nadir nadir_b (body, unit).
/// - u: inout EsUnit (passed rec)
/// - d: EsDesc (passed rec)
/// - nadir_b: real[1][3] (passed a plain number)
/// - returns ok: bool (passed true or false)
/// - returns n: real[1][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn es_sample(u: &mut EsUnit, d: EsDesc, nadir_b: [f64; 3]) -> (bool, [f64; 3]) {
    let mut ok: bool = false;
    let mut n: [f64; 3] = [0.0; 3];
    ok = (!(crate::pm::acos(crate::gen::coilsat::act_clamp(rt::dot(d.bs, nadir_b), (-(1.0)), 1.0)) >= d.fov));
    n = [0.0, 0.0, 0.0];
    if ok {
        let mut g: rt::Stream = (*u).g;
        let mut e0: [f64; 3] = rt::normal3(&mut g);
        (*u).g = g;
        n = crate::gen::facets::unit_or_zero(rt::mv(crate::gen::math::dcm(crate::gen::math::qmult((*u).bias, crate::gen::math::fromrotvec(rt::vscale(e0, d.noise)))), nadir_b));
    }
    (ok, n)
}

/// The Earth sensor's boresight (body, unit): the one the product states for it (stated), else the payload's boresight.
/// - stated: bool (passed true or false)
/// - bs: real[1][3] (passed a plain number)
/// - payload: real[1][3] (passed a plain number)
/// - returns b: real[1][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn es_boresight(stated: bool, bs: [f64; 3], payload: [f64; 3]) -> [f64; 3] {
    let mut b: [f64; 3] = [0.0; 3];
    b = payload;
    if stated {
        b = bs;
    }
    b
}
