/// The noise model's attitude for a head of boresight bs: the attitude q_old through the head's mount dq, turned by
/// normal draws across the boresight (noise_cross) and about it (noise_roll), each times the smear.
/// - q_old: real[1][4] (passed a plain number)
/// - dq: real[1][4] (passed a plain number)
/// - bs: real[1][3] (passed a plain number)
/// - noise_cross: real[1] (passed a plain number)
/// - noise_roll: real[1] (passed a plain number)
/// - smear: real[1] (passed a plain number)
/// - g: inout stream (passed a random stream, as six numbers)
/// - returns q: real[1][4] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn st_noise_head(q_old: [f64; 4], dq: [f64; 4], bs: [f64; 3], noise_cross: f64, noise_roll: f64, smear: f64, g: &mut rt::Stream) -> [f64; 4] {
    let mut q: [f64; 4] = [0.0; 4];
    let mut n0: [f64; 3] = rt::normal3(&mut (*g));
    let mut nr: f64 = rt::normal(&mut (*g));
    let mut e0: [f64; 3] = rt::vscale(n0, (noise_cross * smear));
    let mut e: [f64; 3] = rt::vadd(rt::vsub(e0, rt::vscale(bs, rt::dot(bs, e0))), rt::vscale(bs, ((noise_roll * smear) * nr)));
    q = crate::gen::math::qnorm(crate::gen::math::qmult(q_old, crate::gen::math::qmult(dq, crate::gen::math::fromrotvec(e))));
    q
}

