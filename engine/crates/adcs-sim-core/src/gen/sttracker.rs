/// The spherical linear interpolation from a to b at s, the shorter arc; above a cosine of 0.9995 the linear one, made
/// unit (la.rs slerp).
/// - a: real[1][4] (passed a plain number)
/// - b: real[1][4] (passed a plain number)
/// - s: real[1] (passed a plain number)
/// - returns q: real[1][4] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn st_slerp(a: [f64; 4], b: [f64; 4], s: f64) -> [f64; 4] {
    let mut q: [f64; 4] = [0.0; 4];
    let mut d: f64 = ((((a[0] * b[0]) + (a[1] * b[1])) + (a[2] * b[2])) + (a[3] * b[3]));
    let mut bb: [f64; 4] = b;
    if (d < 0.0) {
        d = (-(d));
        bb = [(-(b[0])), (-(b[1])), (-(b[2])), (-(b[3]))];
    }
    if (d > 0.9995) {
        q = crate::gen::math::qnorm([(a[0] + (s * (bb[0] - a[0]))), (a[1] + (s * (bb[1] - a[1]))), (a[2] + (s * (bb[2] - a[2]))), (a[3] + (s * (bb[3] - a[3])))]);
    } else {
        let mut th: f64 = crate::pm::acos(d);
        let mut ka: f64 = (crate::pm::sin(((1.0 - s) * th)) / crate::pm::sin(th));
        let mut kb: f64 = (crate::pm::sin((s * th)) / crate::pm::sin(th));
        q = [((ka * a[0]) + (kb * bb[0])), ((ka * a[1]) + (kb * bb[1])), ((ka * a[2]) + (kb * bb[2])), ((ka * a[3]) + (kb * bb[3]))];
    }
    q
}

