/// Whether head h answers at t: below the largest rate (slow), not failed, not dazzled by the Sun or the Moon (sun_b,
/// moon_b, body, unit) nor blind since, and the Earth's limb (nadir_b, the Earth's half-angle earth_ang [rad]) outside
/// its exclusion. A dazzled head stays blind for the blind time.
/// - u: inout StUnit (passed rec)
/// - d: StDesc (passed rec)
/// - h: int (passed a whole number)
/// - t: real[1] (passed a plain number)
/// - sun_b: real[1][3] (passed a plain number)
/// - moon_b: real[1][3] (passed a plain number)
/// - nadir_b: real[1][3] (passed a plain number)
