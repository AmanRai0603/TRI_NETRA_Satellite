/// The power [W]: p_steady + |tm om|/eta + tm^2 w_nl/t_stall (the last only for a motor that states its stall torque).
/// - p_steady: real[1] (passed a plain number)
/// - tm: real[1] (passed a plain number)
/// - om: real[1] (passed a plain number)
/// - eta: real[1] (passed a plain number)
/// - t_stall: real[1] (passed a plain number)
/// - w_nl: real[1] (passed a plain number)
/// - returns p: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn wheel_power(p_steady: f64, tm: f64, om: f64, eta: f64, t_stall: f64, w_nl: f64) -> f64 {
    let mut p: f64 = 0.0;
    p = (p_steady + (rt::fabs((tm * om)) / eta));
    if (t_stall > 0.0) {
        p = (p + (((tm * tm) * w_nl) / t_stall));
    }
    p
}
