/// A coil set in flight: its description, each coil's dispersed axis and scale, whether it has failed, its row of the
/// allocation, its dipole now [A m^2] and the command it was last given.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct CoilSet {
    pub a: [[f64; 3]; 8],
    pub scale: [f64; 8],
    pub dead: [bool; 8],
    pub pinv: [[f64; 3]; 8],
    pub m: [f64; 8],
    pub mc: [f64; 8],
}

/// The coil set of a description, its dispersion drawn from disp.
/// - d: CoilDesc (passed rec)
/// - disp: inout stream (passed a random stream, as six numbers)
/// - returns s: CoilSet (passed rec)
#[allow(clippy::too_many_arguments)]
pub fn coilset_new(d: CoilDesc, disp: &mut rt::Stream) -> CoilSet {
    let mut s: CoilSet = CoilSet::default();
    s = CoilSet::default();
    let (mut sc, mut a) = crate::gen::coildisp::coil_dispersion(d.n, d.axes, d.scale_sigma, d.misalign, &mut (*disp));
    s.scale = sc;
    s.a = a;
    s.pinv = crate::gen::coilaxes::coil_allocation(d.axes, d.n);
    s
}

/// The body dipole command [A m^2] held for dt: (the true body dipole averaged over the step, the true body dipole at
/// its end, the power [W]).
/// - s: inout CoilSet (passed rec)
/// - d: CoilDesc (passed rec)
/// - m_cmd: real[1][3] (passed a plain number)
/// - dt: real[1] (passed a plain number)
/// - returns m: real[1][3] (passed a plain number)
/// - returns me: real[1][3] (passed a plain number)
/// - returns p: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn coilset_apply(s: &mut CoilSet, d: CoilDesc, m_cmd: [f64; 3], dt: f64) -> ([f64; 3], [f64; 3], f64) {
    let mut m: [f64; 3] = [0.0; 3];
    let mut me: [f64; 3] = [0.0; 3];
    let mut p: f64 = 0.0;
    m = [0.0, 0.0, 0.0];
    me = [0.0, 0.0, 0.0];
    p = 0.0;
    {
        let __end6: i64 = d.n;
        let mut j: i64 = 0;
        while j < __end6 {
            let mut mc: f64 = crate::gen::coilsat::coil_command((*s).pinv[(j) as usize], m_cmd, d.m_max);
            if (*s).dead[(j) as usize] {
                mc = 0.0;
                (*s).m[(j) as usize] = 0.0;
            }
            let (mut e, mut av) = crate::gen::coillag::coil_lag((*s).m[(j) as usize], mc, d.tau, dt);
            (*s).m[(j) as usize] = e;
            (*s).mc[(j) as usize] = mc;
            p = (p + crate::gen::coilpower::coil_power(av, d.m_max, d.p_max));
            m = rt::vadd(m, rt::vscale((*s).a[(j) as usize], (av * (*s).scale[(j) as usize])));
            me = rt::vadd(me, rt::vscale((*s).a[(j) as usize], (e * (*s).scale[(j) as usize])));
            j += 1;
        }
    }
    (m, me, p)
}
