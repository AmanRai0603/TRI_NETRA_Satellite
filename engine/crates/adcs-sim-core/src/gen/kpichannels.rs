/// The reference attitude of a sample in a mode whose guidance is kind (the flight software's guidance, fsw_guidance;
/// -1, a mode with none: no reference, has false): the attitude the guidance gives at t on the orbit (r, v), the payload
/// boresight bs its roll axis, the nadir family turned by flip.
/// - kind: int (passed a whole number)
/// - r: real[m][3] (passed in m)
/// - v: real[m/s][3] (passed in m/s)
/// - t: real[s] (passed in s)
/// - q_off: real[1][4] (passed a plain number)
/// - roll_deg: real[1] (passed a plain number)
/// - t0: real[s] (passed in s)
/// - t_slew: real[s] (passed in s)
/// - axis: real[1][3] (passed a plain number)
/// - q_inertial: real[1][4] (passed a plain number)
/// - sun_axis: real[1][3] (passed a plain number)
/// - bs: real[1][3] (passed a plain number)
/// - sun_eci: real[1][3] (passed a plain number)
/// - flip: bool (passed true or false)
/// - returns has: bool (passed true or false)
/// - returns qr: real[1][4] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn kpi_reference(kind: i64, r: [f64; 3], v: [f64; 3], t: f64, q_off: [f64; 4], roll_deg: f64, t0: f64, t_slew: f64, axis: [f64; 3], q_inertial: [f64; 4], sun_axis: [f64; 3], bs: [f64; 3], sun_eci: [f64; 3], flip: bool) -> (bool, [f64; 4]) {
    let mut has: bool = false;
    let mut qr: [f64; 4] = [0.0; 4];
    has = (kind >= 0);
    qr = [0.0, 0.0, 0.0, 1.0];
    if has {
        let (mut q, mut w, mut wd) = crate::gen::guidance::guidance(kind, r, v, t, q_off, roll_deg, t0, t_slew, axis, q_inertial, sun_axis, bs, sun_eci, flip);
        qr = q;
    }
    (has, qr)
}

/// The error of the attitude q against qr (both ECI to body): the small-angle error vector e = 2 dq[0..2] [rad] of
/// dq = conj(qr) q with its scalar made positive, and the angle between the payload boresight bs (body) as q and as qr
/// point it [deg]. The performance error against the guidance's reference, the knowledge error against the estimate.
/// - q: real[1][4] (passed a plain number)
/// - qr: real[1][4] (passed a plain number)
/// - bs: real[1][3] (passed a plain number)
/// - returns e: real[1][3] (passed a plain number)
/// - returns los: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn kpi_error(q: [f64; 4], qr: [f64; 4], bs: [f64; 3]) -> ([f64; 3], f64) {
    let mut e: [f64; 3] = [0.0; 3];
    let mut los: f64 = 0.0;
    let mut dq: [f64; 4] = crate::gen::math::qmult(crate::gen::math::qconj(qr), q);
    if (dq[3] < 0.0) {
        dq = [(-(dq[0])), (-(dq[1])), (-(dq[2])), (-(dq[3]))];
    }
    e = [(2.0 * dq[0]), (2.0 * dq[1]), (2.0 * dq[2])];
    let mut b_true: [f64; 3] = crate::gen::math::mat3t_vec(crate::gen::math::dcm(q), bs);
    los = crate::gen::kpichannels::kpi_acosd(rt::dot(b_true, crate::gen::math::mat3t_vec(crate::gen::math::dcm(qr), bs)));
    (e, los)
}

/// The angle between the attitudes q and qr [deg], three-axis (the toolbox's qangle). The engine takes it with its
/// portable maths (adcs-sim-core's, the pure-Rust libm the toolbox's qangle flew), the other angles with the platform's.
/// - q: real[1][4] (passed a plain number)
/// - qr: real[1][4] (passed a plain number)
/// - returns a: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn kpi_three_axis(q: [f64; 4], qr: [f64; 4]) -> f64 {
    let mut a: f64 = 0.0;
    a = (crate::gen::math::qangle(q, qr) * (180.0 / core::f64::consts::PI));
    a
}

/// The body rate's magnitude [deg/s] and the spin about +Z [deg/s] of the body rate w [rad/s].
/// - w: real[1/s][3] (passed in 1/s)
/// - returns rate: real[1/s] (passed in 1/s)
/// - returns spin_z: real[1/s] (passed in 1/s)
#[allow(clippy::too_many_arguments)]
pub fn kpi_rates(w: [f64; 3]) -> (f64, f64) {
    let mut rate: f64 = 0.0;
    let mut spin_z: f64 = 0.0;
    rate = (rt::norm(w) * (180.0 / core::f64::consts::PI));
    spin_z = (w[2] * (180.0 / core::f64::consts::PI));
    (rate, spin_z)
}

/// The Sun's angle from the power face sun_axis (body) [deg], the Sun along sun_body (body): geometric, and only where
/// the spacecraft is lit (the sunlit fraction nu at least one half; nan in the shadow).
/// - sun_axis: real[1][3] (passed a plain number)
/// - sun_body: real[1][3] (passed a plain number)
/// - nu: real[1] (passed a plain number)
/// - returns geo: real[1] (passed a plain number)
/// - returns lit: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn kpi_sun_angle(sun_axis: [f64; 3], sun_body: [f64; 3], nu: f64) -> (f64, f64) {
    let mut geo: f64 = 0.0;
    let mut lit: f64 = 0.0;
    geo = crate::gen::kpichannels::kpi_acosd(rt::dot(sun_axis, sun_body));
    lit = geo;
    if (nu < 0.5) {
        lit = f64::NAN;
    }
    (geo, lit)
}

/// How many record steps the rate stability looks back: one second at the record step record_dt [s] (a plain number),
/// at least one.
/// - record_dt: real[1] (passed a plain number)
/// - returns lag: int (passed a whole number)
#[allow(clippy::too_many_arguments)]
pub fn kpi_rks_lag(record_dt: f64) -> i64 {
    let mut lag: i64 = 0;
    lag = (crate::pm::round((1.0 / rt::fmax(record_dt, 1.0e-9))) as i64);
    if (lag < 1) {
        lag = 1;
    }
    lag
}

/// The rate stability [deg/s] of a sample: the change of the performance error vector from e_lag, lag record steps of
/// record_dt [s] before, to e.
/// - e: real[1][3] (passed a plain number)
/// - e_lag: real[1][3] (passed a plain number)
/// - lag: int (passed a whole number)
/// - record_dt: real[1] (passed a plain number)
/// - returns rks: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn kpi_rks(e: [f64; 3], e_lag: [f64; 3], lag: i64, record_dt: f64) -> f64 {
    let mut rks: f64 = 0.0;
    rks = ((rt::norm(rt::vsub(e, e_lag)) * (180.0 / core::f64::consts::PI)) / ((lag as f64) * record_dt));
    rks
}
