/// The angle [deg] whose cosine is x, x held to [-1, 1].
/// - x: real[1] (passed a plain number)
/// - returns a: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn kpi_acosd(x: f64) -> f64 {
    let mut a: f64 = 0.0;
    a = (crate::pm::acos(rt::clamp(x, (-(1.0)), 1.0)) * (180.0 / core::f64::consts::PI));
    a
}

