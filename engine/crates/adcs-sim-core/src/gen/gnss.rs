/// The fix the receiver reports: the position r [m] and velocity v [m/s] (ECEF) with their noise, the sigmas pos_sigma
/// [m] and vel_sigma [m/s], the position's draws first.
/// - r: real[1][3] (passed a plain number)
/// - v: real[1][3] (passed a plain number)
/// - pos_sigma: real[1] (passed a plain number)
/// - vel_sigma: real[1] (passed a plain number)
/// - g: inout stream (passed a random stream, as six numbers)
/// - returns rg: real[1][3] (passed a plain number)
/// - returns vg: real[1][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn gps_sample(r: [f64; 3], v: [f64; 3], pos_sigma: f64, vel_sigma: f64, g: &mut rt::Stream) -> ([f64; 3], [f64; 3]) {
    let mut rg: [f64; 3] = [0.0; 3];
    let mut vg: [f64; 3] = [0.0; 3];
    let mut a: [f64; 3] = rt::normal3(&mut (*g));
    let mut b: [f64; 3] = rt::normal3(&mut (*g));
    rg = rt::vadd(r, rt::vscale(a, pos_sigma));
    vg = rt::vadd(v, rt::vscale(b, vel_sigma));
    (rg, vg)
}

/// The truth (r [m], v [m/s], J2000) at the epoch te [s] of a run that starts at the Julian date jd0, in ECEF.
/// - jd0: real[1] (passed a plain number)
/// - te: real[1] (passed a plain number)
/// - r: real[m][3] (passed in m)
/// - v: real[m/s][3] (passed in m/s)
/// - returns re: real[m][3] (passed in m)
/// - returns ve: real[m/s][3] (passed in m/s)
#[allow(clippy::too_many_arguments)]
pub fn gnss_ecef(jd0: f64, te: f64, r: [f64; 3], v: [f64; 3]) -> ([f64; 3], [f64; 3]) {
    let mut re: [f64; 3] = [0.0; 3];
    let mut ve: [f64; 3] = [0.0; 3];
    let mut ce: [[f64; 3]; 3] = crate::gen::caltime::eci_to_ecef((jd0 + (te / 86400.0)));
    re = rt::mv(ce, r);
    ve = rt::vsub(rt::mv(ce, v), rt::cross([0.0, 0.0, crate::gen::orbitfast::FAST_OMEGA_E], re));
    (re, ve)
}
