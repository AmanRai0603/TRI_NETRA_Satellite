/// How many stars the onboard table holds (adcs-sim-core N_STARS).
pub const N_STARS: i64 = 4000;

/// The fractional part of x, x - floor(x).
/// - x: real[1] (passed a plain number)
/// - returns f: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn star_frac(x: f64) -> f64 {
    let mut f: f64 = 0.0;
    f = (x - crate::pm::floor(x));
    f
}

/// Star k (from 0) of a catalogue of n: its direction (ECI, unit) and its magnitude.
/// tolerance: 1e-10
/// (The hash multiplies sin by 43758.5453 and 12345.6789, so a last-bit difference in sin between the reference
/// interpreter and the platform grows about 4e4 times; the engine's own maths is the platform's.)
/// - k: int (passed a whole number)
/// - n: int (passed a whole number)
/// - returns r: real[1][3] (passed a plain number)
/// - returns mag: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn star_entry(k: i64, n: i64) -> ([f64; 3], f64) {
    let mut r: [f64; 3] = [0.0; 3];
    let mut mag: f64 = 0.0;
    let mut kf: f64 = ((k as f64) + 0.5);
    let mut nf: f64 = (n as f64);
    let mut z: f64 = (1.0 - ((2.0 * kf) / nf));
    let mut ph: f64 = ((core::f64::consts::PI * (1.0 + crate::pm::sqrt(5.0))) * kf);
    let mut rr: f64 = crate::pm::sqrt((1.0 - (z * z)));
    let mut r0: [f64; 3] = [(rr * crate::pm::cos(ph)), (rr * crate::pm::sin(ph)), z];
    let mut h1: f64 = (crate::gen::starcat::star_frac((crate::pm::sin((kf * 12.9898)) * 43758.5453)) - 0.5);
    let mut h2: f64 = (crate::gen::starcat::star_frac((crate::pm::sin((kf * 78.233)) * 12345.6789)) - 0.5);
    let mut e1: [f64; 3] = [(-(crate::pm::sin(ph))), crate::pm::cos(ph), 0.0];
    let mut e2: [f64; 3] = rt::cross(r0, e1);
    let mut dsp: f64 = (0.35 * crate::pm::sqrt(((4.0 * core::f64::consts::PI) / nf)));
    let mut v: [f64; 3] = [(r0[0] + (dsp * ((h1 * e1[0]) + (h2 * e2[0])))), (r0[1] + (dsp * ((h1 * e1[1]) + (h2 * e2[1])))), (r0[2] + (dsp * ((h1 * e1[2]) + (h2 * e2[2]))))];
    r = crate::gen::facets::unit_or_zero(v);
    mag = (1.0 + (5.0 * crate::gen::starcat::star_frac(((kf * crate::pm::sqrt(2.0)) + (0.5 * h1)))));
    (r, mag)
}

/// The whole table: each star's direction cr and magnitude cm. How many.
/// vectors: 2
/// tolerance: 1e-10
/// (The hash multiplies sin by 43758.5453 and 12345.6789, so a last-bit difference in sin between the reference
/// interpreter and the platform grows about 4e4 times; the engine's own maths is the platform's.)
/// - cr: inout real[1][3][N_STARS] (passed a plain number)
/// - cm: inout real[1][N_STARS] (passed a plain number)
/// - returns n: int (passed a whole number)
#[allow(clippy::too_many_arguments)]
pub fn star_catalogue(cr: &mut [[f64; 3]; 4000], cm: &mut [f64; 4000]) -> i64 {
    let mut n: i64 = 0;
    {
        let __end119: i64 = crate::gen::starcat::N_STARS;
        let mut k: i64 = 0;
        while k < __end119 {
            let (mut r, mut mag) = crate::gen::starcat::star_entry(k, crate::gen::starcat::N_STARS);
            (*cr)[(k) as usize] = r;
            (*cm)[(k) as usize] = mag;
            k += 1;
        }
    }
    n = crate::gen::starcat::N_STARS;
    n
}
