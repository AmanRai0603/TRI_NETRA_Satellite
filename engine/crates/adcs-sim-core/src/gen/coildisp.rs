/// The matrix of a small rotation th (rotation vector [rad]): dcm(fromrotvec(th)) (la.rs small_rot).
/// - th: real[1][3] (passed a plain number)
/// - returns m: real[1][3][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn small_rotation(th: [f64; 3]) -> [[f64; 3]; 3] {
    let mut m: [[f64; 3]; 3] = [[0.0; 3]; 3];
    m = crate::gen::math::dcm(crate::gen::math::fromrotvec(th));
    m
}

