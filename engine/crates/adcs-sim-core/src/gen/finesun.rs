/// - nu: real[1] (passed a plain number)
/// - returns ok: bool (passed true or false)
/// - returns s: real[1][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn sun_sample(u: &mut SunUnit, d: SunDesc, s_body: [f64; 3], nu: f64) -> (bool, [f64; 3]) {
    let mut ok: bool = false;
    let mut s: [f64; 3] = [0.0; 3];
    ok = false;
    s = [0.0, 0.0, 0.0];
    if (!(nu < 0.5)) {
        let mut cm: f64 = (-(2.0));
        let mut jm: i64 = 0;
        {
            let __end110: i64 = d.n;
            let mut j: i64 = 0;
            while j < __end110 {
                let mut c: f64 = rt::dot(s_body, d.normals[(j) as usize]);
                if (c > cm) {
                    cm = c;
                    jm = j;
                }
                j += 1;
            }
        }
        if (!(cm < crate::pm::cos(d.fov))) {
            let mut g: rt::Stream = (*u).g;
            if d.chain {
                let mut rh: [[f64; 3]; 3] = crate::gen::sunquad::head_frame(d.normals[(jm) as usize]);
                let mut sb: [f64; 3] = rt::mv(crate::gen::coildisp::small_rotation((*u).bias[(jm) as usize]), s_body);
                let mut cur: [f64; 4] = crate::gen::sunquad::quad_currents(rt::mv(rh, sb), d.head, &mut g);
                let (mut sh, mut okh) = crate::gen::sunangles::quad_angles(cur, d.head);
                ok = okh;
                if ok {
                    s = crate::gen::math::mat3t_vec(rh, sh);
                }
            } else {
                let mut n: [f64; 3] = rt::normal3(&mut g);
                let mut e: [f64; 3] = rt::vadd((*u).bias[(jm) as usize], rt::vscale(n, d.noise));
                s = crate::gen::facets::unit_or_zero(rt::mv(crate::gen::coildisp::small_rotation(e), s_body));
                ok = true;
            }
            (*u).g = g;
        }
    }
    (ok, s)
}
