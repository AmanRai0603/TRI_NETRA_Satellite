/// A quaternion made unit as the engine's la::qnorm: below a norm of 1e-300 the identity.
/// - q: real[1][4] (passed a plain number)
/// - returns r: real[1][4] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn init_qnorm(q: [f64; 4]) -> [f64; 4] {
    let mut r: [f64; 4] = [0.0; 4];
    let mut n: f64 = crate::pm::sqrt(((((q[0] * q[0]) + (q[1] * q[1])) + (q[2] * q[2])) + (q[3] * q[3])));
    if (n < 1.0e-300) {
        r = [0.0, 0.0, 0.0, 1.0];
    } else {
        r = [(q[0] / n), (q[1] / n), (q[2] / n), (q[3] / n)];
    }
    r
}

/// The attitude (ECI to body) a run starts at: q_nad nadir's reference, q_g the start mode's guidance reference
/// (has_g: the start mode has a guidance), axis (body) and angle [rad] the error asked for, draws from g.
/// - kind: AttStart (passed a choice, as its option's number)
/// - q_nad: real[1][4] (passed a plain number)
/// - has_g: bool (passed true or false)
/// - q_g: real[1][4] (passed a plain number)
/// - axis: real[1][3] (passed a plain number)
/// - angle: real[1] (passed a plain number)
/// - g: inout stream (passed a random stream, as six numbers)
/// - returns q0: real[1][4] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn initial_attitude(kind: i64, q_nad: [f64; 4], has_g: bool, q_g: [f64; 4], axis: [f64; 3], angle: f64, g: &mut rt::Stream) -> [f64; 4] {
    let mut q0: [f64; 4] = [0.0; 4];
    q0 = q_nad;
    if (kind == crate::gen::initstate::ATTSTART_RANDOM) {
        let mut x0: f64 = rt::normal(&mut (*g));
        let mut x1: f64 = rt::normal(&mut (*g));
        let mut x2: f64 = rt::normal(&mut (*g));
        let mut x3: f64 = rt::normal(&mut (*g));
        q0 = crate::gen::initstate::init_qnorm([x0, x1, x2, x3]);
    } else if ((kind == crate::gen::initstate::ATTSTART_ERROR_FROM_TARGET) || (kind == crate::gen::initstate::ATTSTART_ERROR_FROM_GUIDANCE)) {
        let mut qr: [f64; 4] = q_nad;
        if ((kind == crate::gen::initstate::ATTSTART_ERROR_FROM_GUIDANCE) && has_g) {
            qr = q_g;
        }
        q0 = crate::gen::initstate::init_qnorm(crate::gen::math::qmult(qr, crate::gen::math::fromrotvec(rt::vscale(crate::gen::facets::unit_or_zero(axis), angle))));
    }
    q0
}

/// The body rate [rad/s] a run starts at, the body at q0, the satellite at r [m] with velocity v [m/s] (ECI): value the
/// rate stated, mag the random direction's magnitude, w_g the guidance's reference rate (in its reference frame, has_g:
/// the start mode has a guidance, q_g its reference), extra the random direction's magnitude added to it; draws from g.
/// - kind: RateStart (passed a choice, as its option's number)
/// - q0: real[1][4] (passed a plain number)
/// - r: real[1][3] (passed a plain number)
/// - v: real[1][3] (passed a plain number)
/// - value: real[1][3] (passed a plain number)
/// - mag: real[1] (passed a plain number)
/// - has_g: bool (passed true or false)
/// - q_g: real[1][4] (passed a plain number)
/// - w_g: real[1][3] (passed a plain number)
/// - extra: real[1] (passed a plain number)
/// - g: inout stream (passed a random stream, as six numbers)
/// - returns w0: real[1][3] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn initial_rate(kind: i64, q0: [f64; 4], r: [f64; 3], v: [f64; 3], value: [f64; 3], mag: f64, has_g: bool, q_g: [f64; 4], w_g: [f64; 3], extra: f64, g: &mut rt::Stream) -> [f64; 3] {
    let mut w0: [f64; 3] = [0.0; 3];
    w0 = value;
    if (kind == crate::gen::initstate::RATESTART_RANDOM_DIRECTION) {
        let mut n: [f64; 3] = rt::normal3(&mut (*g));
        w0 = rt::vscale(crate::gen::facets::unit_or_zero(n), mag);
    } else if (kind == crate::gen::initstate::RATESTART_LVLH) {
        w0 = rt::mv(crate::gen::math::dcm(q0), rt::vscale(rt::cross(r, v), (1.0 / rt::dot(r, r))));
    } else if (kind == crate::gen::initstate::RATESTART_GUIDANCE) {
        let mut w: [f64; 3] = [0.0; 3];
        if has_g {
            w = rt::mv(crate::gen::math::dcm(crate::gen::math::qmult(crate::gen::math::qconj(q_g), q0)), w_g);
        }
        let mut n: [f64; 3] = rt::normal3(&mut (*g));
        w0 = rt::vadd(w, rt::vscale(crate::gen::facets::unit_or_zero(n), extra));
    }
    w0
}

/// Every rotor's momentum [N m s] at the start: the scenario's h0 for each of the nr rotors, or, when it states none
/// (nan), the flight software's target for that rotor.
/// - nr: int (passed a whole number)
/// - h0: real[1] (passed a plain number)
/// - h_target: real[1][DYN_NR] (passed a plain number)
/// - returns h: real[1][DYN_NR] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn initial_momenta(nr: i64, h0: f64, h_target: [f64; 8]) -> [f64; 8] {
    let mut h: [f64; 8] = [0.0; 8];
    h = [0.0; 8];
    {
        let __end21: i64 = nr;
        let mut i: i64 = 0;
        while i < __end21 {
            h[(i) as usize] = (if (h0).is_nan() { h_target[(i) as usize] } else { h0 });
            i += 1;
        }
    }
    h
}

