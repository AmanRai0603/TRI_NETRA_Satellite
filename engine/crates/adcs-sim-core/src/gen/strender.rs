/// The focal length [px] and the principal point (1-based) of a detector of n pixels a side over a field of half-angle fov.
/// - fov: real[1] (passed a plain number)
/// - n: int (passed a whole number)
/// - returns f: real[1] (passed a plain number)
/// - returns c: real[1] (passed a plain number)
#[allow(clippy::too_many_arguments)]
pub fn st_focal(fov: f64, n: i64) -> (f64, f64) {
    let mut f: f64 = 0.0;
    let mut c: f64 = 0.0;
    let mut nf: f64 = (n as f64);
    f = ((nf / 2.0) / crate::pm::tan(fov));
    c = ((nf + 1.0) / 2.0);
    (f, c)
}

