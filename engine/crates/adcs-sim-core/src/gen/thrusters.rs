/// The couples' duties over the period t: (the torque [N m], the propellant flow [kg/s], the power [W]).
/// - s: ThrusterSet (passed rec)
/// - d: ThrusterDesc (passed rec)
/// - duty: real[1][ACT_NC] (passed a plain number)
/// - t: real[s] (passed in s)
/// - returns tau: real[N m][3] (passed in m^2 kg/s^2)
/// - returns mdot: real[kg/s] (passed in kg/s)
/// - returns p: real[W] (passed in m^2 kg/s^3)
#[allow(clippy::too_many_arguments)]
pub fn thrusters_apply(s: ThrusterSet, d: ThrusterDesc, duty: [f64; 6], t: f64) -> ([f64; 3], f64, f64) {
    let mut tau: [f64; 3] = [0.0; 3];
    let mut mdot: f64 = 0.0;
    let mut p: f64 = 0.0;
    tau = [0.0, 0.0, 0.0];
    let mut fs: f64 = 0.0;
    p = 0.0;
    {
        let __end17: i64 = d.nc;
        let mut j: i64 = 0;
        while j < __end17 {
            let mut on: f64 = crate::gen::rcsmib::valve_on_time(duty[(j) as usize], t, d.mib, d.res);
            if s.failed[(j) as usize] {
                on = 0.0;
            }
            let mut f: f64 = (on / t);
            tau = rt::vadd(tau, rt::vscale(s.tau[(j) as usize], (f * s.tscale[(j) as usize])));
            fs = (fs + (f * s.tscale[(j) as usize]));
            if (on > 0.0) {
                p = (p + crate::gen::rcsvalve::valve_power(on, d.valve_power));
            }
            j += 1;
        }
    }
    mdot = crate::gen::rcsisp::rcs_mass_flow(fs, d.thrust, s.isp);
    (tau, mdot, p)
}

