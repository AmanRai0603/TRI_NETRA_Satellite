/// One tick of the carried clock: the clock's own step d_ns (the difference of its last two readings, which may be negative),
/// the tick's length dt_ns and the bound max_ns, all in ns. The time it advances by, and what happened: 0 the step as read,
/// 1 a step back (held: no advance), 2 a step forward beyond the bound (refused: one tick).
/// vectors: 48
/// - d_ns: int (passed a whole number)
/// - dt_ns: int (passed a whole number)
/// - max_ns: int (passed a whole number)
/// - returns adv_ns: int (passed a whole number)
/// - returns kind: int (passed a whole number)
#[allow(clippy::too_many_arguments)]
pub fn clock_advance(d_ns: i64, dt_ns: i64, max_ns: i64) -> (i64, i64) {
    let mut adv_ns: i64 = 0;
    let mut kind: i64 = 0;
    adv_ns = d_ns;
    kind = 0;
    if (d_ns < 0) {
        adv_ns = 0;
        kind = 1;
    } else if (d_ns > max_ns) {
        adv_ns = dt_ns;
        kind = 2;
    }
    (adv_ns, kind)
}

/// The time since the blob's date (t_ns), corrected by a fix's date jd (have: a fix holds one) against the blob's date jd0:
/// adopted when they differ by more than 20 ms (four times the 5 ms of timestamp jitter the rig flies), and the fix is not
/// before the blob's date. The time, and whether the fix's date was adopted.
/// vectors: 48
/// - t_ns: int (passed a whole number)
/// - have: bool (passed true or false)
/// - jd: real[1] (passed a plain number)
/// - jd0: real[1] (passed a plain number)
/// - returns t_new_ns: int (passed a whole number)
/// - returns adopted: bool (passed true or false)
#[allow(clippy::too_many_arguments)]
pub fn clock_adopt(t_ns: i64, have: bool, jd: f64, jd0: f64) -> (i64, bool) {
    let mut t_new_ns: i64 = 0;
    let mut adopted: bool = false;
    t_new_ns = t_ns;
    adopted = false;
    let mut tg: f64 = ((jd - jd0) * 86400.0);
    if ((have && (tg >= 0.0)) && (rt::fabs((tg - ((t_ns as f64) * 1.0e-9))) > 0.02)) {
        t_new_ns = (((tg * 1000000000.0) + 0.5) as i64);
        adopted = true;
    }
    (t_new_ns, adopted)
}

