// pcode_gen.js -- TRI-NETRA pseudocode v2: the translators to Rust and to MATLAB (docs/PSEUDOCODE_V2.md).
// Both follow the interpreter's arithmetic (pcode.js `rt`): x^k by repeated multiplication, min/max/abs
// written out, sums of products left to right, the same table lookups, every literal already in SI.
