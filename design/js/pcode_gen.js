export function toMatlab(prog, opts = {}) {
  const pkg = opts.pkg || "asils.physics";          // e.g. functions at +asils/+physics/+orbit/radius.m
  const rtp = opts.rt || "asils.pc";
  const files = {};
  const zero = (t) => {
    switch (t.k) {
      case "real": case "int": case "choice": return "0"; case "bool": return "false"; case "stream": return "zeros(6, 1)";
      case "arr": return t.of.k === "arr" ? `zeros(${t.n}, ${t.of.n})` : `zeros(${t.n}, 1)`;
      case "rec": return `${pkg}.${prog.records[t.name].module}.${t.name}_zero()`;
    }
  };
  const valueLit = (v, t) => {
    if (t.k === "arr") return t.of.k === "arr" ? `[${v.map((r) => r.map(lit).join(", ")).join("; ")}]` : `[${v.map((x) => valueLit(x, t.of)).join("; ")}]`;
    if (t.k === "bool") return String(v);
    if (t.k === "int" || t.k === "choice") return String(v);
    if (t.k === "stream") return `[${v.map(ml).join("; ")}]`;
    return L(v);
  };
  const L = (x) => (typeof x === "number" && !Number.isFinite(x) ? nonFinite(x, MATLAB_NF) : lit(x));
  const ml = (x) => L(x).replace(/\.0$/, "").replace(/\.0e/, "e");
  const ex = (e) => {
    switch (e.e) {
      case "num": return e.fill ? zero(e.fill) : isInt(e.ty) ? String(e.v) : ml(e.si);
      case "bool": return String(e.v);
      case "str": return JSON.stringify(e.v);
      case "var":
        if (e.kind === "builtin_const") return e.name === "pi" ? "pi" : nonFinite(CONST_OF[e.name], MATLAB_NF);
        if (e.kind === "const") return valueLitM(constOf(prog, prog.consts[e.name].e), prog.consts[e.name].ty);
        if (e.kind === "data") return `${dataRef(e)}()`;
        if (e.kind === "state") return `st.${e.name}`;
        return e.name;
      case "arr": {
        if (e.scale !== undefined) return `[${e.items.map((x) => ml((x.ty.k === "int" ? x.v : x.si) * e.scale)).join("; ")}]`;
        if (e.ty.of.k === "arr") return `[${e.items.map((x) => `(${ex(x)}).'`).join("; ")}]`;
        return `[${e.items.map(ex).join("; ")}]`;
      }
      case "index": {
        // a data table is a function holding its one copy: it is indexed through its call
        if (e.a.e === "index" && e.a.a.ty.k === "arr" && e.a.a.ty.of.k === "arr") return `${dataRef(e.a.a) || ex(e.a.a)}(${idx(e.a.i)}, ${idx(e.i)})`;
        if (e.a.ty.of.k === "arr") return dataRef(e.a) ? `(${dataRef(e.a)}(${idx(e.i)}, ':')).'` : `(${ex(e.a)}(${idx(e.i)}, :)).'`;
        return `${dataRef(e.a) || ex(e.a)}(${idx(e.i)})`;
      }
      // a call's result cannot be indexed in MATLAB (f().x): its field through getfield
      case "field": return e.choice ? String(e.choice.i) : e.a.e === "call" ? `getfield(${ex(e.a)}, '${e.f}')` : `${ex(e.a)}.${e.f}`;
      case "un": return e.op === "not" ? `(~${ex(e.a)})` : `(-(${ex(e.a)}))`;
      case "ifx":
        // MATLAB has no conditional expression: a branch that could fail when it is not the one taken (an index,
        // a call) is handed over unevaluated, so only the branch taken runs, as in the interpreter
        if (mayFail(e.a) || mayFail(e.b)) return `${rtp}.choose_lazy(${ex(e.c)}, @() ${ex(e.a)}, @() ${ex(e.b)})`;
        return `${rtp}.choose(${ex(e.c)}, ${ex(e.a)}, ${ex(e.b)})`;
      case "bin": return bin(e);
      case "call": return call(e);
    }
    throw new Error(`cannot translate ${e.e}`);
  };
  const mayFail = (e) => {
    if (!e || typeof e !== "object") return false;
    if (e.e === "index" || (e.e === "call" && !e.record && !e.builtin)) return true;
    return ["a", "b", "c", "i"].some((k) => e[k] && typeof e[k] === "object" && mayFail(e[k])) || (e.items || []).some(mayFail) || (e.args || []).some(mayFail);
  };
  const dataRef = (x) => (x.e === "var" && x.kind === "data" ? `${pkg}.${prog.data[x.name].module}.${x.name}` : null);
  const valueLitM = (v, t) => (t.k === "real" ? (v < 0 ? `(${ml(v)})` : ml(v)) : valueLit(v, t));
  const idx = (i) => (i.e === "num" ? String(i.v + 1) : `(${ex(i)}) + 1`);
  const bin = (e) => {
    const op = e.op;
    if (op === "and") return `(${ex(e.a)} && ${ex(e.b)})`;
    if (op === "or") return `(${ex(e.a)} || ${ex(e.b)})`;
    if (op === "^") return `${rtp}.ipow(${ex(e.a)}, ${e.k})`;
    if (op === "!=") return `(${ex(e.a)} ~= ${ex(e.b)})`;
    if (["==", "<", "<=", ">", ">="].includes(op)) return `(${ex(e.a)} ${op} ${ex(e.b)})`;
    if (e.shape === "mv") return `${rtp}.mv(${ex(e.a)}, ${ex(e.b)})`;
    if (e.shape === "mm") return `${rtp}.mm(${ex(e.a)}, ${ex(e.b)})`;
    return `(${ex(e.a)} ${op} ${ex(e.b)})`;
  };
  const call = (e) => {
    if (e.record) return `${pkg}.${prog.records[e.record].module}.${e.record}_zero()`;
    const a = e.args.map(ex);
    if (e.builtin) {
      const f = e.f;
      switch (f) {
        case "sqrt": case "sin": case "cos": case "tan": case "asin": case "acos": case "atan": case "exp": case "log": case "log10": case "log2": case "erf":
        case "floor": case "ceil": case "round": return `${f}(${a[0]})`;
        case "trunc": return `fix(${a[0]})`;
        case "abs": return `${rtp}.fabs(${a[0]})`;
        case "sign": return `sign(${a[0]})`;
        case "atan2": return `atan2(${a[0]}, ${a[1]})`;
        case "hypot": return `hypot(${a[0]}, ${a[1]})`;
        case "fmod": return `rem(${a[0]}, ${a[1]})`;
        case "pow": return `(${a[0]})^(${a[1]})`;
        case "min": case "max": return a.slice(1).reduce((acc, x) => `${rtp}.f${f}(${acc}, ${x})`, a[0]);
        case "clamp": return `${rtp}.clamp(${a[0]}, ${a[1]}, ${a[2]})`;
        case "real": return a[0];
        case "isnan": return `isnan(${a[0]})`;
        case "isfinite": return `isfinite(${a[0]})`;
        case "int": return `fix(${a[0]})`;
        case "div": return `fix((${a[0]}) / (${a[1]}))`;
        case "rem": return `rem(${a[0]}, ${a[1]})`;
        case "band": return `bitand(${a[0]}, ${a[1]})`;
        case "bor": return `bitor(${a[0]}, ${a[1]})`;
        case "bxor": return `bitxor(${a[0]}, ${a[1]})`;
        case "shl": return `bitshift(${a[0]}, ${a[1]})`;
        case "shr": return `bitshift(${a[0]}, -(${a[1]}))`;
        case "len": return String(e.args[0].ty.n);
        case "dot": return `${rtp}.dot_(${a[0]}, ${a[1]})`;
        case "cross": return `${rtp}.cross_(${a[0]}, ${a[1]})`;
        case "norm": return `${rtp}.norm_(${a[0]})`;
        case "unit": return `${rtp}.unit_(${a[0]})`;
        case "transpose": return `(${a[0]}).'`;
        case "sort": return `${rtp}.sort_(${a[0]})`;
        case "stream": return `${rtp}.stream_new(${a[0]}, ${e.sid ? `[${e.sid[0]}, ${e.sid[1]}]` : a[1]})`;
        case "uniform": case "normal": case "normal3": return `${rtp}.stream_${f}(${a[0]})`;
        case "argsort": return `${rtp}.argsort_(${a[0]})`;
      }
    }
    return `${pkg}.${e.target.module}.${e.target.name}(${a.join(", ")})`;
  };
  const lv = (l) => {
    if (l.e === "var") return l.kind === "state" ? `st.${l.name}` : l.name;
    if (l.e === "index") {
      if (l.a.e === "index" && l.a.a.ty.k === "arr" && l.a.a.ty.of.k === "arr") return `${lv(l.a.a)}(${idx(l.a.i)}, ${idx(l.i)})`;
      if (l.a.ty.of.k === "arr") return `${lv(l.a)}(${idx(l.i)}, :)`;
      return `${lv(l.a)}(${idx(l.i)})`;
    }
    return `${lv(l.a)}.${l.f}`;
  };
  const isRowTarget = (l) => l.e === "index" && !(l.a.e === "index" && l.a.a.ty.k === "arr" && l.a.a.ty.of.k === "arr") && l.a.ty.of.k === "arr";
  let tmp = 0;
  const stmts = (body, ind) => body.map((s) => stmt(s, ind)).join("");
  const stmt = (s, ind) => {
    const I = "    ".repeat(ind);
    switch (s.s) {
      case "let":
        if (s.e.inout) return inoutStmt(s.names, null, s.e, I);
        if (s.names.length > 1) return `${I}[${s.names.join(", ")}] = ${ex(s.e)};\n`;
        return `${I}${s.names[0]} = ${ex(s.e)};\n`;
      case "state": return "";
      case "set": {
        if (s.e.inout) return inoutStmt(null, s.targets, s.e, I);
        if (s.targets.length > 1) {
          const ts = s.targets.map(() => `t__${tmp++}`);
          return `${I}[${ts.join(", ")}] = ${ex(s.e)};\n` + s.targets.map((t, i) => `${I}${lv(t)} = ${ts[i]}${isRowTarget(t) ? ".'" : ""};\n`).join("");
        }
        const t = s.targets[0];
        return `${I}${lv(t)} = ${ex(s.e)}${isRowTarget(t) ? ".'" : ""};\n`;
      }
      case "if": {
        let out = "";
        s.arms.forEach((arm, i) => { out += `${I}${i ? "elseif" : "if"} ${ex(arm.c)}\n${stmts(arm.body, ind + 1)}`; });
        if (s.els) out += `${I}else\n${stmts(s.els, ind + 1)}`;
        return out + `${I}end\n`;
      }
      case "for": return `${I}for ${s.v} = (${ex(s.a)}):((${ex(s.b)}) - 1)\n${stmts(s.body, ind + 1)}${I}end\n`;
      case "settle": {
        const k = `k__${tmp++}`, n = `n__${tmp++}`;
        return `${I}${n} = ${ex(s.n)}; ${k} = 0;\n${I}while true\n${stmts(s.body, ind + 1)}${I}    ${k} = ${k} + 1;\n` +
          `${I}    if ${ex(s.c)}, break; end\n${I}    if ${k} >= ${n}\n${s.els ? stmts(s.els, ind + 2) : ""}${I}        break;\n${I}    end\n${I}end\n`;
      }
    }
    throw new Error(`cannot translate statement ${s.s}`);
  };
  // a call that changes its inout inputs: every output and each inout input's new value into a temporary, then
  // the names or targets from the outputs, and the caller's variables from the inout values
  const inoutStmt = (names, targets, e, I) => {
    const outs = (e.builtin ? [0] : e.target.outs).map(() => `t__${tmp++}`);
    const ios = e.inoutArgs.map((i) => [`t__${tmp++}`, e.args[i]]);
    let out = `${I}[${[...outs, ...ios.map((x) => x[0])].join(", ")}] = ${ex(e)};\n`;
    if (names) out += names.map((n, i) => `${I}${n} = ${outs[i]};\n`).join("");
    else out += targets.map((t, i) => `${I}${lv(t)} = ${outs[i]}${isRowTarget(t) ? ".'" : ""};\n`).join("");
    return out + ios.map(([tv, a]) => `${I}${lv(a)} = ${tv};\n`).join("");
  };
  const help = (name, lines) => lines.length ? `%${name.toUpperCase()}  ${lines[0]}\n` + lines.slice(1).map((l) => `%   ${l}`.trimEnd() + "\n").join("") : `%${name.toUpperCase()}\n`;
  for (const m of Object.values(prog.modules)) {
    const dir = `+${m.name}`;
    for (const it of m.items) {
      if (it.kind === "fn" || it.kind === "proc") {
        const outs = [...it.outs, ...it.params.filter((p) => p.inout)].map((o) => o.name), ins = it.params.map((p) => p.name);
        if (it.kind === "proc") { outs.push("st"); ins.unshift("st"); }
        let body = "";
        if (it.kind === "proc") body += `    if isempty(st)\n        st = struct();\n` + it.states.map((s) => `        st.${s.name} = ${valueLitM(constOf(prog, s.e), s.vty)};\n`).join("") + "    end\n";
        body += it.outs.map((o) => `    ${o.name} = ${zero(o.ty)};\n`).join("") + stmts(it.body, 1);
        files[`${dir}/${it.name}.m`] = `function [${outs.join(", ")}] = ${it.name}(${ins.join(", ")})\n` +
          help(it.name, [...it.doc, ...it.params.map(io), ...it.outs.map((o) => `returns ${io(o)}`), HEAD]) +
          body + "end\n";
      } else if (it.kind === "table") {
        const outs = it.outs.map((o) => o.name);
        files[`${dir}/${it.name}.m`] = `function [${outs.join(", ")}] = ${it.name}(${it.key.name})\n` +
          help(it.name, [...it.doc, `table (${it.mode}): ${it.key.name} -> ${outs.join(", ")}`, HEAD]) +
          `    T = [\n${it.si.map((r) => `        ${r.map(ml).join(", ")}`).join("\n")}\n    ];\n` +
          `    r = ${rtp}.lookup_${it.mode}(T, ${it.key.name});\n` + outs.map((o, i) => `    ${o} = r(${i + 1});\n`).join("") + "end\n";
      } else if (it.kind === "data") {
        // one copy, kept between calls: v = NAME() is the whole table, NAME(i, j) an element, NAME(i, ':') a row
        const el = it.ty.of.k === "arr" ? it.ty.of.of : it.ty.of;
        const m = (x) => (el.k === "int" ? String(x) : ml(x));
        const lines = it.ty.of.k === "arr" ? it.value.map((r) => `            ${r.map(m).join(", ")}`) : chunks(it.value, 10).map((c) => `            ${c.map(m).join("; ")}`);
        files[`${dir}/${it.name}.m`] = `function v = ${it.name}(varargin)\n` +
          help(it.name, [...it.doc, `data: ${declText(it.type)}; SI: ${siOf(it.ty)}`, HEAD]) +
          `    persistent T\n    if isempty(T)\n        T = [\n${lines.join("\n")}\n        ];\n    end\n` +
          "    if nargin == 0, v = T; else, v = T(varargin{:}); end\nend\n";
      } else if (it.kind === "record") {
        files[`${dir}/${it.name}_zero.m`] = `function s = ${it.name}_zero()\n` + help(`${it.name}_zero`, [`a ${it.name} with every field zero`, HEAD]) +
          "    s = struct();\n" + it.fields.map((f) => `    s.${f.name} = ${zero(f.ty)};\n`).join("") + "end\n";
      }
    }
  }
  // the vector dispatcher: a function by name, its inputs and outputs flattened (row-major, SI); a record field by
  // field in declaration order, as the vectors flatten it
  const flat = (t) => widthOf(prog, t);
  const callable = Object.values(prog.fns).filter((f) => f.kind === "fn");
  const readArg = (t, at) => {
    const n = flat(t);
    if (t.k === "rec") {
      let k = 0;
      const parts = prog.records[t.name].fields.map((f) => { const r = `'${f.name}', {${readArg(f.ty, at + k)}}`; k += flat(f.ty); return r; });
      return `struct(${parts.join(", ")})`;
    }
    const sl = n === 1 ? `x(${at + 1})` : `x(${at + 1}:${at + n})`;
    if (t.k === "bool") return `(${sl} ~= 0)`;
    if (t.k === "stream") return `reshape(${sl}, 6, 1)`;
    if (t.k === "arr" && t.of.k === "arr") return `reshape(${sl}, ${t.of.n}, ${t.n}).'`;
    if (t.k === "arr") return `reshape(${sl}, ${t.n}, 1)`;
    return sl;
  };
  const flatOut = (t, v) => (t.k === "rec" ? `[${prog.records[t.name].fields.map((f) => flatOut(f.ty, `${v}.${f.name}`)).join("; ")}]`
    : t.k === "arr" && t.of.k === "arr" ? `reshape((${v}).', [], 1)` : t.k === "arr" || t.k === "stream" ? `reshape(${v}, [], 1)` : `double(${v})`);
  let disp = `function y = call(name, x)\n` + help("call", ["a function by its registry name (module::name), inputs and outputs flattened (row-major, SI)", HEAD]) +
    "    switch name\n";
  // an inout input's value after the call follows the outputs
  const ioOuts = (f) => f.params.map((p, i) => (p.inout ? [`io${i + 1}`, p] : null)).filter(Boolean);
  for (const f of callable) {
    let at = 0; const args = [];
    for (const p of f.params) { args.push(readArg(p.ty, at)); at += flat(p.ty); }
    const outs = f.outs.map((_, i) => `o${i + 1}`);
    disp += `        case '${f.module}::${f.name}'\n            [${[...outs, ...ioOuts(f).map((x) => x[0])].join(", ")}] = ${pkg}.${f.module}.${f.name}(${args.join(", ")});\n` +
      `            y = [${[...f.outs.map((o, i) => flatOut(o.ty, outs[i])), ...ioOuts(f).map(([n, p]) => flatOut(p.ty, n))].join("; ")}];\n`;
  }
  disp += "        otherwise\n            error('pcode:call', 'no function %s', name);\n    end\nend\n";
  files["call.m"] = disp;
  const procs = Object.values(prog.fns).filter((f) => f.kind === "proc");
  let seq = `function Y = call_seq(name, X)\n` + help("call_seq", ["a proc called once per column of X, its state carried from each call to the next; Y has a column per call", HEAD]) +
    "    st = []; Y = [];\n    for c = 1:size(X, 2)\n        x = X(:, c);\n        switch name\n";
  for (const f of procs) {
    let at = 0; const args = [];
    for (const p of f.params) { args.push(readArg(p.ty, at)); at += flat(p.ty); }
    const outs = f.outs.map((_, i) => `o${i + 1}`);
    seq += `            case '${f.module}::${f.name}'\n                [${[...outs, ...ioOuts(f).map((x) => x[0])].join(", ")}, st] = ${pkg}.${f.module}.${f.name}(st${args.length ? ", " : ""}${args.join(", ")});\n` +
      `                y = [${[...f.outs.map((o, i) => flatOut(o.ty, outs[i])), ...ioOuts(f).map(([n, p]) => flatOut(p.ty, n))].join("; ")}];\n`;
  }
  seq += "            otherwise\n                error('pcode:call', 'no proc %s', name);\n        end\n        Y = [Y, y];\n    end\nend\n";
  files["call_seq.m"] = seq;
  return files;
}

