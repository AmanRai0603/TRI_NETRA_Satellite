import { makeInterpreter, typeText, declText, dimText, VERSION } from "./pcode.js";

const HEAD = `Generated by tools/pcode.py from the pseudocode (${VERSION}); do not edit.`;

// a value that is not finite, as a language writes it: [inf, -inf, nan]
export const nonFinite = (x, nf) => (Number.isNaN(x) ? nf[2] : x > 0 ? nf[0] : nf[1]);
const RUST_NF = ["f64::INFINITY", "f64::NEG_INFINITY", "f64::NAN"], MATLAB_NF = ["Inf", "-Inf", "NaN"];
// the values of the language's constants inf and nan
export const CONST_OF = { inf: Infinity, nan: NaN };

// the shortest decimal that reads back as the same double, as a float literal
export function lit(x) {
  if (Number.isNaN(x) || !Number.isFinite(x)) throw new Error(`cannot write ${x} as a literal`);
  if (Object.is(x, -0)) return "-0.0";
  let s = String(x);
  if (!/[.eE]/.test(s)) s += ".0";
  if (/e/.test(s) && !/\./.test(s.split("e")[0])) s = s.replace("e", ".0e");
  return s;
}
// how a value is passed: its SI unit ("in m"), or what it is when it has none
function siOf(t) {
  let e = t; while (e.k === "arr") e = e.of;
  if (e.k === "real") { const d = dimText(e.dim); return d === "1" ? "a plain number" : `in ${d}`; }
  return e.k === "bool" ? "true or false" : e.k === "int" ? "a whole number" : e.k === "choice" ? "a choice, as its option's number"
    : e.k === "stream" ? "a random stream, as six numbers" : e.k;
}
const io = (x) => `${x.name}: ${x.inout ? "inout " : ""}${declText(x.type)} (passed ${siOf(x.ty)})`;
// a stream's key and counter from its six numbers (pcode.js), as 64-bit whole numbers
export const streamKey = (w, i) => (BigInt(w[i]) << 32n) | BigInt(w[i + 1]);
// a name's stream id (its two halves) as one hexadecimal number
export const sidHex = (sid) => `0x${((BigInt(sid[0]) << 32n) | BigInt(sid[1])).toString(16)}`;
// a value's width as numbers, as the vectors flatten it
const widthOf = (prog, t) => (t.k === "arr" ? t.n * widthOf(prog, t.of) : t.k === "rec" ? prog.records[t.name].fields.reduce((a, f) => a + widthOf(prog, f.ty), 0) : t.k === "stream" ? 6 : 1);
export { widthOf };
// a data table's values in lines of n
export const chunks = (v, n) => Array.from({ length: Math.ceil(v.length / n) }, (_, i) => v.slice(i * n, (i + 1) * n));
const isInt = (t) => t && t.k === "int";
const isReal = (t) => t && t.k === "real";
const isArr = (t) => t && t.k === "arr";
const leafIsReal = (t) => (t.k === "arr" ? leafIsReal(t.of) : t.k === "real");
const realOf = (t) => (t.k === "arr" ? { ...t, of: realOf(t.of) } : t.k === "int" ? { k: "real", dim: t.dim } : t);

// ================================================================== Rust
export function toRust(prog, opts = {}) {
  const interp = makeInterpreter(prog);
  const files = {};
  const extras = new Set();                       // runtime pieces a program uses beyond RUST_RT (rt.rs carries them only then)
  const crate = opts.crate || "adcs_physics";
  // the flight build (tools/flight_build.py) embeds the code as a module of a no_std crate: its root path, the
  // module its scalar maths comes from, and no vector dispatcher (a test aid that needs the heap)
  const root = opts.root || "crate";
  const fm = (std, name) => (opts.math ? `${opts.math}::${name}` : std);
  const L = (x) => (typeof x === "number" && !Number.isFinite(x) ? nonFinite(x, RUST_NF) : lit(x));
  const rty = (t) => {
    switch (t.k) {
      case "real": return "f64"; case "int": case "choice": return "i64"; case "bool": return "bool"; case "stream": extras.add("stream"); return "rt::Stream";
      case "arr": return `[${rty(t.of)}; ${t.n}]`;
      case "rec": return t.name;
    }
    throw new Error(`no Rust type for ${typeText(t)}`);
  };
  const zero = (t) => {
    switch (t.k) {
      case "real": return "0.0"; case "int": case "choice": return "0"; case "bool": return "false"; case "stream": extras.add("stream"); return "rt::Stream::default()";
      case "arr": return `[${zero(t.of)}; ${t.n}]`;
      case "rec": return `${t.name}::default()`;
    }
  };
  const valueLit = (v, t) => {
    if (t.k === "arr") return `[${v.map((x) => valueLit(x, t.of)).join(", ")}]`;
    if (t.k === "int" || t.k === "choice") return String(v);
    if (t.k === "bool") return String(v);
    if (t.k === "stream") { extras.add("stream"); return `rt::Stream::from_words([${v.map(L).join(", ")}])`; }
    return L(v);
  };
  let curFn = null;
  // an expression, made to fit the type it is wanted as (int -> real)
  const E = (e, want) => {
    if (want && isArr(want) && isArr(e.ty) && leafIsReal(want) && !leafIsReal(e.ty)) {
      if (e.e !== "arr") throw new Error("an array of whole numbers where one of reals is wanted: write its elements as reals");
      return `[${e.items.map((x) => E(x, want.of)).join(", ")}]`;
    }
    const s = ex(e);
    if (want && isReal(want) && isInt(e.ty)) return e.e === "num" ? lit(e.v) : `(${s} as f64)`;
    return s;
  };
  // an argument of a vector builtin: real elements, whatever the literal was written with
  const V = (x) => E(x, realOf(x.ty));
  const ex = (e) => {
    switch (e.e) {
      case "num": return e.fill ? zero(e.fill) : isInt(e.ty) ? String(e.v) : L(e.si);
      case "bool": return String(e.v);
      case "str": return JSON.stringify(e.v);
      case "var":
        if (e.kind === "builtin_const") return e.name === "pi" ? "core::f64::consts::PI" : nonFinite(CONST_OF[e.name], RUST_NF);
        if (e.kind === "const") return `${root}::${prog.consts[e.name].module}::${e.name.toUpperCase()}`;
        if (e.kind === "data") return `${root}::${prog.data[e.name].module}::DATA_${e.name.toUpperCase()}`;
        if (e.kind === "state") return `st.${e.name}`;
        if (e.kind === "inout") return `(*${e.name})`;
        return e.name;
      case "arr": {
        const el = e.ty.of;
        if (e.scale !== undefined) return `[${e.items.map((x) => L((x.ty.k === "int" ? x.v : x.si) * e.scale)).join(", ")}]`;
        return `[${e.items.map((x) => E(x, el)).join(", ")}]`;
      }
      case "index": return `${ex(e.a)}[${e.i.e === "num" ? e.i.v : `(${ex(e.i)}) as usize`}]`;
      case "field":
        if (e.choice) return `${root}::${prog.choices[e.choice.name].module}::${e.choice.name.toUpperCase()}_${e.f.toUpperCase()}`;
        return `${ex(e.a)}.${e.f}`;
      case "un":
        if (e.op === "not") return `(!${ex(e.a)})`;
        if (isArr(e.ty)) return e.ty.of.k === "arr" ? `rt::mneg(${ex(e.a)})` : `rt::vneg(${ex(e.a)})`;
        return `(-(${ex(e.a)}))`;
      case "ifx": return `(if ${ex(e.c)} { ${E(e.a, e.ty)} } else { ${E(e.b, e.ty)} })`;
      case "bin": return bin(e);
      case "call": return call(e);
    }
    throw new Error(`cannot translate ${e.e}`);
  };
  const bin = (e) => {
    const op = e.op;
    if (op === "and") return `(${ex(e.a)} && ${ex(e.b)})`;
    if (op === "or") return `(${ex(e.a)} || ${ex(e.b)})`;
    if (op === "^") return isInt(e.ty) ? `rt::ipowi(${ex(e.a)}, ${e.k})` : `rt::ipow(${E(e.a, { k: "real" })}, ${e.k})`;
    if (["==", "!=", "<", "<=", ">", ">="].includes(op)) {
      const bothInt = isInt(e.a.ty) && isInt(e.b.ty);
      const w = bothInt || e.a.ty.k === "bool" ? null : { k: "real" };
      return `(${E(e.a, w)} ${op} ${E(e.b, w)})`;
    }
    if (op === "+" || op === "-") {
      if (isArr(e.ty)) {
        const m = e.ty.of.k === "arr" ? "m" : "v";
        const z = (x) => (x.ty.k !== "arr" ? zero(e.ty) : ex(x));   // a bare 0 beside an array
        return `rt::${m}${op === "+" ? "add" : "sub"}(${z(e.a)}, ${z(e.b)})`;
      }
      if (isInt(e.ty)) return `(${ex(e.a)} ${op} ${ex(e.b)})`;
      return `(${E(e.a, e.ty)} ${op} ${E(e.b, e.ty)})`;
    }
    if (e.shape === "mv") return `rt::mv(${ex(e.a)}, ${ex(e.b)})`;
    if (e.shape === "mm") return `rt::mm(${ex(e.a)}, ${ex(e.b)})`;
    if (e.shape === "vs" || e.shape === "ms") {
      const m = e.shape === "ms" ? "m" : "v";
      if (op === "/") return `rt::${m}div(${ex(e.a)}, ${E(e.b, { k: "real" })})`;
      return e.arrLeft ? `rt::${m}scale(${ex(e.a)}, ${E(e.b, { k: "real" })})` : `rt::${m}scale_l(${E(e.a, { k: "real" })}, ${ex(e.b)})`;
    }
    if (isInt(e.ty)) return `(${ex(e.a)} ${op} ${ex(e.b)})`;
    return `(${E(e.a, { k: "real" })} ${op} ${E(e.b, { k: "real" })})`;
  };
  const call = (e) => {
    if (e.record) return `${e.record}::default()`;
    const a = e.args;
    const R = (i) => E(a[i], { k: "real" });
    if (e.builtin) {
      const f = e.f;
      switch (f) {
        case "sqrt": return `${fm("f64::sqrt", "sqrt")}(${R(0)})`;
        case "abs": return isInt(e.ty) ? `(${ex(a[0])}).abs()` : `rt::fabs(${R(0)})`;
        case "floor": case "ceil": return isInt(e.ty) ? ex(a[0]) : `${fm(`f64::${f}`, f)}(${R(0)})`;
        case "round": case "trunc": return isInt(e.ty) ? ex(a[0]) : `${fm(`f64::${f}`, f)}(${R(0)})`;
        case "sign": return `rt::sign(${R(0)})`;
        case "sin": case "cos": case "tan": case "asin": case "acos": case "atan": case "exp": case "log10": return `${fm(`f64::${f}`, f)}(${R(0)})`;
        case "log": return `${fm("f64::ln", "log")}(${R(0)})`;
        case "log2": return `${fm("f64::log2", "log2")}(${R(0)})`;
        // std has no erf: the platform's C library's, declared in rt.rs (extras), the same erf C and MATLAB call
        case "erf": if (opts.math) return `${opts.math}::erf(${R(0)})`; extras.add("erf"); return `rt::erf(${R(0)})`;
        case "atan2": return `${fm("f64::atan2", "atan2")}(${R(0)}, ${R(1)})`;
        case "hypot": return `${fm("f64::hypot", "hypot")}(${R(0)}, ${R(1)})`;
        case "fmod": return opts.math ? `${opts.math}::fmod(${R(0)}, ${R(1)})` : `(${R(0)} % ${R(1)})`;
        // std's powf is an LLVM intrinsic the optimiser rewrites (pow(x, 2.0) to x*x): the exponent goes through
        // black_box so the platform's pow is called, as the language says, in every build
        case "pow": return opts.math ? `${opts.math}::pow(${R(0)}, ${R(1)})` : `f64::powf(${R(0)}, core::hint::black_box(${R(1)}))`;
        case "min": case "max": {
          const g = e.allInt ? `rt::i${f}` : `rt::f${f}`;
          const args = a.map((x) => (e.allInt ? ex(x) : E(x, { k: "real" })));
          return args.slice(1).reduce((acc, x) => `${g}(${acc}, ${x})`, args[0]);
        }
        case "clamp": return isInt(e.ty) ? `rt::imin(rt::imax(${ex(a[0])}, ${ex(a[1])}), ${ex(a[2])})` : `rt::clamp(${R(0)}, ${R(1)}, ${R(2)})`;
        case "real": return `(${ex(a[0])} as f64)`;
        case "isnan": return `(${R(0)}).is_nan()`;
        case "isfinite": return `(${R(0)}).is_finite()`;
        case "int": return `(${R(0)} as i64)`;
        case "div": return `(${ex(a[0])} / ${ex(a[1])})`;
        case "rem": return `(${ex(a[0])} % ${ex(a[1])})`;
        case "band": return `(${ex(a[0])} & ${ex(a[1])})`;
        case "bor": return `(${ex(a[0])} | ${ex(a[1])})`;
        case "bxor": return `(${ex(a[0])} ^ ${ex(a[1])})`;
        case "shl": return `(${ex(a[0])} << ${ex(a[1])})`;
        case "shr": return `(${ex(a[0])} >> ${ex(a[1])})`;
        case "len": return String(a[0].ty.n);
        case "dot": return `rt::dot(${V(a[0])}, ${V(a[1])})`;
        case "cross": return `rt::cross(${V(a[0])}, ${V(a[1])})`;
        case "norm": return `rt::norm(${V(a[0])})`;
        case "unit": return `rt::unit(${V(a[0])})`;
        case "transpose": return `rt::tr(${V(a[0])})`;
        case "sort": case "argsort": extras.add("sort"); return `rt::${f}(${ex(a[0])})`;
        case "stream": extras.add("stream"); return `rt::stream(${ex(a[0])}, ${e.sid ? sidHex(e.sid) : `(${ex(a[1])}) as u64`})`;
        case "uniform": case "normal": case "normal3": extras.add("stream"); return `rt::${f}(&mut ${ex(a[0])})`;
      }
    }
    const t = e.target;
    // an inout input is handed over by reference
    const args = a.map((x, i) => (t.kind !== "table" && t.params[i].inout ? `&mut ${ex(x)}` : E(x, (t.kind === "table" ? t.key : t.params[i]).ty))).join(", ");
    return `${root}::${t.module}::${t.name}(${args})`;
  };
  const lv = (l) => {
    if (l.e === "var") return l.kind === "state" ? `st.${l.name}` : l.kind === "inout" ? `(*${l.name})` : l.name;
    if (l.e === "index") return `${lv(l.a)}[${l.i.e === "num" ? l.i.v : `(${ex(l.i)}) as usize`}]`;
    return `${lv(l.a)}.${l.f}`;
  };
  let tmp = 0;
  const stmts = (body, ind) => body.map((s) => stmt(s, ind)).join("");
  const stmt = (s, ind) => {
    const I = "    ".repeat(ind);
    switch (s.s) {
      case "let":
        if (s.names.length > 1) return `${I}let (${s.names.map((n) => `mut ${n}`).join(", ")}) = ${ex(s.e)};\n`;
        return `${I}let mut ${s.names[0]}: ${rty(s.vty)} = ${E(s.e, s.vty)};\n`;
      case "state": return "";
      case "set":
        if (s.targets.length > 1) {
          const n = `__t${tmp++}`;
          return `${I}let ${n} = ${ex(s.e)};\n` + s.targets.map((t, i) => `${I}${lv(t)} = ${n}.${i};\n`).join("");
        }
        return `${I}${lv(s.targets[0])} = ${E(s.e, s.targets[0].ty)};\n`;
      case "if": {
        let out = "";
        s.arms.forEach((arm, i) => { out += `${i ? " else if" : `${I}if`} ${ex(arm.c)} {\n${stmts(arm.body, ind + 1)}${I}}`; });
        if (s.els) out += ` else {\n${stmts(s.els, ind + 1)}${I}}`;
        return out + "\n";
      }
      case "for": {
        const n = `__end${tmp++}`;
        return `${I}{\n${I}    let ${n}: i64 = ${ex(s.b)};\n${I}    let mut ${s.v}: i64 = ${ex(s.a)};\n${I}    while ${s.v} < ${n} {\n${stmts(s.body, ind + 2)}${I}        ${s.v} += 1;\n${I}    }\n${I}}\n`;
      }
      case "settle": {
        const k = `__k${tmp++}`, n = `__n${tmp++}`;
        return `${I}{\n${I}    let ${n}: i64 = ${ex(s.n)};\n${I}    let mut ${k}: i64 = 0;\n${I}    loop {\n${stmts(s.body, ind + 2)}` +
          `${I}        ${k} += 1;\n${I}        if ${ex(s.c)} { break; }\n${I}        if ${k} >= ${n} {\n${s.els ? stmts(s.els, ind + 3) : ""}${I}            break;\n${I}        }\n${I}    }\n${I}}\n`;
      }
    }
    throw new Error(`cannot translate statement ${s.s}`);
  };
  const doc = (lines, ind = "") => lines.map((l) => `${ind}/// ${l}`.trimEnd() + "\n").join("");
  const pascal = (n) => n.split("_").map((w) => w[0].toUpperCase() + w.slice(1)).join("");

  const mods = Object.values(prog.modules);
  // a record (a Rust struct) may be named in another module's code: bring every other module's
  // records into scope (names are unique across the program, so nothing clashes)
  const recordUses = (m) => mods.filter((o) => o !== m && o.items.some((it) => it.kind === "record"))
    .map((o) => `use ${root}::${o.name}::{${o.items.filter((it) => it.kind === "record").map((it) => it.name).join(", ")}};\n`).join("");
  for (const m of mods) {
    let out = `//! ${m.name}: ${(m.doc || []).join(" ") || "the pseudocode module " + m.name}\n//! ${HEAD}\n#![allow(unused_mut, unused_variables, unused_parens, unused_assignments, unused_imports, unreachable_code, non_snake_case, clippy::all)]\nuse ${root}::rt;\n${recordUses(m)}\n`;
    for (const it of m.items) {
      curFn = it;
      if (it.kind === "const") {
        const v = interp.lookup ? null : null; void v;
        const val = evalConst(prog, it);
        out += doc(it.doc) + `pub const ${it.name.toUpperCase()}: ${rty(it.ty)} = ${valueLit(val, it.ty)};\n\n`;
      } else if (it.kind === "choice") {
        // its options as whole numbers, from 0
        out += doc(it.doc) + `/// Choice ${it.name}: ${it.options.map((o) => o.name).join(", ")}.\n` +
          it.options.map((o, i) => `pub const ${it.name.toUpperCase()}_${o.name.toUpperCase()}: i64 = ${i};\n`).join("") + "\n";
      } else if (it.kind === "data") {
        // one copy, indexed in place: a row a line (a 1-D table ten values a line)
        const el = it.ty.of.k === "arr" ? it.ty.of.of : it.ty.of;
        const lines = it.ty.of.k === "arr" ? it.value.map((r) => `    [${r.map((x) => valueLit(x, el)).join(", ")}],\n`)
          : chunks(it.value, 10).map((c) => `    ${c.map((x) => valueLit(x, el)).join(", ")},\n`);
        out += doc(it.doc) + `/// Data: ${declText(it.type)}; SI: ${siOf(it.ty)}.\npub static DATA_${it.name.toUpperCase()}: ${rty(it.ty)} = [\n${lines.join("")}];\n\n`;
      } else if (it.kind === "record") {
        out += doc(it.doc) + `#[derive(Clone, Copy, Debug, Default, PartialEq)]\npub struct ${it.name} {\n` +
          it.fields.map((f) => `    pub ${f.name}: ${rty(f.ty)},\n`).join("") + "}\n\n";
      } else if (it.kind === "table") {
        const C = it.outs.length, Rn = it.si.length;
        const T = `TABLE_${it.name.toUpperCase()}`;
        out += `const ${T}: [[f64; ${C}]; ${Rn}] = [\n` + it.si.map((r) => `    [${r.map(L).join(", ")}],\n`).join("") + "];\n";
        const ret = C === 1 ? "f64" : `(${it.outs.map(() => "f64").join(", ")})`;
        out += doc(it.doc) + `/// Table (${it.mode}): ${it.key.name} -> ${it.outs.map((o) => o.name).join(", ")}.\n` +
          `pub fn ${it.name}(${it.key.name}: f64) -> ${ret} {\n    let r = rt::lookup_${it.mode}(&${T}, ${it.key.name});\n    ` +
          (C === 1 ? "r[0]" : `(${it.outs.map((_, i) => `r[${i}]`).join(", ")})`) + "\n}\n\n";
      } else {
        const ins = it.params.map((p) => `${p.name}: ${p.inout ? "&mut " : ""}${rty(p.ty)}`);
        let stDecl = "";
        if (it.kind === "proc") {
          const S = `${pascal(it.name)}State`;
          stDecl = `/// The state ${it.name} keeps between calls.\n#[derive(Clone, Copy, Debug, PartialEq)]\npub struct ${S} {\n` +
            it.states.map((s) => `    pub ${s.name}: ${rty(s.vty)},\n`).join("") + "}\n" +
            `impl Default for ${S} {\n    fn default() -> Self {\n        ${S} {\n` +
            it.states.map((s) => `            ${s.name}: ${valueLit(constOf(prog, s.e), s.vty)},\n`).join("") + "        }\n    }\n}\n\n";
          ins.unshift(`st: &mut ${S}`);
        }
        const ret = it.outs.length === 1 ? rty(it.outs[0].ty) : `(${it.outs.map((o) => rty(o.ty)).join(", ")})`;
        out += stDecl + doc(it.doc) + doc(it.params.map((p) => `- ${io(p)}`)) +
          doc(it.outs.map((o) => `- returns ${io(o)}`)) +
          `#[allow(clippy::too_many_arguments)]\npub fn ${it.name}(${ins.join(", ")}) -> ${ret} {\n` +
          it.outs.map((o) => `    let mut ${o.name}: ${rty(o.ty)} = ${zero(o.ty)};\n`).join("") +
          stmts(it.body, 1) +
          `    ${it.outs.length === 1 ? it.outs[0].name : `(${it.outs.map((o) => o.name).join(", ")})`}\n}\n\n`;
      }
    }
    files[`src/${m.name}.rs`] = out.trimEnd() + "\n";
  }
  // the dispatcher the vector test calls: every fn whose inputs and outputs are numbers or arrays of them
  // a record is passed field by field in declaration order, as the vectors flatten it
  const flat = (t) => widthOf(prog, t);
  const callable = Object.values(prog.fns).filter((f) => f.kind === "fn");
  const readArg = (t, at) => {
    if (t.k === "stream") { extras.add("stream"); return [`crate::rt::Stream::from_words([${[0, 1, 2, 3, 4, 5].map((k) => `x[${at + k}]`).join(", ")}])`, 6]; }
    if (t.k === "real") return [`x[${at}]`, 1];
    if (t.k === "int" || t.k === "choice") return [`x[${at}] as i64`, 1];
    if (t.k === "bool") return [`x[${at}] != 0.0`, 1];
    let parts = [], k = 0;
    if (t.k === "rec") {
      for (const f of prog.records[t.name].fields) { const [s, n] = readArg(f.ty, at + k); parts.push(`${f.name}: ${s}`); k += n; }
      return [`crate::${prog.records[t.name].module}::${t.name} { ${parts.join(", ")} }`, k];
    }
    // a long array of numbers (a workspace, a table) as a loop, not an expression an element
    if (t.n > 1024 && ["real", "int", "choice", "bool"].includes(t.of.k)) {
      const x = `x[${at} + i]`;
      const [z, v] = t.of.k === "real" ? ["0.0", x] : t.of.k === "bool" ? ["false", `${x} != 0.0`] : ["0i64", `${x} as i64`];
      return [`{ let mut a = [${z}; ${t.n}]; for i in 0..${t.n} { a[i] = ${v}; } a }`, t.n];
    }
    for (let i = 0; i < t.n; i++) { const [s, n] = readArg(t.of, at + k); parts.push(s); k += n; }
    return [`[${parts.join(", ")}]`, k];
  };
  const pushOut = (t, name) => {
    if (t.k === "stream") return `for v in ${name}.words().iter() { let v = *v; out.push(v); }`;
    if (t.k === "real") return `out.push(${name});`;
    if (t.k === "int" || t.k === "choice") return `out.push(${name} as f64);`;
    if (t.k === "bool") return `out.push(if ${name} { 1.0 } else { 0.0 });`;
    if (t.k === "rec") return prog.records[t.name].fields.map((f) => pushOut(f.ty, `${name}.${f.name}`)).join(" ");
    return `for v in ${name}.iter() { let v = *v; ${pushOut(t.of, "v")} }`;
  };
  let disp = `//! The vector dispatcher: call a function by name with its inputs flattened (SI). ${HEAD}\n` +
    "#![allow(unused_mut, unused_variables, unreachable_code, clippy::all)]\n\n/// The outputs, flattened, or None when there is no such function or too few inputs.\npub fn call(name: &str, x: &[f64]) -> Option<Vec<f64>> {\n    let mut out = Vec::new();\n    match name {\n";
  // an inout input is read into a variable of its own, handed over by reference, and given back after the outputs
  const ioLets = (f, args, I) => f.params.map((p, i) => (p.inout ? `${I}let mut io${i} = ${args[i]};\n` : "")).join("");
  const ioArgs = (f, args) => f.params.map((p, i) => (p.inout ? `&mut io${i}` : args[i]));
  const ioPush = (f, I) => f.params.map((p, i) => (p.inout ? `${I}${pushOut(p.ty, `io${i}`)}\n` : "")).join("");
  for (const f of callable) {
    let at = 0; const args = [];
    for (const p of f.params) { const [s, n] = readArg(p.ty, at); args.push(s); at += n; }
    const outs = f.outs.length === 1 ? ["r"] : f.outs.map((_, i) => `r.${i}`);
    disp += `        "${f.module}::${f.name}" => {\n            if x.len() != ${at} { return None; }\n${ioLets(f, args, "            ")}            let r = crate::${f.module}::${f.name}(${ioArgs(f, args).join(", ")});\n` +
      f.outs.map((o, i) => `            ${pushOut(o.ty, outs[i])}\n`).join("") + ioPush(f, "            ") + "        }\n";
  }
  disp += "        _ => return None,\n    }\n    Some(out)\n}\n";
  const procs = Object.values(prog.fns).filter((f) => f.kind === "proc");
  disp += "\n/// A proc called once per entry of `calls`, its state carried from each call to the next.\n" +
    "pub fn call_seq(name: &str, calls: &[Vec<f64>]) -> Option<Vec<Vec<f64>>> {\n    let mut outs = Vec::new();\n    match name {\n";
  for (const f of procs) {
    let at = 0; const args = [];
    for (const p of f.params) { const [s2, n] = readArg(p.ty, at); args.push(s2); at += n; }
    const outs = f.outs.length === 1 ? ["r"] : f.outs.map((_, i) => `r.${i}`);
    disp += `        "${f.module}::${f.name}" => {\n            let mut st = crate::${f.module}::${pascal(f.name)}State::default();\n` +
      `            for x in calls {\n                if x.len() != ${at} { return None; }\n                let mut out = Vec::new();\n` +
      `${ioLets(f, args, "                ")}                let r = crate::${f.module}::${f.name}(&mut st, ${ioArgs(f, args).join(", ")});\n` +
      f.outs.map((o, i) => `                ${pushOut(o.ty, outs[i])}\n`).join("") + ioPush(f, "                ") + "                outs.push(out);\n            }\n        }\n";
  }
  disp += "        _ => return None,\n    }\n    Some(outs)\n}\n";
  if (opts.dispatch !== false) files["src/dispatch.rs"] = disp;
  files["src/rt.rs"] = (opts.math ? RUST_RT.replace("dot(a, a).sqrt()", `${opts.math}::sqrt(dot(a, a))`) : RUST_RT) +
    (extras.has("sort") ? RUST_RT_SORT : "") + (extras.has("stream") ? rustRtStream(opts.math) : "") + (extras.has("erf") ? RUST_RT_ERF : "");
  files[root === "crate" ? "src/lib.rs" : "src/mod.rs"] = `//! ${opts.title || "Functions written in the pseudocode"}. ${HEAD}\n//! Every relation is SI in and SI out; each function's doc lists its inputs and outputs with their units.\n` +
    `#![allow(clippy::all)]\npub mod rt;\n${opts.dispatch !== false ? "pub mod dispatch;\n" : ""}` + mods.map((m) => `pub mod ${m.name};\n`).join("");
  return files;
}

export function constOf(prog, e) {
  // a state's starting value: a constant expression, evaluated once by the interpreter's rules
  const fake = { kind: "fn", name: "__c", params: [], outs: [{ name: "v", ty: e.ty }], body: [{ s: "set", targets: [{ e: "var", name: "v", ty: e.ty }], e }], states: [] };
  const p2 = { ...prog, fns: { ...prog.fns, __c: fake } };
  return makeInterpreter(p2).call("__c", [])[0];
}
function evalConst(prog, c) { return constOf(prog, c.e); }

