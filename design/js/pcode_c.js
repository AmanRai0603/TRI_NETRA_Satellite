// pcode_c.js -- TRI-NETRA pseudocode v2: the translator to C (docs/PSEUDOCODE_V2.md; docs/PLAN_2_0.md S5).
// C99, no dynamic memory, no recursion, in the flight software's conventions (fsw/pseudocode/00_conventions.md):
// every array is a small struct passed and returned by value (so it copies as Rust's fixed arrays do), every
// function and table carries its module as a prefix, a proc keeps its state in a struct it is handed, and the
// arithmetic is the interpreter's (pcode.js `rt`): x^k by repeated multiplication, min/max/abs written out, sums
// of products left to right, the same table lookups, every literal already in SI.
// Owner: Agastya. Copyright (c) 2026 Agastya. All rights reserved.
import { VERSION } from "./pcode.js";
import { lit, constOf, chunks, nonFinite, CONST_OF, streamKey, sidHex, widthOf } from "./pcode_gen.js";

const HEAD = `Generated by tools/pcode.py from the pseudocode (${VERSION}); do not edit.`;
const isInt = (t) => t && t.k === "int";
const isReal = (t) => t && t.k === "real";
const isArr = (t) => t && t.k === "arr";
const leafIsReal = (t) => (t.k === "arr" ? leafIsReal(t.of) : t.k === "real");
const realOf = (t) => (t.k === "arr" ? { ...t, of: realOf(t.of) } : t.k === "int" ? { k: "real", dim: t.dim } : t);

// words a name of the pseudocode may not be in C: its keywords, what <math.h>, <stdint.h> and <stdbool.h> define
// as macros or functions we call, and the names the translation uses itself
const RESERVED = new Set(`auto break case char const continue default do double else enum extern float for goto if inline int long
register restrict return short signed sizeof static struct switch typedef union unsigned void volatile while _Bool _Complex _Imaginary
bool true false NULL errno assert isnan isinf isfinite signbit fpclassify isnormal NAN INFINITY HUGE_VAL M_PI
sqrt sin cos tan asin acos atan atan2 exp log log10 log2 pow floor ceil round trunc fmod fabs hypot llabs
int8_t int16_t int32_t int64_t uint8_t uint16_t uint32_t uint64_t size_t st main`.split(/\s+/));
const cname = (n) => (RESERVED.has(n) ? `${n}_` : n);
const C_NF = ["INFINITY", "(-INFINITY)", "NAN"];
const L = (x) => (typeof x === "number" && !Number.isFinite(x) ? nonFinite(x, C_NF) : lit(x));

export function toC(prog, opts = {}) {
  const lib = opts.lib || "pcode";                 // the header is <lib>.h, the runtime <lib>_rt.h
  const files = {};
  // ------------------------------------------------------------ types: each array shape and record once
  const types = new Map();                         // C name -> definition, in dependency order
  const tag = (t) => {
    switch (t.k) {
      case "real": return "f"; case "int": case "choice": return "i"; case "bool": return "b"; case "stream": return "s";
      case "arr": return `a${t.n}${tag(t.of)}`;
      case "rec": return `r${t.name}`;
    }
    throw new Error(`no C type for ${t.k}`);
  };
  const cty = (t) => {
    switch (t.k) {
      case "real": return "double"; case "int": case "choice": return "int64_t"; case "bool": return "bool";
      case "stream":
        if (!types.has("pc_stream")) types.set("pc_stream", "/* A random stream (adcs-sim-core rng.rs): its key and counter, the spare normal draw and whether there is one. */\ntypedef struct { uint64_t key; uint64_t n; double spare; bool has; } pc_stream;");
        return "pc_stream";
      case "rec": recordType(t.name); return t.name;
      case "arr": {
        const n = `pc_${tag(t)}`;
        if (!types.has(n)) { const el = cty(t.of); types.set(n, `typedef struct { ${el} v[${t.n}]; } ${n};`); }
        return n;
      }
    }
    throw new Error(`no C type for ${t.k}`);
  };
  const recordType = (name) => {
    if (types.has(name)) return;
    const r = prog.records[name];
    types.set(name, null);                          // reserve the place: fields first, then the record
    const fields = r.fields.map((f) => `    ${cty(f.ty)} ${cname(f.name)};\n`).join("");
    types.delete(name);
    types.set(name, `typedef struct {\n${fields}} ${name};`);
  };
  const zero = (t) => (t.k === "real" ? "0.0" : t.k === "int" || t.k === "choice" ? "0" : t.k === "bool" ? "false" : `((${cty(t)}){0})`);
  // a value as an initializer (file-scope constants, a proc's starting state)
  const init = (v, t) => {
    if (t.k === "arr") return `{ { ${v.map((x) => init(x, t.of)).join(", ")} } }`;
    if (t.k === "rec") return `{ ${prog.records[t.name].fields.map((f) => init(v[f.name], f.ty)).join(", ")} }`;
    if (t.k === "bool") return String(!!v);
    if (t.k === "int" || t.k === "choice") return String(v);
    if (t.k === "stream") return `{ UINT64_C(${streamKey(v, 0)}), UINT64_C(${streamKey(v, 2)}), ${L(v[4])}, ${v[5] !== 0 ? "true" : "false"} }`;
    return L(v);
  };
  // ------------------------------------------------------------ the runtime: the scalar helpers, and each array
  // operation once per shape it is used at
  const helpers = new Map();
  const need = (name, body) => { if (!helpers.has(name)) helpers.set(name, body); return name; };
  const vecOp = (op, t) => {                      // t: an array of reals (a vector) or of vectors (a matrix)
    const T = cty(t), n = t.n, mat = isArr(t.of);
    const el = (a, i) => `${a}.v[${i}]`;
    switch (op) {
      case "add": case "sub": {
        const o = op === "add" ? "+" : "-";
        const inner = mat ? (i) => `r.v[${i}] = ${vecOp(op, t.of)}(a.v[${i}], b.v[${i}]);` : (i) => `r.v[${i}] = a.v[${i}] ${o} b.v[${i}];`;
        return need(`pc_${op}_${tag(t)}`, `static inline ${T} pc_${op}_${tag(t)}(${T} a, ${T} b) { ${T} r = a; int i; for (i = 0; i < ${n}; i++) { ${inner("i")} } return r; }`);
      }
      case "neg": {
        const inner = mat ? `r.v[i] = ${vecOp("neg", t.of)}(a.v[i]);` : "r.v[i] = -a.v[i];";
        return need(`pc_neg_${tag(t)}`, `static inline ${T} pc_neg_${tag(t)}(${T} a) { ${T} r = a; int i; for (i = 0; i < ${n}; i++) { ${inner} } return r; }`);
      }
      case "scale": case "scalel": case "div": {
        const inner = mat ? `r.v[i] = ${vecOp(op, t.of)}(${op === "scalel" ? "s, a.v[i]" : "a.v[i], s"});`
          : op === "scale" ? "r.v[i] = a.v[i] * s;" : op === "scalel" ? "r.v[i] = s * a.v[i];" : "r.v[i] = a.v[i] / s;";
        const args = op === "scalel" ? `double s, ${T} a` : `${T} a, double s`;
        return need(`pc_${op}_${tag(t)}`, `static inline ${T} pc_${op}_${tag(t)}(${args}) { ${T} r = a; int i; for (i = 0; i < ${n}; i++) { ${inner} } return r; }`);
      }
      case "dot":
        return need(`pc_dot_${tag(t)}`, `static inline double pc_dot_${tag(t)}(${T} a, ${T} b) { double s = a.v[0] * b.v[0]; int i; for (i = 1; i < ${n}; i++) { s = s + a.v[i] * b.v[i]; } return s; }`);
      case "norm":
        return need(`pc_norm_${tag(t)}`, `static inline double pc_norm_${tag(t)}(${T} a) { return sqrt(${vecOp("dot", t)}(a, a)); }`);
      case "unit":
        return need(`pc_unit_${tag(t)}`, `static inline ${T} pc_unit_${tag(t)}(${T} a) { double n = pc_fmax(${vecOp("norm", t)}(a), 1e-30); ${T} r = a; int i; for (i = 0; i < ${n}; i++) { r.v[i] = a.v[i] / n; } return r; }`);
      case "cross":
        return need(`pc_cross_${tag(t)}`, `static inline ${T} pc_cross_${tag(t)}(${T} a, ${T} b) { ${T} r; r.v[0] = ${el("a", 1)} * ${el("b", 2)} - ${el("a", 2)} * ${el("b", 1)}; r.v[1] = ${el("a", 2)} * ${el("b", 0)} - ${el("a", 0)} * ${el("b", 2)}; r.v[2] = ${el("a", 0)} * ${el("b", 1)} - ${el("a", 1)} * ${el("b", 0)}; return r; }`);
    }
    throw new Error(`no C array operation ${op}`);
  };
  const mvOp = (mt, vt) => {
    const M = cty(mt), Vin = cty(vt), Vout = cty({ k: "arr", n: mt.n, of: mt.of.of });
    const name = `pc_mv_${tag(mt)}`;
    return need(name, `static inline ${Vout} ${name}(${M} a, ${Vin} v) { ${Vout} r; int i; for (i = 0; i < ${mt.n}; i++) { r.v[i] = ${vecOp("dot", mt.of)}(a.v[i], v); } return r; }`);
  };
  const mmOp = (at, bt, rt) => {
    const A = cty(at), B = cty(bt), R = cty(rt), K = at.of.n;
    const name = `pc_mm_${tag(at)}_${tag(bt)}`;
    return need(name, `static inline ${R} ${name}(${A} a, ${B} b) { ${R} r; int i, j, k; for (i = 0; i < ${at.n}; i++) { for (j = 0; j < ${bt.of.n}; j++) { double s = a.v[i].v[0] * b.v[0].v[j]; for (k = 1; k < ${K}; k++) { s = s + a.v[i].v[k] * b.v[k].v[j]; } r.v[i].v[j] = s; } } return r; }`);
  };
  // random streams (pcode.js rt.stream: adcs-sim-core rng.rs), each piece once
  const streamOp = (op) => {
    cty({ k: "stream" });
    const sm = need("pc_splitmix64", "static inline uint64_t pc_splitmix64(uint64_t z) { z = z + UINT64_C(0x9E3779B97F4A7C15); z = (z ^ (z >> 30)) * UINT64_C(0xBF58476D1CE4E5B9); z = (z ^ (z >> 27)) * UINT64_C(0x94D049BB133111EB); return z ^ (z >> 31); }");
    if (op === "stream") return need("pc_stream_new", `static inline pc_stream pc_stream_new(int64_t seed, uint64_t id) { pc_stream s; s.key = ${sm}((uint64_t)seed ^ ${sm}(id)); s.n = 0; s.spare = 0.0; s.has = false; return s; }`);
    const un = need("pc_uniform", `static inline double pc_uniform(pc_stream *s) { uint64_t z; s->n = s->n + 1; z = ${sm}(s->key ^ ${sm}(s->n)); return ((double)(z >> 11) + 0.5) * (1.0 / 9007199254740992.0); }`);
    if (op === "uniform") return un;
    const no = need("pc_normal", `static inline double pc_normal(pc_stream *s) { double u1, u2, r, v; if (s->has) { s->has = false; v = s->spare; s->spare = 0.0; return v; } u1 = ${un}(s); u2 = ${un}(s); r = sqrt(-2.0 * log(u1)); s->spare = r * sin(2.0 * 3.141592653589793 * u2); s->has = true; return r * cos(2.0 * 3.141592653589793 * u2); }`);
    if (op === "normal") return no;
    const V3 = cty({ k: "arr", n: 3, of: { k: "real" } });
    return need("pc_normal3", `static inline ${V3} pc_normal3(pc_stream *s) { ${V3} r; r.v[0] = ${no}(s); r.v[1] = ${no}(s); r.v[2] = ${no}(s); return r; }`);
  };
  // the toolbox sort: an insertion sort, ascending, equal values in their order (pcode.js rt.argsort)
  const sortOp = (op, t) => {
    const A = cty(t), I = cty({ k: "arr", n: t.n, of: { k: "int" } }), n = t.n;
    const as = need(`pc_argsort_${tag(t)}`, `static inline ${I} pc_argsort_${tag(t)}(${A} v) { ${I} ix; int i, j; for (i = 0; i < ${n}; i++) { ix.v[i] = i; } for (i = 1; i < ${n}; i++) { int64_t k = ix.v[i]; j = i; while (j > 0 && v.v[ix.v[j - 1]] > v.v[k]) { ix.v[j] = ix.v[j - 1]; j--; } ix.v[j] = k; } return ix; }`);
    if (op === "argsort") return as;
    return need(`pc_sort_${tag(t)}`, `static inline ${A} pc_sort_${tag(t)}(${A} v) { ${I} ix = ${as}(v); ${A} r = v; int i; for (i = 0; i < ${n}; i++) { r.v[i] = v.v[ix.v[i]]; } return r; }`);
  };
  const trOp = (t) => {
    const rt = { k: "arr", n: t.of.n, of: { k: "arr", n: t.n, of: t.of.of } };
    const A = cty(t), R = cty(rt), name = `pc_tr_${tag(t)}`;
    return need(name, `static inline ${R} ${name}(${A} a) { ${R} r; int i, j; for (i = 0; i < ${t.n}; i++) { for (j = 0; j < ${t.of.n}; j++) { r.v[j].v[i] = a.v[i].v[j]; } } return r; }`);
  };

  // ------------------------------------------------------------ expressions
  const mod = (m) => cname(m);
  const fname = (f) => `${mod(f.module)}_${f.name}`;
  const constName = (c) => `${mod(c.module)}_${c.name.toUpperCase()}`;
  const dataName = (d) => `${mod(d.module)}_DATA_${d.name.toUpperCase()}`;
  const choiceName = (c, o) => `${mod(c.module)}_${c.name.toUpperCase()}_${o.toUpperCase()}`;
  const outsOf = (e) => (e.target ? e.target.outs : []);
  const retType = (f) => (f.outs.length === 1 ? cty(f.outs[0].ty || { k: "real" }) : `${fname(f)}_out`);
  const E = (e, want) => {
    if (want && isArr(want) && isArr(e.ty) && leafIsReal(want) && !leafIsReal(e.ty)) {
      if (e.e !== "arr") throw new Error("an array of whole numbers where one of reals is wanted: write its elements as reals");
      return `((${cty(want)}){ { ${e.items.map((x) => E(x, want.of)).join(", ")} } })`;
    }
    const s = ex(e);
    if (want && isReal(want) && isInt(e.ty)) return e.e === "num" ? lit(e.v) : `((double)(${s}))`;
    return s;
  };
  const V = (x) => E(x, realOf(x.ty));
  const R = (x) => E(x, { k: "real" });
  const idx = (i) => (i.e === "num" ? String(i.v) : `(${ex(i)})`);
  const ex = (e) => {
    switch (e.e) {
      case "num": return e.fill ? zero(e.fill) : isInt(e.ty) ? `INT64_C(${e.v})` : L(e.si);
      case "bool": return String(e.v);
      case "str": return JSON.stringify(e.v);
      case "var":
        if (e.kind === "builtin_const") return e.name === "pi" ? "3.141592653589793" : nonFinite(CONST_OF[e.name], C_NF);
        if (e.kind === "const") return constName(prog.consts[e.name]);
        if (e.kind === "data") return dataName(prog.data[e.name]);
        if (e.kind === "state") return `st->${cname(e.name)}`;
        if (e.kind === "inout") return `(*${cname(e.name)})`;
        return cname(e.name);
      case "arr": {
        const T = cty(e.ty);
        if (e.scale !== undefined) return `((${T}){ { ${e.items.map((x) => L((x.ty.k === "int" ? x.v : x.si) * e.scale)).join(", ")} } })`;
        return `((${T}){ { ${e.items.map((x) => E(x, e.ty.of)).join(", ")} } })`;
      }
      case "index": return `${ex(e.a)}.v[${idx(e.i)}]`;
      case "field": return e.choice ? choiceName(prog.choices[e.choice.name], e.f) : `${ex(e.a)}.${cname(e.f)}`;
      case "un":
        if (e.op === "not") return `(!${ex(e.a)})`;
        if (isArr(e.ty)) return `${vecOp("neg", e.ty)}(${ex(e.a)})`;
        return `(-(${ex(e.a)}))`;
      case "ifx": return `(${ex(e.c)} ? ${E(e.a, e.ty)} : ${E(e.b, e.ty)})`;
      case "bin": return bin(e);
      case "call": return call(e);
    }
    throw new Error(`cannot translate ${e.e}`);
  };
  const bin = (e) => {
    const op = e.op;
    if (op === "and") return `(${ex(e.a)} && ${ex(e.b)})`;
    if (op === "or") return `(${ex(e.a)} || ${ex(e.b)})`;
    if (op === "^") return isInt(e.ty) ? `pc_ipowi(${ex(e.a)}, ${e.k})` : `pc_ipow(${R(e.a)}, ${e.k})`;
    if (["==", "!=", "<", "<=", ">", ">="].includes(op)) {
      const bothInt = isInt(e.a.ty) && isInt(e.b.ty);
      const w = bothInt || e.a.ty.k === "bool" ? null : { k: "real" };
      return `(${E(e.a, w)} ${op} ${E(e.b, w)})`;
    }
    if (op === "+" || op === "-") {
      if (isArr(e.ty)) {
        const z = (x) => (x.ty.k !== "arr" ? zero(e.ty) : E(x, e.ty));   // a bare 0 beside an array
        return `${vecOp(op === "+" ? "add" : "sub", e.ty)}(${z(e.a)}, ${z(e.b)})`;
      }
      if (isInt(e.ty)) return `(${ex(e.a)} ${op} ${ex(e.b)})`;
      return `(${E(e.a, e.ty)} ${op} ${E(e.b, e.ty)})`;
    }
    if (e.shape === "mv") return `${mvOp(e.a.ty, e.b.ty)}(${V(e.a)}, ${V(e.b)})`;
    if (e.shape === "mm") return `${mmOp(e.a.ty, e.b.ty, e.ty)}(${V(e.a)}, ${V(e.b)})`;
    if (e.shape === "vs" || e.shape === "ms") {
      if (op === "/") return `${vecOp("div", e.ty)}(${V(e.a)}, ${R(e.b)})`;
      return e.arrLeft ? `${vecOp("scale", e.ty)}(${V(e.a)}, ${R(e.b)})` : `${vecOp("scalel", e.ty)}(${R(e.a)}, ${V(e.b)})`;
    }
    if (isInt(e.ty)) return `(${ex(e.a)} ${op} ${ex(e.b)})`;
    return `(${R(e.a)} ${op} ${R(e.b)})`;
  };
  const call = (e) => {
    if (e.record) return zero({ k: "rec", name: e.record });
    const a = e.args;
    if (e.builtin) {
      const f = e.f;
      switch (f) {
        case "sqrt": return `sqrt(${R(a[0])})`;
        case "abs": return isInt(e.ty) ? `pc_iabs(${ex(a[0])})` : `pc_fabs(${R(a[0])})`;
        case "floor": case "ceil": case "round": case "trunc": return isInt(e.ty) ? ex(a[0]) : `${f}(${R(a[0])})`;
        case "sign": return `pc_sign(${R(a[0])})`;
        case "sin": case "cos": case "tan": case "asin": case "acos": case "atan": case "exp": case "log": case "log10": case "log2": return `${f}(${R(a[0])})`;
        case "atan2": return `atan2(${R(a[0])}, ${R(a[1])})`;
        case "hypot": return `hypot(${R(a[0])}, ${R(a[1])})`;
        case "fmod": return `fmod(${R(a[0])}, ${R(a[1])})`;
        case "pow": return `pow(${R(a[0])}, ${R(a[1])})`;
        case "min": case "max": {
          const g = e.allInt ? `pc_i${f}` : `pc_f${f}`;
          const args = a.map((x) => (e.allInt ? ex(x) : R(x)));
          return args.slice(1).reduce((acc, x) => `${g}(${acc}, ${x})`, args[0]);
        }
        case "clamp": return isInt(e.ty) ? `pc_imin(pc_imax(${ex(a[0])}, ${ex(a[1])}), ${ex(a[2])})` : `pc_clamp(${R(a[0])}, ${R(a[1])}, ${R(a[2])})`;
        case "real": return `((double)(${ex(a[0])}))`;
        case "isnan": return `(isnan(${R(a[0])}) != 0)`;
        case "isfinite": return `(isfinite(${R(a[0])}) != 0)`;
        case "int": return `((int64_t)(${R(a[0])}))`;
        case "div": return `(${ex(a[0])} / ${ex(a[1])})`;
        case "rem": return `(${ex(a[0])} % ${ex(a[1])})`;
        case "band": return `(${ex(a[0])} & ${ex(a[1])})`;
        case "bor": return `(${ex(a[0])} | ${ex(a[1])})`;
        case "bxor": return `(${ex(a[0])} ^ ${ex(a[1])})`;
        case "shl": return `(${ex(a[0])} << ${ex(a[1])})`;
        case "shr": return `(${ex(a[0])} >> ${ex(a[1])})`;
        case "len": return `INT64_C(${a[0].ty.n})`;
        case "dot": return `${vecOp("dot", realOf(a[0].ty))}(${V(a[0])}, ${V(a[1])})`;
        case "cross": return `${vecOp("cross", realOf(a[0].ty))}(${V(a[0])}, ${V(a[1])})`;
        case "norm": return `${vecOp("norm", realOf(a[0].ty))}(${V(a[0])})`;
        case "unit": return `${vecOp("unit", realOf(a[0].ty))}(${V(a[0])})`;
        case "transpose": return `${trOp(realOf(a[0].ty))}(${V(a[0])})`;
        case "sort": case "argsort": return `${sortOp(f, a[0].ty)}(${ex(a[0])})`;
        case "stream": return `${streamOp(f)}(${ex(a[0])}, ${e.sid ? `UINT64_C(${sidHex(e.sid)})` : `(uint64_t)(${ex(a[1])})`})`;
        case "uniform": case "normal": case "normal3": return `${streamOp(f)}(&${ex(a[0])})`;
      }
      throw new Error(`no C for the builtin ${f}`);
    }
    const t = e.target;
    // an inout input is handed over by its address
    const args = a.map((x, i) => (t.kind !== "table" && t.params[i].inout ? `&${ex(x)}` : E(x, (t.kind === "table" ? t.key : t.params[i]).ty)));
    if (t.kind === "proc") args.unshift("st");     // never reached: a proc is called by the harness, not from code
    return `${fname(t)}(${args.join(", ")})`;
  };
  const lv = (l) => {
    if (l.e === "var") return l.kind === "state" ? `st->${cname(l.name)}` : l.kind === "inout" ? `(*${cname(l.name)})` : cname(l.name);
    if (l.e === "index") return `${lv(l.a)}.v[${idx(l.i)}]`;
    return `${lv(l.a)}.${cname(l.f)}`;
  };
  // ------------------------------------------------------------ statements
  let tmp = 0;
  const stmts = (body, ind) => body.map((s) => stmt(s, ind)).join("");
  const stmt = (s, ind) => {
    const I = "    ".repeat(ind);
    switch (s.s) {
      case "let": {
        if (s.names.length > 1) {
          const outs = outsOf(s.e), n = `t__${tmp++}`;
          return `${I}${retType(s.e.target)} ${n} = ${ex(s.e)};\n` +
            s.names.map((nm, i) => `${I}${cty(outs[i].ty)} ${cname(nm)} = ${n}.${cname(outs[i].name)};\n`).join("");
        }
        return `${I}${cty(s.vty)} ${cname(s.names[0])} = ${E(s.e, s.vty)};\n`;
      }
      case "state": return "";
      case "set": {
        if (s.targets.length > 1) {
          const outs = outsOf(s.e), n = `t__${tmp++}`;
          return `${I}{\n${I}    ${retType(s.e.target)} ${n} = ${ex(s.e)};\n` +
            s.targets.map((t, i) => `${I}    ${lv(t)} = ${n}.${cname(outs[i].name)};\n`).join("") + `${I}}\n`;
        }
        return `${I}${lv(s.targets[0])} = ${E(s.e, s.targets[0].ty)};\n`;
      }
      case "if": {
        let out = "";
        s.arms.forEach((arm, i) => { out += `${i ? " else if" : `${I}if`} (${ex(arm.c)}) {\n${stmts(arm.body, ind + 1)}${I}}`; });
        if (s.els) out += ` else {\n${stmts(s.els, ind + 1)}${I}}`;
        return out + "\n";
      }
      case "for": {
        const n = `end__${tmp++}`, v = cname(s.v);
        return `${I}{\n${I}    int64_t ${n} = ${ex(s.b)};\n${I}    int64_t ${v} = ${ex(s.a)};\n${I}    while (${v} < ${n}) {\n${stmts(s.body, ind + 2)}${I}        ${v} += 1;\n${I}    }\n${I}}\n`;
      }
      case "settle": {
        const k = `k__${tmp++}`, n = `n__${tmp++}`;
        return `${I}{\n${I}    int64_t ${n} = ${ex(s.n)};\n${I}    int64_t ${k} = 0;\n${I}    for (;;) {\n${stmts(s.body, ind + 2)}` +
          `${I}        ${k} += 1;\n${I}        if (${ex(s.c)}) { break; }\n${I}        if (${k} >= ${n}) {\n${s.els ? stmts(s.els, ind + 3) : ""}${I}            break;\n${I}        }\n${I}    }\n${I}}\n`;
      }
    }
    throw new Error(`cannot translate statement ${s.s}`);
  };
  const doc = (lines, ind = "") => lines.map((l) => `${ind}/* ${l.replace(/\*\//g, "* /")} */`.trimEnd() + "\n").join("");
  const pascal = (n) => n.split("_").map((w) => w[0].toUpperCase() + w.slice(1)).join("");
  const stateType = (f) => `${mod(f.module)}_${pascal(f.name)}State`;

  // ------------------------------------------------------------ each module: its constants, tables and functions
  const decls = [];                                  // the header's declarations, in program order
  const mods = Object.values(prog.modules);
  for (const m of mods) {
    let out = `/* ${m.name}: ${(m.doc || []).join(" ").replace(/\*\//g, "* /") || "the pseudocode module " + m.name} */\n/* ${HEAD} */\n#include "${lib}.h"\n#include "${lib}_rt.h"\n\n`;
    for (const it of m.items) {
      if (it.kind === "const") {
        const v = constOf(prog, it.e);
        decls.push(doc(it.doc) + `extern const ${cty(it.ty)} ${constName({ ...it, module: m.name })};\n`);
        out += `const ${cty(it.ty)} ${constName({ ...it, module: m.name })} = ${init(v, it.ty)};\n\n`;
      } else if (it.kind === "choice") {
        // its options as whole numbers, from 0
        const c = { ...it, module: m.name };
        decls.push(doc(it.doc) + `/* Choice ${it.name}: ${it.options.map((o) => o.name).join(", ")}. */\n` +
          it.options.map((o, i) => `#define ${choiceName(c, o.name)} INT64_C(${i})\n`).join(""));
      } else if (it.kind === "data") {
        // one copy, indexed in place: a row a line (a 1-D table ten values a line)
        const d = { ...it, module: m.name }, T = cty(it.ty);
        const el = it.ty.of.k === "arr" ? it.ty.of.of : it.ty.of;
        const lines = it.ty.of.k === "arr" ? it.value.map((r) => `    { { ${r.map((x) => init(x, el)).join(", ")} } },\n`)
          : chunks(it.value, 10).map((c) => `    ${c.map((x) => init(x, el)).join(", ")},\n`);
        decls.push(doc(it.doc) + `/* Data: ${it.name}, its values from the design. */\nextern const ${T} ${dataName(d)};\n`);
        out += `const ${T} ${dataName(d)} = { {\n${lines.join("")}} };\n\n`;
      } else if (it.kind === "record") {
        recordType(it.name);
      } else if (it.kind === "table") {
        const C = it.outs.length, Rn = it.si.length, f = { ...it, module: m.name };
        const T = `${fname(f)}_rows`;
        out += `static const double ${T}[${Rn}][${C}] = {\n` + it.si.map((r) => `    { ${r.map(L).join(", ")} },\n`).join("") + "};\n";
        if (C > 1) decls.push(`typedef struct { ${it.outs.map((o) => `double ${cname(o.name)};`).join(" ")} } ${fname(f)}_out;\n`);
        decls.push(doc(it.doc) + `/* Table (${it.mode}): ${it.key.name} -> ${it.outs.map((o) => o.name).join(", ")}. */\n${C === 1 ? "double" : `${fname(f)}_out`} ${fname(f)}(double ${cname(it.key.name)});\n`);
        out += `${C === 1 ? "double" : `${fname(f)}_out`} ${fname(f)}(double ${cname(it.key.name)}) {\n    double r[${C}];\n` +
          `    pc_lookup_${it.mode}(&${T}[0][0], ${Rn}, ${C}, ${cname(it.key.name)}, r);\n` +
          (C === 1 ? "    return r[0];\n" : `    {\n        ${fname(f)}_out o;\n${it.outs.map((o, i) => `        o.${cname(o.name)} = r[${i}];\n`).join("")}        return o;\n    }\n`) + "}\n\n";
      } else {
        const f = { ...it, module: m.name };
        const ins = it.params.map((p) => `${cty(p.ty)} ${p.inout ? "*" : ""}${cname(p.name)}`);
        if (it.kind === "proc") {
          const S = stateType(f);
          decls.push(`/* The state ${it.name} keeps between calls. */\ntypedef struct {\n` + it.states.map((s) => `    ${cty(s.vty)} ${cname(s.name)};\n`).join("") + `} ${S};\n`);
          decls.push(`/* ${it.name}'s state before its first call. */\nvoid ${fname(f)}_init(${S} *st);\n`);
          out += `void ${fname(f)}_init(${S} *st) {\n` + it.states.map((s) => {
            const tmpName = `s__${cname(s.name)}`;
            return `    {\n        static const ${cty(s.vty)} ${tmpName} = ${init(constOf(prog, s.e), s.vty)};\n        st->${cname(s.name)} = ${tmpName};\n    }\n`;
          }).join("") + "}\n\n";
          ins.unshift(`${S} *st`);
        }
        if (it.outs.length > 1) decls.push(`typedef struct { ${it.outs.map((o) => `${cty(o.ty)} ${cname(o.name)};`).join(" ")} } ${fname(f)}_out;\n`);
        const ret = it.outs.length === 1 ? cty(it.outs[0].ty) : `${fname(f)}_out`;
        const sig = `${ret} ${fname(f)}(${ins.length ? ins.join(", ") : "void"})`;
        decls.push(doc(it.doc) + doc(it.params.map((p) => `- ${p.name}`)) + doc(it.outs.map((o) => `- returns ${o.name}`)) + `${sig};\n`);
        out += `${sig} {\n` + it.outs.map((o) => `    ${cty(o.ty)} ${cname(o.name)} = ${zero(o.ty)};\n`).join("") + stmts(it.body, 1);
        if (it.outs.length === 1) out += `    return ${cname(it.outs[0].name)};\n`;
        else out += `    {\n        ${ret} r__;\n${it.outs.map((o) => `        r__.${cname(o.name)} = ${cname(o.name)};\n`).join("")}        return r__;\n    }\n`;
        out += "}\n\n";
      }
    }
    files[`src/${m.name}.c`] = out.trimEnd() + "\n";
  }

  // ------------------------------------------------------------ the dispatcher: a function by name, flattened
  const flat = (t) => widthOf(prog, t);
  const LONG = 1024;   // an array of numbers longer than this is read and written by a loop
  const readArg = (t, at, into, I) => {          // statements filling `into` from x[at..]
    if (t.k === "stream") return [`${I}${into}.key = ((uint64_t)x[${at}] << 32) | (uint64_t)x[${at + 1}];\n${I}${into}.n = ((uint64_t)x[${at + 2}] << 32) | (uint64_t)x[${at + 3}];\n` +
      `${I}${into}.spare = x[${at + 4}];\n${I}${into}.has = x[${at + 5}] != 0.0;\n`, 6];
    if (t.k === "real") return [`${I}${into} = x[${at}];\n`, 1];
    if (t.k === "int" || t.k === "choice") return [`${I}${into} = (int64_t)x[${at}];\n`, 1];
    if (t.k === "bool") return [`${I}${into} = x[${at}] != 0.0;\n`, 1];
    let s = "", k = 0;
    if (t.k === "rec") {
      for (const f of prog.records[t.name].fields) { const [c, n] = readArg(f.ty, at + k, `${into}.${cname(f.name)}`, I); s += c; k += n; }
      return [s, k];
    }
    // a long array of numbers (a workspace, a table) as a loop, not a statement an element
    if (t.n > LONG && ["real", "int", "choice", "bool"].includes(t.of.k)) {
      const x = `x[${at} + i_]`;
      const v = t.of.k === "real" ? x : t.of.k === "bool" ? `${x} != 0.0` : `(int64_t)${x}`;
      return [`${I}{ int i_; for (i_ = 0; i_ < ${t.n}; i_++) ${into}.v[i_] = ${v}; }\n`, t.n];
    }
    for (let i = 0; i < t.n; i++) { const [c, n] = readArg(t.of, at + k, `${into}.v[${i}]`, I); s += c; k += n; }
    return [s, k];
  };
  const pushOut = (t, v, I) => {
    if (t.k === "stream") return `${I}out[(*ny)++] = (double)(${v}.key >> 32);\n${I}out[(*ny)++] = (double)(${v}.key & UINT64_C(0xFFFFFFFF));\n` +
      `${I}out[(*ny)++] = (double)(${v}.n >> 32);\n${I}out[(*ny)++] = (double)(${v}.n & UINT64_C(0xFFFFFFFF));\n${I}out[(*ny)++] = ${v}.spare;\n${I}out[(*ny)++] = ${v}.has ? 1.0 : 0.0;\n`;
    if (t.k === "real") return `${I}out[(*ny)++] = ${v};\n`;
    if (t.k === "int" || t.k === "choice") return `${I}out[(*ny)++] = (double)${v};\n`;
    if (t.k === "bool") return `${I}out[(*ny)++] = ${v} ? 1.0 : 0.0;\n`;
    if (t.k === "rec") return prog.records[t.name].fields.map((f) => pushOut(f.ty, `${v}.${cname(f.name)}`, I)).join("");
    if (t.n > LONG && ["real", "int", "choice", "bool"].includes(t.of.k)) {
      const e = `${v}.v[i_]`;
      const o = t.of.k === "real" ? e : t.of.k === "bool" ? `${e} ? 1.0 : 0.0` : `(double)${e}`;
      return `${I}{ int i_; for (i_ = 0; i_ < ${t.n}; i_++) out[(*ny)++] = ${o}; }\n`;
    }
    let s = "";
    for (let i = 0; i < t.n; i++) s += pushOut(t.of, `${v}.v[${i}]`, I);
    return s;
  };
  const allFns = Object.values(prog.fns);
  let disp = `/* The vector dispatcher: a function by its name (module::name), its inputs and outputs flattened (SI). */\n/* ${HEAD} */\n` +
    `#include <string.h>\n#include "${lib}.h"\n\n`;
  const callBody = (f, I) => {
    let s = "", at = 0;
    f.params.forEach((p, i) => { s += `${I}${cty(p.ty)} a${i};\n`; });
    f.params.forEach((p, i) => { const [c, n] = readArg(p.ty, at, `a${i}`, I); s += c; at += n; });
    return [s, at];
  };
  // an inout input's value after the call follows the outputs
  const ioPush = (f, I) => f.params.map((p, i) => (p.inout ? pushOut(p.ty, `a${i}`, I) : "")).join("");
  const outsBody = (f, call, I) => {
    if (f.outs.length === 1) return `${I}{\n${I}    ${cty(f.outs[0].ty)} r = ${call};\n${pushOut(f.outs[0].ty, "r", I + "    ")}${ioPush(f, I + "    ")}${I}}\n`;
    return `${I}{\n${I}    ${fname(f)}_out r = ${call};\n` + f.outs.map((o) => pushOut(o.ty, `r.${cname(o.name)}`, I + "    ")).join("") + ioPush(f, I + "    ") + `${I}}\n`;
  };
  const callArgs = (f) => f.params.map((p, i) => (p.inout ? `&a${i}` : `a${i}`));
  disp += "/* 0 and the outputs in out (*ny of them), or -1: no such function, or not the number of inputs it takes. */\n" +
    "int pc_call(const char *name, const double *x, int nx, double *out, int *ny) {\n    *ny = 0;\n";
  for (const f of allFns.filter((g) => g.kind === "fn")) {
    const [setup, at] = callBody(f, "        ");
    disp += `    if (strcmp(name, "${f.module}::${f.name}") == 0) {\n        if (nx != ${at}) { return -1; }\n    {\n${setup}${outsBody(f, `${fname(f)}(${callArgs(f).join(", ")})`, "        ")}    }\n        return 0;\n    }\n`;
  }
  disp += "    (void)x; (void)nx; (void)out;\n    return -1;\n}\n\n";
  disp += "/* A proc called once per call, its state carried: x holds ncalls rows of nx inputs; out gets ncalls rows of\n   *ny outputs each. 0, or -1. */\n" +
    "int pc_call_seq(const char *name, const double *xs, int ncalls, int nx, double *outs, int *ny) {\n    int c;\n    *ny = 0;\n";
  for (const f of allFns.filter((g) => g.kind === "proc")) {
    const [setup, at] = callBody(f, "            ");
    disp += `    if (strcmp(name, "${f.module}::${f.name}") == 0) {\n        ${stateType(f)} st;\n        if (nx != ${at}) { return -1; }\n        ${fname(f)}_init(&st);\n` +
      `        for (c = 0; c < ncalls; c++) {\n            const double *x = xs + (long)c * nx;\n            double *out = outs + (long)c * 256;\n            *ny = 0;\n` +
      `            {\n${setup}${outsBody(f, `${fname(f)}(&st${f.params.length ? ", " : ""}${callArgs(f).join(", ")})`, "            ")}            }\n            (void)x;\n        }\n        return 0;\n    }\n`;
  }
  disp += "    (void)xs; (void)ncalls; (void)nx; (void)outs; (void)c;\n    return -1;\n}\n";
  if (opts.dispatch !== false) files["src/dispatch.c"] = disp;

  // ------------------------------------------------------------ the header and the runtime
  const guard = `${lib.toUpperCase().replace(/[^A-Z0-9]/g, "_")}_H`;
  files[`include/${lib}.h`] = `/* ${opts.title || "Functions written in the pseudocode"}. ${HEAD} */\n/* Every relation is SI in and SI out. C99, no dynamic memory. */\n` +
    `#ifndef ${guard}\n#define ${guard}\n#include <stdbool.h>\n#include <stdint.h>\n\n` +
    [...types.values()].join("\n") + "\n\n" + decls.join("\n") +
    (opts.dispatch !== false ? "\nint pc_call(const char *name, const double *x, int nx, double *out, int *ny);\n" +
    "int pc_call_seq(const char *name, const double *xs, int ncalls, int nx, double *outs, int *ny);\n" : "") +
    `\n#endif\n`;
  const rguard = `${lib.toUpperCase().replace(/[^A-Z0-9]/g, "_")}_RT_H`;
  files[`include/${lib}_rt.h`] = `/* The arithmetic every translation shares with the interpreter (design/js/pcode.js \`rt\`). ${HEAD} */\n` +
    `#ifndef ${rguard}\n#define ${rguard}\n#include <math.h>\n#include <stdint.h>\n#include "${lib}.h"\n\n` + C_RT + "\n" + [...helpers.values()].join("\n") + `\n\n#endif\n`;
  return files;
}

const C_RT = `/* x^k by repeated multiplication, left to right; x^-k = 1/(x^k). */
static inline double pc_ipow(double x, int k) { double r = x; int i, n = k < 0 ? -k : k; if (k == 0) { return 1.0; } for (i = 1; i < n; i++) { r = r * x; } return k < 0 ? 1.0 / r : r; }
static inline int64_t pc_ipowi(int64_t x, int k) { int64_t r = 1; int i; for (i = 0; i < k; i++) { r *= x; } return r; }
static inline double pc_fmin(double a, double b) { return b < a ? b : a; }
static inline double pc_fmax(double a, double b) { return b > a ? b : a; }
static inline int64_t pc_imin(int64_t a, int64_t b) { return b < a ? b : a; }
static inline int64_t pc_imax(int64_t a, int64_t b) { return b > a ? b : a; }
static inline int64_t pc_iabs(int64_t a) { return a < 0 ? -a : a; }
static inline double pc_fabs(double x) { if (x < 0.0) { return -x; } if (x == 0.0) { return 0.0; } return x; }
static inline double pc_clamp(double x, double lo, double hi) { return pc_fmin(pc_fmax(x, lo), hi); }
static inline double pc_sign(double x) { return x > 0.0 ? 1.0 : (x < 0.0 ? -1.0 : 0.0); }
/* The last row whose key is at or below x (the first row below the first key). */
static inline void pc_lookup_step(const double *t, int rows, int cols, double x, double *r) {
    int i = 0, j;
    while (i + 1 < rows && t[(i + 1) * cols] <= x) { i++; }
    for (j = 0; j < cols; j++) { r[j] = t[i * cols + j]; }
}
/* Straight-line between the two rows around x, held at the ends. */
static inline void pc_lookup_linear(const double *t, int rows, int cols, double x, double *r) {
    double xc = pc_clamp(x, t[0], t[(rows - 1) * cols]), s;
    int i = 0, j;
    while (i + 2 < rows && t[(i + 1) * cols] <= xc) { i++; }
    s = (xc - t[i * cols]) / (t[(i + 1) * cols] - t[i * cols]);
    for (j = 0; j < cols; j++) { r[j] = t[i * cols + j] + s * (t[(i + 1) * cols + j] - t[i * cols + j]); }
}`;
