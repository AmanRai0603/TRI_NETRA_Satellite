#!/usr/bin/env python3
"""The database/code boundary (docs/PLAN_2_0.md S7 done-when, docs/CODE_ARCHITECTURE.md §1): a relation or a
published model found in code outside the generated files and the toolbox fails the build.

    python3 tools/boundary.py              check; exit 1 on any problem
    python3 tools/boundary.py --list       every hand-written file with its class, then the check
    python3 tools/boundary.py --root DIR   check another tree (the tests plant relations in a copy)

What it holds, over every source file of the code (the engine's crates, the flight software in C and Rust and its
targets, the MATLAB twin, the tools, the Python package, the pages' scripts: tools/boundary.toml `scope`):
  generated  a file under a generated folder (`[[generated]]`) says so in its first lines; it is the design's, and
             is not searched (its generator's --check holds it to the design)
  classified every other file is classified (`[[part]]`, the first glob that matches): toolbox, reader, core,
             runtime, rig, translator, library, application, cli, tools, test or vendored, each with why. There is
             no class for a relation or a published model: such a file has no place in the code
  searched   every classified file but a test's (a test fixture may hold a published value, docs/CODE_ARCHITECTURE.md
             §1) is searched for the marks of a relation or a published model: the published constants (the Earth's
             GM, radius, rotation rate and J2, the Sun's and the Moon's GM, the solar constant and the Sun's pressure,
             the astronomical unit, the speed of light, WGS-84's flattening, G, Stefan-Boltzmann, the sidereal day,
             sea-level density), the shapes of a gravity or drag law, and a table (twelve or more long numbers in a
             run of lines). A Rust file is searched up to its `#[cfg(test)]`
  allowed    a find is allowed only by an `[[allow]]` naming the file and the mark, with why: either it is not a
             relation (a unit's definition in the toolbox, an integrator's tableau, a file format's fill values, the
             check's own patterns), or it is a declared exception, a relation still in code (`exception = true`),
             each naming what removes it (`until`). A relation the search cannot see (a law with no published
             constant) is declared the same way, `find = "known"`. Every exception is printed on every run.
             An allowance or a part that no longer matches anything is itself a problem, so the list cannot rot.

Owner: Agastya. Copyright (c) 2026 Agastya. All rights reserved.
"""
import argparse
import fnmatch
import pathlib
import re
import sys
import tomllib

from common import ROOT

REGISTRY = "tools/boundary.toml"
FORBIDDEN_CLASSES = {"model", "relation", "published model", "physics", "algorithm"}

# the marks of a relation or a published model in code (a regular expression each)
MARKS = {
    "earth GM": r"3\.98600441[0-9]*e\+?14|398600\.44[0-9]*|3\.986004418e5",
    "earth radius": r"(?<![0-9.])6378137(?:\.0*)?(?![0-9])|6378\.137|6\.378137e\+?6|6378136\.3",
    "earth rotation rate": r"7\.292115[0-9]*e-0?5|0\.0000729211[0-9]*",
    "J2": r"1\.0826[0-9]*e-0?3|0\.0010826|1082\.6[0-9]*e-0?6",
    "solar constant": r"(?<![0-9.])136[01]\.[0-9]+|(?<![0-9.])1361(?![0-9.])|(?<![0-9.])1367(?![0-9.])|1366\.1",
    "solar pressure": r"4\.5[0-9]*e-0?6",
    "speed of light": r"299792458|2\.99792458e\+?8|299792\.458",
    "astronomical unit": r"1\.495978707e\+?11|149597870\.7|149597870700|1\.496e\+?11",
    "sun GM": r"1\.32712440[0-9]*e\+?20",
    "moon GM": r"4\.9028[0-9]*e\+?12",
    "gravitational constant": r"6\.67[34][0-9]*e-11",
    "WGS-84 flattening": r"298\.257223563|0\.00335281066",
    "Stefan-Boltzmann": r"5\.670[0-9]*e-0?8",
    "sidereal day": r"86164\.09",
    "sea-level density": r"(?<![0-9.])1\.225(?![0-9])",
    "inverse-cube gravity": r"\bmu\w*\s*[*/].*\b(r|rn|rr|rmag|norm|a)\w*\s*(\^|\*\*|\.powi\(|\.powf\()\s*\(?3\b",
    "dynamic pressure": r"0\.5\s*\*\s*rho\w*\s*\*",
}
TABLE = "table"                   # a run of lines holding twelve or more long numbers (a coefficient table)
KNOWN = "known"                   # an allowance's find for a relation the search cannot see, declared by name
ANY = "any"                       # an allowance's find for every mark in its files (a vendored program)
NUM = re.compile(r"(?<![\w.])[-+]?(?:\d+\.\d*|\.\d+|\d+)(?:[eE][-+]?\d+)?(?![\w.])")
GENERATED = re.compile(r"generated by|written from the design|written by\s+tools/|do not edit", re.I)


def _sig(s):
    """Significant digits of a numeric literal."""
    m = s.lstrip("+-").lower().split("e")[0]
    if "." not in m:
        return len(m.lstrip("0").rstrip("0"))
    return len(m.replace(".", "").lstrip("0"))


def _code(line, ext):
    """The line without its comment (a rough cut: a comment's numbers are not a relation)."""
    if ext == ".m":
        return line.split("%")[0]
    if ext == ".py":
        return line.split("#")[0]
    return line.split("//")[0]


def search(text, ext):
    """[(line, mark, text)] of every mark of a relation or a published model in a source file."""
    lines = text.split("\n")
    if ext == ".rs":
        for i, ln in enumerate(lines):
            if ln.strip().startswith("#[cfg(test)]"):
                lines = lines[:i]
                break
    pats = {k: re.compile(v) for k, v in MARKS.items()}
    out = []
    run, start = 0, 0
    for i, ln in enumerate(lines, 1):
        code = _code(ln, ext)
        for k, p in pats.items():
            if p.search(ln if k not in ("inverse-cube gravity", "dynamic pressure") else code):
                out.append((i, k, ln.strip()[:120]))
        n = sum(1 for x in NUM.findall(code) if _sig(x) >= 4)
        if n >= 3:
            start = start if run else i
            run += n
        else:
            if run >= 12:
                out.append((start, TABLE, f"lines {start}-{i - 1}: {run} long numbers"))
            run = 0
    if run >= 12:
        out.append((start, TABLE, f"lines {start}-{len(lines)}: {run} long numbers"))
    return out


def _names(glob):
    return glob if isinstance(glob, str) else ", ".join(glob)


def _match(path, glob):
    """A path against a glob, or against any of a list of them (an allowance may name several files)."""
    return any(fnmatch.fnmatchcase(path, g) for g in ([glob] if isinstance(glob, str) else glob))


def files_in(root, reg):
    """Every source file of the code under the scope, as a path relative to root."""
    exts = tuple(reg["extensions"])
    out = []
    for top in reg["scope"]:
        base = root / top
        if not base.exists():
            continue
        for p in sorted(base.rglob("*")):
            if not p.is_file() or not p.name.endswith(exts):
                continue
            rel = p.relative_to(root).as_posix()
            if any(_match(rel, g) for g in reg.get("skip", [])):
                continue
            out.append(rel)
    return sorted(set(out))


def check(root=ROOT, registry=None, listing=False):
    """(problems, report lines) of the boundary check on a tree."""
    root = pathlib.Path(root)
    reg = tomllib.loads((pathlib.Path(registry) if registry else root / REGISTRY).read_text(encoding="utf-8"))
    classes = reg["classes"]
    problems, report = [], []
    bad = sorted(set(classes) & FORBIDDEN_CLASSES)
    if bad:
        problems.append(f"the registry declares a class for design in code ({', '.join(bad)}): a relation, a published model or an "
                        "algorithm has no class in the code")
    parts, allows, gens = reg.get("part", []), reg.get("allow", []), reg.get("generated", [])
    for p in parts:
        if p["class"] not in classes:
            problems.append(f"{p['glob']}: class {p['class']!r} is not one of the code's ({', '.join(classes)})")
        if not p.get("why"):
            problems.append(f"{p['glob']}: classified with no reason")
    for a in allows:
        if not a.get("why") or (a.get("exception") and not a.get("until")):
            problems.append(f"{_names(a['file'])} ({a['find']}): an allowance needs why, and an exception what removes it (until)")
    used_parts, used_allows, used_gens = set(), set(), set()
    by_class, finds, exceptions = {}, 0, []
    for f in files_in(root, reg):
        g = next((i for i, x in enumerate(gens) if _match(f, x["glob"])), None)
        if g is not None:
            used_gens.add(g)
            if not GENERATED.search((root / f).read_text(encoding="utf-8", errors="replace")):
                problems.append(f"{f}: in a generated folder ({gens[g]['by']}) but does not say it is generated: a hand-written file "
                                "cannot hide among the generated ones")
            by_class["generated"] = by_class.get("generated", 0) + 1
            continue
        k = next((i for i, x in enumerate(parts) if _match(f, x["glob"])), None)
        if k is None:
            problems.append(f"{f}: not classified (tools/boundary.toml [[part]]): every hand-written file says what part of the "
                            "code it is, and none may be a relation or a published model")
            continue
        used_parts.add(k)
        cls = parts[k]["class"]
        by_class[cls] = by_class.get(cls, 0) + 1
        if listing:
            report.append(f"  {cls:<12} {f}")
        # a relation the search cannot see (no published constant, no table): declared by name, never silently
        used_allows |= {i for i, a in enumerate(allows) if a["find"] == KNOWN and _match(f, a["file"])}
        if cls == "test":
            continue
        for line, mark, text in search((root / f).read_text(encoding="utf-8", errors="replace"), pathlib.Path(f).suffix):
            j = next((i for i, a in enumerate(allows) if _match(f, a["file"]) and a["find"] in (mark, ANY)), None)
            if j is None:
                problems.append(f"{f}:{line}: {mark} in code ({cls}): {text}")
                continue
            used_allows.add(j)
            finds += 1
    for i, p in enumerate(parts):
        if i not in used_parts:
            problems.append(f"tools/boundary.toml: the part {p['glob']} matches no file")
    for i, a in enumerate(allows):
        if i not in used_allows:
            problems.append(f"tools/boundary.toml: the allowance {_names(a['file'])} ({a['find']}) matches nothing")
        elif a.get("exception"):
            exceptions.append(f"  {_names(a['file'])} ({a['find']}): {a['why']} Until: {a['until']}")
    for i, x in enumerate(gens):
        if i not in used_gens:
            problems.append(f"tools/boundary.toml: the generated folder {x['glob']} holds no file")
    n = sum(by_class.values())
    report.append(f"boundary: {n} source files: " + ", ".join(f"{v} {k}" for k, v in sorted(by_class.items(), key=lambda kv: -kv[1])))
    report.append(f"boundary: {finds} finds allowed by {len(used_allows)} allowances, of which {len(exceptions)} are declared exceptions "
                  "(a relation or published model still in code):")
    report += exceptions
    return problems, report


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(ROOT))
    ap.add_argument("--registry", help="the registry (default ROOT/tools/boundary.toml)")
    ap.add_argument("--list", action="store_true")
    a = ap.parse_args(argv)
    problems, report = check(pathlib.Path(a.root), a.registry, a.list)
    print("\n".join(report))
    for p in problems:
        print("boundary: " + p, file=sys.stderr)
    print(f"boundary: {len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
