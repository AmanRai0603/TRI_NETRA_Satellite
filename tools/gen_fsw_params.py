#!/usr/bin/env python3
"""Generate the flight-software parameter and table sources from their single definitions.

  fsw/params/params.toml      -> fsw/include/adcs_params.h, fsw/src/adcs_params.c, fsw-rs/src/params.rs
  matlab_sils/data/igrf13.json -> fsw/include/adcs_igrf13.h, fsw-rs/src/igrf13.rs
  fsw/params/modes (below)     -> the controller-state enumeration in both languages

The config blob ("adcs-fswcfg/1"): b"ADCSCFG1" | u32 payload length | fields in table order,
little-endian | u32 CRC-32 (IEEE 802.3, reflected, init/xorout 0xFFFFFFFF) of the payload.
Generated files carry a header saying so; they are never edited by hand.
Copyright (c) 2026 Agastya. All rights reserved.
"""
import json, pathlib, tomllib
from common import write_text

ROOT = pathlib.Path(__file__).resolve().parents[1]
P = tomllib.loads((ROOT / "fsw" / "params" / "params.toml").read_text())
F = P["field"]
MODES = ["DETUMBLE", "NADIR_MTQ", "NADIR_FINE", "TARGET_FINE", "SLEW_FINE", "SPINUP", "SUN_SPIN",
         "DETUMBLE_RCS", "SUN_ACQ_ROTOR", "SUN_MTQ", "SUN_FINE"]          # = asils.fsw.modes order
SIZE = {"f64": 8, "u32": 4, "u8": 1}
CT = {"f64": "double", "u32": "uint32_t", "u8": "uint8_t"}
RT = {"f64": "f64", "u32": "u32", "u8": "u8"}
HDR = "Generated by tools/gen_fsw_params.py from fsw/params/params.toml -- do not edit."


def count(f):
    n = 1
    for d in f.get("shape", []):
        n *= d
    return n


PAYLOAD = sum(SIZE[f["type"]] * count(f) for f in F)
BLOB = 8 + 4 + PAYLOAD + 4


def c_header():
    L = [f"/* adcs_params.h -- {HDR} */", "#ifndef ADCS_PARAMS_H", "#define ADCS_PARAMS_H", "",
         "#include <stddef.h>", "#include <stdint.h>", "",
         f"#define ADCS_PARAMS_PAYLOAD {PAYLOAD}u", f"#define ADCS_PARAMS_BLOB_SIZE {BLOB}u",
         f"#define ADCS_MAX_ROTORS {P['max_rotors']}", f"#define ADCS_MAX_GIMBALS {P['max_gimbals']}",
         f"#define ADCS_MAX_COUPLES {P['max_couples']}", f"#define ADCS_MAX_HEADS {P['max_heads']}",
         f"#define ADCS_MAX_SCHEDULE {P['max_schedule']}", "#define ADCS_MODE_NONE 255u", "",
         "typedef enum {"] + [f"    ADCS_MODE_{m} = {i}," for i, m in enumerate(MODES)] + [
         f"    ADCS_MODE_COUNT = {len(MODES)}", "} adcs_mode_t;", "", "typedef struct {"]
    for f in F:
        sh = "".join(f"[{d}]" for d in f.get("shape", []))
        doc = f"  /* {f['doc']} */" if "doc" in f else ""
        L.append(f"    {CT[f['type']]} {f['name']}{sh};{doc}")
    L += ["} adcs_params_t;", "",
          "/* Decode an adcs-fswcfg/1 blob. 0 on success; -1 bad magic, -2 bad length, -3 bad CRC. */",
          "int32_t adcs_params_decode(const uint8_t *blob, size_t len, adcs_params_t *out);",
          "/* Encode into buf (cap >= ADCS_PARAMS_BLOB_SIZE); returns the blob length or 0. Ground and test use. */",
          "size_t adcs_params_encode(const adcs_params_t *in, uint8_t *buf, size_t cap);",
          "uint32_t adcs_crc32(const uint8_t *p, size_t n);", "", "#endif", ""]
    return "\n".join(L)


def c_source():
    L = [f"/* adcs_params.c -- {HDR} */", '#include "adcs_params.h"', "#include <string.h>", "",
         "uint32_t adcs_crc32(const uint8_t *p, size_t n)", "{",
         "    uint32_t c = 0xFFFFFFFFu;", "    size_t i; int k;",
         "    for (i = 0; i < n; i++) {", "        c ^= p[i];",
         "        for (k = 0; k < 8; k++) c = (c >> 1) ^ (0xEDB88320u & (0u - (c & 1u)));", "    }",
         "    return c ^ 0xFFFFFFFFu;", "}", "",
         "static uint32_t rd_u32(const uint8_t *p) { return (uint32_t)p[0] | ((uint32_t)p[1] << 8) | ((uint32_t)p[2] << 16) | ((uint32_t)p[3] << 24); }",
         "static double rd_f64(const uint8_t *p)", "{",
         "    uint64_t u = 0; double d; int k;", "    for (k = 7; k >= 0; k--) u = (u << 8) | p[k];",
         "    memcpy(&d, &u, sizeof d);", "    return d;", "}", "",
         "int32_t adcs_params_decode(const uint8_t *blob, size_t len, adcs_params_t *out)", "{",
         "    const uint8_t *p;", "    size_t i;",
         "    if (len < ADCS_PARAMS_BLOB_SIZE || memcmp(blob, \"ADCSCFG1\", 8) != 0) return -1;",
         "    if (rd_u32(blob + 8) != ADCS_PARAMS_PAYLOAD) return -2;",
         "    if (adcs_crc32(blob + 12, ADCS_PARAMS_PAYLOAD) != rd_u32(blob + 12 + ADCS_PARAMS_PAYLOAD)) return -3;",
         "    p = blob + 12;", "    (void)i;"]
    for f in F:
        n = count(f); t = f["type"]
        rd = {"f64": "rd_f64(p)", "u32": "rd_u32(p)", "u8": "p[0]"}[t]
        if n == 1:
            L.append(f"    out->{f['name']} = {rd}; p += {SIZE[t]};")
        else:
            flat = f"(({CT[t]} *)out->{f['name']})"
            L.append(f"    for (i = 0; i < {n}u; i++) {{ {flat}[i] = {rd}; p += {SIZE[t]}; }}")
    L += ["    return 0;", "}", "",
          "static void wr_u32(uint8_t *p, uint32_t v) { p[0] = (uint8_t)v; p[1] = (uint8_t)(v >> 8); p[2] = (uint8_t)(v >> 16); p[3] = (uint8_t)(v >> 24); }",
          "static void wr_f64(uint8_t *p, double d) { uint64_t u; int k; memcpy(&u, &d, sizeof u); for (k = 0; k < 8; k++) { p[k] = (uint8_t)(u & 0xFFu); u >>= 8; } }",
          "size_t adcs_params_encode(const adcs_params_t *in, uint8_t *buf, size_t cap)", "{",
          "    uint8_t *p;", "    size_t i;",
          "    if (cap < ADCS_PARAMS_BLOB_SIZE) return 0;",
          "    memcpy(buf, \"ADCSCFG1\", 8); wr_u32(buf + 8, ADCS_PARAMS_PAYLOAD);", "    p = buf + 12;", "    (void)i;"]
    for f in F:
        n = count(f); t = f["type"]
        wr = {"f64": "wr_f64(p, {v})", "u32": "wr_u32(p, {v})", "u8": "p[0] = {v}"}[t]
        if n == 1:
            L.append(f"    {wr.format(v='in->' + f['name'])}; p += {SIZE[t]};")
        else:
            flat = f"((const {CT[t]} *)in->{f['name']})"
            L.append(f"    for (i = 0; i < {n}u; i++) {{ {wr.format(v=flat + '[i]')}; p += {SIZE[t]}; }}")
    L += ["    wr_u32(p, adcs_crc32(buf + 12, ADCS_PARAMS_PAYLOAD));", "    return ADCS_PARAMS_BLOB_SIZE;", "}", ""]
    return "\n".join(L)


def rs_source():
    def rty(f):
        t = RT[f["type"]]
        for d in reversed(f.get("shape", [])):
            t = f"[{t}; {d}]"
        return t

    def zero(f):
        z = {"f64": "0.0", "u32": "0", "u8": "0"}[f["type"]]
        for d in reversed(f.get("shape", [])):
            z = f"[{z}; {d}]"
        return z

    L = [f"//! Flight-software parameters (adcs-fswcfg/1). {HDR}", "#![allow(non_snake_case, clippy::all)]", "",
         f"pub const PAYLOAD: usize = {PAYLOAD};", f"pub const BLOB_SIZE: usize = {BLOB};",
         f"pub const MAX_ROTORS: usize = {P['max_rotors']};", f"pub const MAX_GIMBALS: usize = {P['max_gimbals']};",
         f"pub const MAX_COUPLES: usize = {P['max_couples']};", f"pub const MAX_HEADS: usize = {P['max_heads']};",
         f"pub const MAX_SCHEDULE: usize = {P['max_schedule']};", "pub const MODE_NONE: u8 = 255;", "",
         "/// Controller states (= asils.fsw.modes order).", "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
         "#[repr(u8)]", "pub enum Mode {"] + [f"    {''.join(w.capitalize() for w in m.split('_'))} = {i}," for i, m in enumerate(MODES)] + [
         "}", "", "impl Mode {", "    pub fn from_u8(v: u8) -> Option<Mode> {", "        match v {"] + [
         f"            {i} => Some(Mode::{''.join(w.capitalize() for w in m.split('_'))})," for i, m in enumerate(MODES)] + [
         "            _ => None,", "        }", "    }", "}", "",
         "#[derive(Clone, Copy, Debug)]", "pub struct Params {"]
    for f in F:
        if "doc" in f:
            L.append(f"    /// {f['doc']}")
        L.append(f"    pub {f['name']}: {rty(f)},")
    L += ["}", "", "impl Default for Params {", "    fn default() -> Self {", "        Params {"]
    L += [f"            {f['name']}: {zero(f)}," for f in F]
    L += ["        }", "    }", "}", "",
          "pub fn crc32(p: &[u8]) -> u32 {", "    let mut c: u32 = 0xFFFF_FFFF;",
          "    for &b in p {", "        c ^= b as u32;", "        for _ in 0..8 {",
          "            c = (c >> 1) ^ (0xEDB8_8320 & (0u32.wrapping_sub(c & 1)));", "        }", "    }",
          "    c ^ 0xFFFF_FFFF", "}", "",
          "#[derive(Debug, PartialEq, Eq)]", "pub enum DecodeError { Magic, Length, Crc }", "",
          "struct Rd<'a> { b: &'a [u8], i: usize }",
          "impl<'a> Rd<'a> {",
          "    fn f64(&mut self) -> f64 { let mut a = [0u8; 8]; a.copy_from_slice(&self.b[self.i..self.i + 8]); self.i += 8; f64::from_le_bytes(a) }",
          "    fn u32(&mut self) -> u32 { let mut a = [0u8; 4]; a.copy_from_slice(&self.b[self.i..self.i + 4]); self.i += 4; u32::from_le_bytes(a) }",
          "    fn u8(&mut self) -> u8 { let v = self.b[self.i]; self.i += 1; v }", "}",
          "struct Wr<'a> { b: &'a mut [u8], i: usize }",
          "impl<'a> Wr<'a> {",
          "    fn f64(&mut self, v: f64) { self.b[self.i..self.i + 8].copy_from_slice(&v.to_le_bytes()); self.i += 8; }",
          "    fn u32(&mut self, v: u32) { self.b[self.i..self.i + 4].copy_from_slice(&v.to_le_bytes()); self.i += 4; }",
          "    fn u8(&mut self, v: u8) { self.b[self.i] = v; self.i += 1; }", "}", "",
          "impl Params {",
          "    /// Decode an adcs-fswcfg/1 blob.",
          "    pub fn decode(blob: &[u8]) -> Result<Params, DecodeError> {",
          "        if blob.len() < BLOB_SIZE || &blob[0..8] != b\"ADCSCFG1\" { return Err(DecodeError::Magic); }",
          "        let mut r = Rd { b: blob, i: 8 };",
          "        if r.u32() as usize != PAYLOAD { return Err(DecodeError::Length); }",
          "        let mut c = Rd { b: blob, i: 12 + PAYLOAD };",
          "        if crc32(&blob[12..12 + PAYLOAD]) != c.u32() { return Err(DecodeError::Crc); }",
          "        let mut p = Params::default();"]

    def walk(f, rw):
        n = f.get("shape", [])
        acc = f"p.{f['name']}"
        t = f["type"]
        if not n:
            return [f"        {acc} = r.{t}();"] if rw == "r" else [f"        w.{t}({acc});"]
        idx = "".join(f"[i{k}]" for k in range(len(n)))
        loops = "".join(f"for i{k} in 0..{d} {{ " for k, d in enumerate(n))
        close = " }" * len(n)
        body = f"{acc}{idx} = r.{t}();" if rw == "r" else f"w.{t}({acc}{idx});"
        return [f"        {loops}{body}{close}"]

    for f in F:
        L += walk(f, "r")
    L += ["        Ok(p)", "    }", "",
          "    /// Encode into an adcs-fswcfg/1 blob (buf.len() >= BLOB_SIZE); returns the blob length.",
          "    pub fn encode(&self, buf: &mut [u8]) -> usize {",
          "        let p = self;", "        buf[0..8].copy_from_slice(b\"ADCSCFG1\");",
          "        let mut w = Wr { b: buf, i: 8 };", f"        w.u32(PAYLOAD as u32);"]
    for f in F:
        L += walk(f, "w")
    L += ["        let crc = crc32(&w.b[12..12 + PAYLOAD]);", "        w.u32(crc);", "        w.i", "    }", "}", ""]
    return "\n".join(L)


def igrf():
    d = json.loads((ROOT / "matlab_sils" / "data" / "igrf13.json").read_text())
    E = d["epochs"]
    yrs = [e["year"] for e in E]
    c = [f"/* adcs_igrf13.h -- IGRF-13 Gauss coefficients [nT], 5-year epochs {yrs[0]}-{yrs[-1]}, "
         f"195 per epoch (degree 13). Generated by tools/gen_fsw_params.py from matlab_sils/data/igrf13.json. */",
         "#ifndef ADCS_IGRF13_H", "#define ADCS_IGRF13_H", f"#define ADCS_IGRF_EPOCHS {len(E)}", "#define ADCS_IGRF_NCOEF 195",
         f"static const double adcs_igrf_year[ADCS_IGRF_EPOCHS] = {{{', '.join(str(y) for y in yrs)}}};",
         "static const double adcs_igrf_tab[ADCS_IGRF_EPOCHS][ADCS_IGRF_NCOEF] = {"]
    for e in E:
        c.append("    {" + ", ".join(repr(float(x)) for x in e["gh"]) + "},")
    c += ["};", "#endif", ""]
    r = [f"//! IGRF-13 Gauss coefficients [nT], generated by tools/gen_fsw_params.py -- do not edit.",
         f"pub const EPOCHS: usize = {len(E)};", "pub const NCOEF: usize = 195;",
         f"pub const YEAR: [f64; EPOCHS] = [{', '.join(repr(float(y)) for y in yrs)}];",
         "pub const GH: [[f64; NCOEF]; EPOCHS] = ["]
    for e in E:
        r.append("    [" + ", ".join(repr(float(x)) for x in e["gh"]) + "],")
    r += ["];", ""]
    return "\n".join(c), "\n".join(r)


def outputs():
    """Every generated file and its text."""
    ch, rs = igrf()
    return [(ROOT / "fsw" / "include" / "adcs_params.h", c_header()), (ROOT / "fsw" / "src" / "adcs_params.c", c_source()),
            (ROOT / "fsw-rs" / "src" / "params.rs", rs_source()),
            (ROOT / "fsw" / "include" / "adcs_igrf13.h", ch), (ROOT / "fsw-rs" / "src" / "igrf13.rs", rs)]


if __name__ == "__main__":
    import sys
    if sys.argv[1:] == ["--check"]:
        stale = [p for p, text in outputs() if not p.exists() or p.read_text() != text]
        for p in stale:
            print(f"{p.relative_to(ROOT)} is not what its definition gives: run python3 tools/gen_fsw_params.py")
        print(f"gen_fsw_params --check: {'every generated file is current' if not stale else f'{len(stale)} stale'}")
        sys.exit(1 if stale else 0)
    if sys.argv[1:]:
        sys.exit("usage: python3 tools/gen_fsw_params.py [--check]")
    for p, text in outputs():
        write_text(p, text)
    print(f"params: {len(F)} fields, payload {PAYLOAD} bytes, blob {BLOB} bytes; IGRF tables written")
