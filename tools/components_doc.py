#!/usr/bin/env python3
"""Write docs/COMPONENTS.md from catalogue/components/*.toml: every sensor and
actuator, the model the SILS flies, its processing chain node by node with its
status, and where in-house development plugs in.
Copyright (c) 2026 Agastya. All rights reserved.
"""
import pathlib, tomllib

ROOT = pathlib.Path(__file__).resolve().parents[1]
C = [tomllib.loads(f.read_text()) for f in sorted((ROOT / "catalogue" / "components").glob("*.toml"))]
C.sort(key=lambda c: (c["kind"] != "sensor", c["id"]))
L = ["# Components: models and chains", "", "**Owner: Agastya.** Copyright (c) 2026 Agastya. All rights reserved.", "",
     "Generated by `tools/components_doc.py` from `catalogue/components/*.toml`.", "",
     "Each unit has a **model**: what the SILS flies in its place, truth in and output out, with the part's",
     "errors. It also has a **chain**: the unit's own processing, which is where in-house development",
     "plugs in node by node. A chain node's status is one of three:",
     "- `implemented`",
     "- `baseline`: a standard method stands in until the in-house one arrives",
     "- `stub`",
     "",
     "The unit's interface to the rest of the ADCS is always its HAL frame, so a model, a chain or the real",
     "unit (HILS) can take its place without changing anything else.", "",
     "| component | kind | in-house | chain nodes (status) | HAL output |", "|---|---|---|---|---|"]
for c in C:
    ch = ", ".join(f"{n['node']} ({n['status']})" for n in c.get("chain", [])) or "—"
    L.append(f"| {c['id']} | {c['kind']} | {c['in_house']} | {ch} | {c['hal_output']} |")
for c in C:
    L += ["", f"## {c['id']}", "", f"- model: `{c['model']}`", f"- parts: {', '.join(c['parts'])}",
          f"- levels: {'; '.join(c['levels'])}", f"- HAL output: {c['hal_output']}"]
    if c.get("chain"):
        L += ["", "| node | file | status | what |", "|---|---|---|---|"]
        for n in c["chain"]:
            L.append(f"| {n['node']} | `{n['file']}` | {n['status']} | {n['what']} |")
(ROOT / "docs" / "COMPONENTS.md").write_text("\n".join(L) + "\n")
print("wrote docs/COMPONENTS.md", len(C), "components")
