#!/usr/bin/env python3
"""The explanation kit: the one copy of the CSS and script that every HTML page
uses to follow the explanation standard adcs-explain/1 (SPEC.md §5.12).

    python3 tools/explain_kit.py --write   put the kit into every template
    python3 tools/explain_kit.py --check   exit 1 if any template's copy differs

Every template is a single self-contained file (it must open from disk, offline,
with no second file), so each carries its own copy of the kit between the
markers below. This module is the source; the copies are generated, and CI
fails when one drifts.

What the kit gives a page:

* the depth switch, Learn · Read · Expert (E03). Content marked
  data-show="learn read" is shown only at those depths. The reader's choice is
  remembered in this browser when the browser allows it, and the page works when
  it does not;
* the four kind badges, tutorial, how-to, reference and explanation (E02);
* claim chips, sourced [n], derived, reference and example (E18);
* the station labels, Say it simply, Now the real thing, Where the simple
  version breaks, Try it (E10);
* the boxes for the answer (E01), a common wrong idea (E13), an analogy and
  where it breaks (E14), a why-chain (E15), and where the page breaks (E20);
* window.ADCS_EXPLAIN, for pages drawn by script: badge(kind), claim(type,
  label, href), station(step), state(ok, word).
"""

