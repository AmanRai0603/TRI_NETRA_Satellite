def block(begin, body, end):
    return begin + "\n" + body.strip("\n") + "\n" + end


def apply(text):
    """The template's text with the kit's two blocks replaced (or inserted)."""
    css = block(CSS_BEGIN, CSS, CSS_END)
    js = block(JS_BEGIN, JS, JS_END)
    if CSS_BEGIN in text:
        text = re.sub(re.escape(CSS_BEGIN) + r".*?" + re.escape(CSS_END), lambda m: css, text, count=1, flags=re.S)
    else:
        i = text.index("</style>")
        text = text[:i] + css + "\n" + text[i:]
    if JS_BEGIN in text:
        text = re.sub(re.escape(JS_BEGIN) + r".*?" + re.escape(JS_END), lambda m: js, text, count=1, flags=re.S)
    else:
        i = text.index("</head>")
        text = text[:i] + "<script>\n" + js + "\n</script>\n" + text[i:]
    return text


def page_head():
    """The kit for a page a tool writes whole (the quarterly narrative)."""
    return block(CSS_BEGIN, CSS, CSS_END), block(JS_BEGIN, JS, JS_END)


def main():
    args = sys.argv[1:]
    if args not in (["--write"], ["--check"]):
        print(__doc__)
        return 2
    stale = []
    for rel in TEMPLATES:
        p = os.path.join(ROOT, rel)
        text = open(p, encoding="utf-8").read()
        new = apply(text)
        if new != text:
            if args == ["--write"]:
                open(p, "w", encoding="utf-8").write(new)
                print("wrote the kit into %s" % rel)
            else:
                stale.append(rel)
    if stale:
        print("STALE: %s — run python3 tools/explain_kit.py --write" % ", ".join(stale))
        return 1
    if args == ["--check"]:
        print("the explanation kit is current in %d templates" % len(TEMPLATES))
    return 0


if __name__ == "__main__":
    sys.exit(main())
